# -*- coding: utf-8 -*-
r"""ПРИЁМКА: ЧИСЛО, СЛИПШЕЕСЯ С МЕТКОЙ, СЧЁТОМ НЕ БЫВАЕТ (сторож стандарта роли, признак ④+).

КЛАСС. Признак «утверждение о количестве» ищет цифры перед словом-счётчиком. Но цифра,
которой ВПЛОТНУЮ предшествует разделитель метки, принадлежит не счёту, а дате/часу/номеру:
    «08.08  правил право в трёх местах»   → «правил 8»  (дата;  принёс @STUD, записка #3509)
    «16.08 10:00    правило „…"»          → «правил 0»  (час;   принёс @CHROME, записка #4068)
Обе роли текст под прибор НЕ подогнали, а принесли разбор — правильный ответ. Цена ложного
обвинения названа ими же: гард, обвиняющий роль во лжи там, где она точна, перестают читать
целиком — и вместе с ложным уходит настоящее.

⚡ ПОЧЕМУ ПРИЁМКА ШИРЕ ЗАЯВКИ. Замер 2026-08-29 09:43 UTC перед правкой: один и тот же час
ломал ТРИ счётчика («правил» · «ролей» · «инвариантов»), а заявка была про один. Заявка
задаёт МЕСТО, дефект живёт в КЛАССЕ мест.

⚖️ ГРАНИЦА ЛЕЧЕНИЯ НАЗВАНА ВСЛУХ И ПРОВЕРЯЕТСЯ ЗДЕСЬ ЖЕ: запрещён разделитель ВПЛОТНУЮ.
Двоеточие с пробелом («итого: 69 правил») — законный счёт и обязано краснеть. Без этой
контрольной пары лечение неотличимо от ослепления прибора.

⛔ Число случаев печатает прогон, а не эта строка.
"""
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GUARD = os.path.join(HERE, "guard-role-standard.py")
if not os.path.exists(GUARD):
    print(f"⛔ ИСПЫТУЕМОГО НЕТ: {GUARD} — отказ мерить, не «чисто»")
    sys.exit(2)
sys.path.insert(0, HERE)
spec = importlib.util.spec_from_file_location("guard_stamp_under_test", GUARD)
G = importlib.util.module_from_spec(spec)
spec.loader.exec_module(G)

# Числа стенда — СВОИ, не живого контура: приёмка не должна зависеть от того,
# сколько правил в базе сегодня (класс ⑥ «впечатанное число врёт уверенно»).
COUNTS = {"правил": 60, "инвариантов": 12, "ролей": 9}

# (заголовок, строка, обязана ли краснеть)
CASES = [
    # ── РАЗЛИЧАЮЩИЕ: метка вплотную — счёта здесь нет ─────────────────────
    ("① час+«правило» — живая строка @CHROME (записка #4068 §③)",
     "16.08 10:00    правило «часть составного имени — не упоминание»", False),
    ("② тот же класс, другой час — дефект не в конкретных минутах",
     "09:40 правило свода заведено, читать целиком", False),
    ("③ час ломал и счётчик ролей — класс шире заявки",
     "синк 09:30 ролей это не касается", False),
    ("④ час ломал и счётчик инвариантов — третий из шести",
     "в 11:00 инвариант перемерен своей рукой", False),
    ("⑤ дата вплотную — прежнее лечение (@STUD, записка #3509) цело",
     "08.08  правил право в трёх местах памяти", False),
    # ── КОНТРОЛЬНАЯ ПАРА: прибор не ослеп, настоящий счёт ловится ─────────
    ("⑥ КОНТРОЛЬ: настоящий счёт правил разошёлся с фактом",
     "в своде 69 правил, все с основанием", True),
    ("⑦ КОНТРОЛЬ: счёт ВЕРЕН — молчание заслужено, а не случайно",
     "в своде 60 правил, все с основанием", False),
    ("⑧ КОНТРОЛЬ: настоящий счёт ролей разошёлся с фактом",
     "в контуре 7 ролей, остальные закрыты", True),
    ("⑨ ГРАНИЦА: двоеточие с ПРОБЕЛОМ — законный счёт, обязан краснеть",
     "итого: 69 правил на сегодня", True),
]


def main() -> int:
    print("═══ ПРИЁМКА: число, слипшееся с меткой ═══")
    differ = 0
    for title, line, must_fire in CASES:
        try:
            out = G.check_stale_numbers([line], COUNTS, "state")
        except Exception as exc:                 # третий исход: НЕ ЗАПУСТИЛАСЬ
            print(f"⛔ НЕ ЗАПУСТИЛАСЬ  {title}: {exc}")
            differ += 1
            continue
        fired = bool(out)
        ok = fired == must_fire
        said = out[0][1] if fired else "молчит"
        print(f"{'✅' if ok else '🔴'} {title}")
        print(f"   ждали {'красное' if must_fire else 'молчание'} → {said}")
        differ += not ok
    print(f"═══ ИТОГ: случаев {len(CASES)}, расхождений {differ} ═══")
    return 1 if differ else 0


if __name__ == "__main__":
    sys.exit(main())
