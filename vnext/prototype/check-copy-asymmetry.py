# -*- coding: utf-8 -*-
r"""check-copy-asymmetry.py — доедет ли инструмент до потребителя.

═══ ЗАЧЕМ, И ПОЧЕМУ РАВЕНСТВО КАТАЛОГОВ — НЕВЕРНОЕ СВОЙСТВО ═══
Замер 2026-08-09 17:15 UTC (карточка #145). Пара «рабочий каталог ↔ шаблон» разошлась на
27 файлов. Первое, что просится, — сделать каталоги одинаковыми. Я так и сделал — и через
две минуты прогон это опроверг:
```
перенос рабочий → шаблон (13 файлов) .... ВЕРНО: приёмок в общем прогоне 27 → 34, все зелёные
перенос шаблон → рабочий (14 файлов) .... НЕВЕРНО: из 14 девять там НЕ РАБОТАЮТ ВОВСЕ
                                          (строят стенд из схемы, лежащей рядом с шаблоном)
```
⇒ Каталоги НЕ равноправны, и требовать равенства — чинить признак вместо свойства.
🪤 И это ловушка «зелёного любой ценой»: зеркало ради молчания сторожа кладёт к потребителю
   девять инструментов, падающих при запуске. Сторож при этом доволен.

═══ ВЕРНОЕ СВОЙСТВО — АСИММЕТРИЧНОЕ ═══
```
🔴 файл есть в РАБОЧЕМ, нет в ШАБЛОНЕ  → при раскатке НЕ ДОЕДЕТ до потребителя.
                                         Худший случай: у потребителя файла нет ВОВСЕ,
                                         а сверка молчит (@RCC #3338, @COORD 09.08)
🔴 файл есть в обоих, содержимое РАЗНОЕ → дрейф: копии разошлись молча
✅ файл есть только в ШАБЛОНЕ           → НОРМА. Шаблон полнее по построению: он несёт
                                         и то, что работает лишь рядом со схемой и стендом
```
⚠️ И ГЛАВНОЕ, ЧТО ЭТОТ ПРИЗНАК НЕ УМЕЕТ И НЕ ДОЛЖЕН ВЫДАВАТЬ ЗА УМЕНИЕ:
   побайтовое совпадение НЕ означает, что копии равносильны. Замер того же часа:
   каталоги совпали файл в файл, сторож напечатал «69 общих совпадают», а прогон из
   рабочего дал «сломано 2, не проверено 7» против «34 держится» из шаблона.
   ⇒ Совпадение байтов — про ФАЙЛЫ. Работоспособность — про ОКРУЖЕНИЕ, и она не проверяется
   сравнением. Признак говорит об этом вслух, чтобы его зелёное не читалось шире себя.

═══ ПОЧЕМУ ПУТИ — АРГУМЕНТЫ, А НЕ КОНСТАНТЫ ═══
Живой сторож этой пары (`guard-scripts-drift.py`) держит пути жёстко и не принимает их
снаружи ⇒ испытать его можно только на настоящих каталогах, то есть его «зелёное»
приходится принимать на веру. Сторож, который нельзя запустить по копии, нельзя и проверить.

ЗАПУСК:
    python check-copy-asymmetry.py --runtime <рабочий> --template <шаблон>
"""
import argparse
import hashlib
import sys
from pathlib import Path


def digest(p: Path) -> str:
    # перевод строки нормализуем: git на Windows правит его сам, и это не дрейф
    return hashlib.sha256(p.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runtime", required=True, help="рабочий каталог (потребитель)")
    ap.add_argument("--template", required=True, help="шаблон (источник раскатки)")
    ap.add_argument("--glob", default="*.py")
    a = ap.parse_args()

    rt, tpl = Path(a.runtime), Path(a.template)
    for d, name in ((rt, "рабочий"), (tpl, "шаблон")):
        if not d.is_dir():
            print(f"⛔ {name} каталог не найден: {d} — сверять нечем (это НЕ «чисто»)")
            return 2

    r = {p.name: p for p in rt.glob(a.glob)}
    t = {p.name: p for p in tpl.glob(a.glob)}
    if not r and not t:
        print("⛔ оба каталога пусты — сверять нечего. Это НЕ «совпадают»")
        return 2

    orphan = sorted(set(r) - set(t))                     # 🔴 не доедет
    drift = sorted(n for n in set(r) & set(t) if digest(r[n]) != digest(t[n]))
    extra = sorted(set(t) - set(r))                      # ✅ норма

    for n in orphan:
        print(f"🔴 НЕ ДОЕДЕТ: {n} — есть у потребителя, в шаблоне НЕТ")
    for n in drift:
        print(f"🔴 ДРЕЙФ: {n} — есть в обоих, содержимое разошлось")
    print(f"✅ шаблон полнее на {len(extra)} — это НОРМА, а не дефект"
          if extra else "✅ шаблон и рабочий совпадают по составу")
    print(f"📏 сверено: рабочий {len(r)} · шаблон {len(t)} · общих {len(set(r) & set(t))}")
    print("⚖️ ГРАНИЦА: сверены ФАЙЛЫ. Совпадение байтов НЕ означает, что копии равносильны —"
          " инструмент зависит от того, что лежит рядом. Доказывается только ПРОГОНОМ обеих.")
    return 1 if (orphan or drift) else 0


if __name__ == "__main__":
    sys.exit(main())
