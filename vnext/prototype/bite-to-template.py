# -*- coding: utf-8 -*-
r"""bite-to-template.py — приёмка карточки #576: перенос в публичный образец обезличивает пути сам.

═══ ЧТО СУДИМ
Перенос инструмента в образец делался руками, и дважды за смену 05.09 я едва не увёз туда
путь этой машины (2 файла в 20:48, 4 файла в 22:39). Оба раза поймал сличением ДО отправки,
то есть случайно. Теперь перенос зовёт ТУ ЖЕ функцию обезличивания, что и сверка расхождений.

═══ ГЛАВНОЕ, ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ, И ПОЧЕМУ ЭТО НЕ ОЧЕВИДНО
Обезличить путь ЦЕЛИКОМ нельзя: строка, которую код ВЫЧИСЛЯЕТ, после подстановки заглушки
падает у потребителя на первом же прогоне (оплачено соседним контуром, записано в шапке
самой сверки). Значит перенос обязан РАЗЛИЧАТЬ читаемый человеком текст и исполняемый код —
и отказываться, когда путь стои́т во втором.

═══ ГРАНИЦА
Судится ПЕРЕНОС. Верность содержимого по существу он не знает и не обещает — прогон
образца остаётся за человеком, и инструмент говорит это вслух своей последней строкой.
"""
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import mezo_paths  # noqa: E402
import mezo_stand  # noqa: E402

СВЕРКА = Path(mezo_paths.live_scripts(__file__)) / "guard-scripts-drift.py"
КОНТЕЙНЕР = str(Path(mezo_paths.container_root(__file__)))

итог: list[tuple[str, bool, str]] = []


def случай(имя: str, ок: bool, слово: str) -> None:
    итог.append((имя, ок, слово))
    print(f"{'✅' if ок else '🔴'} {имя}: {слово}")


def перенести(файлы, откуда: Path, куда: Path):
    r = subprocess.run([sys.executable, str(СВЕРКА), "--to-template", *файлы,
                        "--vnext-runtime", str(откуда), "--vnext-template", str(куда)],
                       capture_output=True, text=True, encoding="utf-8", timeout=300)
    return r.returncode, (r.stdout or "") + (r.stderr or "")


def main() -> int:
    стенд = Path(tempfile.mkdtemp(prefix="bite-to-template-"))
    mezo_stand.release(стенд)
    исток = стенд / "исток"
    образец = стенд / "образец"
    исток.mkdir()
    образец.mkdir()

    # ── подопытный ①: путь этой машины стои́т ТОЛЬКО в читаемом человеком тексте
    (исток / "мирный.py").write_text(
        f'"""Зови так: python {КОНТЕЙНЕР}/vnext-tools/мирный.py --role X"""\n'
        f'import sys\n'
        f'print("подсказка: смотри {КОНТЕЙНЕР}/vnext-tools рядом")\n'
        f'# и в комментарии тоже: {КОНТЕЙНЕР}/vnext-tools\n'
        f'sys.exit(0)\n', encoding="utf-8")

    # ── подопытный ②: тот же путь ВЫЧИСЛЯЕТСЯ кодом. Заглушка здесь — изготовление поломки
    (исток / "опасный.py").write_text(
        f'from pathlib import Path\n'
        f'КОРЕНЬ = Path(r"{КОНТЕЙНЕР}") / "vnext-tools"\n'
        f'print(КОРЕНЬ)\n', encoding="utf-8")

    # ── ① перенос кладёт файл обезличенным
    код, вывод = перенести(["мирный.py"], исток, образец)
    копия = образец / "мирный.py"
    осталось = копия.read_text(encoding="utf-8").count(КОНТЕЙНЕР) if копия.exists() else -1
    случай("① перенесённый файл не несёт пути этой машины",
           код == 0 and осталось == 0,
           f"код {код}, вхождений пути {осталось}")

    # ── ② заглушка встала ТУДА ЖЕ, куда её ставит сверка: отпечатки «с точностью до
    #    обезличивания» у источника и копии обязаны совпасть. Это и есть доказательство,
    #    что правило ОДНО, а не два похожих.
    sys.path.insert(0, str(СВЕРКА.parent))
    сверка_модуль = __import__("importlib").import_module("importlib.util")
    спец = сверка_модуль.spec_from_file_location("drift", СВЕРКА)
    drift = сверка_модуль.module_from_spec(спец)
    спец.loader.exec_module(drift)
    # 🩸 ДВЕ РЕДАКЦИИ ЭТОГО СЛУЧАЯ БЫЛИ НЕВЕРНЫ, и обе нашла нарочная поломка, а не глаз:
    #   ① сравнение отпечатков «с точностью до обезличивания» — зелено, когда перенос
    #     не делает НИЧЕГО: сверка обезличивает обе стороны сама;
    #   ② точное совпадение с обезличенным текстом источника — недостижимо и не нужно:
    #     сверка заменяет путь ВЕЗДЕ, а перенос — только в читаемых человеком местах,
    #     и это его смысл, а не изъян.
    # ⇒ Судим то, что и хотели: заглушек ровно столько, сколько путей стояло в читаемых
    #   местах, и вид заглушки ВЗЯТ ИЗ СВЕРКИ. Перенос со своей меткой уронит этот случай,
    #   а случай ① при этом останется зелёным — потому он и различающий.
    метки = {m for _, m in drift.PLACEHOLDERS}
    текст_копии = копия.read_text(encoding="utf-8") if копия.exists() else ""
    заглушек = sum(текст_копии.count(m) for m in метки)
    случай("② заглушек столько же, сколько путей, и вид заглушки взят ИЗ СВЕРКИ",
           заглушек == 3 and метки and any(m in текст_копии for m in метки),
           f"заглушек {заглушек} при трёх путях в источнике; виды заглушек — сверкины")

    # ── ③ путь в ИСПОЛНЯЕМОМ месте: отказ, строка названа, файл в образец не попал
    код3, вывод3 = перенести(["опасный.py"], исток, образец)
    не_записан = not (образец / "опасный.py").exists()
    назвал = "строка" in вывод3 and "ОТКАЗ" in вывод3
    случай("③ путь в исполняемом месте — ОТКАЗ, и строка названа",
           код3 != 0 and не_записан and назвал,
           f"код {код3}, в образец не записан: {не_записан}, строка названа: {назвал}")

    # ── ③б ВСТРЕЧНЫЙ к ③: мирный файл переносится молча. Без него ③ зелен и у переноса,
    #    который отказывает ВСЕГДА, — а такой перенос бесполезен.
    образец2 = стенд / "образец2"
    образец2.mkdir()          # каталог создаём МЫ: перенос не заводит публичный каталог сам
    код4, _ = перенести(["мирный.py"], исток, образец2)
    случай("③б встречный: файл без исполняемого пути переносится",
           код4 == 0 and (образец2 / "мирный.py").exists(),
           f"код {код4}")

    # ── ③в ОТКАЗ СЛОВОМ, А НЕ ПАДЕНИЕМ. Найдено этой же приёмкой: первая редакция переноса
    #    падала трассировкой на несуществующем каталоге, и роль видела семь строк про
    #    внутренности языка вместо одной строки про свой каталог.
    код6, вывод6 = перенести(["мирный.py"], исток, стенд / "которого-нет")
    словом = "КАТАЛОГА ОБРАЗЦА НЕТ" in вывод6 and "Traceback" not in вывод6
    случай("③в каталога образца нет — отказ СЛОВОМ, без падения",
           код6 != 0 and словом,
           f"код {код6}, сказано словом: {словом}")

    # ── ④ перенесённый файл разбирается: обезличивание не сломало код
    r5 = subprocess.run([sys.executable, "-m", "py_compile", str(копия)],
                        capture_output=True, text=True, encoding="utf-8", timeout=120)
    случай("④ перенесённый файл разбирается без ошибок",
           r5.returncode == 0, f"код {r5.returncode}")

    # ── ⑤ КОНТРОЛЬ: подопытному было что обезличивать. Без этого случай ① зелен и тогда,
    #    когда пути в файле не было вовсе.
    было = (исток / "мирный.py").read_text(encoding="utf-8").count(КОНТЕЙНЕР)
    случай("⑤ контроль: в подопытном файле путь БЫЛ",
           было >= 3, f"вхождений в источнике {было}")

    shutil.rmtree(стенд, ignore_errors=True)
    красных = [и for и, ок, _ in итог if not ок]
    print("")
    print("=" * 78)
    print(f"РАЗЛИЧАЮЩИХ СЛУЧАЕВ {len(итог)}, из них ВСТРЕЧНЫХ 2 (③б и ⑤)")
    print("⚖️ Доказательство порчей — отдельным прогоном рядом: отключение обезличивания")
    print("   роняет ① и ②, «безопасно везде» роняет ③, «каталог не проверяем» роняет ③в.")
    print("   Порча живёт рядом с оригиналом, а не внутри приёмки: иначе приёмка судила бы себя.")
    if красных:
        print(f"🔴 ПРОВАЛЕНО {len(красных)}: {' · '.join(красных)}")
        return 1
    print("✅ ВСЕ СЛУЧАИ ПРОЙДЕНЫ")
    return 0


if __name__ == "__main__":
    sys.exit(mezo_stand.finish(main()))
