#!/usr/bin/env python
# SURFACES: skills
# -*- coding: utf-8 -*-
r"""ПРОВЕРКА: навык не отстал от свода правил, из которого собран.

🪤 ПОЧЕМУ ОНА ЗАВЕДЕНА ВМЕСТЕ С ГЕНЕРАТОРОМ, А НЕ ПОСЛЕ. Навык — снимок правил на момент
сборки. Правка правила без пересборки делает его лгущим ТИХО: роль зовёт навык, читает
норму и исполняет отменённое, а всё выглядит исправным. Контур этот класс уже оплачивал —
стартовый набор правил для новых контуров отстал на месяц и никто не видел, потому что
номер версии там отвечал не на тот вопрос.

⚖️ СУДИМ ПО ЧАСУ ПРАВКИ, А НЕ ПО ТЕКСТУ. Тело навыка не обязано совпадать с телом правила
дословно — генератор волен менять оформление. Отставание — это «правило изменилось ПОСЛЕ
того, как навык собран», и отпечаток в конце файла навыка хранит ровно это.

ИСХОДЫ, И ОНИ РАЗНЫЕ:
  🔴 правило правлено ПОСЛЕ сборки навыка — навык учит вчерашнему, пересобрать;
  ⛔ правило СНЯТО, а навык его несёт — хуже отставания: учит отменённому;
  ⚠️ у навыка нет отпечатка — судить о свежести НЕЧЕМ (это не «свежо»);
  ⚪ правило есть в своде, а решения о доставке у него НЕТ — см. ниже, это карточка #526;
  🟠 решение «доставлять» есть, а до навыков правило не доехало.

🩸 ТРЕТИЙ ВОПРОС — «А ВСЁ ЛИ, ЧТО ДОЛЖНО, ДОЕХАЛО» — ДОБАВЛЕН 2026-09-04, И ВОТ ПОЧЕМУ.
До этого дня проверка судила ТОЛЬКО правила, уже попавшие в навык: свежи ли они. Вопрос
«а не забыли ли правило взять вовсе» не задавался НИКАК — и потому 2026-09-04 10:31 UTC
COORD завёл правило, пересобрал навыки, получил «✅ все навыки собраны по нынешнему своду»
и обнаружил рукой, что правила нет ни в одном навыке. Проверка не солгала ни в одной
строке: она ответила на свой вопрос верно, а второго вопроса ей не задавали.

⚡ КЛАСС, ради которого это записано здесь, а не в карточке: **проверка, судящая только
попавшее, слепа к НЕ ПОПАВШЕМУ ровно настолько, насколько уверенно она зеленеет.**
Список не лжёт построчно — он лжёт составом.

⚖️ Различает пропуск и решение поле `rules.skill_delivery` (шаг схемы
20260904-rule-skill-delivery): 'yes' — обязано быть в навыке · 'no' — не переезжает
намеренно, проверка молчит · ПУСТО — НЕ РЕШЕНО, и это краснеет поимённо. Пустота, которая
краснеет, — единственная форма, при которой забывчивость отличима от замысла.

Зовут так:
    python C:/guts/.atlas/vnext-tools/guard-skills-fresh.py
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sqlite3
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import mezo_paths  # noqa: E402 — пути машины выводятся, не впечатаны (#153)

ОТПЕЧАТОК = "СОБРАНО ИЗ БАЗЫ"
# 🪤 Первая редакция принимала только латинские ключи ([a-z0-9-]) — и на ключе
# с другими буквами отпечаток разбирался в ПУСТОЙ словарь. Сторож при этом
# отвечал «свежо»: пустой отпечаток нечему противоречить. Поймано приёмкой
# в первый же прогон. Ключ — это просто имя до знака равенства.
СТРОКА = re.compile(r"^\s{5}([^\s=]+)\s=\s(.+)$")
ОПИСАНИЕ_МАКС = 200


def отпечаток(текст: str) -> dict[str, str] | None:
    """Правила и час их правки на момент сборки. None — отпечатка нет вовсе."""
    if ОТПЕЧАТОК not in текст:
        return None
    внутри, найдено = False, {}
    for line in текст.splitlines():
        if ОТПЕЧАТОК in line:
            внутри = True
            continue
        if внутри:
            if line.strip() == "-->":
                break
            m = СТРОКА.match(line)
            if m:
                найдено[m.group(1)] = m.group(2).strip()
    return найдено


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--skills", help="каталог навыков (по умолчанию — .claude/skills контейнера)")
    ap.add_argument("--db", help="свод (по умолчанию — база контура)")
    a = ap.parse_args()

    корень = (pathlib.Path(a.skills) if a.skills
              else mezo_paths.container_root() / ".claude" / "skills")
    if not корень.is_dir():
        # ⚖️ ДВА РАЗНЫХ ОТСУТСТВИЯ, И ОНИ ЗВУЧАТ ПО-РАЗНОМУ. Путь назван рукой (--skills)
        # и его нет — это опечатка вызова, отказ кодом 2: молчание здесь скрыло бы, что
        # проверено НЕ ТО место. Путь выведен по умолчанию и его нет — контур просто
        # ещё не заводил навыков: это законное состояние, а не поломка. Красное на нём
        # у новорождённого контура — красное, которое нельзя погасить никаким своим
        # действием (поймано приёмкой сборки из шаблона, случай ⑦, 22.08).
        if a.skills:
            print(f"⛔ НЕ ЗАПУСТИЛАСЬ: каталога навыков нет — {корень}")
            return 2
        print(f"⚪ навыков в контуре ещё нет ({корень} не заведён) — судить не о чем. "
              "Это НЕ «всё свежо»: появятся — эта проверка начнёт их сличать со сводом.")
        return 0
    db = pathlib.Path(a.db) if a.db else mezo_paths.live_db()
    con = sqlite3.connect(str(db))
    свод = {r[0]: (r[1][:16] if r[1] else "", r[2]) for r in
            con.execute("SELECT rule_key, updated_at, status FROM rules")}
    # ⚖️ Поле решения о доставке может отсутствовать: база старше шага
    # 20260904-rule-skill-delivery или это чужой контур. Тогда третий вопрос
    # НЕ ЗАДАЁТСЯ — и проверка говорит об этом вслух, а не молчит: молчание
    # прочли бы как «спросили и всё хорошо», то есть как ровно ту беду, ради
    # которой третий вопрос и заведён.
    есть_поле = "skill_delivery" in {r[1] for r in con.execute("PRAGMA table_info(rules)")}
    доставка = ({r[0]: r[1] for r in con.execute(
        "SELECT rule_key, skill_delivery FROM rules WHERE status='active'")}
        if есть_поле else {})
    con.close()

    отстали, снятые, безотпечатка, длинные, свежие = [], [], [], [], 0
    смотрено = 0
    доехали: set[str] = set()   # ключи, реально записанные хоть в один навык
    for f in sorted(корень.glob("*/SKILL.md")):
        текст = f.read_text(encoding="utf-8", errors="ignore")
        след = отпечаток(текст)
        if след is None:
            continue          # чужой навык, не наш порождаемый — не наше дело
        смотрено += 1
        # 🎯 Судим по ОТПЕЧАТКУ файла навыка, а не по списку в сборщике: отпечаток —
        # след того, что записано на диск. Правило, названное в сборщике, но не
        # доехавшее (сборку не запускали), так остаётся видимым как недоехавшее.
        доехали.update(след)
        имя = f.parent.name
        m = re.search(r'^description:\s*"?(.*?)"?\s*$', текст, re.M)
        if m and len(m.group(1)) > ОПИСАНИЕ_МАКС:
            длинные.append((имя, len(m.group(1))))
        плохо = False
        for ключ, было in след.items():
            стало, статус = свод.get(ключ, (None, None))
            if стало is None:
                отстали.append((имя, ключ, было, "правила больше нет в своде"))
                плохо = True
            elif статус != "active":
                снятые.append((имя, ключ, статус))
                плохо = True
            elif стало > было:
                отстали.append((имя, ключ, было, f"правлено {стало}"))
                плохо = True
        if not плохо:
            свежие += 1

    # ── ТРЕТИЙ ВОПРОС: а всё ли, что должно было доехать, доехало ──
    # ⚖️ Задаётся только когда навыки ЕСТЬ: судить о доставке там, где везти некуда,
    # значило бы красить новорождённый контур красным, которое он не может погасить.
    не_решено, не_доехали, кривые = [], [], []
    if есть_поле and смотрено:
        for ключ, решение in sorted(доставка.items()):
            if решение is None or решение == "":
                не_решено.append(ключ)
            elif решение == "no":
                continue                      # не переезжает НАМЕРЕННО — молчим
            elif решение == "yes":
                if ключ not in доехали:
                    не_доехали.append(ключ)
            else:
                кривые.append((ключ, решение))

    print("=" * 84)
    print(f"НАВЫКИ ПРОТИВ СВОДА — навыков смотрено {смотрено} (собранных из базы)")
    print(f"  навыки: {корень}")
    print(f"  свод:   {db}")
    print("=" * 84)
    for имя, ключ, было, почему in отстали:
        print(f"🔴 {имя:22} {ключ:30} собран по {было} · {почему}")
    for имя, ключ, статус in снятые:
        print(f"⛔ {имя:22} {ключ:30} правило СНЯТО ({статус}) — навык учит отменённому")
    for имя, n in длинные:
        print(f"⚠️ {имя:22} описание {n} знаков — оно в контексте роли ВСЕГДА")
    for ключ in не_доехали:
        print(f"🟠 {'—':22} {ключ:30} решено ДОСТАВЛЯТЬ, а в навыках его нет — "
              "либо внести в пакет сборщика, либо пересобрать навыки")
    for ключ, значение in кривые:
        print(f"⛔ {'—':22} {ключ:30} негодное решение о доставке: {значение!r} "
              "(допустимо: yes · no · пусто)")
    if не_решено:
        print(f"⚪ РЕШЕНИЯ О ДОСТАВКЕ НЕТ У {len(не_решено)} ПРАВИЛ — поимённо, "
              "потому что разбирают их по списку, а не по числу:")
        for ключ in не_решено:
            print(f"   ⚪ {ключ}")
        print("   👉 Каждому: python "
              f"{pathlib.Path(__file__).resolve().parents[1]}/.mezosync/scripts/set-rule.py"
              " --key <ключ> --skill-delivery yes|no")
        print("   ⚖️ Список ПОЛНЫЙ и намеренно не урезан: «и ещё N» скрыло бы ровно то, "
              "чего не хватает. Он исчезает сам, когда правила разобраны.")
    if not есть_поле:
        print("⚠️ ТРЕТИЙ ВОПРОС НЕ ЗАДАН: в своде нет поля решения о доставке "
              "(шаг 20260904-rule-skill-delivery не накатан на эту базу). "
              "«Забыли взять правило» здесь по-прежнему неотличимо от «решили не брать».")
    if смотрено == 0:
        print("⚠️ собранных из базы навыков не найдено — судить не о чем "
              "(это НЕ «всё свежо»)")

    print("-" * 84)
    print(f"свежих {свежие} · 🔴 отставших {len(отстали)} · ⛔ учащих снятому {len(снятые)} "
          f"· ⚠️ длинных описаний {len(длинные)}")
    if есть_поле and смотрено:
        везут = sum(1 for v in доставка.values() if v == "yes")
        не_везут = sum(1 for v in доставка.values() if v == "no")
        print(f"доставка: ✅ везём {везут} · ⛔ не везём намеренно {не_везут} "
              f"· ⚪ не решено {len(не_решено)} · 🟠 обещано и не доехало {len(не_доехали)}")
    плохо = отстали or снятые or не_решено or не_доехали or кривые
    if отстали or снятые or не_доехали:
        print("👉 Пересобрать: python "
              f"{pathlib.Path(__file__).resolve().parent}/rules-to-skills.py --write")
        print("⛔ Править файл навыка рукой НЕЛЬЗЯ: он порождаемый, правка исчезнет "
              "при следующей сборке, а расхождение со сводом останется.")
    elif смотрено and not плохо:
        # ⚖️ Формулировка сужена намеренно. Прежняя — «все навыки собраны по нынешнему
        # своду» — звучала как ответ на ОБА вопроса, а отвечала на один: свежесть
        # попавшего. Ровно в этом зазоре 04.09 и утонуло правило COORD.
        # ⚡ И ЗЕЛЁНОЕ ОБЕЩАЕТ РОВНО ТО, ЧТО ПРОВЕРЕНО. Без поля второй вопрос не задавался
        #    вовсе — сказать тут «всё доехало» значило бы повторить исходную беду на
        #    ступень выше: обещание охвата шире самого охвата. Поймано приёмкой, случай ⑤.
        print("✅ навыки свежи ПО СВОДУ и всё, что решено доставлять, доехало."
              if есть_поле else
              "✅ навыки свежи ПО СВОДУ. ⚠️ Про доставку здесь НЕ сказано ничего — "
              "поля решения в этой базе нет.")
    return 1 if плохо else 0


if __name__ == "__main__":
    sys.exit(main())
