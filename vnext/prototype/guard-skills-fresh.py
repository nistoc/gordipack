#!/usr/bin/env python
# SURFACES: skills
# -*- coding: utf-8 -*-
r"""ПРОВЕРКА: навык не отстал от свода правил, из которого собран.

🪤 ПОЧЕМУ ОНА ЗАВЕДЕНА ВМЕСТЕ С ГЕНЕРАТОРОМ, А НЕ ПОСЛЕ. Навык — снимок правил на момент
сборки. Правка правила без пересборки делает его лгущим ТИХО: роль зовёт навык, читает
норму и исполняет отменённое, а всё выглядит исправным. Контур этот класс уже оплачивал —
стартовый набор правил для новых контуров отстал на месяц и никто не видел, потому что
номер версии там отвечал не на тот вопрос.

⚖️ СУДИМ ПО ЧАСУ ПРАВКИ, А НЕ ПО ТЕКСТУ. Тело навыка не обязано совпадать с телом правила
дословно — генератор волен менять оформление. Отставание — это «правило изменилось ПОСЛЕ
того, как навык собран», и отпечаток в конце файла навыка хранит ровно это.

ТРИ ИСХОДА, И ОНИ РАЗНЫЕ:
  🔴 правило правлено ПОСЛЕ сборки навыка — навык учит вчерашнему, пересобрать;
  ⛔ правило СНЯТО, а навык его несёт — хуже отставания: учит отменённому;
  ⚠️ у навыка нет отпечатка — судить о свежести НЕЧЕМ (это не «свежо»).

Зовут так:
    python <КОНТУР>/vnext-tools/guard-skills-fresh.py
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sqlite3
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import mezo_paths  # noqa: E402 — пути машины выводятся, не впечатаны (#153)

ОТПЕЧАТОК = "СОБРАНО ИЗ БАЗЫ"
# 🪤 Первая редакция принимала только латинские ключи ([a-z0-9-]) — и на ключе
# с другими буквами отпечаток разбирался в ПУСТОЙ словарь. Сторож при этом
# отвечал «свежо»: пустой отпечаток нечему противоречить. Поймано приёмкой
# в первый же прогон. Ключ — это просто имя до знака равенства.
СТРОКА = re.compile(r"^\s{5}([^\s=]+)\s=\s(.+)$")
ОПИСАНИЕ_МАКС = 200


def отпечаток(текст: str) -> dict[str, str] | None:
    """Правила и час их правки на момент сборки. None — отпечатка нет вовсе."""
    if ОТПЕЧАТОК not in текст:
        return None
    внутри, найдено = False, {}
    for line in текст.splitlines():
        if ОТПЕЧАТОК in line:
            внутри = True
            continue
        if внутри:
            if line.strip() == "-->":
                break
            m = СТРОКА.match(line)
            if m:
                найдено[m.group(1)] = m.group(2).strip()
    return найдено


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--skills", help="каталог навыков (по умолчанию — .claude/skills контейнера)")
    ap.add_argument("--db", help="свод (по умолчанию — база контура)")
    a = ap.parse_args()

    корень = (pathlib.Path(a.skills) if a.skills
              else mezo_paths.container_root() / ".claude" / "skills")
    if not корень.is_dir():
        # ⚖️ ДВА РАЗНЫХ ОТСУТСТВИЯ, И ОНИ ЗВУЧАТ ПО-РАЗНОМУ. Путь назван рукой (--skills)
        # и его нет — это опечатка вызова, отказ кодом 2: молчание здесь скрыло бы, что
        # проверено НЕ ТО место. Путь выведен по умолчанию и его нет — контур просто
        # ещё не заводил навыков: это законное состояние, а не поломка. Красное на нём
        # у новорождённого контура — красное, которое нельзя погасить никаким своим
        # действием (поймано приёмкой сборки из шаблона, случай ⑦, 22.08).
        if a.skills:
            print(f"⛔ НЕ ЗАПУСТИЛАСЬ: каталога навыков нет — {корень}")
            return 2
        print(f"⚪ навыков в контуре ещё нет ({корень} не заведён) — судить не о чем. "
              "Это НЕ «всё свежо»: появятся — эта проверка начнёт их сличать со сводом.")
        return 0
    db = pathlib.Path(a.db) if a.db else mezo_paths.live_db()
    con = sqlite3.connect(str(db))
    свод = {r[0]: (r[1][:16] if r[1] else "", r[2]) for r in
            con.execute("SELECT rule_key, updated_at, status FROM rules")}
    con.close()

    отстали, снятые, безотпечатка, длинные, свежие = [], [], [], [], 0
    смотрено = 0
    for f in sorted(корень.glob("*/SKILL.md")):
        текст = f.read_text(encoding="utf-8", errors="ignore")
        след = отпечаток(текст)
        if след is None:
            continue          # чужой навык, не наш порождаемый — не наше дело
        смотрено += 1
        имя = f.parent.name
        m = re.search(r'^description:\s*"?(.*?)"?\s*$', текст, re.M)
        if m and len(m.group(1)) > ОПИСАНИЕ_МАКС:
            длинные.append((имя, len(m.group(1))))
        плохо = False
        for ключ, было in след.items():
            стало, статус = свод.get(ключ, (None, None))
            if стало is None:
                отстали.append((имя, ключ, было, "правила больше нет в своде"))
                плохо = True
            elif статус != "active":
                снятые.append((имя, ключ, статус))
                плохо = True
            elif стало > было:
                отстали.append((имя, ключ, было, f"правлено {стало}"))
                плохо = True
        if not плохо:
            свежие += 1

    print("=" * 84)
    print(f"НАВЫКИ ПРОТИВ СВОДА — навыков смотрено {смотрено} (собранных из базы)")
    print(f"  навыки: {корень}")
    print(f"  свод:   {db}")
    print("=" * 84)
    for имя, ключ, было, почему in отстали:
        print(f"🔴 {имя:22} {ключ:30} собран по {было} · {почему}")
    for имя, ключ, статус in снятые:
        print(f"⛔ {имя:22} {ключ:30} правило СНЯТО ({статус}) — навык учит отменённому")
    for имя, n in длинные:
        print(f"⚠️ {имя:22} описание {n} знаков — оно в контексте роли ВСЕГДА")
    if смотрено == 0:
        print("⚠️ собранных из базы навыков не найдено — судить не о чем "
              "(это НЕ «всё свежо»)")

    print("-" * 84)
    print(f"свежих {свежие} · 🔴 отставших {len(отстали)} · ⛔ учащих снятому {len(снятые)} "
          f"· ⚠️ длинных описаний {len(длинные)}")
    if отстали or снятые:
        print("👉 Пересобрать: python "
              f"{pathlib.Path(__file__).resolve().parent}/rules-to-skills.py --write")
        print("⛔ Править файл навыка рукой НЕЛЬЗЯ: он порождаемый, правка исчезнет "
              "при следующей сборке, а расхождение со сводом останется.")
    elif смотрено:
        print("✅ все навыки собраны по нынешнему своду.")
    return 1 if (отстали or снятые) else 0


if __name__ == "__main__":
    sys.exit(main())
