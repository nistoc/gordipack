# -*- coding: utf-8 -*-
r"""bite-two-locks.py — приёмка карточки #575: первый отказ называет ВТОРОЙ замок.

═══ ЧТО БЫЛО
Инструмент, вынесенный из своего каталога, упирается в два разных замка подряд. Первый
печатал два выхода и говорил, что оба проверены прогоном, а про второй — «корень тогда
не нужен вовсе». Но этот выход снимает только ПЕРВЫЙ замок: следом приходит отказ
«контейнер группы НЕ НАЙДЕН», где он не помогает.
📏 Замер @COORD: 176 инструментов из 243 (72%) упрутся во второй замок.

═══ ПОЧЕМУ ЭТО ХУЖЕ НЕВЕРНОГО СОВЕТА
Первый отказ НЕ врёт: про свой замок он прав. Неисполнимая строка краснеет сразу,
а недостаточная доводит до ДРУГОГО отказа — и роль ищет вторую беду, думая, что
не справилась с первой. Три живых случая за сутки, последний — внутри чужой приёмки,
где непрошедший вызов выдал себя за «поломки нет».

═══ ОЖИДАНИЯ ПОЛОМОК — НАЗВАНЫ ДО ПРОГОНА, И ОДНО ОКАЗАЛОСЬ ШИРЕ ИСТИНЫ
    П1 из первого отказа убрано предупреждение о втором замке
       ждали ① ② ... вышло ТОЛЬКО ①. Ожидание было ШИРЕ истины: случай ② судит не
                     предупреждение, а пометки охвата у самих выходов («снимает ОБА» /
                     «ТОЛЬКО ЭТОТ») — их эта поломка не трогала. Значит ① и ② проверяют
                     РАЗНОЕ, и это хорошо: убери одно — второе не прикроет.
    П2 из второго отказа убрана ссылка на первый
       ждали ③ ⑤ ... вышло точно.
⚖️ Записано как было. Ожидание, подогнанное задним числом, не проверяет ничего.

═══ ГРАНИЦА, НАЗВАННАЯ ПРЯМО (и почему критерий сужен)
Критерий требовал ещё и встречного: инструменту, которому второй замок НЕ нужен, — короткий
совет без лишнего. ЭТО НЕ СДЕЛАНО и сделано быть не может здесь: отказ печатается в тот
момент, когда о вызывающем известно только имя его файла; нужен ли ЕМУ (или его соседу
по каталогу) каталог группы — в этой точке неизвестно.
⇒ Предупреждение о втором замке видят все, включая тех, кому оно не понадобится. Цена —
четыре строки текста; плата за них — те 72%, кто иначе пойдёт чинить не то.
"""
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import mezo_paths  # noqa: E402
import mezo_stand  # noqa: E402

ПУТИ = Path(mezo_paths.live_scripts(__file__)) / "mezo_paths.py"
ИСХОДНИК = ПУТИ.read_text(encoding="utf-8")

итог: list[tuple[str, bool, str]] = []


def случай(имя: str, ок: bool, слово: str) -> None:
    итог.append((имя, ок, слово))
    print(f"{'✅' if ок else '🔴'} {имя}: {слово}")


def текст_отказа(имя_функции: str) -> str:
    """Тело sys.exit(...) названной функции — судим ТО, что напечатается, а не пересказ."""
    начало = ИСХОДНИК.index(f"def {имя_функции}(")
    кусок = ИСХОДНИК[начало:начало + 4000]
    м = re.search(r"sys\.exit\(", кусок)
    return кусок[м.start():] if м else ""


def main() -> int:
    первый = текст_отказа("mezo_root")
    второй = текст_отказа("container_root")

    случай("① первый отказ НАЗЫВАЕТ существование второго замка",
           "ВТОРОЙ" in первый and "контейнер группы" in первый,
           "сказано прямо" if "ВТОРОЙ" in первый else "о втором замке ни слова")

    случай("② первый отказ говорит, КАКОЙ из выходов снимает ОБА",
           "снимает ОБА" in первый and "ТОЛЬКО ЭТОТ" in первый,
           "оба выхода помечены по охвату" if "снимает ОБА" in первый
           else "выходы перечислены без различия охвата")

    случай("③ второй отказ ссылается на первый и снимает ложное чувство вины",
           "ВТОРОЙ ЗАМОК" in второй and "--db" in второй,
           "объясняет, что совет первого верен про свой замок")

    # ④ ВСТРЕЧНЫЙ: сообщения РАЗЛИЧНЫ. Без него ① ② ③ зелены и у отказа, который
    #    печатает один и тот же текст в обоих местах — а тогда роль не поймёт, где она.
    случай("④ ВСТРЕЧНЫЙ: тексты двух отказов различны",
           первый != второй and "корень мезосинка" in первый and "контейнер группы" in второй,
           "разные заголовки и разные советы")

    # ⑤ ЖИВОЙ ПРОГОН: зовём инструмент ВНЕ контейнера с абсолютным --db — то есть идём
    #    ровно по совету первого замка — и смотрим, что скажет второй.
    стенд = Path(mezo_stand.new("bite-two-locks-"))
    (стенд / "проба.py").write_text(
        "import sys\nfrom pathlib import Path\n"
        f"sys.path.insert(0, r'{ПУТИ.parent}')\n"
        "import mezo_paths\nprint(mezo_paths.container_root(__file__))\n",
        encoding="utf-8")
    r = subprocess.run([sys.executable, str(стенд / "проба.py")], capture_output=True,
                       text=True, encoding="utf-8", timeout=120,
                       env={"PATH": "", "SYSTEMROOT": "C:\\Windows"})
    вывод = (r.stdout or "") + (r.stderr or "")
    случай("⑤ живой второй замок печатает объяснение, а не голый отказ",
           r.returncode != 0 and "ЭТО ВТОРОЙ ЗАМОК" in вывод,
           "объяснение на месте" if "ЭТО ВТОРОЙ ЗАМОК" in вывод
           else f"код {r.returncode}, объяснения нет")

    красных = [и for и, ок, _ in итог if not ок]
    print("")
    print("=" * 78)
    print(f"РАЗЛИЧАЮЩИХ СЛУЧАЕВ {len(итог)}, из них ВСТРЕЧНЫЙ 1 (④)")
    print("⚖️ Встречный случай критерия «инструменту без второго замка — короткий совет»")
    print("   НЕ сделан и не может быть сделан здесь: в точке отказа неизвестно, нужен ли")
    print("   вызывающему каталог группы. Названо в шапке как несделанное, а не умолчано.")
    if красных:
        print(f"🔴 ПРОВАЛЕНО {len(красных)}: {' · '.join(красных)}")
        return 1
    print("✅ ВСЕ СЛУЧАИ ПРОЙДЕНЫ")
    return 0


if __name__ == "__main__":
    sys.exit(mezo_stand.finish(main()))
