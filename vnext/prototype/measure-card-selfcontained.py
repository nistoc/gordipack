"""
measure-card-selfcontained.py — понятна ли карточка БЕЗ чата, в котором она родилась.

═══ ВОПРОС ВЛАДЕЛЬЦА 2026-08-07 10:43 UTC ═══
    «перечитай последние 50 задач в базе: оцени критически, насколько они понятны
     без контекста чата, как самостоятельные единицы? стоит ли ввести более суровые
     требования… чек-лист с вопросами для описания контекста задачи при заведении?»

═══ 🪤 ПОЧЕМУ СЧИТАЕТ МАШИНА, А НЕ Я ═══
Я автор части этих карточек и помню их контекст из чата. Читая, я «пойму» даже невнятную —
и оценка выйдет завышенной ровно там, где нужнее всего честность.
    **Измеритель, знающий ответ, меряет свою память, а не предмет.**
Тот же класс, за который контур платил сегодня дважды: укус включил себя в измеряемое,
а вердикт «поле не спасает» родился из доверия своему выводу вместо чтения чужого кода.
⇒ Здесь считаются ПРИЗНАКИ ТЕКСТА. Память не участвует ни в одном условии.

═══ ⚖️ ГРАНИЦА СПОСОБА — НАЗВАНА ДО ПРОГОНА, НЕ ПОСЛЕ ═══
Наличие признака ≠ понятность. Карточка может нести дату, цифры и зону рук — и всё равно
быть невнятной; и наоборот, короткая карточка бывает исчерпывающей.
⇒ Прогон даёт РАСПРЕДЕЛЕНИЕ НЕХВАТОК (чего не хватает чаще всего) — это и есть опора для
ответа «вводить ли чек-лист и какие поля делать обязательными».
⛔ Он НЕ выносит приговор отдельной карточке. Кто прочтёт его так — прочтёт неверно.

Запуск:  python <абсолютный путь>/measure-card-selfcontained.py [--last 50]
"""

import argparse
import re
import sqlite3
import sys
from pathlib import Path

LIVE = mezo_paths.live_db()

# 🪤 Поиск неразрешимых ссылок ЖИВЁТ В ОДНОМ МЕСТЕ и берётся оттуда, а не повторяется здесь.
#    Здешняя копия однажды соврала: в список поясняющих слов попала сама решётка, и каждый
#    голый «#3120» считался пояснённым сам собою — счёт печатал «0» ПРИ ЛЮБЫХ данных.
#    Две копии одного правила расходятся молча, и разошедшись, обе выглядят исправными.
import importlib.util  # noqa: E402
import mezo_paths  # пути машины выводятся, не впечатаны (#153)
_spec = importlib.util.spec_from_file_location(
    "chk", Path(__file__).with_name("check-dangling-refs.py"))
chk = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(chk)

# ── СЕМЬ ВОПРОСОВ. Каждый — признак ТЕКСТА, проверяемый без знания контекста ──
CHECKS = [
    ("повод",   "почему делается: дата, слово владельца или замер",
     re.compile(r"\d{4}-\d{2}-\d{2}|\d{2}\.\d{2}\.\d{4}|\d{2}\.\d{2}\b(?=[^\d]|$)"
                r"|слово владельца|поручени|замер\b|находка @|UTC", re.I)),
    ("числа",   "боль названа ЧИСЛОМ, а не «плохо работает»",
     re.compile(r"\b\d+\s*(?:из|/)\s*\d+\b|\b\d{2,}\s*(?:строк|карточ|нот|шт|раз|файл|случа)"
                r"|\b\d+\s*%|\bноль\b|\b0 (?:строк|из)", re.I)),
    ("граница", "что в предмет НЕ входит",
     re.compile(r"⛔|не входит|вне предмета|не тр(?:огаем|огать)|только .{0,40}, и только"
                r"|за границей|не автоматизир|не ловит|НЕ засчитыва", re.I)),
    ("проверка", "чем докажешь, что сделано (критерий приёмки)", None),   # особый: поле done_when
    ("зона",    "чья рука вносит, кто принимает",
     re.compile(r"\bрука\b|рук[ае] (?:твоя|моя|координатора)|зона \w+|вносит|принимает"
                r"|@(?:COORD|CORE|STUD|ING|TAXO|RCC|OPSSRE|PROTO|CHROME)", re.I)),
    ("цена",    "что сломается, если сделать неверно",
     re.compile(r"ломающ|сломает|цена ошибки|риск\b|опасн|обесцен|потеря|разруш", re.I)),
    ("срок",    "когда задача перестаёт быть нужной",
     re.compile(r"срок годности|перестаёт быть нужн|условие снятия|снимается когда"
                r"|устареет|пока не|до тех пор", re.I)),
]

# ── ССЫЛКИ В ПУСТОТУ: то, что читается только внутри породившего чата ────────
DANGLING = re.compile(r"см\.\s*выше|как (?:мы )?(?:обсуждали|договорились)|выше в чате"
                      r"|та сама[яй]|этот вопрос|как говорил|ранее обсужд|см\. переписк", re.I)
BARE_REF = re.compile(r"(?<![\w#])#(\d{1,4})\b")


def load(last: int):
    con = sqlite3.connect(f"file:{LIVE.as_posix()}?mode=ro", uri=True)
    con.execute("PRAGMA query_only=ON")
    con.row_factory = sqlite3.Row
    rows = con.execute("SELECT id, role, status, title, body_md, done_when, created_at "
                       "FROM backlog ORDER BY id DESC LIMIT ?", (last,)).fetchall()
    con.close()
    return list(reversed([dict(r) for r in rows]))


def assess(card: dict) -> dict:
    text = f"{card['title']}\n{card['body_md'] or ''}"
    got = {}
    for name, _, rx in CHECKS:
        if name == "проверка":
            got[name] = bool((card["done_when"] or "").strip())
        else:
            got[name] = bool(rx.search(text))
    # голые номера: по замеру карточки #63 номера нот и карточек — одно пространство,
    # пересечение 62 из 62 ⇒ «#N» без пояснения неразличим в принципе, а не по небрежности
    got["_bare"] = len(chk.find(text))          # единственный источник правила — см. шапку
    got["_dangling"] = len(DANGLING.findall(text))
    got["_len"] = len((card["body_md"] or "").strip())
    return got


def main() -> int:
    ap = argparse.ArgumentParser(description="самодостаточность карточек бэклога")
    ap.add_argument("--last", type=int, default=50, help="сколько последних карточек брать")
    ap.add_argument("--full", action="store_true", help="печатать все карточки, не только слабые")
    args = ap.parse_args()

    cards = load(args.last)
    if not cards:
        print("⛔ карточек не нашлось")
        return 2

    names = [c[0] for c in CHECKS]
    rows = [(c, assess(c)) for c in cards]

    print("ЗАМЕР: понятна ли карточка БЕЗ чата, в котором родилась")
    print(f"предмет ........ карточки #{cards[0]['id']}…#{cards[-1]['id']} ({len(cards)} шт.)")
    print("способ ......... признаки ТЕКСТА; память автора не участвует ни в одном условии\n")

    hdr = "  id   роль     " + " ".join(f"{n[:6]:>7}" for n in names) + "   ⚠ссылки  длина"
    print(hdr)
    print("  " + "─" * (len(hdr) - 2))
    for c, g in rows:
        if not args.full and sum(g[n] for n in names) >= 6:
            continue
        marks = " ".join(f"{'✅' if g[n] else '·':>7}" for n in names)
        warn = g["_bare"] + g["_dangling"]
        print(f"  #{c['id']:<4} {c['role']:8} {marks}   {warn:>5}    {g['_len']:>5}")
    if not args.full:
        strong = sum(1 for _, g in rows if sum(g[n] for n in names) >= 6)
        print(f"  … и ещё {strong} карточек с 6–7 признаками из 7 (не показаны, зови --full)")

    print("\n═══ РАСПРЕДЕЛЕНИЕ НЕХВАТОК — ЭТО И ЕСТЬ ОТВЕТ ПРО ЧЕК-ЛИСТ ═══")
    for name, desc, _ in CHECKS:
        miss = sum(1 for _, g in rows if not g[name])
        bar = "█" * round(miss / len(rows) * 40)
        print(f"  {name:9} нет у {miss:>2} из {len(rows)}  {bar}")
        print(f"            ({desc})")

    print("\n═══ СКОЛЬКО ПРИЗНАКОВ НЕСЁТ КАРТОЧКА ═══")
    for k in range(len(names) + 1):
        n = sum(1 for _, g in rows if sum(g[x] for x in names) == k)
        if n:
            print(f"  {k} из {len(names)}: {'▇' * n} {n}")

    print("\n═══ ССЫЛКИ, ЧИТАЕМЫЕ ТОЛЬКО ВНУТРИ ЧАТА ═══")
    bare = sum(g["_bare"] for _, g in rows)
    dang = sum(g["_dangling"] for _, g in rows)
    with_bare = sum(1 for _, g in rows if g["_bare"])
    print(f"  голых «#N» без пояснения ..... {bare} шт. в {with_bare} карточках")
    print("     📌 по замеру карточки #63 номера нот и карточек — ОДНО пространство,")
    print("        пересечение 62 из 62 ⇒ «#N» неразличим В ПРИНЦИПЕ, а не по небрежности")
    print(f"  оборотов «см. выше»/«как обсуждали» .. {dang} шт.")
    empty = sum(1 for _, g in rows if g["_len"] < 200)
    print(f"  тело короче 200 символов ............. {empty} карточек")

    print("\n⚖️ ЧЕГО ЭТОТ ЗАМЕР НЕ ГОВОРИТ: наличие признака ≠ понятность. Он даёт РАСПРЕДЕЛЕНИЕ")
    print("   нехваток — опору для решения «какие поля делать обязательными», а НЕ приговор")
    print("   отдельной карточке. Приговор требует свежего читателя, у которого нет моей памяти.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
