# -*- coding: utf-8 -*-
r"""ПРИЁМКА границ тела правила при разборе свода — записка @COORD #3762.

🩸 ЧЕМ ОПЛАЧЕНО. Проверка «зеркало правил» сравнивает тело правила в базе с телом
в порождённом файле. Тело в файле она отрезает по следующему заголовку — и дважды
отрезала не по тому:
```
① граница = первый `^## `   → обрыв на подзаголовке ВНУТРИ правила (1699 → 481 знак)
② граница = любой `^### `   → обрыв на подзаголовке третьего уровня (4550 → 2442)
```
⛔ И вот отчего второй случай хуже простого ложного красного, словами его автора:
**у правила с внутренним `###` проверка перестаёт РАЗЛИЧАТЬ состояния.** Она красная
и при совпадении текста, и при настоящем расхождении. К вечно-красному привыкают,
и следующее, уже настоящее, прочтут как привычное.

📏 ЗАМЕР, РЕШИВШИЙ СПОР О ПОЧИНКЕ (PROTO 2026-08-24 16:52 UTC, по живому своду):
```
заголовков `## `  — 14, ВНУТРИ тел правил 13   ⇒ резать по ним нельзя
заголовков `### ` — 76, ВНУТРИ тел правил 12   ⇒ и по ним нельзя
заголовков ПРАВИЛА (ключ + замок + версия) — 64 ⇒ вот он и различает
```
⚠️ Предложенная починка «следующее правило ЛИБО `^## `» не годилась ровно поэтому:
она вернула бы ошибку ①, потому что почти все `## ` живут внутри тел.

⚖️ КАК ПОСТАВЛЕН ОПЫТ И ПОЧЕМУ ИМЕННО ТАК. Файл собирается ИЗ БАЗЫ тем же генератором,
что и в жизни, — значит база и файл равны ПО ПОСТРОЕНИЮ, и краснота может прийти только
от разбора. 🩸 Первая редакция этой приёмки правила файл и базу порознь, «в одно и то же
место», — и контрольный случай, где не менялось ничего, краснел сам. Опыт, чей контроль
красен, не доказывает ничего: я чуть не прочла это как «починка не работает».

Случаи (различающий = обязан ответить ИНАЧЕ, а не одинаково):
  ① КОНТРОЛЬ: ничего не вставляли — молчит (иначе опыт неисправен)              РАЗЛИЧАЮЩИЙ
  ② `###` внутри тела правила — молчит, тексты-то равны                         РАЗЛИЧАЮЩИЙ
  ③ `##` внутри тела правила — молчит                                           РАЗЛИЧАЮЩИЙ
  ④ ВСТРЕЧНЫЙ: настоящее расхождение при внутреннем `###` — ВИДНО              РАЗЛИЧАЮЩИЙ
  ⑤ ОБРАТНЫЙ ХОД: с ПРЕЖНЕЙ границей случай ② краснеет                         РАЗЛИЧАЮЩИЙ

🎯 Случай ⑤ — главный: без него зелень ②③ означала бы только «сегодня не болит»,
а не «починка работает». Он ломает разбор обратно и требует, чтобы стало больно.

⛔ Живой базы не касается: каждый случай строит свою копию базы и свой файл.
"""
from __future__ import annotations

import pathlib
import shutil
import sqlite3
import subprocess
import sys
import tempfile

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import mezo_paths  # noqa: E402 — пути машины выводятся, не впечатаны

КОРЕНЬ = mezo_paths.container_root(__file__)
БАЗА = КОРЕНЬ / ".mezosync" / "mezosync.db"
ГЕНЕРАТОР = КОРЕНЬ / ".mezosync" / "scripts" / "export-rules.py"
РАЗБОР = pathlib.Path(__file__).with_name("check-rules-mirror.py")
НОСИТЕЛЬ = "role-roster-and-zones"      # правило без внутренних заголовков — чистый носитель
CASES = DIFFER = 0


def case(title, verdict, detail, differ=False):
    global CASES, DIFFER
    CASES += 1
    DIFFER += bool(differ)
    print(f"{'✅' if verdict else '🔴'} {title}")
    print(f"   {detail}")
    return verdict


def стенд(вставка: str | None, расхождение: bool = False, разбор: pathlib.Path = None):
    """Копия базы + файл, СОБРАННЫЙ ИЗ НЕЁ живым генератором → (код, вывод)."""
    d = pathlib.Path(tempfile.mkdtemp(prefix="bite-bounds-"))
    try:
        б, ф = d / "mezosync.db", d / "sync.rules.md"
        shutil.copy(БАЗА, б)
        if вставка:
            con = sqlite3.connect(б)
            тело = con.execute("SELECT body FROM rules WHERE rule_key=?",
                               (НОСИТЕЛЬ,)).fetchone()[0]
            строки = тело.split("\n")
            строки.insert(len(строки) // 2, вставка)
            con.execute("UPDATE rules SET body=? WHERE rule_key=?",
                        ("\n".join(строки), НОСИТЕЛЬ))
            con.commit()
            con.close()
        сб = subprocess.run([sys.executable, str(ГЕНЕРАТОР), "--db", str(б),
                             "--out", str(ф), "--apply"], capture_output=True, text=True,
                            encoding="utf-8", errors="replace", timeout=300)
        if сб.returncode != 0:
            return None, f"файл не собрался: {(сб.stderr or сб.stdout).strip()[:120]}"
        if расхождение:
            con = sqlite3.connect(б)
            тело = con.execute("SELECT body FROM rules WHERE rule_key=?",
                               (НОСИТЕЛЬ,)).fetchone()[0]
            con.execute("UPDATE rules SET body=? WHERE rule_key=?",
                        (тело + "\nРАСХОЖДЕНИЕ, КОТОРОГО НЕТ В ФАЙЛЕ", НОСИТЕЛЬ))
            con.commit()
            con.close()
        r = subprocess.run([sys.executable, str(разбор or РАЗБОР), "--file", str(ф),
                            "--db", str(б)], capture_output=True, text=True,
                           encoding="utf-8", errors="replace", timeout=300)
        return r.returncode, (r.stdout or "") + (r.stderr or "")
    finally:
        shutil.rmtree(d, ignore_errors=True)


def main() -> int:
    ok = True
    for нужен in (БАЗА, ГЕНЕРАТОР, РАЗБОР):
        if not нужен.exists():
            sys.exit(f"⛔ НЕ ЗАПУСТИЛАСЬ: нет файла — {нужен}")

    код, _ = стенд(None)
    ok &= case("① КОНТРОЛЬ: ничего не вставляли — молчит",
               код == 0,
               f"код {код}; опыт, чей контроль красен, не доказывает ничего — "
               "первая редакция этой приёмки была именно такой", differ=True)

    код2, вывод2 = стенд("### ВНУТРЕННИЙ ПОДЗАГОЛОВОК")
    ok &= case("② `###` внутри тела правила — молчит (тексты равны)",
               код2 == 0,
               f"код {код2}; здесь прежняя граница краснела на СОВПАДАЮЩЕМ тексте",
               differ=True)

    код3, _ = стенд("## ВНУТРЕННИЙ РАЗДЕЛ")
    ok &= case("③ `##` внутри тела правила — молчит",
               код3 == 0,
               f"код {код3}; 13 из 14 таких заголовков в живом своде лежат ВНУТРИ тел",
               differ=True)

    код4, _ = стенд("### ВНУТРЕННИЙ ПОДЗАГОЛОВОК", расхождение=True)
    ok &= case("④ ВСТРЕЧНЫЙ: настоящее расхождение при внутреннем `###` — ВИДНО",
               код4 == 1,
               f"код {код4}; без этого случая ② зеленел бы и от разбора, "
               "который перестал сравнивать вовсе", differ=True)

    # ⑤ ОБРАТНЫЙ ХОД. Ломаем границу обратно на «любой ###» и требуем, чтобы стало больно.
    #    🎯 Без него ②③ означают «сегодня не болит», а не «починка работает»: автор правила,
    #    на котором дефект нашли, СНЯЛ его оформление, и живой свод зелен при обеих границах.
    сломанный = pathlib.Path(tempfile.mkdtemp(prefix="bite-bounds-old-")) / "прежний.py"
    цел = РАЗБОР.read_text(encoding="utf-8")
    поломка = цел.replace(
        "        if i + 1 < len(heads):\n            end = heads[i + 1].start()",
        "        if True:\n            _any = [mm.start() for mm in re.finditer(r'^###\\s', text, re.M)]\n"
        "            end = next((p for p in _any if p > m.end()), len(text))", 1)
    if поломка == цел:
        ok &= case("⑤ ОБРАТНЫЙ ХОД: с ПРЕЖНЕЙ границей случай ② краснеет",
                   False,
                   "⛔ НЕ ЗАПУСТИЛСЯ: место границы в разборе не найдено — разбор "
                   "менялся, правь приёмку. Молча пропустить нельзя: это был бы "
                   "зелёный без опыта")
    else:
        сломанный.write_text(поломка, encoding="utf-8")
        shutil.copy(РАЗБОР.with_name("mezo_paths.py"), сломанный.with_name("mezo_paths.py"))
        код5, _ = стенд("### ВНУТРЕННИЙ ПОДЗАГОЛОВОК", разбор=сломанный)
        ok &= case("⑤ ОБРАТНЫЙ ХОД: с ПРЕЖНЕЙ границей случай ② краснеет",
                   код5 == 1,
                   f"код прежней редакции {код5} против {код2} у нынешней — "
                   "разница и есть доказательство починки", differ=True)
        shutil.rmtree(сломанный.parent, ignore_errors=True)

    print()
    print(f"{'✅ ГРАНИЦЫ ТЕЛА ПРАВИЛА ПРИНЯТЫ' if ok else '🔴 НЕ ПРИНЯТО'} — случаев {CASES}, "
          f"различающих {DIFFER}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
