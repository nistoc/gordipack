#!/usr/bin/env python
# -*- coding: utf-8 -*-
r"""ПРИЁМКА запрета обрезки вывода на уровне среды (карточка #246, класс от контура tapas).

⚖️ ГЛАВНОЕ СВОЙСТВО, КОТОРОЕ ЗДЕСЬ ИСПЫТЫВАЕТСЯ: механизм обязан ловить ЧУЖИЕ команды
(в этом весь смысл уровня среды) и при этом НЕ ТРОГАТЬ законное. Ложная блокировка дороже
пропуска: пропуск стоит одного обрезанного вывода, ложный отказ — доверия к механизму
целиком, и первым его выключит тот, кому он нужнее всего.

Случаи (различающий = обязан ответить ИНАЧЕ, а не одинаково):
  ① контроль: обрезка вывода инструмента координации → ОТКАЗ с причиной
  ② ВСТРЕЧНЫЙ: тот же инструмент БЕЗ фильтра → молчит                       РАЗЛИЧАЮЩИЙ
  ③ ВСТРЕЧНЫЙ: тот же фильтр к ЧУЖОЙ команде (git, ls) → молчит             РАЗЛИЧАЮЩИЙ
  ④ `| cat` — не режет, молчим (мерим намерение, а не канал)                РАЗЛИЧАЮЩИЙ
  ⑤ фильтр ДО инструмента в конвейере → молчит (обрезки нет)                РАЗЛИЧАЮЩИЙ
  ⑥ инструмент и фильтр в РАЗНЫХ командах через `;` → молчит                РАЗЛИЧАЮЩИЙ
  ⑦ труба ВНУТРИ кавычек не считается конвейером                            РАЗЛИЧАЮЩИЙ
  ⑧ НОВЫЙ инструмент, которого нет ни в одном списке → ловится по месту     РАЗЛИЧАЮЩИЙ
  ⑨ обрезка ФАЙЛА, куда ушёл вывод, — четвёртая дыра, названная нашим COORD ⛔ ЗНАЕМ, ЧТО НЕ ЛОВИМ
  ⑩ слово выключения гасит, а опечатка в нём — НЕ гасит                     РАЗЛИЧАЮЩИЙ
  ⑪ ввод не разобрался → молчит, а не запрещает вслепую                     РАЗЛИЧАЮЩИЙ

⛔ Живого контура не касается: механизму подаётся текст команды, ничего не исполняется.
"""
from __future__ import annotations

import json
import os
import pathlib
import subprocess
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import mezo_paths  # noqa: E402 — пути машины выводятся, не впечатаны (#153)

МЕХАНИЗМ = pathlib.Path(__file__).resolve().parent / "hook-pipe-tool-output.py"
КОРЕНЬ = str(mezo_paths.container_root(__file__)).replace("\\", "/")
CASES = DIFFER = 0


def case(title, ok, detail, differ=False):
    global CASES, DIFFER
    CASES += 1
    DIFFER += bool(differ)
    print(f"{'✅' if ok else '🔴'} {title}")
    print(f"   {detail}")
    return ok


def спросить(cmd: str, env_extra: dict | None = None, сырой: str | None = None) -> dict:
    """→ разобранный ответ механизма ({} — промолчал)."""
    ввод = сырой if сырой is not None else json.dumps(
        {"tool_name": "Bash", "tool_input": {"command": cmd}}, ensure_ascii=False)
    r = subprocess.run([sys.executable, str(МЕХАНИЗМ)], input=ввод, capture_output=True,
                       text=True, encoding="utf-8", timeout=120,
                       env=dict(os.environ, **(env_extra or {})))
    out = (r.stdout or "").strip()
    if not out:
        return {}
    return json.loads(out).get("hookSpecificOutput", {})


def отказ(ответ: dict) -> bool:
    return ответ.get("permissionDecision") == "deny"


def main() -> int:
    ok = True
    if not МЕХАНИЗМ.exists():
        sys.exit(f"⛔ НЕ ЗАПУСТИЛАСЬ: нет механизма — {МЕХАНИЗМ}")
    инстр = f"python {КОРЕНЬ}/.mezosync/scripts/read-messages.py --role PROTO"

    # ① КОНТРОЛЬ. Без него всё дальнейшее молчание неотличимо от слепоты.
    о = спросить(f"{инстр} | head -5")
    ok &= case("① обрезка вывода инструмента координации — ОТКАЗ с причиной",
               отказ(о) and "head" in о.get("permissionDecisionReason", "")
               and "ОБОИХ КОНЦАХ" in о.get("permissionDecisionReason", ""),
               "отказ обязан называть, ЧТО именно режет и почему это дорого")

    # ② ВСТРЕЧНЫЙ: тот же инструмент без фильтра.
    ok &= case("② ВСТРЕЧНЫЙ: тот же инструмент БЕЗ фильтра — молчит",
               not спросить(инстр),
               "иначе механизм запрещал бы саму работу с инструментами", differ=True)

    # ③ ВСТРЕЧНЫЙ: тот же фильтр, но к чужой команде. Правило про инструменты координации,
    #    а не про любую оболочку: `git log | head` — не его предмет.
    ok &= case("③ ВСТРЕЧНЫЙ: тот же фильтр к ЧУЖОЙ команде — молчит",
               not спросить("git log --oneline | head -5")
               and not спросить("ls -la | tail -3"),
               "запрет шире своего предмета — верный способ, чтобы его выключили", differ=True)

    # ④ КАНАЛ ПРОТИВ НАМЕРЕНИЯ. Дыра ② соседей: их модуль видит трубу и не видит, что
    #    на её конце. Мы видим имя и потому МОЛЧИМ на безвредном.
    ok &= case("④ `| cat` — не режет, молчим",
               not спросить(f"{инстр} | cat"),
               "их модуль здесь краснеет (мерит канал), наш — нет: в тексте видно имя",
               differ=True)

    # ⑤ ФИЛЬТР ДО ИНСТРУМЕНТА: вывод инструмента не обрезан, обрезан вход.
    ok &= case("⑤ фильтр ДО инструмента — молчит",
               not спросить(f"grep -l что-то *.md | xargs -I@ {инстр}"),
               "обрезка — это фильтр ПОСЛЕ инструмента; до — сужение входа", differ=True)

    # ⑥ РАЗНЫЕ КОМАНДЫ ЧЕРЕЗ `;`. 🪤 Первая редакция искала оба признака во всей строке
    #    и краснела здесь: инструмент и фильтр не связаны вовсе.
    ok &= case("⑥ инструмент и фильтр в РАЗНЫХ командах — молчит",
               not спросить(f"{инстр} > вывод.txt; grep ошибка другой-файл.log"),
               "ложный отказ на несвязанных командах — прямая дорога к выключению",
               differ=True)

    # ⑦ ТРУБА ВНУТРИ КАВЫЧЕК — не конвейер.
    ok &= case("⑦ труба внутри кавычек не считается конвейером",
               not спросить(f"{инстр} --body \"a|head -1\""),
               "иначе текст записки, содержащий трубу, читался бы как обрезка", differ=True)

    # ⑧ НОВЫЙ ИНСТРУМЕНТ. 🎯 Само правило заведено после того, как запрет по ИМЕНИ
    #    не перенёсся на соседний инструмент. Признак — МЕСТО, и новый файл накрыт сразу.
    ok &= case("⑧ НОВЫЙ инструмент, которого нет ни в одном списке — ловится по месту",
               отказ(спросить(f"python {КОРЕНЬ}/vnext-tools/такого-ещё-нет.py | tail -2")),
               "перечень имён неполон ровно на тот инструмент, которым ещё не обожглись",
               differ=True)

    # ⑨ ГРАНИЦА, НАЗВАННАЯ ВСЛУХ. Четвёртая дыра нашего COORD: вывод ушёл в файл,
    #    обрезали ПОЗЖЕ чтением файла. Здесь механизм молчит — и это НЕ победа, а предел.
    #    Случай стои́т в приёмке, чтобы предел был записан, а не забыт.
    ok &= case("⑨ ⛔ ЗНАЕМ, ЧТО НЕ ЛОВИМ: обрезка ФАЙЛА, куда ушёл вывод",
               not спросить("tail -5 вывод.txt"),
               "разрыв во ВРЕМЕНИ: инструмента в этой команде уже нет. Предел записан "
               "случаем, а не обещанием — молчание здесь ожидаемо и не выдаётся за чистоту")

    # ⑩ ВЫКЛЮЧАТЕЛЬ. Узкое слово — приём соседей, взят целиком: выключатель, гаснущий
    #    от чего угодно непустого, гасится ОПЕЧАТКОЙ, и молча.
    ok &= case("⑩ слово выключения гасит, опечатка в нём — НЕ гасит",
               not спросить(f"{инстр} | head -5", {"MEZO_PIPE_GUARD": "off"})
               and отказ(спросить(f"{инстр} | head -5", {"MEZO_PIPE_GUARD": "0"}))
               and отказ(спросить(f"{инстр} | head -5", {"MEZO_PIPE_GUARD": "false"})),
               "приём взят у соседей: `0` и `false` НЕ гасят — иначе запрет снимается "
               "опечаткой и молча", differ=True)

    # ⑪ НЕ РАЗОБРАЛСЯ ВВОД — молчим. Непрочитанное не улика: запрещать вслепую значит
    #    ломать работу на своей же неудаче разбора.
    ok &= case("⑪ ввод не разобрался — молчит, а не запрещает вслепую",
               not спросить("", сырой="это не разбирается вовсе"),
               "механизм, падающий в запрет от своей же неудачи, останавливает контур",
               differ=True)

    print()
    print(f"{'✅ ЗАПРЕТ ОБРЕЗКИ ПРИНЯТ' if ok else '🔴 НЕ ПРИНЯТ'} — случаев {CASES}, "
          f"различающих {DIFFER}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
