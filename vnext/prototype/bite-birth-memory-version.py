r"""ПРИЁМКА: рождение контура кладёт памяти не только тело, но и ВЕРСИЮ.

🩸 ЧЕМ ОПЛАЧЕНО. Заявка @OPSSRE о защите сохранённой памяти (записка #3756) опирается
на инвариант: у каждой секции памяти есть версия, дословно равная её телу. Из него следуют
три вещи разом — пустая история значит «механизм не работал», правка мимо инструмента
становится видимой, приёмке есть что сличать.
В README заявки сказано: «save-phoenix.py — единственная дверь к телу секции».

📏 ЗАМЕР ПЕРЕД ПРИМЕНЕНИЕМ (PROTO 2026-08-24 23:19 UTC) — дверь НЕ единственная:
```
кто пишет в phoenix напрямую ..... init-group.py, при рождении контура
прогон рождения .................. 2 секции памяти засеяно, версий НОЛЬ
```
⇒ Инвариант у новорождённого нарушался СРАЗУ и нарушался не ролью. Это ровно тот класс,
который в самом init-group.py назван ТРИЖДЫ: первый экран первой роли встречает отказом,
которого она не создавала.

⚖️ Довод починки — тот же, которым засеяна история при шаге схемы: без посева первое же
сохранение прошло бы без защиты. Здесь то же самое, но у новорождённого.

Случаи (различающий = обязан ответить ИНАЧЕ, а не одинаково):
  ① рождение по схеме С историей — инвариант держится                      РАЗЛИЧАЮЩИЙ
  ② рождение по схеме БЕЗ истории — НЕ падает (законный режим)             РАЗЛИЧАЮЩИЙ
  ③ ОБРАТНЫЙ ХОД: посев версии убран — инвариант НАРУШАЕТСЯ                РАЗЛИЧАЮЩИЙ
  ④ в рождённом контуре приёмка защиты памяти ПРОХОДИТ                     РАЗЛИЧАЮЩИЙ

🎯 ③ — главный: без него ① означал бы «сегодня сошлось», а не «кладётся по построению».
⛔ Живой базы не касается: каждый случай рождает свой контур во временном каталоге.
"""
from __future__ import annotations

import os
import pathlib
import shutil
import sqlite3
import subprocess
import sys
import tempfile

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import mezo_paths  # noqa: E402 — пути машины выводятся, не впечатаны

# ⚡ ПУТЬ К ОБРАЗЦУ ВЫВОДИТСЯ, А НЕ ВПЕЧАТАН. Приёмка живёт в двух местах сразу:
# у автора (в контуре, рядом с рабочими инструментами) и в самом образце. Впечатанный
# путь верен ровно у автора — у потребителя он целил бы в несуществующий каталог,
# и приёмка отказывалась бы запускаться по ложной причине.
# ⚖️ Порядок поиска: ① приёмка лежит ВНУТРИ образца ⇒ образец над ней; ② переменная
# среды MEZO_TEMPLATE — способ назвать чужую раскладку словом; ③ соседний каталог
# github/gordipack рядом с домом пользователя — раскладка автора, названная последней.
def _образец() -> pathlib.Path:
    свой = pathlib.Path(__file__).resolve()
    над = свой.parent.parent.parent          # <образец>/vnext/prototype/эта.py
    if (над / "scripts" / "init-group.py").exists():
        return над
    из_среды = os.environ.get("MEZO_TEMPLATE")
    if из_среды and (pathlib.Path(из_среды) / "scripts" / "init-group.py").exists():
        return pathlib.Path(из_среды)
    рядом = pathlib.Path.home().anchor
    гадание = pathlib.Path(рядом) / "github" / "gordipack"
    return гадание


ОБРАЗЕЦ = _образец()
CASES = DIFFER = 0


def case(title, verdict, detail, differ=False):
    global CASES, DIFFER
    CASES += 1
    DIFFER += bool(differ)
    print(f"{'✅' if verdict else '🔴'} {title}")
    print(f"   {detail}")
    return verdict


def родить(образец: pathlib.Path, имя: str):
    """Свой контур во временном каталоге → (код, путь к базе, каталог)."""
    d = pathlib.Path(tempfile.mkdtemp(prefix=f"bite-birth-{имя}-"))
    # ⚠️ ПУТЬ УКАЗЫВАЕТ НА КАТАЛОГ `.mezosync`, А НЕ НА КОНТЕЙНЕР.
    # 🩸 Первая редакция звала `--path <контейнер>` — контур рождался, но раскладка
    # выходила неканонической: база ложилась в корень, и инструменты, ищущие маркер
    # `.mezosync/mezosync.db` вверх по дереву, в таком контуре НЕ РАБОТАЛИ. Приёмка при
    # этом зеленела: она смотрела прямо в базу и не звала ни одного инструмента.
    # ⇒ Стенд, не воспроизводящий раскладку, проверяет не тот предмет. Замер 23:37 UTC:
    #   при верной раскладке приёмка защиты памяти в рождённом контуре даёт 17 из 17.
    цель = d / "контур" / ".mezosync"
    r = subprocess.run([sys.executable, str(образец / "scripts" / "init-group.py"),
                        "--name", имя, "--path", str(цель), "--roles", "COORD", "CORE"],
                       capture_output=True, text=True, encoding="utf-8", errors="replace",
                       timeout=600, cwd=str(образец))
    база = цель / "mezosync.db"
    if not база.exists():
        найдено = next(цель.rglob("mezosync.db"), None)
        база = найдено if найдено else база
    return r.returncode, база, d


def инвариант(база: pathlib.Path):
    """→ (есть ли таблица, сколько секций, сколько секций БЕЗ версии, равной телу)."""
    con = sqlite3.connect(f"file:{база.as_posix()}?mode=ro", uri=True)
    есть = bool(con.execute("SELECT 1 FROM sqlite_master WHERE type='table' "
                            "AND name='phoenix_history'").fetchone())
    секций = con.execute("SELECT COUNT(*) FROM phoenix").fetchone()[0]
    без = None
    if есть:
        без = con.execute("""
            SELECT COUNT(*) FROM phoenix p
             WHERE NOT EXISTS (SELECT 1 FROM phoenix_history h
                                WHERE h.role=p.role AND h.section=p.section AND h.body=p.body)
        """).fetchone()[0]
    con.close()
    return есть, секций, без


def образец_без_истории(куда: pathlib.Path) -> pathlib.Path:
    """Копия образца, чья схема НЕ знает таблицы истории — состояние до шага схемы."""
    копия = куда / "образец-без-истории"
    shutil.copytree(ОБРАЗЕЦ, копия,
                    ignore=shutil.ignore_patterns(".git", "__pycache__", "*.db"))
    for sql in (копия / "schema").glob("mezosync_v*.sql"):
        текст = sql.read_text(encoding="utf-8")
        # вырезаем ТОЛЬКО объявления истории, остальное трогать нельзя
        куски, брать = [], True
        for блок in текст.split(";"):
            if "phoenix_history" in блок:
                continue
            куски.append(блок)
        sql.write_text(";".join(куски), encoding="utf-8")
    return копия


def main() -> int:
    ok = True
    if not (ОБРАЗЕЦ / "scripts" / "init-group.py").exists():
        sys.exit(f"⛔ НЕ ЗАПУСТИЛАСЬ: образца нет — {ОБРАЗЕЦ}. Рождение испытывать нечем, "
                 "и молчаливый зелёный здесь был бы ложью")

    # ① РОЖДЕНИЕ ПО СХЕМЕ С ИСТОРИЕЙ
    код, база, d1 = родить(ОБРАЗЕЦ, "проба-а")
    есть, секций, без = инвариант(база)
    ok &= case("① рождение по схеме С историей — инвариант держится",
               код == 0 and есть and секций > 0 and без == 0,
               f"код {код} · секций памяти {секций} · таблица истории "
               f"{'есть' if есть else 'НЕТ'} · без версии: {без}", differ=True)

    # ④ РОЖДЁННЫЙ КОНТУР РАБОТОСПОСОБЕН, А НЕ ТОЛЬКО ПРАВИЛЕН ПО ДАННЫМ.
    #    🩸 Оплачено прогоном 2026-08-24 23:37 UTC: первая редакция этой приёмки смотрела
    #    прямо в базу и не звала НИ ОДНОГО инструмента — и зеленела на контуре, где
    #    раскладка была неканонической и инструменты не работали вовсе.
    #    ⇒ Данные верны, а механизм мёртв — состояние, которое проверка данных не различает.
    приёмка_защиты = база.parent / "scripts" / "bite-phoenix-empty.py"
    if приёмка_защиты.exists():
        r4 = subprocess.run([sys.executable, str(приёмка_защиты)], capture_output=True,
                            text=True, encoding="utf-8", errors="replace", timeout=900)
        весь = (r4.stdout or "") + (r4.stderr or "")
        ok &= case("④ в рождённом контуре приёмка защиты памяти ПРОХОДИТ",
                   r4.returncode == 0 and "ЗАЩИТА ПРИНЯТА" in весь,
                   f"код {r4.returncode} · "
                   + (next((s.strip() for s in весь.splitlines() if "ЗАЩИТА" in s
                            or "НЕ ЗАПУСТИЛАСЬ" in s), "(итога нет)"))
                   + " · данные верны ещё не значит, что механизм жив", differ=True)
    else:
        ok &= case("④ в рождённом контуре приёмка защиты памяти ПРОХОДИТ", False,
                   f"⛔ НЕ ЗАПУСТИЛСЯ: в рождённом контуре нет {приёмка_защиты.name} — "
                   "значит образец её не раздаёт, и потребитель останется без проверки")
    shutil.rmtree(d1, ignore_errors=True)

    # ② РОЖДЕНИЕ ПО СХЕМЕ БЕЗ ИСТОРИИ — законный режим (контур до шага схемы).
    #    ⚖️ Рождение не вправе упасть из-за отсутствующей защиты: один шаг схемы не может
    #       обездвижить появление контура.
    d = pathlib.Path(tempfile.mkdtemp(prefix="bite-birth-old-"))
    старый = образец_без_истории(d)
    код2, база2, d2 = родить(старый, "проба-б")
    есть2, секций2, _ = инвариант(база2) if база2.exists() else (False, 0, None)
    ok &= case("② рождение по схеме БЕЗ истории — НЕ падает (законный режим)",
               код2 == 0 and not есть2 and секций2 > 0,
               f"код {код2} · секций {секций2} · таблицы истории нет — и это норма "
               "для контура, родившегося до шага схемы", differ=True)
    shutil.rmtree(d2, ignore_errors=True)

    # ③ ОБРАТНЫЙ ХОД: убираем посев версии и требуем, чтобы инвариант СЛОМАЛСЯ.
    сломанный = d / "образец-без-посева"
    shutil.copytree(ОБРАЗЕЦ, сломанный,
                    ignore=shutil.ignore_patterns(".git", "__pycache__", "*.db"))
    файл = сломанный / "scripts" / "init-group.py"
    цел = файл.read_text(encoding="utf-8")
    порча = цел.replace("            if history_cols:", "            if False:", 1)
    if порча == цел:
        ok &= case("③ ОБРАТНЫЙ ХОД: посев версии убран — инвариант НАРУШАЕТСЯ", False,
                   "⛔ НЕ ЗАПУСТИЛСЯ: места посева в сборке контура нет — она менялась, "
                   "правь приёмку. Молча пропустить нельзя: это был бы зелёный без опыта")
    else:
        файл.write_text(порча, encoding="utf-8")
        код3, база3, d3 = родить(сломанный, "проба-в")
        есть3, секций3, без3 = инвариант(база3) if база3.exists() else (False, 0, None)
        ok &= case("③ ОБРАТНЫЙ ХОД: посев версии убран — инвариант НАРУШАЕТСЯ",
                   код3 == 0 and есть3 and без3 == секций3 and секций3 > 0,
                   f"код {код3} · секций {секций3}, из них БЕЗ версии {без3} — "
                   "разница с ① и есть доказательство, что версия кладётся по построению, "
                   "а не совпала", differ=True)
        shutil.rmtree(d3, ignore_errors=True)
    shutil.rmtree(d, ignore_errors=True)

    print()
    print(f"{'✅ ПОСЕВ ВЕРСИИ ПРИ РОЖДЕНИИ ПРИНЯТ' if ok else '🔴 НЕ ПРИНЯТО'} — "
          f"случаев {CASES}, различающих {DIFFER}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
