    ПРОБА = "--zzprobe"

    def распознана(текст):
        """→ True, если подсаженная строка попала в разбор КАК КОМАНДА (по своему ключу)."""
        d, scripts_, db_ = sandbox()
        путь = str(scripts_).replace("\\", "/")
