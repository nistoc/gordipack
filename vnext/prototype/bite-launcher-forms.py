#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""ПРИЁМКА: проверка «формы вызова из памяти ролей» ВИДИТ поломку, а не рапортует зелёным.

Повод — проба-канарейка 2026-08-09: `role-rights.py list --role <РОЛЬ>` падала у каждой роли,
а приёмка была зелёной, потому что звала форму БЕЗ имени роли. Прибор, который ловит такое,
сам обязан быть испытан ПОЛОМКОЙ: иначе он ровно та же зелёная бумажка, только больше.

Случаи (различающий = прибор обязан ответить ИНАЧЕ, а не одинаково):
  ① контроль: неиспорченная копия — прибор молчит (зелёный)
  ② у скрипта СЛОМАН РАЗБОР ПАРАМЕТРА → прибор краснеет            РАЗЛИЧАЮЩИЙ
     ровно дефект 09.08: без флага работает, с флагом падает
  ③ скрипт ИСЧЕЗ из каталога → прибор краснеет и говорит «файла нет» РАЗЛИЧАЮЩИЙ
  ④ прибор идёт по УКАЗАННОМУ каталогу, а не по живому                РАЗЛИЧАЮЩИЙ
     без этого зелёный прогон доказывал бы исправность ОРИГИНАЛА, а не копии
  ⑤ упоминание в пояснении НЕ считается командой                      РАЗЛИЧАЮЩИЙ
     у ING в памяти лежит `.mezosync\\scripts\\x.py` — пример опасной формы, а не вызов
  ⑥ мутирующая форма НЕ запускается на живой базе (--ack не гасит ключ) РАЗЛИЧАЮЩИЙ

⛔ Живого контура не касается: работает на копии каталога скриптов и копии базы.
"""
import os
import re
import shutil
import sqlite3
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import mezo_target  # noqa: E402 — какую копию испытываем, решается ОДНИМ местом
import mezo_paths  # пути машины выводятся, не впечатаны (#153)
import mezo_stand  # noqa: E402 — временный каталог убирается при успехе, сохраняется при провале

TOOL = Path(__file__).resolve().parent / "guard-launcher-forms.py"
LIVE_SCRIPTS = mezo_target.scripts_root()
LIVE_DB = mezo_paths.live_db()
CASES = DIFFER = 0


def case(title, ok, detail, differ=False):
    global CASES, DIFFER
    CASES += 1
    DIFFER += bool(differ)
    print(f"{'✅' if ok else '🔴'} {title}")
    print(f"   {detail}")
    return ok


def sandbox():
    """Копия каталога скриптов + копия базы, где память переписана на этот каталог."""
    d = mezo_stand.new("bite-forms-")
    # Песочница — НАСТОЯЩАЯ раскладка контура (.mezosync/scripts + база рядом), а не файлы
    # рядом. С 20.08 помощник путей отказывает ГРОМКО, если корень не найден: в прежней
    # раскладке КАЖДЫЙ механизм падал ещё до разбора доводов, и поломка флага переставала
    # что-либо менять — проверка честно не видела разницы между целым и сломанным.
    # 🎯 Так «слепых» стало пятеро, и ни один из них не был дефектом самой проверки.
    контур = d / ".mezosync"
    scripts = контур / "scripts"
    shutil.copytree(LIVE_SCRIPTS, scripts)
    db = контур / "mezosync.db"
    shutil.copy(LIVE_DB, db)
    return d, scripts, db


def run(scripts, db, *extra):
    r = subprocess.run([sys.executable, str(TOOL), "--scripts-root", str(scripts),
                        "--db", str(db), *extra],
                       capture_output=True, text=True, encoding="utf-8", timeout=600)
    return (r.stdout or "") + (r.stderr or ""), r.returncode


def main() -> int:
    ok = True
    if not TOOL.exists():
        sys.exit(f"⛔ НЕ ЗАПУСТИЛАСЬ: инструмента нет — {TOOL}")

    # ── ① контроль ────────────────────────────────────────────────────────────
    d, scripts, db = sandbox()
    out, code = run(scripts, db, "--only", "role-rights")
    ok &= case("① контроль: неиспорченная копия — проверка зелёная",
               code == 0 and "🔴 ПАДАЮТ ИЛИ НЕТ ФАЙЛА 0" in out,
               f"код {code} · без этого краснота дальше ничего не доказывает")

    # ── ② сломан разбор параметра (дефект 09.08 дословно) ─────────────────────
    d2, scripts2, db2 = sandbox()
    target = scripts2 / "role-rights.py"
    src = target.read_text(encoding="utf-8")
    broken = src.replace('sql + " ORDER BY role, right_key", par',
                         'sql + " ORDER BY role, right_key"')
    if broken == src:
        sys.exit("⛔ НЕ ЗАПУСТИЛАСЬ: место для поломки не найдено — инструмент менялся, правь приёмку")
    target.write_text(broken, encoding="utf-8")
    out, code = run(scripts2, db2, "--only", "role-rights")
    ok &= case("② сломан разбор параметра — проверка КРАСНЕЕТ",
               code != 0 and "ПАДАЕТ" in out,
               "форма без флага работает, с флагом падает: ровно то, что прожило незамеченным",
               differ=True)

    # ── ③ скрипт исчез ────────────────────────────────────────────────────────
    d3, scripts3, db3 = sandbox()
    (scripts3 / "read-phoenix.py").unlink()
    out, code = run(scripts3, db3, "--only", "read-phoenix")
    ok &= case("③ скрипт ИСЧЕЗ — проверка краснеет и называет это «файла нет»",
               code != 0 and ("ФАЙЛА НЕТ" in out or "НЕТ ПО НАЗВАННОМУ" in out),
               "роль получила бы «can't open file» в первую же секунду жизни", differ=True)

    # ── ④ прибор идёт по УКАЗАННОМУ каталогу, а не по живому ──────────────────
    # живой role-rights.py исправен; в копии он сломан. Если бы прибор ходил по пути
    # из памяти (абсолютному), он остался бы зелёным — и доказывал бы исправность ОРИГИНАЛА
    ok &= case("④ испытан УКАЗАННЫЙ каталог, а не живой",
               code != 0,
               "живой каталог цел; краснота пришла из копии ⇒ проверка смотрела именно на копию",
               differ=True)

    # ── ⑤ упоминание ≠ команда ────────────────────────────────────────────────
    out, code = run(scripts, db, "--only", "x.py")
    ok &= case("⑤ пример в пояснении НЕ считается командой",
               code == 0 and "🔴 ПАДАЮТ ИЛИ НЕТ ФАЙЛА 0" in out,
               "у ING это строка про ОПАСНОСТЬ относительного пути — проверка обвиняла её зря",
               differ=True)

    # ── ⑤-бис..⑤-кватер: ЧТО СЧИТАТЬ КОМАНДОЙ (заявка @COORD, записка #4011, карточка #332)
    # 🩸 ЧЕМ ОПЛАЧЕНО. Условие «команда — если в блоке кода ИЛИ перед именем есть python»
    # второй половиной не срабатывало НИКОГДА: слово python захватывалось совпадением,
    # и текст ДО совпадения был пуст по построению. Замер живой базы 27.08 17:11 UTC:
    # 109 строк «python <путь>.py» вне блоков кода, проверялось из них 0.
    # Зеркальная половина того же дефекта: ОПИСЬ файлов внутри блока кода считалась
    # командой — прибор запускал перечень предметов и краснел на исправном.
    # 🪤 ПЕРВАЯ РЕДАКЦИЯ ЭТИХ ЧЕТЫРЁХ СУДИЛА ПО ОБЩЕМУ ИСХОДУ прогона — и два случая
    # краснели на исправном приборе: я ломала role-rights.py, а его формы есть в памяти
    # ДРУГИХ ролей, и краснота приходила от них, а не от подсаженной строки. Случай
    # не различал ничего. ⇒ судим по ТОЙ САМОЙ форме: подсаживаем уникальный ключ
    # и смотрим, попал ли он в разбор. Ломать механизм для этого не нужно вовсе.
    ПРОБА = "--zzprobe"

    def распознана(текст):
        """→ True, если подсаженная строка попала в разбор КАК КОМАНДА (по своему ключу)."""
        d, scripts_, db_ = sandbox()
        путь = str(scripts_).replace("\\", "/")
        con = sqlite3.connect(db_)
        con.execute("UPDATE phoenix SET body = body || ? WHERE role='PROTO' AND section='sources'",
                    (chr(10) + текст.format(путь=путь, проба=ПРОБА) + chr(10),))
        con.commit()
        con.close()
        out, _ = run(scripts_, db_, "--only", "role-rights")
        return ПРОБА in out

    # ⑤-бис: КАНОНИЧЕСКАЯ ФОРМА В ПРОЗЕ — команда.
    ok &= case("⑤-бис форма «python <путь>» ВНЕ блока кода — КОМАНДА, и она разбирается",
               распознана("Зови так: python {путь}/role-rights.py list {проба}"),
               "именно так записан вызов в прозе у девяти ролей: 109 живых строк, "
               "и до 27.08 не разбиралась ни одна", differ=True)

    # ⑤-трис ВСТРЕЧНЫЙ: то же имя в прозе БЕЗ слова python — упоминание, обвинять нельзя.
    ok &= case("⑤-трис ВСТРЕЧНЫЙ: имя в прозе БЕЗ «python» — упоминание, в разбор не идёт",
               not распознана("относительный префикс перед именем — "
                              "scripts/role-rights.py list {проба} — так НЕ зови"),
               "пояснение об опасности говорит обратное тому, что услышал бы прибор",
               differ=True)

    # ⑤-кватер: ОПИСЬ внутри блока кода — перечень предметов, а не то, что роль скопирует.
    ok &= case("⑤-кватер ОПИСЬ в блоке кода (имя + русское описание) — НЕ команда",
               not распознана("```" + chr(10)
                              + "{путь}/role-rights.py  расхождение прав {проба}" + chr(10)
                              + "```"),
               "прибор запускал перечень и краснел на исправном: обвинял память "
               "за строку, которая командой не была", differ=True)

    # ⑤-квинт ВСТРЕЧНЫЙ к ⑤-кватер: русское ЗНАЧЕНИЕ за латинским ключом — всё ещё команда.
    # Без него ⑤-кватер зеленел бы оттого, что кириллица где угодно гасит разбор.
    ok &= case("⑤-квинт ВСТРЕЧНЫЙ: русское значение за латинским ключом — КОМАНДА",
               распознана("```" + chr(10)
                          + "python {путь}/role-rights.py list {проба} ВЛАДЕЛЕЦ" + chr(10)
                          + "```"),
               "иначе починка описи ослепила бы прибор на всякую команду с русским словом",
               differ=True)

    # ── ⑥ мутирующая форма не запускается ─────────────────────────────────────
    # ⚠️ Память СЕГОДНЯ может не содержать ни одной такой формы (у RCC она записана прозой,
    # а не командой). Случай, зависящий от чужого текста, зеленел бы «по отсутствию предмета»,
    # поэтому предмет кладём в копию памяти САМИ.
    d6, scripts6, db6 = sandbox()
    con = sqlite3.connect(db6)
    con.execute("UPDATE phoenix SET body = body || ? WHERE role='PROTO' AND section='sources'",
                ("\n```\npython " + str(LIVE_SCRIPTS).replace("\\", "/")
                 + "/read-messages.py --role PROTO --ack КЛЮЧ\n```\n",))
    con.commit()
    con.close()
    out, code = run(scripts6, db6, "--only", "read-messages")
    ok &= case("⑥ форма с гашением ключа НЕ запущена, и сказано почему",
               "гасит ОДНОРАЗОВЫЙ ключ" in out,
               "запуск съел бы у роли её батч — молчаливый пропуск скрыл бы это", differ=True)

    # ── ⑦ МЕХАНИЗМ УБИТ НАСМЕРТЬ И МОЛЧИТ ─────────────────────────────────────
    # 🪤 Оплачено опытом 20.08: от механизма оставлена ОДНА строка `raise SystemExit(9)`,
    # а проверка отвечала «✅ отвечают 2». Судила она только по ТЕКСТУ ответа, а код
    # возврата не смотрела вовсе. Роль в таком случае видит пустоту и идёт дальше.
    d7a, scripts7a, db7a = sandbox()
    (scripts7a / "role-rights.py").write_text("raise SystemExit(9)", encoding="utf-8")
    out, code = run(scripts7a, db7a, "--only", "role-rights")
    ok &= case("⑦ механизм отказывает МОЛЧА — проверка краснеет",
               code != 0 and "МОЛЧА ОТКАЗЫВАЕТ" in out,
               "пустой ответ при отказе неотличим для роли от сработавшего запуска",
               differ=True)

    # ── ⑧ ВСТРЕЧНЫЙ к ⑦: ненулевой код при ВНЯТНОМ отчёте — не обвинение ───────
    # Проверки контура законно отвечают кодом 1, когда нашли расхождения. Суди прибор
    # по одному коду — и он обвинил бы каждую такую находку как поломку формы.
    d8, scripts8, db8 = sandbox()
    строки = ["print('нашёл 3 расхождения — это находка, а не поломка')",
              "raise SystemExit(1)"]
    (scripts8 / "role-rights.py").write_text(chr(10).join(строки), encoding="utf-8")
    out, code = run(scripts8, db8, "--only", "role-rights")
    ok &= case("⑧ отказ кодом при ВНЯТНОМ отчёте — обвинения нет (встречный к ⑦)",
               code == 0 and "МОЛЧА ОТКАЗЫВАЕТ" not in out,
               "иначе она красила бы законные находки проверок контура", differ=True)

    # ── ⑨ СПЛОШНАЯ ПОЛОМКА: КАЖДЫЙ механизм по очереди ────────────────────────
    # Критерий карточки #147 дословно: «сломать разбор параметра у каждой такой команды
    # по очереди, прогон обязан покраснеть на каждой». Одна поломка на одном скрипте
    # доказывает, что прибор видит ЭТОТ скрипт, а не что он видит вообще.
    # Ломаем ОБЪЯВЛЕНИЕ флага: механизм перестаёт знать «--role», и вызов из памяти
    # отвечает «unrecognized arguments» — без падения. Прибор обязан счесть это отказом.
    print()
    print("⑨ СПЛОШНАЯ ПОЛОМКА — по одному механизму за раз:")
    d7, scripts7, db7 = sandbox()
    # ⚠️ Цель — скрипты, ОБЪЯВЛЯЮЩИЕ --role своим флагом, а не любое упоминание строки:
    # 13.08 guard-all получил "--role" как аргумент ПОДПРОЦЕССА (замер памяти зовёт
    # проверка памяти по ролям), и отбор по упоминанию записал его в цели. Поломка упоминания
    # контракта guard-all не рушит (его зовут без аргументов) — приёмка объявила прибор
    # «слепым» на поломке, которую роль не может встретить. Это случай ⑤ («упоминание ≠
    # команда») в самой приёмке — тем же классом, которым она судит других.
    targets = sorted({p.name for p in scripts7.glob("*.py")
                      if 'add_argument("--role"' in p.read_text(encoding="utf-8", errors="ignore")})
    # 🪤 ВСТРЕЧНЫЙ ПРОГОН НА ЦЕЛОЙ КОПИИ, найденный на себе 20.08. Прежде краснота
    # засчитывалась за «увидела поломку» — но краснеть проверка может и оттого, что этот
    # механизм краснеет САМ ПО СЕБЕ, ещё до всякой поломки. Тогда «увидел все 11» значило
    # бы «одиннадцать раз покраснело неизвестно на что»: третий исход читался как зелёный.
    # ⚖️ Судить можно только тем же запросом, каким судится сломанный: --only на тот же
    # механизм. Общий прогон по ВСЕЙ памяти для этого не годится — он краснеет законно,
    # от чужих механизмов, и запретил бы серию целиком (проверено: так и вышло).
    _, scripts_ok, db_ok = sandbox()

    blind, seen, unjudged = [], 0, []
    for name in targets:
        только = name.replace(".py", "")
        out_ok, code_ok = run(scripts_ok, db_ok, "--only", только)
        d_i, scripts_i, db_i = sandbox()
        f = scripts_i / name
        src = f.read_text(encoding="utf-8")
        f.write_text(src.replace('"--role"', '"--rolezz"'), encoding="utf-8")
        out_i, code_i = run(scripts_i, db_i, "--only", только)
        # прибор мог вовсе не проверять этот механизм (нет форм) — это НЕ «увидел»
        checked = "отвечают 0 · 🔴 ПАДАЮТ ИЛИ НЕТ ФАЙЛА 0 · ⚠️ не проверены 0" not in out_i
        caught = code_i != 0
        if not checked:
            mark = "⚪ форм этого механизма в памяти нет — ломать нечего"
        elif code_ok != 0:
            # красный ДО поломки: краснота на сломанном ничего не доказывает
            unjudged.append(name)
            mark = "⛔ НЕ СУДИМ: красный и на целой копии"
        else:
            seen += 1
            mark = "✅ увидел" if caught else "🔴 СЛЕП"
            if not caught:
                blind.append(name)
        print(f"   {mark:52} {name}")
    ok &= case(f"⑨ сплошная поломка: проверка увидела все {seen} судимых механизмов",
               not blind and seen > 0,
               f"механизмов с формами в памяти {seen + len(unjudged)} из {len(targets)} · "
               f"слепых {len(blind)}{': ' + ', '.join(blind) if blind else ''} · "
               f"не судимы {len(unjudged)}"
               f"{' (' + ', '.join(unjudged) + ') — красны и без поломки' if unjudged else ''}",
               differ=True)

    print()
    print(f"{'✅ ПРОВЕРКА ПРИНЯТА' if ok else '🔴 НЕ ПРИНЯТ'} — случаев {CASES}, различающих {DIFFER}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(mezo_stand.finish(main()))
