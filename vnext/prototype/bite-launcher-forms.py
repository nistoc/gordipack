    print("⑨ СПЛОШНАЯ ПОЛОМКА — по одному механизму за раз:")
    d7, scripts7, db7 = sandbox()
    # ⚠️ Цель — скрипты, ОБЪЯВЛЯЮЩИЕ --role своим флагом, а не любое упоминание строки:
    # 13.08 guard-all получил "--role" как аргумент ПОДПРОЦЕССА (замер памяти зовёт
    # проверка памяти по ролям), и отбор по упоминанию записал его в цели. Поломка упоминания
    # контракта guard-all не рушит (его зовут без аргументов) — приёмка объявила прибор
    # «слепым» на поломке, которую роль не может встретить. Это случай ⑤ («упоминание ≠
    # команда») в самой приёмке — тем же классом, которым она судит других.
    targets = sorted({p.name for p in scripts7.glob("*.py")
                      if 'add_argument("--role"' in p.read_text(encoding="utf-8", errors="ignore")})
    # 🪤 ВСТРЕЧНЫЙ ПРОГОН НА ЦЕЛОЙ КОПИИ, найденный на себе 20.08. Прежде краснота
    # засчитывалась за «увидела поломку» — но краснеть проверка может и оттого, что этот
    # механизм краснеет САМ ПО СЕБЕ, ещё до всякой поломки. Тогда «увидел все 11» значило
    # бы «одиннадцать раз покраснело неизвестно на что»: третий исход читался как зелёный.
    # ⚖️ Судить можно только тем же запросом, каким судится сломанный: --only на тот же
    # механизм. Общий прогон по ВСЕЙ памяти для этого не годится — он краснеет законно,
    # от чужих механизмов, и запретил бы серию целиком (проверено: так и вышло).
    _, scripts_ok, db_ok = sandbox()

    # 🪤 ЧЕТЫРЕ ИСХОДА НА МЕХАНИЗМ, А НЕ ДВА (правка 29.08, карточка #356). Прежде их было
    # три, и один из них — «ломать нечего» — вычислялся по ОБЩЕМУ итогу прогона: строка
    # «отвечают 0 · падают 0 · не проверены 0». Отбор прибора идёт ПОДСТРОКОЙ имени, поэтому
    # формы соседа (read-broadcasts.py при «broadcast») делали эту строку непустой, механизм
    # выглядел судимым, и его молчание записывалось в слепоту. Теперь ведро выбирается по
    # ТОЧНОМУ имени (см. формы()), и ведра стало четыре:
    #   ⚪ форм нет вовсе ................ ломать нечего
    #   ⚪ формы есть, но НЕ ЗАПУСКАЮТСЯ .. прибор назвал причину («не проверена»), и поломка
    #                                      физически не может проявиться. Это НЕ зелёное:
    #                                      ведро печатается поимённо, а встречный ⑨-бис
    #                                      доказывает, что оно не прячет слепоту
    #   ⛔ не судим ...................... красный и на ЦЕЛОЙ копии
    #   ✅/🔴 ............................ судим: увидел или слеп
    blind, seen, unjudged, nothing, unrunnable = [], 0, [], [], []
    for name in targets:
        только = name.replace(".py", "")
        out_ok, code_ok = run(scripts_ok, db_ok, "--only", только)
        свои_ok = формы(out_ok, name)
        d_i, scripts_i, db_i = sandbox()
        f = scripts_i / name
        src = f.read_text(encoding="utf-8")
        f.write_text(src.replace('"--role"', '"--rolezz"'), encoding="utf-8")
        out_i, code_i = run(scripts_i, db_i, "--only", только)
        свои_i = формы(out_i, name)
        if not (свои_ok["ok"] or свои_ok["red"] or свои_ok["skip"]):
            nothing.append(name)
            mark = "⚪ форм этого механизма в памяти нет — ломать нечего"
        elif свои_ok["red"]:
            # красный ДО поломки: краснота на сломанном ничего не доказывает
            unjudged.append(name)
            mark = "⛔ НЕ СУДИМ: красный и на целой копии"
        elif not свои_ok["ok"]:
            unrunnable.append(name)
            mark = "⚪ формы есть, но НИ ОДНА не запускается — поломке негде проявиться"
        else:
            seen += 1
            # краснеть обязан ИМЕННО этот механизм: код возврата общий на весь прогон
            caught = bool(свои_i["red"])
            mark = "✅ увидел" if caught else "🔴 СЛЕП"
            if not caught:
                blind.append(name)
        print(f"   {mark:52} {name}")
    ok &= case(f"⑨ сплошная поломка: слепых {len(blind)} из {seen} судимых механизмов",
               not blind and seen > 0,
               f"судимых {seen} из {len(targets)} · "
               f"слепых {len(blind)}{': ' + ', '.join(blind) if blind else ''} · "
               f"не судимы {len(unjudged)}"
               f"{' (' + ', '.join(unjudged) + ') — красны и без поломки' if unjudged else ''} · "
               f"форм нет {len(nothing)} · формы есть, но не запускаются {len(unrunnable)}"
               f"{' (' + ', '.join(unrunnable) + ') — их держит ⑨-бис' if unrunnable else ''}",
               differ=True)
    # ⚖️ ГРАНИЦА ЭТОГО СЛУЧАЯ, НАЗВАННАЯ ВСЛУХ (замер 29.08, карточка #358). Поломка здесь —
    # переименование ОБЪЯВЛЕНИЯ флага. Разборщик доводов допускает сокращения: «--role»
    # остаётся однозначным началом «--rolezz», и у механизма, который это поле не читает,
    # форма продолжает работать ПО-НАСТОЯЩЕМУ. Значит «🔴 СЛЕП» здесь — ещё не приговор
    # прибору: сперва перемерь, изменила ли поломка поведение ИМЕННО этой формы.
    # Проверено на lease.py: `status --role PROTO` с переименованным объявлением отвечает
    # кодом 0 и печатает список — ломать было нечего, и молчание прибора было правдой.
    print("   ⚖️ поломка ⑨ = переименование объявления флага; сокращения разборщика делают её")
    print("      невидимой для формы, которая это поле не читает ⇒ «СЛЕП» перемеряй (карточка #358)")

    # ── ⑨-бис ВСТРЕЧНЫЙ к ведру «формы есть, но не запускаются» ────────────────
    # 🪤 Ведро, заведённое выше, СНИМАЕТ обвинение с прибора — и ровно поэтому обязано быть
    # испытано: иначе оно стало бы тихой амнистией, и настоящая слепота пряталась бы в нём
    # под названной причиной. Берём механизм ИЗ ЭТОГО ВЕДРА, кладём ему в копию памяти
    # запускаемую форму и убиваем механизм насмерть: прибор обязан покраснеть ИМЕННО на нём.
    # 🩸 ПЕРВАЯ РЕДАКЦИЯ ЭТОГО СЛУЧАЯ (29.08, час назад) ломала объявление флага — и
    # покраснела на исправном приборе. Разборщик доводов допускает СОКРАЩЕНИЯ: «--role»
    # осталось однозначным началом «--rolezz», а lease.py в подкоманде status это поле
    # не читает вовсе ⇒ форма отвечала кодом 0 и печатала список. Поломки не было —
    # молчание прибора было правдой. Тот же класс, который случай и призван ловить:
    # ИСПЫТЫВАЛИ НЕ ТО, ЧТО ЧИНИМ. ⇒ поломка здесь ДЕТЕРМИНИРОВАННАЯ и не зависит
    # от того, какое поле механизм читает.
    if unrunnable:
        подопытный = unrunnable[0]
        имя_без = подопытный.replace(".py", "")

        def с_формой(хвост, убить):
            d_, scripts_, db_ = sandbox()
            путь = str(scripts_).replace("\\", "/")
            con = sqlite3.connect(db_)
            con.execute("UPDATE phoenix SET body = body || ? WHERE role='PROTO' AND section='sources'",
                        (chr(10) + "```" + chr(10)
                         + f"python {путь}/{подопытный} {хвост}" + chr(10)
                         + "```" + chr(10),))
            con.commit()
            con.close()
            if убить:
                # молчаливый отказ — та поломка, которую роль читает как сработавший запуск
                (scripts_ / подопытный).write_text("raise SystemExit(9)", encoding="utf-8")
            out_, _ = run(scripts_, db_, "--only", имя_без)
            return формы(out_, подопытный)

        # ⚖️ Форму подбираем, а не угадываем: у одних механизмов подкоманда обязательна,
        # у других её нет вовсе. Негодная форма дала бы КРАСНОЕ на целой копии — и встречный
        # случай покраснел бы по своей же вине, тем самым классом, который сегодня чинится.
        целая = {"ok": []}
        хвост = None
        for кандидат in ("status --role PROTO", "--role PROTO", "list --role PROTO"):
            проба = с_формой(кандидат, False)
            if проба["ok"]:
                целая, хвост = проба, кандидат
                break
        if хвост is None:
            ok &= case("⑨-бис ВСТРЕЧНЫЙ: положили ЗАПУСКАЕМУЮ форму — поломка стала видна",
                       False,
                       f"⛔ НЕ ЗАПУСТИЛАСЬ: у {подопытный} не подобралась ни одна запускаемая "
                       "форма из трёх проб ⇒ ведро «формы есть, но не запускаются» остаётся "
                       "НЕДОКАЗАННЫМ. Недоказанный встречный случай — не зелёный", differ=True)
        else:
            сломанная = с_формой(хвост, True)
            ok &= case("⑨-бис ВСТРЕЧНЫЙ: положили ЗАПУСКАЕМУЮ форму — поломка стала видна",
                       bool(сломанная["red"]),
                       f"{подопытный} «{хвост}»: на целой копии форма отвечает "
                       f"({len(целая['ok'])}), у убитого насмерть механизма краснеет "
                       f"({len(сломанная['red'])}) ⇒ разряд «не запускается» говорит об "
                       "ОТСУТСТВИИ запускаемой формы, а не о слепоте проверки", differ=True)
    else:
        # предмета нет — это ТРЕТИЙ исход, и он не зелёный: печатаем вслух
        print("⚪ ⑨-бис не на чем прогнать: ведро «формы есть, но не запускаются» пусто")

    print()
    print(f"{'✅ ПРОВЕРКА ПРИНЯТА' if ok else '🔴 НЕ ПРИНЯТ'} — случаев {CASES}, различающих {DIFFER}")
    return 0 if ok else 1


