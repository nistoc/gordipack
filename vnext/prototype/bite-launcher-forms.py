CASES = DIFFER = 0


def case(title, ok, detail, differ=False):
    global CASES, DIFFER
    CASES += 1
    DIFFER += bool(differ)
    print(f"{'✅' if ok else '🔴'} {title}")
    print(f"   {detail}")
    return ok


def sandbox():
    """Копия каталога скриптов + копия базы, где память переписана на этот каталог."""
    d = mezo_stand.new("bite-forms-")
    # Песочница — НАСТОЯЩАЯ раскладка контура (.mezosync/scripts + база рядом), а не файлы
    # рядом. С 20.08 помощник путей отказывает ГРОМКО, если корень не найден: в прежней
    # раскладке КАЖДЫЙ механизм падал ещё до разбора доводов, и поломка флага переставала
    # что-либо менять — проверка честно не видела разницы между целым и сломанным.
    # 🎯 Так «слепых» стало пятеро, и ни один из них не был дефектом самой проверки.
    контур = d / ".mezosync"
    scripts = контур / "scripts"
    shutil.copytree(LIVE_SCRIPTS, scripts)
    db = контур / "mezosync.db"
    shutil.copy(LIVE_DB, db)
    return d, scripts, db


def run(scripts, db, *extra):
    r = subprocess.run([sys.executable, str(TOOL), "--scripts-root", str(scripts),
                        "--db", str(db), *extra],
                       capture_output=True, text=True, encoding="utf-8", timeout=600)
    return (r.stdout or "") + (r.stderr or ""), r.returncode


def формы(вывод, имя):
    """Строки прибора, относящиеся ИМЕННО к этому механизму — по ТОЧНОМУ имени файла.

    🩸 ОПЛАЧЕНО ЗАМЕРОМ 2026-08-29 (карточка #356). Прежняя редакция судила ⑨ по ОБЩЕМУ
    исходу прогона `--only <имя без .py>`, а отбор у прибора — ПОДСТРОКА имени.
    «broadcast» ловит ещё и read-broadcasts.py: формы СОСЕДА делали вид, что механизм
    судится, и молчание прибора о самом broadcast.py (форм которого в памяти нет вовсе)
    засчитывалось в «🔴 СЛЕП». Оба «слепых» вердикта 28.08 оказались НЕ дефектом прибора,
    а ложным красным самой приёмки — класс «проверка срабатывает не по своей причине».
    ⚖️ Зеркальная половина того же: краснота СОСЕДА по подстроке засчитывалась за
    «✅ увидел» — приёмка хвалила прибор за чужую находку. Обе половины лечит один
    отбор: имя механизма — ПЕРВОЕ слово показанной формы, и оно должно совпасть ТОЧНО.

    → {"ok": [...], "red": [...], "skip": [...]} — показанные формы этого механизма.
    """
    итог = {"ok": [], "red": [], "skip": []}
    for line in вывод.splitlines():
        for знак, ключ in (("✅", "ok"), ("\U0001f534", "red"), ("⚠️", "skip")):
            if not line.startswith(знак):
                continue
            показ = line[len(знак):].strip()
            if показ.split(" ", 1)[0] == имя:
                итог[ключ].append(показ)
    return итог


def main() -> int:
    ok = True
    if not TOOL.exists():
        sys.exit(f"⛔ НЕ ЗАПУСТИЛАСЬ: инструмента нет — {TOOL}")

    # ── ① контроль ────────────────────────────────────────────────────────────
    d, scripts, db = sandbox()
