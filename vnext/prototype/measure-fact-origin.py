# -*- coding: utf-8 -*-
r"""measure-fact-origin.py — ЗАМЕР к идее 2.1 «замер или пересказ у факта».

Вопрос замера, до всякого кода признака: какие КОЛИЧЕСТВЕННЫЕ утверждения живут в телах
слепков ролей, и несут ли они рядом дату/источник замера.

Почему предмет — ЧИСЛА. Оплаченные случаи класса (все — числа):
    «guard-all — 11 проверок» в слепке, когда их 13 (найдено guard-stale-commands)
    «схема v2» при v3, «проверок было 11, стало 12» — моя же секция §3, 08.08
    «⇒ 8 ролей» при девяти — сосед-контур, 7 недель
    «ролей 7» — канон уже запрещает держать ЭТО число текстом
Число выглядит точным, поэтому ему верят сильнее прозы — и протухает оно молча.

⛔ Это ЗАМЕР, не сторож: ничего не красит, только считает и показывает. Форма признака
выбирается ПОСЛЕ него — «формы сужены замером, а не сочинены» (@COORD, вчера).
"""
import re
import sqlite3
import sys
from pathlib import Path
import mezo_paths  # пути машины выводятся, не впечатаны (#153)

DB = mezo_paths.live_db()

# Количественное утверждение О КОНТУРЕ: слово-предмет + число (или число + слово).
# Слова взяты из живого словаря контура, а не из головы: роли, проверки, приёмки, шаги,
# правила, карточки, записки, скрипты, механизмы, файлы, случаи, секции.
SUBJECT = (r"рол[ьи е й]{0,2}|провер[а-я]+|гард[а-я]*|приёмк[а-я]*|укус[а-я]*|шаг[а-я]*|"
           r"правил[а-я]*|карточ[а-я]+|запис[оа]к|скрипт[а-я]*|механизм[а-я]*|файл[а-я]*|"
           r"случа[а-я]+|секци[а-я]+|таблиц[а-я]*|наход[оа]к")
NUM = r"\b\d{1,4}\b"
FACT = re.compile(rf"(?:({SUBJECT})\D{{0,12}}({NUM})|({NUM})\s{{0,3}}({SUBJECT}))", re.I)

# Приметы «рядом есть замер»: дата/время, слово замера, источник-команда.
MEASURED = re.compile(
    r"20\d\d-\d\d-\d\d|\d\d:\d\d|замер|перемер|прогон|запрос(?:ом)?\s+к|печатает|"
    r"спроси|SELECT|python |собрано|na\s|на\s+\d\d\.\d\d", re.I)
# Приметы «это НЕ утверждение о текущем состоянии»: история/надгробие/цитата/запрет держать
NOT_CLAIM = re.compile(
    r"⚰️|ОТОЗВАН|истори|был[оаи]?\b|прежн|летопис|не держ|не пиш|НЕ БЕРИ|запрещ|"
    r"#\d|v\d|:\d\d|Ш\d|R\d|№|F\d|Э-", re.I)


def main() -> int:
    conn = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
    rows = conn.execute("SELECT role, section, body FROM phoenix ORDER BY role, section").fetchall()
    if not rows:
        print("⛔ слепков нет — мерить нечего (это не «чисто»)")
        return 2

    total = marked = unmarked = excluded = 0
    per_role = {}
    samples_unmarked = []
    for role, section, body in rows:
        for i, line in enumerate((body or "").splitlines(), 1):
            for m in FACT.finditer(line):
                total += 1
                if NOT_CLAIM.search(line):
                    excluded += 1
                    continue
                if MEASURED.search(line):
                    marked += 1
                else:
                    unmarked += 1
                    per_role[role] = per_role.get(role, 0) + 1
                    if len(samples_unmarked) < 25:
                        samples_unmarked.append((role, section, i, line.strip()[:110]))
                break   # одна строка — один факт в счёте, иначе плотная строка удвоит счёт

    print("📏 ЗАМЕР «замер или пересказ» по телам слепков (phoenix, все роли и секции)")
    print(f"   количественных строк всего .... {total}")
    print(f"   исключено (история/ссылки) .... {excluded}")
    print(f"   с приметой замера рядом ....... {marked}")
    print(f"   🔴 ГОЛОЕ ЧИСЛО-УТВЕРЖДЕНИЕ ..... {unmarked}")
    print(f"   по ролям: " + " · ".join(f"{r} {n}" for r, n in sorted(per_role.items())))
    print("\n   образцы голых (роль · секция · строка):")
    for role, sec, i, line in samples_unmarked:
        print(f"   [{role}·{sec}:{i}] {line}")
    print("\n⚖️ ГРАНИЦА ЗАМЕРА: приметы — регекспы, а не понимание; «исключено» может прятать"
          "\n   настоящие утверждения, «с приметой» — пересказ чужого замера. Числа для"
          "\n   ВЫБОРА ФОРМЫ признака, не для приговора ролям.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
