def printing_helpers(tree: ast.AST) -> set[str]:
    """Имена функций модуля, которые печатают собственный параметр.

    Контроль обратного: функция, которая параметры только копит или возвращает, сюда
    НЕ попадает — иначе признак начнёт считать показываемым любой текст в любом вызове.
    """
    names: set[str] = set()
    for fn in ast.walk(tree):
        if not isinstance(fn, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        params = {a.arg for a in list(fn.args.args) + list(fn.args.kwonlyargs)}
        if not params:
            continue
        for n in ast.walk(fn):
            if not (isinstance(n, ast.Call) and getattr(n.func, "id", None) == "print"):
                continue
            if any(isinstance(s, ast.Name) and s.id in params for s in ast.walk(n)):
                names.add(fn.name)
                break
    return names


def доезжают_до_человека(tree: ast.AST, helpers: set[str]) -> set[str]:
    """Имена, чьё СОДЕРЖИМОЕ человек в итоге прочтёт — выведено из кода, не из списка имён.

    🪤 ПЯТЫЙ ПУТЬ ДОСТАВКИ, найден @COORD 2026-09-06 (карточка #577) на живом инструменте:
    строки копились в `red`, потом распаковывались циклом и печатались — и прежнее слово
    доезжало до человека невидимо для этой приёмки.
    ⚖️ ПЕРЕМЕРЕНО МНОЮ ДО ПРАВКИ, И ДИАГНОЗ ВЫШЕЛ ДРУГИМ. Не кортеж делал текст невидимым:
    тот же кортеж в приёмнике с именем `out` виден (проба B), а голая строка в приёмнике
    `red` — нет. Слепым признак делало ИМЯ: перечень COLLECTORS закрыт восемью словами.
    🎯 Значит класс тот же, что уже лечили у печатающих помощников: «проверяем перечисленное».
    Список имён нельзя пополнить настолько, чтобы он перестал быть списком, — поэтому
    приёмник здесь ВЫВОДИТСЯ: имя показываемое, если его содержимое доезжает до печати.

    Два пути, оба обязательны:
      ① имя стои́т в аргументах печатающего вызова: print(x) · print(sep.join(x)) · print(*x)
      ② цикл идёт ПО имени, а в теле печатается то, что из него распаковано
    ⛔ ГРАНИЦА, НАЗВАННАЯ ПРЯМО: имя, чьё содержимое уезжает НЕ к человеку (в базу, в файл,
       в возврат функции), приёмником НЕ считается — это и проверяет встречный случай.
       Возврат наружу не прослеживается вовсе: пришлось бы идти за вызывающим, а он в другом
       файле. Значит слепота у признака ОСТАЁТСЯ, и она здесь названа, а не умолчана.
    """
    def печатающий(n: ast.AST) -> bool:
        if not isinstance(n, ast.Call):
            return False
        nm = getattr(n.func, "id", None) or getattr(n.func, "attr", None)
        return nm in SHOWN_CALLS or nm in helpers

    имена: set[str] = set()
    for n in ast.walk(tree):
        if печатающий(n):
            for arg in list(n.args) + [kw.value for kw in n.keywords]:
                имена.update(s.id for s in ast.walk(arg) if isinstance(s, ast.Name))
        if isinstance(n, (ast.For, ast.AsyncFor)):
            распакованные = {t.id for t in ast.walk(n.target) if isinstance(t, ast.Name)}
            источники = {s.id for s in ast.walk(n.iter) if isinstance(s, ast.Name)}
            if not (распакованные and источники):
                continue
            for узел in ast.walk(n):
                if not печатающий(узел):
                    continue
                видимые = list(узел.args) + [kw.value for kw in узел.keywords]
                if any(isinstance(s, ast.Name) and s.id in распакованные
                       for a in видимые for s in ast.walk(a)):
                    имена.update(источники)
                    break
    return имена


def case(title, ok, detail, differ=False):
    global CASES, DIFFER
    CASES += 1
    DIFFER += bool(differ)
    print(f"{'✅' if ok else '🔴'} {title}")
    print(f"   {detail}")
    return ok


def shown_lines(src: str) -> set[int]:
    """Номера строк, где стоит ПОКАЗЫВАЕМЫЙ роли текст (print / --help / описания)."""
    try:
        tree = ast.parse(src)
    except SyntaxError:
        return set()
    out: set[int] = set()
    helpers = printing_helpers(tree)
    # Приёмники: восемь имён списком (как было) ПЛЮС выведенные из кода этого файла.
    # Список оставлен намеренно: он ловит имя, чей путь к человеку идёт через возврат
    # наружу, — а туда разбор не заходит (граница названа в доезжают_до_человека).
    приёмники = COLLECTORS | доезжают_до_человека(tree, helpers)
    показанные_имена: set[str] = set()
    for n in ast.walk(tree):
        if isinstance(n, ast.Call):
            nm = getattr(n.func, "id", None) or getattr(n.func, "attr", None)
            shown = nm in SHOWN_CALLS or nm in helpers
            if nm in ("append", "extend") and isinstance(n.func, ast.Attribute):
                recv = getattr(n.func.value, "id", None)
                shown = shown or (recv in приёмники)
            if shown:
                for arg in list(n.args) + [kw.value for kw in n.keywords]:
                    out.update(_own_text(arg))
                    показанные_имена.update(_own_names(arg))
    # ═══ Карточка #416: ЧЕТВЁРТЫЙ путь доставки текста человеку — через переменную.
    # `дела = "…(пайка)"` затем `print(f"…{дела}…")`: человек видит обе формы одинаково,
    # признак видел только явную. Опыт TAXO: то же слово в явном print — 1 находка,
    # присвоенное переменной — 0 на тех же файлах. Судим ЛИТЕРАЛ ПРИСВОЕНИЯ имени,
    # которое попадает в показываемый узел; само имя (граница ⑩) как не красилось,
    # так и не красится — судится значение, которое человек прочтёт.
    if показанные_имена:
        for n in ast.walk(tree):
            if isinstance(n, ast.Assign):
                цели, значение = n.targets, n.value
            elif isinstance(n, (ast.AnnAssign, ast.AugAssign)) and n.value is not None:
                цели, значение = [n.target], n.value
            else:
                continue
            if any(isinstance(t, ast.Name) and t.id in показанные_имена for t in цели):
                out.update(_own_text(значение))
    return out


def _own_names(node: ast.AST) -> set[str]:
    """Имена переменных, чьи ЗНАЧЕНИЯ человек увидит в этом вызове (карточка #416).

    Граница ТА ЖЕ, что у _own_text: во вложенный вызов не заходим — его аргументы
    читает испытуемый механизм, а не человек (случай ⑨), и присвоения таких имён
    судить нельзя — это подопытные данные, а не показываемый текст.
    """
    имена: set[str] = set()
    if isinstance(node, ast.Call):
        return имена
    if isinstance(node, ast.Name):
        имена.add(node.id)
    for child in ast.iter_child_nodes(node):
        имена.update(_own_names(child))
    return имена


def _own_text(node: ast.AST) -> set[int]:
    """Строки СОБСТВЕННОГО текста этого вызова — без данных, отданных другому вызову.

    🪤 НАЙДЕНО НА СЕБЕ 2026-08-20. Первая редакция брала весь обход внутрь печатающего
    вызова — и красила ПОДОПЫТНЫЕ строки приёмок: текст, который приёмка подкладывает
    проверяемому механизму, стои́т внутри того же выражения, что и заголовок случая.
    Человек его не читает — его читает испытуемый. Признак, требующий переписать
    подопытные данные, толкает подгонять текст под проверку и ломать саму приёмку.
    ⇒ внутрь вложенного вызова НЕ заходим: это уже чужой текст, не наш показываемый.
    """
    строки: set[int] = set()
    if isinstance(node, ast.Call):
        return строки
    # Только ТЕКСТ. Число или True, стоящие рядом, текстом не являются — а помечали строку
    # показываемой наравне со словами: из-за этого строка с подопытными данными и числом
    # сравнения объявлялась читаемой человеком (поймано случаем ⑨ этой же приёмки).
    if isinstance(node, ast.JoinedStr) or (isinstance(node, ast.Constant)
                                           and isinstance(node.value, str)):
        # 🪤 НАЙДЕНО @COORD 2026-08-27 (карточка #304): здесь стояло `строки.add(node.lineno)` —
        # то есть ОДНА строка, где текст НАЧИНАЕТСЯ. Соседние литералы Python склеивает в один
        # узел ещё при разборе, поэтому продолжение отказа или справки для признака не
        # существовало вовсе. Замер на живом хранителе памяти: строку 341 видит, 342-343 нет;
        # 187-188 видит, 189-190 нет. И в невидимом стои́т текст ОТКАЗА и СПРАВКА ключа —
        # то, что роль читает глазами чаще всего.
        # ⚡ Класс: ЕДИНИЦА СУЖДЕНИЯ МЕНЬШЕ ЕДИНИЦЫ ЧТЕНИЯ. Человек читает абзац, признак
        # читал его первую строку и говорил «чисто» — и был по построению зелёным ровно там,
        # где текста больше всего. Лечится границей узла, а не списком мест.
        строки.update(range(node.lineno, (node.end_lineno or node.lineno) + 1))
    for child in ast.iter_child_nodes(node):
        строки.update(_own_text(child))
    return строки


