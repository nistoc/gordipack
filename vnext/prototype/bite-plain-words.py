    globals()["INVENTED"] = re.compile(
        "|".join(pat for pat, _ in PATTERN_AND_PROBES[:-1]), re.I)
    try:
        (d14 / "probe_pat.py").write_text(
            '# -*- coding: utf-8 -*-\n'
            'def main():\n'
            '    print("итог: паёк прогона")\n',
            encoding="utf-8")
        blind_scan, _, _ = scan(d14)
    finally:
        globals()["INVENTED"] = whole_pattern
        (d14 / "probe_pat.py").unlink()
    ok &= case("⑮-бис ОБРАТНЫЙ ХОД: часть волны ослеплена → её проба не ловится",
               not any("probe_pat.py" in h for h in blind_scan),
               "у ослеплённого образца проба части волны молчит — значит на целом её "
               "ловит ИМЕННО эта часть, и ослепление уронит случай ⑮ (прежде — 0 из 15)",
               differ=True)
    mezo_stand.release(d14)

    # ── ⑤ КОНТРОЛЬ: ПРИЁМКА ВООБЩЕ СМОТРИТ ───────────────────────────────────
    ok &= case("⑤ контроль: приёмке было на что смотреть",
               f1 + f2 > 30 and l1 + l2 > 500,
               f"файлов {f1 + f2}, показываемых строк {l1 + l2} — без этого случая зелёный "
               f"мог бы означать «ничего не нашлось, потому что ничего не искали»")

    print()
    if ok:
        print(f"✅ ОБЩЕПОНЯТНЫЕ СЛОВА — ПРИНЯТО — случаев {CASES}, различающих {DIFFER}")
        return 0
    print(f"🔴 НЕ ПРИНЯТО — случаев {CASES}, различающих {DIFFER}")
    return 1


