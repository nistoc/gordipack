#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
ПРИЁМКА проверки «правило без прослеживаемого основания» (check-rule-basis.py).

У каждого различающего случая — контрольное слепое правило: если проверка не нашла ЕГО,
её молчание про здоровое ничего не доказывает.
> Молчание засчитывается за верный ответ ТОЛЬКО когда доказано, что программа не молчит вообще.

⛔ ЧИСЛО СЛУЧАЕВ ЗДЕСЬ НЕ ПИШЕТСЯ СЛОВОМ — его печатает прогон. Прежняя строка «шесть
случаев, четыре различающих» пережила добавление седьмого и восьмого и соврала в зелёном выводе.

  ① слепое правило (ни слова, ни ссылки)          → найти
  ② слово владельца с датой рядом                 → не считать слепым
  ③ ссылка на записку без слова                   → не считать слепым (ГДЕ названо)
  ④ дата ЕСТЬ, но далеко от слова о решении       → дату не засчитывать как «когда»
  ⑤ дата от ЗАМЕРА, слова о решении нет вовсе     → правило слепое, дата не спасает
  ⑥ пустой свод правил                            → сказать «сверять нечего», а не «чисто»
  ⑦ основание — замер КОЛЛЕГИ, не слово владельца → не считать слепым
  ⑧ роль упомянута ПРОЦЕДУРНО, решение ей не приписано → основанием НЕ считать

⛔ Живой базы не касается: своя временная база в песочнице.
"""
import os
import re
import sqlite3
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
CHECK = os.path.join(HERE, "check-rule-basis.py")

BLIND = ("контрольное слепое правило", "Просто текст правила без всякого основания.")


def build(path: str, rules):
    con = sqlite3.connect(path)
    con.execute("""CREATE TABLE rules (id INTEGER PRIMARY KEY, rule_key TEXT, body TEXT,
                   locked_by TEXT, version INTEGER, created_at TEXT, updated_at TEXT)""")
    for i, (key, body, lock) in enumerate(rules, 1):
        con.execute("INSERT INTO rules (id, rule_key, body, locked_by, version)"
                    " VALUES (?,?,?,?,1)", (i, key, body, lock))
    con.commit()
    con.close()


def run(path: str, extra=()):
    r = subprocess.run([sys.executable, CHECK, "--db", path, *extra],
                       capture_output=True, text=True, encoding="utf-8")
    return (r.stdout or "") + (r.stderr or ""), r.returncode


def num(text: str, pattern: str):
    m = re.search(pattern, text)
    return int(m.group(1)) if m else None


CASES = 0
DIFFERENTIATING = 0


def case(title: str, verdict: bool, detail: str, differ: bool = False) -> bool:
    """🪤 Число случаев СЧИТАЕТСЯ, а не пишется словом в подписи.

    Подпись «шесть случаев, четыре различающих» пережила добавление седьмого и восьмого
    и соврала в ЗЕЛЁНОМ выводе. Тот же класс я чинил час назад в соседней приёмке —
    и починил там ЭКЗЕМПЛЯР, а не ОБРАЗЕЦ, поэтому он вернулся в другом файле.
    """
    global CASES, DIFFERENTIATING
    CASES += 1
    DIFFERENTIATING += bool(differ)
    print(f"{'✅' if verdict else '🔴'} {title}")
    print(f"   {detail}")
    return verdict


def with_control(tmp: str, name: str, rule, title: str, expect_blind: int) -> bool:
    """Испытуемое правило + КОНТРОЛЬНОЕ слепое, которое обязано найтись всегда."""
    path = os.path.join(tmp, f"{name}.db")
    build(path, [rule, (BLIND[0], BLIND[1], "coord")])
    out, _ = run(path)
    blind = num(out, r"ОСНОВАНИЕ НЕ НАЙТИ ВОВСЕ \.+ (\d+)")
    control_found = blind is not None and blind >= 1
    ok = blind == expect_blind and control_found
    return case(f"{name} {title}", ok,
                f"слепых найдено {blind}, ждали {expect_blind} · "
                f"контроль {'найден' if control_found else 'НЕ НАЙДЕН — случай не зачитывается'}",
                differ=True)


def main() -> int:
    tmp = tempfile.mkdtemp(prefix="bite-rule-basis-")
    ok = True

    # ① слепое находится
    path = os.path.join(tmp, "a.db")
    build(path, [("совсем-слепое", "Текст правила. Основания нет.", "owner")])
    out, _ = run(path)
    ok &= case("① слепое правило найдено, и замок владельца назван отдельно",
               num(out, r"ОСНОВАНИЕ НЕ НАЙТИ ВОВСЕ \.+ (\d+)") == 1
               and num(out, r"из них с замком владельца \.+ (\d+)") == 1,
               "правило без слова и без ссылки, замок owner → обязано попасть в оба счёта")

    # ②③ различающие: основание названо
    ok &= with_control(
        tmp, "②", ("со-словом",
                   "Слово владельца 2026-08-07 10:20 UTC: «делаем так». Далее текст.", "owner"),
        "слово владельца с датой рядом слепым НЕ считается", 1)

    ok &= with_control(
        tmp, "③", ("со-ссылкой",
                   "Основание объявлено запиской #3291, разбор там же.", "coord"),
        "ссылка на записку слепым НЕ считается", 1)

    # ⑪ ПАДЕЖ И ЗАМОК ИМЕНЕМ. Ровно та форма, которой в живом своде записаны ПЯТЬ правил
    # разом. До 08.08 проверка её не видела («владелец» ≠ «владельцем») и объявляла эти
    # правила слепыми — я едва не пошёл спрашивать основание того, что уже записано.
    ok &= with_control(
        tmp, "⑪", ("залочено-владельцем",
                   "Q1.2 (залочено владельцем 2026-07-02). Гейт перед коммитом: зелёные тесты.",
                   "owner"),
        "«залочено владельцем <дата>» слепым НЕ считается — это и КТО, и КОГДА", 1)

    # ⑫ ВСТРЕЧНЫЙ К ⑪: имя роли в тексте БЕЗ приписки решения основанием НЕ становится.
    # Без этого случая починка ⑪ сделала бы проверку беззубой: роли упоминаются в правилах
    # постоянно по делу процедуры («правку вносит COORD», «спроси владельца»).
    ok &= with_control(
        tmp, "⑫", ("роль-упомянута-по-делу",
                   "Перед разрушающим шагом спроси владельца. Правку в базу вносит дежурный.",
                   "owner"),
        "имя роли БЕЗ приписки решения основанием НЕ становится (встречный к ⑪)", 2)

    # ④ дата далеко от слова — «когда» не засчитывается, но правило не слепое (слово есть)
    far = ("далёкая-дата",
           "Слово владельца: делаем так." + (" текст." * 60) + " Замер сделан 2026-08-07.",
           "owner")
    path = os.path.join(tmp, "d.db")
    build(path, [far, (BLIND[0], BLIND[1], "coord")])
    out, _ = run(path)
    ok &= case("④ дата ДАЛЕКО от слова о решении не засчитывается как «когда»",
               # 🪤 Ищем по УСТОЙЧИВОМУ куску строки, а не по всей формулировке: полное
               # название «дата рядом со словом» я переименовал в «рядом с припиской»,
               # и приёмка покраснела на ИСПРАВНОМ коде. Приёмка, привязанная к точной
               # формулировке вывода, ломается от правки текста — и учит, что сломан код.
               num(out, r"названо КОГДА[^.]*\.+ (\d+)") == 0
               and num(out, r"ОСНОВАНИЕ НЕ НАЙТИ ВОВСЕ \.+ (\d+)") == 1,
               "дата от ЗАМЕРА в 400 знаках от слова → «когда» не названо, "
               "контрольное слепое при этом найдено", differ=True)

    # ⑤ дата есть, слова о решении нет вовсе → слепое
    ok &= with_control(
        tmp, "⑤", ("только-дата",
                   "Замер 2026-08-07 показал 44 правила. Поэтому пишем так.", "owner"),
        "одна лишь дата основанием не считается", 2)

    # ⑦ основание — ЗАМЕР КОЛЛЕГИ, а не слово владельца. Случай `dowry-facts-carry-source`
    # (07.08 17:31 UTC): рабочая норма роли, намеренно НЕ под замком владельца, основание
    # выписано полностью. Первая редакция проверки объявляла такое слепым — то есть
    # отвергала правило, написанное по её же требованию.
    ok &= with_control(
        tmp, "⑦", ("норма-роли",
                   "ОСНОВАНИЕ (кто · когда · где): замер @RCC, 2026-08-07 17:26 UTC, "
                   "записка #3345. Внесено рукой COORD. ⛔ Замком владельца НЕ помечено: "
                   "это рабочая норма роли, а не решение владельца.", "coord"),
        "основание от КОЛЛЕГИ, а не от владельца, слепым не считается", 1)

    # ⑧ РАЗЛИЧАЮЩИЙ, и он главный: роль УПОМЯНУТА, но решение ей НЕ ПРИПИСАНО.
    # Без этого случая правка ⑦ сделала бы проверку беззубой: роли поминают в каждом
    # втором правиле по делу процедуры, и любое упоминание сошло бы за основание.
    ok &= with_control(
        tmp, "⑧", ("процедура",
                   "Правку в свод вносит COORD, прогон гарда обязателен, а STUD и CORE "
                   "получают уведомление. Порядок действий описан ниже.", "coord"),
        "роль упомянута ПРОЦЕДУРНО — основанием это НЕ считается", 2)

    # ⑨ НАДГРОБИЕ: отозванное правило считается ОТДЕЛЬНО и его основание — сам отзыв.
    # Пять надгробий свода были объявлены слепыми, хотя каждое несёт «ОТОЗВАНО владельцем
    # 2026-07-18 14:09 UTC (живое слово, чат COORD)» — то есть кто, когда и где разом.
    # Проверка обвинила ровно те записи, которые сделаны образцово.
    path = os.path.join(tmp, "g.db")
    build(path, [("надгробие",
                  "⛔ ОТОЗВАНО владельцем 2026-07-18 14:09 UTC (живое слово, чат COORD). "
                  "НЕ ИСПОЛНЯТЬ. Ниже — что требовала прежняя редакция, для истории.", "owner"),
                 (BLIND[0], BLIND[1], "coord")])
    out, _ = run(path)
    ok &= case("⑨ надгробие: отзыв — это основание, и живым оно не считается",
               num(out, r"из них надгробий \(отозваны\) \.+ (\d+)") == 1
               and num(out, r"✅ ЖИВЫХ ПРАВИЛ \.+ (\d+)") == 1
               and num(out, r"ОСНОВАНИЕ НЕ НАЙТИ ВОВСЕ \.+ (\d+)") == 1,
               "надгробие отделено от живых, контрольное слепое найдено, "
               "а сам отзыв за отсутствие основания НЕ засчитан", differ=True)

    # ⑩ РАЗЛИЧАЮЩИЙ к ⑨: надгробие БЕЗ основания отзыва обязано быть названо отдельно.
    # Иначе правка ⑨ прощала бы любое «⛔ ОТОЗВАНО» без указания, кто и когда отменил.
    path = os.path.join(tmp, "h.db")
    build(path, [("надгробие-без-основания",
                  "⛔ ОТОЗВАНО. Не исполнять. Причина не названа.", "owner")])
    out, _ = run(path)
    ok &= case("⑩ надгробие БЕЗ основания отзыва названо отдельной строкой",
               num(out, r"надгробий без основания отзыва \.+ (\d+)") == 1,
               "«отозвано» без указания кто и когда — это не основание, а объявление; "
               "молча прощать его нельзя", differ=True)

    # ⑥ пустой свод
    path = os.path.join(tmp, "f.db")
    build(path, [])
    out, code = run(path)
    ok &= case("⑥ пустой свод: сказано «сверять нечего», а не «чисто»",
               "сверять нечего" in out and code == 1,
               "ноль правил обязан читаться как отказ мерить, а не как чистота", differ=True)

    print()
    print(f"✅ ПРОВЕРКА ПРИНЯТА — случаев {CASES}, различающих {DIFFERENTIATING}, "
          "у каждого различающего контроль" if ok
          else "🔴 ПРОВЕРКА НЕ ПРИНЯТА — числа из неё нести нельзя")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
