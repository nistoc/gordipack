# -*- coding: utf-8 -*-
r"""bite-copy-tool-neighbours.py — приёмка карточки #572: стенд привозит СОСЕДЕЙ инструмента.

═══ ЧТО СУДИМ
Помощник стендов научился копировать инструмент вместе с файлами-соседями, без которых
он не запускается (mezo_stand.copy_tool / neighbours_of). Находка @COORD, сделанная
внутри приёмки карточки #571: копия инструмента упала с «нет модуля dryrun» — то есть
инструмент, вынесенный ОДНИМ файлом, не нашёл соседей рядом с собой.

═══ ПОЧЕМУ ВСТРЕЧНЫЙ СЛУЧАЙ ЗДЕСЬ ОБЯЗАТЕЛЕН
Случай «скопировали и запустилось» зелен и без починки — если инструмент случайно
оказался из тех, кто едет поодиночке. Поэтому случай ② копирует ТОТ ЖЕ файл ГОЛЫМ
способом на ТОТ ЖЕ стенд и требует падения: разницу даёт починка, а не выбор инструмента.

═══ ОЖИДАНИЯ ПОРЧИ — НАЗВАНЫ ДО ПРОГОНА, И ДВА ИЗ ТРЁХ НЕ ПОДТВЕРДИЛИСЬ
Записано как было, вместе с тем, чем всё кончилось: ожидание, подогнанное задним числом
под результат, ничего не проверяет.
    П1 обход на ОДИН шаг (не транзитивный)
       ждали ① и ④ ......... вышло ТОЛЬКО ④. Ожидание по ① было НЕВЕРНЫМ: для запуска
                             с --help хватает соседей ПЕРВОГО шага, глубина нужна
                             дальше. Различающим остаётся ④
    П2 соседей не копируем вовсе
       ждали ① и ④ ......... вышло ① и ③, а ④ в первой редакции остался ЗЕЛЁНЫМ:
                             он судил СПИСОК соседей, а не привезённые файлы.
                             Случай исправлен — теперь судит результат, и краснеет
    П3 соседом считаем любой импорт, даже когда файла рядом нет
       ждали ① ............. вышло ПАДЕНИЕ разбора (KeyError на 'argparse') до печати
                             случаев. Поломка не проехала — но приёмка её не ПОКРАСИЛА,
                             а упала. Разница названа, потому что для читателя вывода
                             «упало» и «покрашено» — разные вещи

═══ ГРАНИЦА, НАЗВАНА ПРЯМО
Приёмка судит НОВЫЙ способ копирования. Она НЕ судит 62 уже написанные приёмки,
копирующие файл своей рукой: там отказ остался прежним, и это записано в карточке #572
как незакрытая половина, а не как сделанное.
"""
import ast
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import mezo_paths  # noqa: E402
import mezo_stand  # noqa: E402

СКРИПТЫ = Path(mezo_paths.live_scripts(__file__))
ИНСТРУМЕНТЫ = Path(__file__).resolve().parent

# Инструмент с ДЛИННОЙ цепочкой соседей: сам подключает одних, а те тянут других.
ЦЕПОЧКА = СКРИПТЫ / "read-messages.py"

итог: list[tuple[str, bool, str]] = []


def случай(имя: str, ок: bool, слово: str) -> None:
    итог.append((имя, ок, слово))
    print(f"{'✅' if ок else '🔴'} {имя}: {слово}")


def запустить(файл: Path) -> tuple[int, str]:
    """Позвать инструмент с --help ИЗ ЕГО каталога. Код и первая строка ошибки."""
    r = subprocess.run([sys.executable, str(файл), "--help"],
                       capture_output=True, text=True, encoding="utf-8",
                       cwd=str(файл.parent), timeout=120)
    хвост = (r.stderr or "").strip().splitlines()
    return r.returncode, (хвост[-1] if хвост else "")


def main() -> int:
    стенд = Path(tempfile.mkdtemp(prefix="bite-copy-neighbours-"))
    mezo_stand.release(стенд)

    # ── ① ЦЕЛИКОМ: инструмент с цепочкой соседей уезжает и ЗАПУСКАЕТСЯ на стенде
    полный = стенд / "полный"
    копия = mezo_stand.copy_tool(ЦЕПОЧКА, полный)
    код, ошибка = запустить(копия)
    случай("① инструмент с цепочкой соседей запускается на стенде",
           код == 0,
           "код 0 — соседи приехали" if код == 0 else f"код {код}: {ошибка}")

    # ── ② ВСТРЕЧНЫЙ: тот же файл голым копированием — падает
    голый = стенд / "голый"
    голый.mkdir()
    shutil.copy2(ЦЕПОЧКА, голый / ЦЕПОЧКА.name)
    код2, ошибка2 = запустить(голый / ЦЕПОЧКА.name)
    случай("② встречный: голая копия того же файла падает",
           код2 != 0 and "modul" in ошибка2.lower(),
           f"код {код2}: {ошибка2}" if код2 != 0 else "🔴 запустилась БЕЗ соседей — "
           "значит случай ① ничего не доказывает")

    # ── ③ НЕ ТАЩИТ ЛИШНЕГО: в стенде ровно инструмент и его соседи, ни файлом больше
    соседи = mezo_stand.neighbours_of(ЦЕПОЧКА)
    привезено = sorted(p.name for p in полный.glob("*.py"))
    ожидалось = sorted([ЦЕПОЧКА.name] + [p.name for p in соседи])
    случай("③ привезено ровно нужное, без лишних файлов",
           привезено == ожидалось,
           f"{len(привезено)} файлов" if привезено == ожидалось
           else f"привезено {привезено}, ожидалось {ожидалось}")

    # ── ④ ТРАНЗИТИВНОСТЬ: среди привезённых есть тот, кого САМ инструмент не подключает
    прямые = set()
    for узел in ast.walk(ast.parse(ЦЕПОЧКА.read_text(encoding="utf-8"))):
        if isinstance(узел, ast.Import):
            прямые.update(a.name.split(".")[0] for a in узел.names)
        elif isinstance(узел, ast.ImportFrom) and узел.level == 0 and узел.module:
            прямые.add(узел.module.split(".")[0])
    # ⚠️ Судим ПРИВЕЗЁННЫЕ ФАЙЛЫ, а не список из neighbours_of. Первая редакция судила
    # список — и порча «соседей не копируем вовсе» оставляла случай ЗЕЛЁНЫМ: список-то
    # вычислялся верно, просто по нему никто не ехал. Проверка результата, а не намерения.
    вторым_шагом = sorted(п.name for п in полный.glob("*.py")
                          if п.stem not in прямые and п.name != ЦЕПОЧКА.name)
    случай("④ на стенд ПРИВЕЗЕНЫ соседи второго шага, а не только прямые",
           bool(вторым_шагом),
           f"через посредника приехали: {', '.join(вторым_шагом)}" if вторым_шагом
           else "ни одного соседа второго шага — обход остановился на первом либо не ехал вовсе")

    # ── ⑤ ПОВТОРНЫЙ ВЫЗОВ: не падает и не плодит копий
    было = len(list(полный.glob("*.py")))
    mezo_stand.copy_tool(ЦЕПОЧКА, полный)
    стало = len(list(полный.glob("*.py")))
    случай("⑤ повторный вызов не падает и не плодит файлов",
           стало == было, f"{было} → {стало}")

    # ── ⑥ ИНСТРУМЕНТ БЕЗ СОСЕДЕЙ: приезжает один, и это НЕ ошибка
    одиночка = None
    for p in sorted(ИНСТРУМЕНТЫ.glob("*.py")):
        if p.stem != "mezo_paths" and not mezo_stand.neighbours_of(p):
            одиночка = p
            break
    if одиночка is None:
        случай("⑥ инструмент без соседей приезжает один", False,
               "не нашлось ни одного инструмента без соседей — случай не проверен")
    else:
        соло = стенд / "соло"
        mezo_stand.copy_tool(одиночка, соло)
        файлы = list(соло.glob("*.py"))
        случай("⑥ инструмент без соседей приезжает один",
               len(файлы) == 1 and файлы[0].name == одиночка.name,
               f"{одиночка.name}: привезён 1 файл" if len(файлы) == 1
               else f"привезено {len(файлы)}")

    # ── ⑦ НЕРАЗБИРАЕМЫЙ ФАЙЛ не роняет разбор соседей
    кривой = стенд / "кривой.py"
    кривой.write_text("def f(:\n    пусть будет синтаксическая ошибка\n", encoding="utf-8")
    try:
        mezo_stand.neighbours_of(кривой)
        случай("⑦ неразбираемый файл не роняет разбор", True, "вернулся пустой список")
    except Exception as e:                                  # noqa: BLE001
        случай("⑦ неразбираемый файл не роняет разбор", False, f"упало: {type(e).__name__}: {e}")

    красных = [и for и, ок, _ in итог if not ок]
    print("\n" + "=" * 78)
    print(f"РАЗЛИЧАЮЩИХ СЛУЧАЕВ {len(итог)}, из них ДОКАЗАНО ПОРЧЕЙ 3 (① ③ ④)")
    print("⚖️ ② доказан не порчей, а СОБОЙ: он и есть встречный случай — голая копия")
    print("   того же файла на том же стенде падает, и это видно в его же выводе.")
    print("⚖️ ⑤ ⑥ ⑦ порчей не доказаны — это границы поведения, а не суть починки;")
    print("   названо, а не скрыто.")
    if красных:
        print(f"🔴 ПРОВАЛЕНО {len(красных)}: {' · '.join(красных)}")
        return 1
    print("✅ ВСЕ СЛУЧАИ ПРОЙДЕНЫ")
    return 0


if __name__ == "__main__":
    sys.exit(mezo_stand.finish(main()))
