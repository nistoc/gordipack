# 🎯 РОЛЬ НОМЕРА В ПРЕДЛОЖЕНИИ: ИСПРАВЛЯЕМОЕ или ПРЕДМЕТ РЕЧИ (карточка #520, TAXO 05.09)
#
# Класс, ради которого функция заведена, — тот же, что у всего модуля, но на шаг глубже.
# Модуль выше отвечает: «это РАЗГОВОР о форме или сама форма?» Здесь вопрос другой:
# строка ЕСТЬ поправка, слово поправки в ней настоящее, тема совпадает — и всё равно
# названный номер может быть не тем, что исправляют:
#     «ПОПРАВКА К #3055 … Это ВТОРОЙ раз за смену (первый — #2958)»
# Исправляется #3055. #2958 назван ПРИМЕРОМ — и гас вместе с ним, будучи живым дефектом.
#
# 📏 МАТЕРИАЛ, НА КОТОРОМ ВЫВЕДЕНО (замер TAXO 04.09 22:50 и 05.09 03:12 UTC, живая лента):
#     213 гашений всего · ДЕЙСТВУЮЩИХ (жертва впрямь дефектна) 19
#     из них ложных 4 ..... #2388 ⟸ #4622 · #2958 ⟸ #3056 · #3626 ⟸ #3858 · #4078 ⟸ #4086
#     настоящих 15 ........ все сохраняются, поимённо в приёмке bite-correction-target.py
# ⛔ ПОЧЕМУ НЕ ПО ТЕГУ И НЕ ПО СЛОВУ — обе догадки проверены и отвергнуты замером:
#     по тегу ... у ДВУХ ложных из четырёх тега `correction` нет вовсе
#     по слову .. слово «поправка» стои́т во ВСЕХ четырёх ложных и во всех настоящих
#   ⇒ различает не наличие слова, а СВЯЗЬ этого слова с номером.
#
# ⚖️ ГРАНИЦА, НАЗВАННАЯ СРАЗУ (правило ⑨ стандарта): это ПРИМЕТЫ ПАДЕЖА, а не разбор
# русского языка. Формы, на которых НЕ проверено, перечислены в приёмке отдельным списком —
# там же стоят встречные случаи с ДРУГИМ определением предмета. Сомневаешься — считай
# исправляемым: ложное гашение прячет живой дефект, а лишнее суждение лишь красит его.
СВЯЗКА_ОТОЖДЕСТВЛЕНИЯ = r"(?:—|–|--|\bбыл[аои]?\b|\bэто\b|\bесть\b|\bявляется\b)"
ПРЕДЛОГ_НАПРАВЛЕНИЯ = r"(?:\bко?\b|\bво?\b)"
ПРИТЯЖАТЕЛЬНОЕ = r"(?:\bмо[яейиюё]\w*|\bсво[яейиюё]\w*|\bнаш\w*)"
НОСИТЕЛЬ_НОМЕРА = r"(?:записк\w*|нот[аеуы]\w*|сообщени\w*)"
_ОДНОРОДНЫЙ = re.compile(r"#\d{2,6}\s*(?:и|,|/|·)\s*$")


def fix_target(unit: str, n: int, _глубина: int = 0) -> tuple:
    """Чем номер #n является В ЭТОЙ единице: ("исправляемое"|"ссылка", почему).

    «исправляемое» — строка говорит, что в #n неверно и как читать: её МОЖНО гасить.
    «ссылка» ....... #n назван примером, носителем поправки или предметом разбора:
                     гасить НЕЛЬЗЯ, иначе разговор о дефекте убирает сам дефект.
    """
    m = re.search(rf"#{n}\b", unit or "")
    if not m:
        return "исправляемое", "номера нет"          # не наше дело — судит вызывающий
    слева, справа = (unit or "")[:m.start()], (unit or "")[m.end():m.end() + 90]
    # слово-носитель («записке», «ноте») пропускаем: связь стои́т ПЕРЕД ним
    окно = re.sub(rf"\s*{НОСИТЕЛЬ_НОМЕРА}\s*$", " ", слева, flags=re.I)[-45:]

    # ① однородный член перечисления наследует роль соседа: «в моих записках #3427 и #3430»
    if _ОДНОРОДНЫЙ.search(слева) and _глубина < 6:
        сосед = int(re.findall(r"#(\d{2,6})", слева)[-1])
        роль, _ = fix_target(unit, сосед, _глубина + 1)
        return роль, f"перечисление, наследует от #{сосед}"

    # ② связка отождествления вплотную ⇒ номер ЕСТЬ то, о чём речь, а не адресат правки
    св = re.search(rf"{СВЯЗКА_ОТОЖДЕСТВЛЕНИЯ}\s*$", окно, re.I)
    if св:
        return "ссылка", f"связка «{св.group(0).strip()}» перед номером"

    # ③ направление К жертве или притяжательное при ней ⇒ её ИСПРАВЛЯЮТ
    if re.search(rf"{ПРЕДЛОГ_НАПРАВЛЕНИЯ}\s*(?:{ПРИТЯЖАТЕЛЬНОЕ}\s*)*(?:же\s*)?$", окно, re.I):
        return "исправляемое", "предлог направления"
    if re.search(rf"{ПРИТЯЖАТЕЛЬНОЕ}\s*$", окно, re.I):
        return "исправляемое", "притяжательное при носителе"

    # ④ номер-подлежащее без притяжательного, а справа через тире — ХАРАКТЕРИСТИКА его
    #    («записка #2388 (@STUD, 18.07) — НАСТОЯЩИЙ дефект»): это разбор, не правка
    if re.search(r"^[^—–]{0,40}[—–]\s*\S", справа):
        return "ссылка", "номер-подлежащее, справа характеристика через тире"
    return "исправляемое", "иное"
