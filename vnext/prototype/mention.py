import re

# ── РОДЫ ПРИМЕТ. Слова собраны из пяти живых реализаций, а не придуманы.
CANCEL = r"⚰️|снят|отозв|отмен|упраздн|больше\s+не|не\s+держ|запрещ|устарел|надгроб|retired"
# 🪤 РОД CORRECTION ЗАБЫТ В ПЕРВОЙ РЕДАКЦИИ — нашла собственная приёмка (случай ⑦, 21:40 UTC).
# Я вывел роды из ПЯТИ реализаций и всё равно потерял один, хотя писал его час назад в
# guard-phoenix-time. Отмена и поправка — РАЗНЫЕ вещи: отмена говорит «этого больше нет»,
# поправка — «здесь было неверно, читайте так». Для дописываемой ленты живёт только вторая.
# 📌 Обобщение по пяти образцам не гарантирует полноты: приёмка нужна и обобщению.
CORRECTION = r"поправк|исправлен|опечатк|читайте?\s+минус|минус\s+два|correction|верно\s+читать"
QUOTE = r"«[^»]*»|было:|говорилось|цитат"
EXAMPLE = r"наприм|формат|вида\b|образец|образц|шаблон|напр\."
HISTORY = r"прежн|раньше|летопис|истори|\bбыл[оаи]?\b|20\d\d-\d\d-\d\d|\d\d\.\d\d\b"
REFERENCE = r"#\d|§\s?\d|\b[SFRЭШQ]-?\d|\bv\d"

KINDS = {"cancel": CANCEL, "correction": CORRECTION, "quote": QUOTE, "example": EXAMPLE,
         "history": HISTORY, "reference": REFERENCE}
_RX = {k: re.compile(v, re.I) for k, v in KINDS.items()}

# 🪤 ТРЕТЬЕ ПРАВИЛО, ОПЛАЧЕННОЕ ЧЕРЕЗ ЧАС ПОСЛЕ ДВУХ ПЕРВЫХ (09.08 23:44 UTC).
# Перевод второго потребителя (guard-printed-forms) на общий словарь сделал красное
# ЗЕЛЁНЫМ: живую находку погасило слово «retired» ВНУТРИ ИМЕНИ ФАЙЛА
#     python …/check-retired-mechanism.py --db <копия>
# Примета сработала как часть НАЗВАНИЯ ПРЕДМЕТА, а не как разговор о нём.
# ⇒ ИМЕНА И ПУТИ — НЕ РЕЧЬ. Перед судом они вымарываются: имя файла, путь, длинный
# слипшийся идентификатор говорят, О ЧЁМ строка, но ничего не утверждают.
# ⚖️ Поймал это ЗАМЕР «до/после», а не рассуждение: расширение словаря выглядело
# безобидным улучшением, и без сверки вывода я бы отдал ослепший гард как «переведённый».
IDENTIFIER = re.compile(
    r"""(?:[A-Za-z]:)?[\\/][^\s'"]+                    # путь
        |[\w.-]+\.(?:py|md|db|json|sql|txt|sh|ps1)\b    # имя файла
        |\b[a-z0-9]+(?:[-_][a-z0-9]+){2,}\b             # slug
    """, re.I | re.X)


def speech(unit: str) -> str:
    """Единица БЕЗ имён и путей — то, что в ней действительно СКАЗАНО."""
    return IDENTIFIER.sub(" ", unit or "")


DEFAULT = ("cancel", "correction", "quote", "example", "history")


def marks(unit: str, kinds=DEFAULT) -> set:
    """Какие роды примет встретились В ЭТОЙ ЕДИНИЦЕ. Пустое множество ⇒ похоже на дело."""
    said = speech(unit)
    return {k for k in kinds if _RX[k].search(said)}


def is_mention(unit: str, subject: str = None, kinds=DEFAULT) -> bool:
    """Единица УПОМИНАЕТ форму (а не предписывает её)?

    subject — регексп ТЕМЫ. Если задан, примета засчитывается ТОЛЬКО когда тема названа
    в той же единице: «поправка вообще» не гасит дефект «про время» (правило ②).
    """
    if not marks(unit, kinds):
        return False
    if subject is None:
        return True
    return bool(re.search(subject, unit or "", re.I))


def units(text: str):
    """(номер первой строки, текст) — ЗАКОНЧЕННЫЕ ВЫРАЖЕНИЯ для кода, строки для прозы.

    Незакрытые скобки означают, что инструкция не кончилась ⇒ продолжение — та же единица.
    Самостоятельная соседняя строка так не приклеится: правило ① обеими сторонами.
    """
    buf, start, depth = [], None, 0
    for n, line in enumerate((text or "").splitlines(), 1):
        if start is None:
            start = n
        buf.append(line)
        depth += line.count("(") - line.count(")")
        if depth <= 0:
            yield start, "\n".join(buf)
            buf, start, depth = [], None, 0
    if buf:
        yield start, "\n".join(buf)


