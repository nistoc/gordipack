import pathlib
import re
import sqlite3
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import mezo_paths  # noqa: E402

БАЗА = mezo_paths.live_db()   # путь выводится, не впечатан (#248)
ДАНО = re.compile(r"(push|отправк\w*|пушить).{0,90}(разрешён|разрешен|разрешено|можно|✅)"
                  r".{0,50}(без отдельного слова|без отдельного вопроса|без вопроса|без слова)"
                  r"|(разрешён|разрешена|разрешено)\s+без\s+(отдельного\s+)?(слова|вопроса)",
                  re.I | re.S)
ИСКЛ = re.compile(r"de-live|db_falcon|db-falcon|чужой команды|DE/DWH|именн\w+ исключ", re.I)
СУЖЕНО = re.compile(r"\bНАШ\w*\b|\bСВОИ\w*\b|\bсвоих\b|\bСВОЁ\b", re.I)

con = sqlite3.connect(f"file:{БАЗА}?mode=ro", uri=True)
строки = con.execute("SELECT role, section, body FROM phoenix ORDER BY role, section").fetchall()
con.close()

раздают, красные = [], []
for роль, раздел, тело in строки:
    if not ДАНО.search(тело):
        continue
    раздают.append((роль, раздел))
    if not ИСКЛ.search(тело) and not СУЖЕНО.search(тело):
        # покажем САМУ строку права, а не первую попавшуюся
        место = next((i + 1 for i, s in enumerate(тело.splitlines()) if ДАНО.search(s)), 0)
        строка = тело.splitlines()[место - 1].strip()[:110] if место else "(право в нескольких строках)"
        красные.append((роль, раздел, место, строка))

print(f"разделов смотрено 63 · РАЗДАЮТ право {len(раздают)}")
for роль, раздел in раздают:
    метка = "🔴" if any(r == роль and s == раздел for r, s, _, _ in красные) else "✅"
    print(f"   {метка} {роль}·{раздел}")
print()
if красные:
    print(f"🔴 ПРАВО ШИРЕ ДАННОГО — {len(красные)}:")
    for роль, раздел, n, s in красные:
        print(f"   {роль}·{раздел}:{n}  {s}")
