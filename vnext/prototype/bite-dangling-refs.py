"""
bite-dangling-refs.py — приёмка на `check-dangling-refs.py`.

Проверка, которую никто не проверяет, — та же непроверенная гипотеза, что и код.
А эта проверка уже один раз соврала: её первая редакция жила внутри замера карточек,
считала поясняющим словом саму решётку и печатала «0 находок» ПРИ ЛЮБЫХ данных.
Ложный ноль читается как чистота — потому здесь ловится в первую очередь именно он.

ЧЕТЫРЕ ВОПРОСА:
  ① ЛОВИТ голый «#N».
  ② МОЛЧИТ на пояснённом («карточка #86», «записка #3148», «миграция #038»).
  ③ НЕ СЧИТАЕТ пояснением ТОКЕН РОЛИ: «TAXO #2625» не отвечает «записка или карточка»,
     а лишь называет автора. Пропустить это — значит простить самый частый в контуре вид.
  ④ НАЗЫВАЕТ МЕСТО: строка, позиция, окрестность. Правило требует перечня прямо:
     «есть неразрешимые ссылки» без мест — то же молчание.

Запуск:  python <абсолютный путь>/bite-dangling-refs.py
Выход:   0 — все четыре ответа верны · 1 — нет
"""

import importlib.util
import sys
from pathlib import Path

spec = importlib.util.spec_from_file_location(
    "chk", Path(__file__).with_name("check-dangling-refs.py"))
chk = importlib.util.module_from_spec(spec)
spec.loader.exec_module(chk)

# (текст, сколько находок ждём, чем случай важен)
CASES = [
    ("Смотри #3148.", 1, "голый номер — основной случай"),
    ("Смотри карточку #86.", 0, "пояснено словом «карточка»"),
    ("Смотри записку #3148.", 0, "пояснено словом «записка»"),
    ("Накатана миграция #038.", 0, "пояснено словом «миграция» — законный текст не трогаем"),
    ("Находка TAXO #2625 про это.", 1, "🎯 токен роли НЕ пояснение: автор назван, вид — нет"),
    ("Правка в шаге #7 и в карточке #92.", 0, "два пояснённых подряд"),
    ("см. #12, #13 и #14", 3, "несколько голых в одной строке"),
    ("Цвет #fff и решётка ## сами по себе.", 0, "не число и не ссылка — ложных срабатываний нет"),
    # ── #63 доделан 10.08: оговорка охвата оказалась ПРАВДОЙ — tracks/invariants/
    #    backlog_tests сидят в той же полосе номеров; слова-типы внесены ЗАМЕРОМ
    #    (12 живых употреблений в нотах писали так ДО того, как список это узнал).
    ("Идём по треку #3, держим инвариант #5.", 0, "типы новых сущностей поясняют (#63)"),
    ("Проверка теста #2 прошла.", 0, "тест бэклога — тоже тип, полоса общая"),
    ("У трека дела хорошо: #3 закрыт.", 1,
     "🎯 встречный: слово-тип ВДАЛИ не поясняет — номер остался голым"),
    ("Первая строка\nвторая со ссылкой #500", 1, "перенос строки не сбивает счёт"),
    ("Голый «#3120» считался пояснённым сам собою.", 0,
     "🎯 УПОМИНАНИЕ, не употребление: пример ссылки в кавычках никого никуда не шлёт"),
    ("В коде было `#777` как образец.", 0, "то же в обратных кавычках"),
    ("Цитата «см. #12» и живая ссылка #13 рядом.", 1,
     "🎯 РАЗЛИЧАЮЩИЙ: цитата прощена, соседняя живая — нет. Без него послабление"
     " для кавычек означало бы просто «стало тише»"),
]


def main() -> int:
    print("ПРИЁМКА: проверяет ли себя охотник за неразрешимыми ссылками\n")
    bad = []
    for text, want, why in CASES:
        got = len(chk.find(text))
        ok = got == want
        print(f"   {'✅' if ok else '🔴'} ждём {want}, получено {got}   {why}")
        if not ok:
            bad.append((text, want, got))
            print(f"        текст: {text!r}")

    # ── ④ НАЗЫВАЕТ ЛИ МЕСТО ──────────────────────────────────────────────────
    print("\n④ НАЗЫВАЕТ ЛИ МЕСТО (правило требует перечня, а не «находки есть»)")
    hits = chk.find("первая строка\nвторая, а тут ссылка #777 и хвост")
    place_ok = bool(hits) and hits[0][0] == 2 and hits[0][1] > 1 and "#777" in hits[0][3]
    if hits:
        line, col, ref, around = hits[0]
        print(f"   строка {line}, позиция {col}, {ref}, окрестность «{around}»")
    print(f"   {'✅ место названо полностью' if place_ok else '🔴 МЕСТО НЕ НАЗВАНО'}")

    # ── ЛОЖНЫЙ НОЛЬ: главный класс, ради которого укус и написан ─────────────
    print("\n⑤ ЗАЩИТА ОТ ЛОЖНОГО НУЛЯ: проверка обязана хоть на чём-то краснеть")
    fires = sum(1 for t, w, _ in CASES if w and chk.find(t))
    zero_ok = fires >= 4
    print(f"   случаев, где находки ЕСТЬ и найдены: {fires} из "
          f"{sum(1 for _, w, _ in CASES if w)}   {'✅' if zero_ok else '🔴'}")
    print("   (первая редакция этой логики печатала 0 при любых данных — и выглядела чистой)")

    if bad or not place_ok or not zero_ok:
        print(f"\nИТОГ: 🔴 ПРОВЕРКА НЕИСПРАВНА — расхождений {len(bad)}, "
              f"место {'названо' if place_ok else 'НЕ названо'}, "
              f"ложный ноль {'исключён' if zero_ok else 'ВОЗМОЖЕН'}")
        return 1
    print("\nИТОГ: ✅ ЛОВИТ ГОЛОЕ, МОЛЧИТ НА ПОЯСНЁННОМ, НЕ ВЕРИТ ТОКЕНУ РОЛИ, НАЗЫВАЕТ МЕСТО")
    return 0


if __name__ == "__main__":
    sys.exit(main())
