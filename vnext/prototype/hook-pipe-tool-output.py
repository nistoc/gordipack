r"""ЗАПРЕТ ОБРЕЗКИ ВЫВОДА ИНСТРУМЕНТОВ КООРДИНАЦИИ — НА УРОВНЕ СРЕДЫ, А НЕ ИНСТРУМЕНТА.

🎯 ЧЕЙ ЭТО ВОПРОС. Класс принесли соседи (контур tapas, 22.08 06:02 UTC, слово их владельца)
и адресовали сюда поимённо. Их замер: за одну смену одна роль, ЗНАЮЩАЯ правило, нарушила
его ШЕСТЬ раз; координатор того же контура назвал пять своих. Наш координатор — пять,
и пятый дал ЛОЖНЫЙ ЗЕЛЁНЫЙ: `команда | head` вернула код `head`, а не команды, и лежащий
сервер прочитался как живой. Вывод соседей, который мы подтверждаем своим счётом:
**правило, которое держится памятью, не держится.**

🪤 ПОЧЕМУ ИХ МЕХАНИЗМ НЕ МОГ ЗАКРЫТЬ КЛАСС — и это не упрёк, а разбор границы.
Их модуль живёт ВНУТРИ инструмента и смотрит на свой описатель вывода. Отсюда три дыры,
названные ими самими: ловит только СВОИ инструменты · видит канал, но не намерение
(`| cat` и `| head` неотличимы) · молчит при выводе в файл. Плюс четвёртая, наша:
вывод ушёл в файл, а обрезали его ПОЗЖЕ, чтением файла — там инструмента уже нет вовсе.
🎯 Общее у всех четырёх: **обрезка живёт не в инструменте, а в КОМАНДЕ РОЛИ.**
Инструмент не может увидеть чужую команду — по построению.

⚖️ ЧТО ВИДИТ СРЕДА. Механизм, вызываемый оболочкой ПЕРЕД запуском, получает текст команды
целиком. Отсюда он видит то, чего не видит ни один инструмент:
    ЧЬЮ БЫ ТО НИ БЫЛО команду ... свою, чужую, общую, системную
    НАМЕРЕНИЕ, а не канал ....... в тексте стои́т имя: `head` режет, `cat` нет
    ДО ЗАПУСКА .................. можно не дать выполниться, а не сожалеть после
    ЧТЕНИЕ ФАЙЛА ПОЗЖЕ .......... `tail файл` — тоже команда, тоже видна

⛔ ОБЛАСТЬ — ПО ПРИЧИНЕ, А НЕ ПО СПИСКУ ИМЁН. Само правило `no-pipe-tool-output` заведено
после того, как запрет, названный ИМЕНЕМ инструмента, не перенёсся на соседний: роль честно
применила его по имени и обрезала другой. Поэтому здесь нет и не будет перечня инструментов:
предмет — вывод того, что лежит В КАТАЛОГЕ ИНСТРУМЕНТОВ контура. Новый инструмент,
положенный туда, накрыт с первой минуты, вносить его никуда не надо.

⚖️ ЧЕГО ЭТОТ МЕХАНИЗМ НЕ УМЕЕТ (названо до внедрения, а не после):
    · не видит обрезку ВНУТРИ скрипта: роль пишет программу, та сама режет — команда чиста;
    · не видит обрезку внутри кавычек: `bash -c "инструмент | head"` — для нас это одно
      слово-строка, а не конвейер. Тот же разрыв, что и в первом случае;
    · не видит сужение ЛИМИТОМ (`--limit 3`) — это законное сужение запроса, и о его цене
      говорит сам инструмент строкой «показаны не все»;
    · живёт в среде исполнения: контур без такой среды получит правило без механизма.

🩸 ДВА ЛОЖНЫХ ОТКАЗА ПЕРВОГО ДНЯ — ОБА ПОЧИНЕНЫ, ОБА ОПЛАЧЕНЫ ЖИВОЙ РАБОТОЙ (23.08).
Приёмка требовала молчания в шести случаях, и все шесть держались. Мимо прошли два других,
и нашлись они не разбором, а работой: @COORD 15:43 UTC и я 15:57 UTC, одна форма у обоих.
```
① ГРАНИЦА КОМАНД ≠ ЗВЕНО КОНВЕЙЕРА. `sed -n '1,5p' файл || find . | head -3`
   Разборщик резал только по `|`, поэтому `||` читалось как два звена — и фильтр
   из ВТОРОЙ команды приписывался инструменту из ПЕРВОЙ. То же с `&&` и `;`
② УПОМИНАНИЕ ПУТИ ≠ ВЫЗОВ. `grep -n "check" .mezosync/scripts/guard-all.py | head -30`
   Здесь инструмент — ПРЕДМЕТ чтения, а режется вывод `grep`. Обрезать вывод grep'а
   правило не запрещает и запрещать не может: значимое-в-обоих-концах — свойство
   вывода ИНСТРУМЕНТА, а не всякой строки, где встретилось его имя
```
🎯 Общее у обоих: механизм судил по СОСЕДСТВУ в тексте, а предмет — «вывод инструмента
попал на вход резака». Соседство в строке этого не значит.
⚖️ Почему чиню, а не терплю: ложный отказ дороже пропуска — но здесь он ещё и БЬЁТ ПО
ТОМУ ЖЕ МЕСТУ, ради которого механизм заведён. Роль, которой запретили читать код
инструмента, пойдёт читать его иначе или выключит запрет целиком.
📌 Форма вызова программы — множество ЗАКРЫТОЕ и древнее (`имя`, `python имя`, обёртка
перед ними), ровно как множество способов резать. Поэтому здесь перечень уместен по тому
же доводу, что и в `РЕЖУЩИЕ`: перечисляются не подзащитные, а формы.
"""
from __future__ import annotations

import json
import os
import re
import sys

СЛОВО_ВЫКЛЮЧЕНИЯ = "off"
ВЫКЛЮЧАТЕЛЬ = "MEZO_PIPE_GUARD"

# Каталоги инструментов координации. Признак — МЕСТО, а не имя файла: см. шапку.
КАТАЛОГИ = (".mezosync/scripts", ".mezosync\\scripts", "vnext-tools")

# Обрезающие команды. Здесь список УМЕСТЕН и не противоречит доводу выше: перечисляются
# не подзащитные (их множество открыто), а сами способы резать — их немного и они древние.
# `cat` намеренно НЕ входит: он не режет, и краснеть на нём значило бы мерить канал.
РЕЖУЩИЕ = re.compile(
    r"(?:^|\||;|&&)\s*(?:head|tail|more|less)\b"
    r"|(?:^|\||;|&&)\s*sed\s+-n\b"
    r"|(?:^|\||;|&&)\s*(?:grep|rg|findstr|Select-String)\b"
    r"|(?:^|\||;|&&)\s*awk\s+[\"']?NR\s*[<>=]",
    re.IGNORECASE)

# Путь к инструменту координации: каталог инструментов + имя файла .py.
# ⚠️ Само по себе НЕ значит «инструмент вызван» — см. `вызван()`: путь может стоять
# аргументом у читающей команды, и тогда режется вывод ЧИТАТЕЛЯ, а не инструмента.
ИНСТРУМЕНТ = re.compile(
    r"[^\s\"']*(?:" + "|".join(re.escape(k) for k in КАТАЛОГИ) + r")[\\/][\w.-]+\.py",
    re.IGNORECASE)

# Формы запуска программы. Перечень уместен по доводу шапки: множество форм вызова
# закрыто и древне, в отличие от множества подзащитных инструментов.
ИНТЕРПРЕТАТОР = re.compile(r"^(?:[^\s]*[\\/])?(?:python[0-9w]*|py|pypy[0-9]*)(?:\.exe)?$",
                           re.IGNORECASE)
ОБЁРТКА = {"env", "nohup", "time", "sudo", "exec", "command", "&", "uv", "run",
           "poetry", "pipenv", "npx", "winpty", "xargs"}
ПРИСВАИВАНИЕ = re.compile(r"^[A-Za-z_][A-Za-z_0-9]*=")


def разложить(cmd: str) -> list[list[str]]:
    """Строка оболочки → список конвейеров, каждый — список звеньев.

    ⚖️ ГРАНИЦА КОМАНД (`;` `&&` `||` `&` перевод строки) — НЕ звено конвейера (`|`).
    🩸 Первая редакция резала только по `|`, поэтому `||` читалось как два звена, и фильтр
    из второй команды приписывался инструменту из первой. Ложный отказ, случай ⑫.
    ⚖️ Труба ВНУТРИ кавычек не разделяет: `--body "a|b"` — одно звено.
    """
    конвейеры: list[list[str]] = []
    звенья: list[str] = []
    текущий: list[str] = []
    кавычка = ""
    i = 0
    while i < len(cmd):
        ch = cmd[i]
        if кавычка:
            текущий.append(ch)
            if ch == кавычка:
                кавычка = ""
            i += 1
            continue
        if ch in "\"'":
            кавычка = ch
            текущий.append(ch)
            i += 1
            continue
        граница = cmd[i:i + 2] in ("||", "&&")
        # 🩸 `&` — ГРАНИЦА КОМАНД ТОЛЬКО КОГДА ЭТО ФОНОВЫЙ ЗАПУСК, А НЕ ЧАСТЬ
        # ПЕРЕНАПРАВЛЕНИЯ (`2>&1`, `>&2`, `&>файл`). Дыру принёс @COORD 23.08 22:13,
        # поймав на СЕБЕ: восьмое нарушение правила за сутки, и механизм смолчал.
        # ⚡ И открыла её МОЯ ЖЕ вчерашняя правка — та, что чинила ложный отказ: я добавила
        # `&` в разделители, а `2>&1` содержит `&`, и команда рвалась пополам ровно между
        # инструментом и фильтром. До правки этот случай ловился.
        # 🎯 Мой же вчерашний довод, исполнившийся буквально: «починка ложного отказа
        # лечится ослаблением, и ослабление надо ловить встречным случаем». Встречный
        # случай ⑭ у меня был — но на `&&`, а не на `&` внутри перенаправления.
        # 📌 Замер точнее заявки: коллега считал, что дыра в ХВОСТОВОМ `2>&1`. На деле
        # хвостовой безвреден, а губит стоящий ПЕРЕД конвейером — случаи ⑰⑱.
        if ch == "&" and not граница:
            пред = cmd[i - 1] if i else ""
            след = cmd[i + 1] if i + 1 < len(cmd) else ""
            if пред in "><" or след.isdigit() or след in "><":
                текущий.append(ch)      # часть перенаправления, команду не рвёт
                i += 1
                continue
        if граница or ch in ";\n&":
            звенья.append("".join(текущий))
            текущий = []
            конвейеры.append(звенья)
            звенья = []
            i += 2 if граница else 1
            continue
        if ch == "|":
            звенья.append("".join(текущий))
            текущий = []
            i += 1
            continue
        текущий.append(ch)
        i += 1
    звенья.append("".join(текущий))
    конвейеры.append(звенья)
    return конвейеры


def слова(звено: str) -> list[str]:
    """Звено по словам, кавычки держат пробел вместе."""
    из_слов, текущее, кавычка = [], [], ""
    for ch in звено:
        if кавычка:
            if ch == кавычка:
                кавычка = ""
            else:
                текущее.append(ch)
            continue
        if ch in "\"'":
            кавычка = ch
            continue
        if ch.isspace():
            if текущее:
                из_слов.append("".join(текущее))
                текущее = []
            continue
        текущее.append(ch)
    if текущее:
        из_слов.append("".join(текущее))
    return из_слов


def вызван(звено: str) -> bool:
    """Стои́т ли инструмент координации на месте ИСПОЛНЯЕМОГО, а не аргумента.

    🩸 `grep -n "check" .mezosync/scripts/guard-all.py | head -30` — инструмент здесь
    ПРЕДМЕТ чтения; режется вывод `grep`, а не вывод инструмента. Первая редакция искала
    путь где угодно в звене и отказывала. Ложный отказ, случай ⑬.
    ⚖️ Идём слева, пропуская присваивания и обёртки. Первое ЗНАЧАЩЕЕ слово решает:
    путь инструмента → вызван · интерпретатор → ждём путь следующим · что угодно иное →
    это чужая команда, и путь в ней может быть только аргументом.
    """
    ждём_путь = False
    for слово in слова(звено):
        if ПРИСВАИВАНИЕ.match(слово):
            continue
        if ИНСТРУМЕНТ.fullmatch(слово):
            return True
        if слово.lower() in ОБЁРТКА or ИНТЕРПРЕТАТОР.match(слово):
            ждём_путь = True
            continue
        if ждём_путь and слово.startswith("-"):
            continue        # флаги интерпретатора и обёртки: -u, -X, -I@
        return False
    return False


def разбор(cmd: str) -> tuple[bool, str]:
    """→ (обрезан ли вывод инструмента координации, чем именно).

    ⚖️ СУДИМ ПО ЗВЕНЬЯМ ОДНОГО КОНВЕЙЕРА, А НЕ ПО ВСЕЙ СТРОКЕ. Первая редакция искала оба
    признака в тексте целиком — и красила `guard-all.py > файл; grep что-то другое.txt`,
    где инструмент и фильтр не связаны вовсе. Обрезка есть только там, где фильтр стои́т
    ПОСЛЕ вызова инструмента в ОДНОМ конвейере.
    """
    for звенья in разложить(cmd):
        for i, звено in enumerate(звенья):
            if not вызван(звено):
                continue
            for хвост in звенья[i + 1:]:
                m = РЕЖУЩИЕ.search("|" + хвост)
                if m:
                    return True, m.group(0).strip("| ;&")
    return False, ""


def main() -> int:
    try:
        данные = json.load(sys.stdin)
    except (json.JSONDecodeError, ValueError):
        # ⛔ «НЕ СМОГ ПРОЧИТАТЬ» НЕ РАВНО «ВСЁ ЧИСТО», но и запрещать вслепую нельзя:
        # непрочитанный ввод — не улика. Молчим и НЕ решаем (правило read-failure-blocks-write
        # требует не выдавать непрочитанное за пустое: мы ничего и не утверждаем).
        return 0
    if (os.environ.get(ВЫКЛЮЧАТЕЛЬ) or "").strip().lower() == СЛОВО_ВЫКЛЮЧЕНИЯ:
        return 0
    cmd = str((данные.get("tool_input") or данные).get("command") or "")
    if not cmd:
        return 0
    обрезано, чем = разбор(cmd)
    if not обрезано:
        return 0
    print(json.dumps({"hookSpecificOutput": {
        "hookEventName": "PreToolUse",
        "permissionDecision": "deny",
        "permissionDecisionReason": (
            f"⛔ ОБРЕЗКА ВЫВОДА ИНСТРУМЕНТА КООРДИНАЦИИ («{чем}») — запрещена правилом "
            "no-pipe-tool-output. У этих инструментов значимое лежит В ОБОИХ КОНЦАХ: "
            "у читающего ленту так разрезан ключ подтверждения, у пишущего записку "
            "подтверждение записи стои́т третьей строкой С КОНЦА. Обрезав, роль не видит, "
            "что запись прошла, и шлёт заново — так родились дубли у двух ролей за день. "
            "👉 Сужай ЗАПРОС, а не вывод: --limit, отбор по роли, конкретный ключ. "
            "Нужен весь вывод глазами — перенаправь в файл и прочитай файл ЦЕЛИКОМ."
        )}}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
