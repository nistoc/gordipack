#!/usr/bin/env python
# -*- coding: utf-8 -*-
r"""КОМАНДА, БЕРУЩАЯ ПРЕДМЕТ ПО ПОЛОЖЕНИЮ, В ОБЩЕМ ХРАНИЛИЩЕ ЗАХВАТЫВАЕТ ЧУЖОЕ.

🩸 ОПЛАЧЕНО ДВАЖДЫ, РАЗНЫМИ РОЛЯМИ И РАЗНЫМИ КОМАНДАМИ.
    29.07  `git add -A` в общем репозитории унёс в чужой коммит 4 файла соседней роли;
    18.08  правка последнего коммита (`--amend`) пришлась на коммит другой роли, легший
           между двумя попытками. 26 секунд разницы. Его работа (345 строк) цела, но
           на сервере носит чужое сообщение; чинится только разрушающим ходом.
🎯 Класс назвал @COORD правилом `command-picks-target-by-position`: опасна не команда,
а СПОСОБ, которым она выбирает предмет. «Всё вокруг» · «последнее» · «что накопилось» —
в общем хранилище это молча означает «и чужое тоже».

⚖️ ПОЧЕМУ ПРИЗНАК НЕ «АВТОР HEAD НЕ ТЫ» — замер @TAXO (записка #3675), и он снял мою же
первую заявку: под одним именем в контуре коммитят ВСЕ роли. Проверка по автору сказала бы
«твой» и на чужом коммите, то есть смолчала бы ровно в том случае, ради которого заводится.
⇒ Признаки взяты ДРУГИЕ, оба проверяемы замером:
    СОСТАВ ... что эта смена писала своей рукой (журнал ведётся тем же механизмом);
    ВОЗРАСТ .. файл, изменённый ДО начала смены, этой сменой не трогался по построению.

🪤 И ГЛАВНОЕ РАЗЛИЧЕНИЕ, БЕЗ КОТОРОГО МЕХАНИЗМ БЫЛ БЫ ВРЕДЕН: у него ТРИ исхода, а не два.
    свой ....... пропускаем молча;
    чужой ...... отказ, называющий ЧЕМ отличили и какие файлы чужие — поимённо;
    НЕ ЗНАЮ .... смена ещё не коммитила в этот репозиторий, сравнивать не с чем. Это НЕ
                 «свой»: тихо пропустить здесь значит вернуть ровно ту беду. Отказ говорит
                 отдельными словами, что механизм не знает, и называет выход.

Зовётся средой:  --judge   перед командой (PreToolUse)
                 --record  после команды и после записи файлов (PostToolUse)
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import sys
import time
from pathlib import Path

СЛОВО_ВЫКЛЮЧЕНИЯ = "off"
ВЫКЛЮЧАТЕЛЬ = "MEZO_SHARED_REPO_GUARD"

# Команды, выбирающие предмет ПО ПОЛОЖЕНИЮ. Перечисляются не подзащитные (их множество
# открыто), а сами СПОСОБЫ брать «всё вокруг» — ровно то, что правило называет причиной.
ПРАВКА_ПОСЛЕДНЕГО = re.compile(r"\bgit\b[^|;&]*\bcommit\b[^|;&]*--amend", re.IGNORECASE)
ВСЁ_ВОКРУГ = re.compile(
    r"\bgit\b[^|;&]*\badd\b\s+(?:-A|--all|-u|--update|\.)(?:\s|$)"
    r"|\bgit\b[^|;&]*\bstash\b(?!\s+(?:list|show|pop|apply|drop))",
    re.IGNORECASE)
CD = re.compile(r"\bcd\s+[\"']?([^\"'&|;]+)")


def состояние_рядом(контейнер: Path) -> Path:
    d = контейнер / ".mezosync" / ".hook-state"
    d.mkdir(parents=True, exist_ok=True)
    return d


def контейнер_от(путь: Path) -> Path | None:
    for p in [путь, *путь.parents]:
        if (p / ".mezosync" / "mezosync.db").exists():
            return p
    return None


def репозиторий(путь: Path) -> Path | None:
    for p in [путь, *путь.parents]:
        if (p / ".git").exists():
            return p
    return None


def рабочий_каталог(данные: dict, cmd: str) -> Path:
    """Каталог, в котором команда БУДЕТ исполнена: `cd` внутри команды сильнее cwd вызова."""
    m = CD.search(cmd)
    if m:
        кандидат = Path(m.group(1).strip())
        if кандидат.is_absolute() and кандидат.exists():
            return кандидат
    return Path(данные.get("cwd") or ".")


def журнал(контейнер: Path, sid: str) -> dict:
    p = состояние_рядом(контейнер) / f"{sid}.json"
    if not p.exists():
        return {"начало": None, "писала": [], "коммиты": {}}
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, ValueError, OSError):
        # ⛔ Не смогли прочесть — НЕ выдаём за «пустой журнал»: пустой значит «ничего
        # не писала», а это утверждение о смене, которого мы не проверяли.
        return {"__не_прочитан__": True, "начало": None, "писала": [], "коммиты": {}}


def сохранить(контейнер: Path, sid: str, ж: dict) -> None:
    ж.pop("__не_прочитан__", None)
    (состояние_рядом(контейнер) / f"{sid}.json").write_text(
        json.dumps(ж, ensure_ascii=False), encoding="utf-8")


def git(корень: Path, *args) -> tuple[int, str]:
    try:
        r = subprocess.run(["git", "-C", str(корень), "-c", "core.quotepath=false", *args],
                           capture_output=True, text=True, encoding="utf-8",
                           errors="replace", timeout=60)
    except (OSError, subprocess.SubprocessError):
        return 1, ""
    return r.returncode, (r.stdout or "")


def отказ(текст: str) -> None:
    print(json.dumps({"hookSpecificOutput": {
        "hookEventName": "PreToolUse", "permissionDecision": "deny",
        "permissionDecisionReason": текст}}, ensure_ascii=False))


# ── РЕЖИМ ЗАПИСИ ───────────────────────────────────────────────────────────────────
def записать(данные: dict) -> int:
    cwd = Path(данные.get("cwd") or ".")
    контейнер = контейнер_от(cwd)
    if контейнер is None:
        return 0
    sid = str(данные.get("session_id") or "без-имени")
    ж = журнал(контейнер, sid)
    ж["начало"] = ж.get("начало") or time.time()
    инструмент = данные.get("tool_name") or ""
    ввод = данные.get("tool_input") or {}

    if инструмент in ("Write", "Edit", "NotebookEdit"):
        путь = str(ввод.get("file_path") or "")
        if путь:
            ж.setdefault("писала", [])
            if путь not in ж["писала"]:
                ж["писала"].append(путь)
    elif инструмент == "Bash":
        cmd = str(ввод.get("command") or "")
        if re.search(r"\bgit\b[^|;&]*\bcommit\b", cmd, re.IGNORECASE):
            корень = репозиторий(рабочий_каталог(данные, cmd))
            if корень is not None:
                код, head = git(корень, "rev-parse", "HEAD")
                if код == 0 and head.strip():
                    # Запоминаем HEAD ПОСЛЕ нашего коммита: с ним и сравним при правке.
                    ж.setdefault("коммиты", {})[str(корень)] = head.strip()
    сохранить(контейнер, sid, ж)
    return 0


# ── РЕЖИМ СУДА ─────────────────────────────────────────────────────────────────────
def судить(данные: dict) -> int:
    cmd = str((данные.get("tool_input") or данные).get("command") or "")
    if not cmd:
        return 0
    правка = bool(ПРАВКА_ПОСЛЕДНЕГО.search(cmd))
    всё_вокруг = bool(ВСЁ_ВОКРУГ.search(cmd))
    if not (правка or всё_вокруг):
        return 0

    каталог = рабочий_каталог(данные, cmd)
    контейнер = контейнер_от(каталог)
    if контейнер is None:
        # ⚖️ Хранилище ВНЕ контура — не наш предмет: правило про общее хранилище ролей.
        return 0
    корень = репозиторий(каталог)
    if корень is None:
        return 0
    sid = str(данные.get("session_id") or "без-имени")
    ж = журнал(контейнер, sid)

    if правка:
        мой = (ж.get("коммиты") or {}).get(str(корень))
        код, head = git(корень, "rev-parse", "HEAD")
        head = head.strip()
        if ж.get("__не_прочитан__"):
            отказ("⛔ ПРАВКА ПОСЛЕДНЕГО КОММИТА: журнал смены НЕ ПРОЧИТАН, чей это коммит — "
                  "неизвестно. Это не «твой»: в общем хранилище «последний» перестаёт "
                  "означать «мой» молча. Проверь сам (git log -1 --stat) и, если коммит "
                  f"твой, повтори с {ВЫКЛЮЧАТЕЛЬ}={СЛОВО_ВЫКЛЮЧЕНИЯ}.")
            return 0
        if not мой:
            отказ("⛔ ПРАВКА ПОСЛЕДНЕГО КОММИТА: эта смена ещё НЕ КОММИТИЛА в этот "
                  f"репозиторий ({корень.name}), поэтому сравнивать не с чем — чей сейчас "
                  "последний коммит, механизм НЕ ЗНАЕТ. Тихо пропустить значило бы вернуть "
                  "случай 18.08: правка легла на коммит другой роли, и его работа ушла "
                  "на сервер под чужим именем. 👉 Посмотри сам: git log -1 --stat. "
                  f"Если коммит твой — повтори с {ВЫКЛЮЧАТЕЛЬ}={СЛОВО_ВЫКЛЮЧЕНИЯ}.")
            return 0
        if код == 0 and head and head != мой:
            _, чужие = git(корень, "show", "--name-only", "--format=%h · %s", head)
            отказ("⛔ ПОСЛЕДНИЙ КОММИТ УЖЕ НЕ ТВОЙ. После твоего коммита в этом репозитории "
                  "появился другой — правка пришлась бы на него, и чужая работа ушла бы "
                  "под твоим сообщением (так было 18.08: 26 секунд разницы).\n"
                  f"   твой был ....... {мой[:12]}\n"
                  f"   сейчас HEAD .... {head[:12]}\n"
                  f"   а это в нём: {' | '.join(чужие.split(chr(10))[:6])}\n"
                  "   ⚖️ Отличили НЕ по автору: под одним именем коммитят все роли. "
                  "Отличили по тому, что HEAD сдвинулся после твоей записи.")
            return 0
        return 0

    # ВСЁ ВОКРУГ: смотрим, что именно захватит команда, и вычитаем СВОЁ.
    код, состояние = git(корень, "status", "--porcelain")
    if код != 0:
        return 0
    начало = ж.get("начало") or time.time()
    свои = {os.path.normcase(os.path.abspath(p)) for p in (ж.get("писала") or [])}
    чужие = []
    for строка in состояние.splitlines():
        имя = строка[3:].strip().strip('"')
        if " -> " in имя:                      # переименование: берём цель
            имя = имя.split(" -> ", 1)[1]
        полный = корень / имя
        ключ = os.path.normcase(os.path.abspath(str(полный)))
        if ключ in свои:
            continue
        try:
            # ВОЗРАСТ: изменённое ДО начала смены этой сменой не трогалось по построению.
            if полный.exists() and полный.stat().st_mtime >= начало:
                continue
        except OSError:
            pass
        чужие.append(имя)
    if not чужие:
        return 0
    показ = "\n".join(f"   · {и}" for и in чужие[:8])
    ещё = f"\n   … и ещё {len(чужие) - 8}" if len(чужие) > 8 else ""
    отказ("⛔ КОМАНДА БЕРЁТ «ВСЁ ВОКРУГ», А ВОКРУГ ЛЕЖИТ ЧУЖОЕ. В этом репозитории "
           f"({корень.name}) есть незаписанные изменения, которых эта смена НЕ ДЕЛАЛА:\n"
           f"{показ}{ещё}\n"
           "   ⚖️ Отличили замером, а не по автору: этих файлов нет среди записанных "
           "этой сменой, и они изменены до её начала.\n"
           "   👉 Добавляй ПОИМЁННО: git add <файл> <файл>. Так 29.07 в чужой коммит "
           f"уехали 4 файла соседней роли. Осознанно и правда всё твоё — {ВЫКЛЮЧАТЕЛЬ}="
           f"{СЛОВО_ВЫКЛЮЧЕНИЯ}.")
    return 0


def main() -> int:
    режим = "--judge" if "--judge" in sys.argv else "--record" if "--record" in sys.argv else ""
    try:
        данные = json.load(sys.stdin)
    except (json.JSONDecodeError, ValueError):
        return 0                       # непрочитанный ввод — не улика, ничего не утверждаем
    if (os.environ.get(ВЫКЛЮЧАТЕЛЬ) or "").strip().lower() == СЛОВО_ВЫКЛЮЧЕНИЯ:
        return 0
    if режим == "--record":
        return записать(данные)
    if режим == "--judge":
        return судить(данные)
    return 0


if __name__ == "__main__":
    sys.exit(main())
