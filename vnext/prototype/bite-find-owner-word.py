def зов(инструмент: pathlib.Path, слово: str, корень: pathlib.Path, *доп: str):
    p = subprocess.run(
        [sys.executable, str(инструмент), "--слово", слово, "--корень", str(корень), *доп],
        capture_output=True, text=True, encoding="utf-8",
        env=dict(os.environ, PYTHONIOENCODING="utf-8"))
    return p.returncode, (p.stdout or "") + (p.stderr or "")


def раздел(вывод: str, имя: str) -> str:
    """Кусок вывода от заголовка раздела до следующего разделителя. Пусто — раздела нет."""
    if имя not in вывод:
        return ""
    после = вывод.split(имя, 1)[1]
    for стоп in ("·" * 92, "-" * 92, "📎"):
        if стоп in после:
            после = после.split(стоп, 1)[0]
    return после


