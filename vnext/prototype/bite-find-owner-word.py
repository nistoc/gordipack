#!/usr/bin/env python
# SURFACES: memory, owner-words
# -*- coding: utf-8 -*-
r"""ПРИЁМКА find-owner-word.py — карточка #521, различающие случаи + порча на копии.

⚖️ ЧЕМ СУДИТ ЭТА ПРИЁМКА. Не живыми записями разговоров — они меняются от каждого нашего
хода (инструмент это сам и поймал: его собственный вывод ложится в запись). Судит
ПЕСОЧНИЦЕЙ: подсадные файлы с известным содержимым, где верный ответ назначен заранее.

СЛУЧАИ — по критерию карточки: «роль обязана РАЗЛИЧИТЬ (а) слова не было и (б) слово
пришло интерфейсом выбора; встречный случай обязателен, иначе способ вечно зелёный».
    ① слово НАБРАНО текстом .......... 📝, час равен часу реплики
    ② слово ВЫБРАНО кнопкой .......... 🔘, виден и вопрос, и выбранный вариант
    ③ слова НЕТ ...................... ⚪ и ПРЯМО сказано, что это НЕ доказательство
       ⚡ это и есть встречный случай, которого требует карточка
    ④ ЭХО прогона .................... наш собственный вывод НЕ считается словом владельца
    ⑤ служебная вставка системы ...... сводка сжатия НЕ считается словом владельца
    ⑥ каталога записей нет ........... ОТКАЗ МЕРИТЬ (код 2), а не «не найдено»
    ⑦ ПОРЧА: убрать привязку к началу → эхо обязано проехать (чувствительность ④)
    ⑧ ПОРЧА: убрать отсев служебных   → сводка обязана проехать (чувствительность ⑤)

Зовут так:
    python C:/guts/.atlas/vnext-tools/bite-find-owner-word.py
"""
from __future__ import annotations

import io
import json
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")

ЗДЕСЬ = pathlib.Path(__file__).resolve().parent
# ⛔ инструмент берётся ОТ СЕБЯ, а не по впечатанному пути: иначе приёмка, положенная
# в песочницу вместе с испорченной копией, продолжит судить живой оригинал (оплачено
# 04.09 на приёмке памяти — порча давала зелёное).
ИНСТРУМЕНТ = ЗДЕСЬ / "find-owner-word.py"

прошло: list[str] = []
пало: list[str] = []


def случай(имя: str, ок: bool, чем: str = "") -> None:
    (прошло if ок else пало).append(имя)
    print(f"  {'✅' if ок else '🔴'} {имя}")
    if not ок and чем:
        for с in чем.strip().splitlines()[:6]:
            print(f"       {с}")


def запись(час: str, тип: str, содержимое) -> str:
    return json.dumps({"type": тип, "timestamp": час,
                       "message": {"content": содержимое}}, ensure_ascii=False)


def песочница(каталог: pathlib.Path) -> None:
    """Подсадные записи разговора с ЗАРАНЕЕ ИЗВЕСТНЫМ содержимым."""
    чат = каталог / "C--sandbox--proba"
    чат.mkdir(parents=True, exist_ok=True)
    строки = [
        # ① слово набрано текстом
        запись("2026-01-02T03:04:05.678Z", "user", "делай синеглазку, и побыстрее"),
        # ② слово выбрано кнопкой
        запись("2026-01-02T03:10:00.111Z", "user", [
            {"type": "tool_result",
             "content": 'Your questions have been answered: "Как поступаем с рыжиком?"'
                        '="Оставить рыжика как есть". You can now continue with these '
                        'answers in mind.'}]),
        # ④ ЭХО: наш собственный вывод, внутри которого те же слова
        запись("2026-01-02T03:20:00.222Z", "user", [
            {"type": "tool_result",
             "content": "── строк: 1\nнашёл в записи: Your questions have been "
                        'answered: "Как поступаем с рыжиком?"="Оставить рыжика как '
                        'есть"\nвсего совпадений: 1'}]),
        # ⑤ служебная вставка системы, содержащая искомое слово
        запись("2026-01-02T03:30:00.333Z", "user",
               "This session is being continued from a previous conversation that ran "
               "out of context.\nSummary: владелец сказал «делай синеглазку»"),
    ]
    (чат / "aaaaaaaa-1111-2222-3333-444444444444.jsonl").write_text(
        "\n".join(строки) + "\n", encoding="utf-8")


def зов(инструмент: pathlib.Path, слово: str, корень: pathlib.Path):
    p = subprocess.run(
        [sys.executable, str(инструмент), "--слово", слово, "--корень", str(корень)],
        capture_output=True, text=True, encoding="utf-8",
        env=dict(os.environ, PYTHONIOENCODING="utf-8"))
    return p.returncode, (p.stdout or "") + (p.stderr or "")


def main() -> int:
    print("=" * 88)
    print("ПРИЁМКА find-owner-word.py — карточка #521")
    print(f"инструмент: {ИНСТРУМЕНТ}")
    print("=" * 88)
    if not ИНСТРУМЕНТ.is_file():
        sys.exit(f"⛔ ИСПЫТУЕМОГО НЕТ рядом: {ИНСТРУМЕНТ} — это отказ мерить, а не «чисто»")

    with tempfile.TemporaryDirectory() as tmp:
        песок = pathlib.Path(tmp)
        корень = песок / "projects"
        песочница(корень)

        print("\n── КОНТРОЛЬ: НЕиспорченный инструмент на подсадке ────────────────────")
        # 🩸 СНАЧАЛА КОНТРОЛЬ, ПОТОМ ПОРЧА — форма @COORD, оплаченная им 04.09: его опыт
        # с порчей падал ДО первого случая (не хватало модуля), а красное он чуть не
        # засчитал как настоящее. Не зелен контроль — опыта нет, и порча не значит ничего.

        код, вывод = зов(ИНСТРУМЕНТ, "синеглазку", корень)
        случай("① слово НАБРАНО текстом → 📝, час равен часу реплики",
               код == 0 and "НАЙДЕНО ТЕКСТОМ" in вывод
               and "2026-01-02T03:04:05.678Z" in вывод, вывод)

        код, вывод = зов(ИНСТРУМЕНТ, "рыжика", корень)
        случай("② слово ВЫБРАНО кнопкой → 🔘, виден вопрос и выбранный вариант",
               код == 0 and "НАЙДЕНО ВЫБОРОМ" in вывод
               and "Оставить рыжика как есть" in вывод
               and "2026-01-02T03:10:00.111Z" in вывод, вывод)

        # ③ ВСТРЕЧНЫЙ, которого требует карточка: способ обязан уметь сказать «нет»
        код, вывод = зов(ИНСТРУМЕНТ, "черепаховая кошка", корень)
        случай("③ ВСТРЕЧНЫЙ: слова НЕТ → ⚪ и прямо сказано, что это НЕ доказательство",
               "НЕ НАЙДЕНО" in вывод and "НЕ ДОКАЗАТЕЛЬСТВО" in вывод
               and "Просмотрено файлов" in вывод, вывод)

        # ④ эхо: слово есть ТОЛЬКО внутри нашего же вывода
        код, вывод = зов(ИНСТРУМЕНТ, "рыжиком", корень)
        эхо_прошло = "03:20:00" in вывод
        случай("④ ЭХО прогона НЕ считается словом владельца",
               not эхо_прошло, "в выводе есть запись 03:20 — это наш собственный след")

        # ⑤ служебная вставка
        код, вывод = зов(ИНСТРУМЕНТ, "синеглазку", корень)
        служебное_прошло = "03:30:00" in вывод
        случай("⑤ служебная вставка системы НЕ считается словом владельца",
               not служебное_прошло, "в выводе есть запись 03:30 — это сводка сжатия")

        # ⑥ каталога нет — отказ мерить, а не «не найдено»
        код, вывод = зов(ИНСТРУМЕНТ, "синеглазку", песок / "нет-такого-каталога")
        случай("⑥ каталога записей НЕТ → ОТКАЗ МЕРИТЬ (код 2), а не «не найдено»",
               код == 2 and "ОТКАЗ МЕРИТЬ" in вывод and "искать было негде" in вывод,
               f"код {код}\n{вывод}")

        print("\n── ПОРЧА НА КОПИИ: ИНСТРУМЕНТ ОБЯЗАН ПЕРЕСТАТЬ РАЗЛИЧАТЬ ─────────────")
        исходный = ИНСТРУМЕНТ.read_text(encoding="utf-8")

        # ⑦ снимаем привязку к началу — эхо обязано проехать
        копия = песок / "find-owner-word.py"
        порча = исходный.replace(
            's.lstrip().startswith("Your " + МЕТКА_ВЫБОРА)',
            'МЕТКА_ВЫБОРА in s')
        if порча == исходный:
            случай("⑦ ПОРЧА привязки к началу: образец не найден — ОПЫТ НЕ ПОСТАВЛЕН",
                   False, "строка различителя изменилась; порча не легла, "
                          "и молчать об этом нельзя — прогон бессмыслен, а не зелён")
        else:
            копия.write_text(порча, encoding="utf-8")
            код, вывод = зов(копия, "рыжиком", корень)
            случай("⑦ ПОРЧА привязки к началу → эхо ПРОЕЗЖАЕТ (различитель работал)",
                   "03:20:00" in вывод,
                   "порченый инструмент эхо всё равно не пустил ⇒ ④ проходил "
                   "не из-за привязки к началу, а по посторонней причине")

        # ⑧ снимаем отсев служебных — сводка обязана проехать
        порча2 = исходный.replace(
            "return any(н.startswith(п) for п in СЛУЖЕБНЫЕ_НАЧАЛА)",
            "return False")
        if порча2 == исходный:
            случай("⑧ ПОРЧА отсева служебных: образец не найден — ОПЫТ НЕ ПОСТАВЛЕН",
                   False, "порча не легла, прогон бессмыслен")
        else:
            копия.write_text(порча2, encoding="utf-8")
            код, вывод = зов(копия, "синеглазку", корень)
            случай("⑧ ПОРЧА отсева служебных → сводка сжатия ПРОЕЗЖАЕТ",
                   "03:30:00" in вывод,
                   "порченый инструмент сводку всё равно не пустил ⇒ ⑤ проходил "
                   "по посторонней причине")

    print("\n" + "=" * 88)
    print(f"ИТОГ: прошло {len(прошло)} · пало {len(пало)}")
    if пало:
        for и in пало:
            print(f"   🔴 {и}")
    else:
        print("   ✅ все случаи сошлись, и обе порчи ломают ровно то, что должны —")
        print("      значит ④ и ⑤ проходят ПО СВОЕЙ причине, а не по посторонней")
    print("=" * 88)
    print("⚖️ ЧЕГО ЭТА ПРИЁМКА НЕ ПРОВЕРЯЕТ, названо прямо:")
    print("   · полноту перечня служебных вставок — он ЗАКРЫТ и состарится; новая форма")
    print("     проедет как слово владельца, и ни один случай здесь не покраснеет;")
    print("   · верхнюю границу часа у выбора — сколько владелец думал до нажатия,")
    print("     не знает ни инструмент, ни эта приёмка, ни сама запись.")
    return 1 if пало else 0


if __name__ == "__main__":
    sys.exit(main())
