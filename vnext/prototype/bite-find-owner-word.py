def call(tool: pathlib.Path, word: str, root: pathlib.Path, *extra: str):
    # ⚖️ прежние русские флаги — нарочно: ими инструмент зовут свод правил и память ролей,
    # синонимы обязаны жить. Английские судит случай ㉝ (call_en).
    p = subprocess.run(
        [sys.executable, str(tool), "--слово", word, "--корень", str(root), *extra],
        capture_output=True, text=True, encoding="utf-8",
        env=dict(os.environ, PYTHONIOENCODING="utf-8"))
    return p.returncode, (p.stdout or "") + (p.stderr or "")


def call_en(tool: pathlib.Path, word: str, root: pathlib.Path, *extra: str):
    p = subprocess.run(
        [sys.executable, str(tool), "--word", word, "--root", str(root), *extra],
        capture_output=True, text=True, encoding="utf-8",
        env=dict(os.environ, PYTHONIOENCODING="utf-8"))
    return p.returncode, (p.stdout or "") + (p.stderr or "")


def section(out: str, name: str) -> str:
    """Кусок вывода от заголовка раздела до следующего разделителя. Пусто — раздела нет."""
    if name not in out:
        return ""
    rest = out.split(name, 1)[1]
    for stop in ("·" * 92, "-" * 92, "📎"):
        if stop in rest:
            rest = rest.split(stop, 1)[0]
    return rest


