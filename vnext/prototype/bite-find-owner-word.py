def make_record(ts: str, rec_type: str, content, **fields) -> str:
    """Подсадная запись разговора. **поля — верхние ключи записи: origin, isMeta,
    isCompactSummary. ⚖️ С 04.09 20:15 UTC инструмент судит по ПОЛЮ происхождения,
    и подсадка без него проверяла бы вчерашний инструмент, а не сегодняшний."""
    rec = {"type": rec_type, "timestamp": ts, "message": {"content": content}}
    rec.update(fields)
    return json.dumps(rec, ensure_ascii=False)


