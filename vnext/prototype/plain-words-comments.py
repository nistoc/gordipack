NUMBER = re.compile(r"^\d+$")
# Справа: сказуемое или определение, согласуемое по роду. Смена рода ломает их все.
# Расширено ПРЕДПРОСМОТРОМ (вторая итерация): прежняя редакция знала только прошедшее
# время и один промежуточный член — и пропустила «проверка обязан», «проверка печатал»
# (через «при этом»), «Проверка, ищущий». Отступ до трёх слов, добавлены краткие формы.
VERB_RIGHT = re.compile(
    r"^\W*(?:\S+\s+){0,3}\S*(?:ал|ел|ил|ыл|ял|нул|лся|лась|лись|лось|ло|ла|ли)\b", re.I)
SHORT_FORM = re.compile(
    r"^\W*(?:\S+\s+){0,3}(?:обязан|должен|готов|слеп|чист|нужен|важен|виден|"
    r"способен|исправен|честен|верен|прав|доволен|полон|мёртв|жив|молчалив|нем|"
    # прошедшее время без привычного окончания — «мог», «нашёл»: их не поймать по «-л»
    r"мог|смог|помог|нашёл|шёл|вёл|привёл|лёг|пёк|мок)\b|"
    r"^\W*(?:\S+\s+){0,2}\S+(?:ан|ян|ен|ён)\b", re.I)
ADJ_RIGHT = re.compile(
    r"^\W*(?:\S+\s+){0,2}\S+(?:ий|ый|ой|ая|яя|ое|ее|ые|ие|ого|его|ому|ему|ым|им|ом|ем|ую|юю|ых|их|ыми|ими)\b",
    re.I)
# Слева глагол в личной форме ⇒ слово стоит в винительном падеже: «видит курсор» →
# «видит отметку», а не «отметка». Падежа машина не знает — такое откладывается рукой.
VERB_LEFT = re.compile(
    r"(?:ет|ёт|ит|ут|ют|ат|ят|ает|яет|ал|ял|ил|ел|ул|ёл|ла|ло|ли|лся|лась|ть|ться|"
    r"ают|яют|ишь|ешь)$", re.I)
# Глагол СПРАВА в настоящем времени — слово перед ним чаще всего дополнение в винительном
# падеже («курсор не двигают» = «не двигают отметку», а не «отметка»). Тот же разбор
# падежа машине недоступен ⇒ откладываем.
VERB_RIGHT_NOW = re.compile(r"^\W*(?:не\s+)?\S+(?:ет|ёт|ит|ут|ют|ат|ят)\b", re.I)
QUOTED = re.compile(r"«[^»]*»")


# ⚰️ ПОПЫТКА СОГЛАСОВЫВАТЬ СОСЕДНЕЕ СЛОВО — ОТВЕРГНУТА ЗАМЕРОМ 18.08 14:15 UTC.
# Замысел был очевиден: все новые слова женского рода, окончания меняются механически
# («вечно-жёлтый сторож» → «вечно-жёлтая проверка», «покраснел» → «покраснела»), значит
# код справится. Прогон на 19 строках дал: «ПЯТая ПРИЁМКА», «отматываей отметка», «ради
# которой проверка заведён», «Пустая память неотличим», «ПЕРЕЗАТИРАЛ живая отметка».
# Причина не в мелких огрехах: чтобы согласовать, надо ЗНАТЬ, какое слово к какому
# относится и в каком падеже стоит, — это разбор языка, а не подстановка окончаний.
# ⇒ Инструмент правит ТОЛЬКО там, где согласование не задето. Остальное — рукой.
# Оставляю надгробие, а не молчание: без него следующий возьмётся за ту же работу заново.

def editable_spans(src: str) -> dict[int, int]:
    """Номер строки → колонка, С КОТОРОЙ её можно править.

    ⚖️ ПРАВИМ ТОЛЬКО ДВА РОДА ТЕКСТА: комментарии (# …) и пояснения в тройных кавычках.
    Первая редакция инструмента бралась за ЛЮБУЮ строку, кроме показываемой, — и тронула бы
    образцы поиска внутри строк (`re.compile(r"…сторож…")`). Это ровно то ослепление, от
    которого правило `plain-words` предостерегает: проверка осталась бы зелёной и слепой.
    Поймано холостым прогоном ДО правки файлов, а не после.
    """
    spans: dict[int, int] = {}
    try:
        tree = ast.parse(src)
    except SyntaxError:
        return spans
    # пояснения в тройных кавычках: строка-выражение первой в модуле, классе или функции
    for node in ast.walk(tree):
        body = getattr(node, "body", None)
        if not isinstance(body, list) or not body:
            continue
        first = body[0]
        if (isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant)
                and isinstance(first.value.value, str)):
            for ln in range(first.lineno, (first.end_lineno or first.lineno) + 1):
                spans[ln] = 0
    # комментарии — берём разбором на лексемы, чтобы не спутать с решёткой внутри строки
    import io, tokenize
    try:
        for tok in tokenize.generate_tokens(io.StringIO(src).readline):
            if tok.type == tokenize.COMMENT:
                spans.setdefault(tok.start[0], tok.start[1])
    except (tokenize.TokenError, IndentationError):
        pass
    return spans


def keep_case(old: str, new: str) -> str:
    if old.isupper():
        return new.upper()
    if old[:1].isupper():
        return new[:1].upper() + new[1:]
    return new


def convert_line(line: str) -> tuple[str, list[str]]:
    """Возвращает (новая строка, причины пропусков). Пропущенное остаётся как было."""
    skips: list[str] = []
    quoted_spans = [m.span() for m in QUOTED.finditer(line)]
    # ⚠️ Цитата может тянуться через строки: тогда в строке видна ОДНА половина кавычек.
    # Правя такую строку, мы правили бы чужую или прежнюю речь. ⇒ строку целиком не трогаем.
    if line.count("«") != line.count("»"):
        return line, ["цитата через несколько строк — строка не тронута"]

    def repl(m: re.Match) -> str:
        s, e = m.span()
        if any(a <= s < b for a, b in quoted_spans):
            skips.append(f"цитата: {m.group(0)}")
            return m.group(0)
        left_words = line[:s].rstrip().split()
        # «же» прозрачно: «того же сторожа» согласуется с «того», а не с «же»
        left_word = ""
        for w in reversed(left_words):
            w = w.strip("(),.:;—-·").lower()
            if w and w not in ("же", "бы", "ли"):
                left_word = w
                break
        # Предлог слева задаёт падеж, а падеж нового слова машине неизвестен:
        # «за курсор» → «за отметкУ», а не «за отметка». Вычитка применённой правки
        # показала ровно это: «ушли за отметка прочитанного 28 записок».
        if left_word in PREPOSITIONS:
            skips.append(f"слева предлог «{left_word}» (падеж неизвестен): {m.group(0)}")
            return m.group(0)
        if (ADJ_LEFT.search(left_word) or left_word in DETERMINERS
                or NUMBER.match(left_word)):
            skips.append(f"слева согласуемое «{left_word}»: {m.group(0)}")
            return m.group(0)
        # Слово ПОСЛЕДНЕЕ в строке: согласуемое слово уехало на следующую строку, и машине
        # его не видно. Вычитка показала «…, а проверка» с продолжением «живости смотрел…».
        if not line[e:].strip():
            skips.append(f"слово последнее в строке (согласование ниже): {m.group(0)}")
            return m.group(0)
        for rx, why in ((VERB_RIGHT, "справа глагол"), (SHORT_FORM, "справа краткая форма"),
                        (ADJ_RIGHT, "справа определение"),
                        (VERB_RIGHT_NOW, "справа глагол настоящего времени")):
            if rx.match(line[e:]):
                skips.append(f"{why} «{line[e:].strip()[:30]}»: {m.group(0)}")
                return m.group(0)
        if VERB_LEFT.search(left_word):
            skips.append(f"слева глагол «{left_word}» (винительный падеж): {m.group(0)}")
            return m.group(0)
        return keep_case(m.group(0), FORMS[m.group(0).lower()])

    return WORD.sub(repl, line), skips


def main() -> int:
    ap = argparse.ArgumentParser(description="перевод пояснений на общепонятные слова")
    ap.add_argument("--apply", action="store_true",
                    help="править файлы (без флага — холостой прогон, файлы не трогаются)")
    # Каталоги по умолчанию — от СВОЕГО расположения, а не жёстко нашим путём:
    # в чужом контуре жёсткий путь заставил бы инструмент править ЧУЖИЕ файлы.
    _own = pathlib.Path(__file__).resolve().parent
    _default_roots = [str(_own)]
    for cand in (_own.parent / ".mezosync" / "scripts", _own.parent.parent / ".mezosync" / "scripts"):
        if cand.is_dir():
            _default_roots.insert(0, str(cand))
            break
    ap.add_argument("--roots", nargs="*", default=_default_roots)
    ap.add_argument("--show-skips", action="store_true", help="перечислить отложенное")
    a = ap.parse_args()

    changed_files = changed = skipped = 0
    skip_list: list[str] = []
    for root in a.roots:
        for p in sorted(pathlib.Path(root).rglob("*.py")):
            if p.name == pathlib.Path(__file__).name:
                continue
            src = p.read_text(encoding="utf-8", errors="replace")
            spans = editable_spans(src)
            out, n_here = [], 0
            for i, line in enumerate(src.splitlines(keepends=True), 1):
                if i not in spans or not WORD.search(line):
                    out.append(line)
                    continue
                col = spans[i]
                head, tail = line[:col], line[col:]
                new_tail, skips = convert_line(tail)
                skipped += len(skips)
                skip_list += [f"{p.name}:{i} {s}" for s in skips]
                new = head + new_tail
                if new != line:
                    n_here += 1
                out.append(new)
            if n_here:
                changed_files += 1
                changed += n_here
                if a.apply:
                    text = "".join(out)
                    try:
                        ast.parse(text)          # правка не имеет права ломать разбор файла
                    except SyntaxError as e:
                        print(f"🔴 {p.name}: правка сломала бы разбор ({e}) — файл НЕ тронут")
                        continue
                    p.write_text(text, encoding="utf-8")

    print(f"{'ПРАВКА' if a.apply else 'ХОЛОСТОЙ ПРОГОН'}: строк изменено {changed} "
          f"в {changed_files} файлах · отложено рукой {skipped}")
    if a.show_skips:
        for s in skip_list[:60]:
            print("   ", s)
        if len(skip_list) > 60:
            print(f"    … ещё {len(skip_list) - 60}")
    if not a.apply:
        print("   файлы не тронуты; для правки — тот же вызов с --apply")
    return 0


if __name__ == "__main__":
    sys.exit(main())
