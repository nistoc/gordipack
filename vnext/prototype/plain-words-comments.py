"""plain-words-comments — перевод ПОЯСНЕНИЙ (комментарии и шапки) на общепонятные слова.

    python <КОНТУР>/vnext-tools/plain-words-comments.py            # холостой прогон
    python <КОНТУР>/vnext-tools/plain-words-comments.py --apply    # правка файлов

ПОВОД: слово владельца 17.08 08:27 UTC (правило `plain-words`). Показываемый текст переведён
17.08; здесь — вторая половина работы, пояснения внутри инструментов.

⚖️ ГЛАВНОЕ ОГРАНИЧЕНИЕ, НАЗВАННОЕ ДО КОДА: у новых слов ДРУГОЙ РОД. «сторож покраснел» →
«проверка покраснел» — замена по словарю ломает согласование. Это не догадка: 17.08 массовая
замена дважды за день выдала «не мешает правящая рольу» и «механизм стал бы бессмысленной»,
и оба раза поймал глаз, а не машина. ⇒ инструмент правит ТОЛЬКО там, где согласование
заведомо не задето, а спорное ОТКЛАДЫВАЕТ И ПЕРЕЧИСЛЯЕТ — рукой правится меньшинство.

ЧТО ОН НЕ ТРОГАЕТ (границы = границы правила `plain-words`):
  ⛔ показываемый текст (print / --help): он уже переведён 17.08, там своя приёмка;
  ⛔ образцы поиска (re.compile…): они ищут ПРЕЖНИЕ слова в памятях ролей, ещё не переписанных;
  ⛔ имена файлов, флагов, полей базы и ключей правил;
  ⛔ слова с двумя разными смыслами в разных местах — «витрина» (готовая выборка базы ИЛИ
     файл, собранный из базы), «врезка» (применение шага ИЛИ подстановка живого числа),
     «рубеж» (база сравнения ИЛИ отметка версии). Машине их не различить: отложены рукой.

ПРАВИЛО ПРОПУСКА (почему строка откладывается):
  · слева примыкает прилагательное или причастие («вечно-жёлтый сторож»);
  · справа в пределах двух слов стоит глагол прошедшего времени («сторож покраснел»);
  · слово стоит внутри кавычек-ёлочек — это ЦИТАТА чужой или прежней речи, её не правят.
"""
