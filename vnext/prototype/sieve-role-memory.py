# Строка ПРЕДОСТЕРЕГАЕТ или хоронит, а не приказывает. Тот же приём, что в признаке
# «форма вызова»: без него роль получает красное ЗА ПРАВИЛЬНО ЗАПИСАННЫЙ УРОК (карточка #50).
EXCUSED = re.compile(
    r"⛔|⚰️|❌|✗|надгроб|отмен|сня[лт]|больше не|прежн|устарел|не держ|НЕ ЗАПОМИНАЙ"
    r"|не зов|нельзя|запрещ|падает|неверн|ошибочн|было:|вместо|поймал|урок|цена"
    # ── Расширение 2026-08-13 (карточка #185). Формы взяты ИЗ ТАБЛИЦЫ ВЕРДИКТОВ по всем
    # 49 кандидатам девяти ролей (комментарий в карточке #185), а не из головы:
    # 22 из 49 оказались уроками и надгробиями, которых прибор не узнавал, и роль получала
    # красное за правильно записанный урок — ровно класс карточки #50, вторым заходом.
    r"|здесь стояло|стоял[аио]?\b|стал[аио]\b|стухш|перекрыт|опознан"   # рассказ прошедшим
    r"|учил[аи]?\b|нашл[аи]?\b"                                          # «учили звать не того»
    r"|говорит\s|а не «|а НЕ «"          # учит ТОЛКОВАНИЮ: «ahead 0 говорит X, а не «Y»»
    r"|бери запросом|из реестра"          # учит ЗАПРОСУ вместо хранения
    r"|точка отказа"                      # констатация риска, а не владение
    r"|протуха|нарочн",                   # «протухает»-урок · «нарочными поломками»-провенанс
    re.IGNORECASE)
# 🪤 «сня[лт]», а не «снят»: 2026-08-10 16:15 UTC решето показало кандидатом строку-урок
# «аварийную запись владелец СНЯЛ 08.08» — форма прошедшего времени в мужском роде мимо
# образца. Один суффикс — и верная строка попадает в список подозреваемых, а роль,
# устав от ложных, начинает пролистывать список целиком.

# Совпадение ВНУТРИ «ёлочек» — цитата, а не утверждение роли. Покрывает главный сорт ложных
# срабатываний: «ролей 8», «роли 6/6→7/7», «ALL SYNC каждые 2–15 мин», «реестр push — только
# из реестра», «9 проверок» — всё это цитаты протухших форм в уроках о том, что они протухли.
# ⚖️ Живой приказ В КАВЫЧКАХ этим прощением замолчится — граница названа в подсказке вывода;
# --show-excused показывает и цитаты, роль обязана их просматривать.
def _in_quotes(line: str, span: tuple[int, int]) -> bool:
    return line.rfind("«", 0, span[0]) > line.rfind("»", 0, span[0]) and "»" in line[span[1]:]


# Хэш/идентификатор — ПРОВЕНАНС, а не производный факт, когда он запись о СДЕЛАННОМ:
# коммит неизменяем, протухает только УТВЕРЖДЕНИЕ О НАСТОЯЩЕМ («дерево чисто», «ahead 0»).
# Формы — из таблицы вердиктов (22 из 49 были такими записями):
#   · вся секция history — хроника по построению;
#   · строка-гроссбух «hhhhhhh  что сделано» (хэш первым словом, двойной пробел);
#   · дата или маркер дела в ТОЙ ЖЕ строке: коммит · гейт N · миграция · сессия ·
#     записка #N · карточка #N · «Починено» · фаза.
# ⚠️ Правило нарочно НЕ прощает «дерево чисто»/«ahead N»/«неотправленного нет» — это
# состояния, их печатает живьём машинный слой §4⅞, хранить их канон запрещает.
_PROV_MARKERS = re.compile(
    r"\d{4}-\d{2}-\d{2}|\d{2}\.\d{2}\b|UTC|коммит|гейт\s*\d|миграци|сесси"
    r"|записка #|карточка #|Почин|фаза", re.IGNORECASE)
_LEDGER_ROW = re.compile(r"^[0-9a-f]{7,12}\s{2}")
_STATE_CLAIM = re.compile(r"дерево чисто|неотправленн|\bahead\s+\d", re.IGNORECASE)


def _is_provenance(label: str, sec: str, line: str) -> bool:
    if not label.startswith("производный факт"):
        return False
    # §history — хроника по построению: «записал ahead 1» там — РАССКАЗ о том дне, а не
    # утверждение о сегодняшнем. Первая редакция ставила проверку состояний ВЫШЕ хроники
    # и держала кандидатом рассказ ING о push-падении 25.07 — вердикт таблицы «провенанс».
    if sec == "history":
        return True
    if _STATE_CLAIM.search(line):
        return False          # утверждение о настоящем ВНЕ хроники — всегда кандидат
    return (_LEDGER_ROW.match(line.strip()) is not None
            or _PROV_MARKERS.search(line) is not None)

# Формы — по одному предмету на строку, чтобы находку можно было назвать словом.
FORMS = {
    "аварийная запись файлами (выход снят 08.08 16:53 UTC)":
        re.compile(r"--md\b|аварийн\w*\s+(?:opt-in|выход|запис)", re.I),
    "такт/таймер синка (ритм печатает механизм)":
        re.compile(r"кажд\w+\s+\d+[–\-]?\d*\s*мин|ставить таймер|подн\w+ такт|такт синка", re.I),
    "запрет отправки (снят владельцем 08.08 15:56 UTC)":
        re.compile(r"push\b[^.\n]{0,40}(?:только|нельзя|запрещ|по слову|не пуш)", re.I),
    # «спроси(?!л)»: повелительное — приказ, «спросил» — рассказ. Прежняя форма сматчила
    # рассказ PROTO о своём промахе («спросил „сколько записок" проверкой…») — вердикт УРОК.
    "спроси, прежде чем запускать проверки (снято 10.08 13:57 UTC)":
        re.compile(r"(?:не молча|спроси(?!л))[^.\n]{0,40}(?:guard|проверк|запуск)", re.I),
    "число ролей ТЕКСТОМ (канон запрещает держать вовсе)":
        re.compile(r"рол(?:ей|и)\s+(?:—\s*)?\d+|\d+\s+(?:живых\s+)?ролей", re.I),
    # Образец знает ОБА написания: «рубеж v4» (как писали до 17.08) и «отметка версии v4»
    # (как печатают инструменты теперь). Снять старое — только по замеру, что в памятях
    # ролей его не осталось: иначе проверка ослепнет ровно на тех, кто ещё не переписал.
    "номер версии схемы значением":
        re.compile(r"схем\w*\s+v\d|рубеж\w*\s+v\d|отметк\w*\s+версии\s+v\d", re.I),
    "число проверок/приёмок значением":
        re.compile(r"\d+\s*(?:гард|проверк\w*|приёмок|приёмк\w*|сторож)", re.I),
    "производный факт: хэш · ahead · порт":
        re.compile(r"\bahead\s+\d|\b[0-9a-f]{7,12}\b(?!\w)|:\s?5\d{3}\s+(?:отвеча|жив|200)", re.I),
    "относительный вызов скрипта (форма запрещена)":
        re.compile(r"python\s+\.?[\\/]?\.mezosync[\\/]scripts", re.I),
    "владение механизмом (сверь с реестром зон)":
        re.compile(r"владе\w+\s+(?:протокол|скрипт|механизм|базой|схем)|мо[йяе]\s+(?:скрипт|механизм)", re.I),
}


# ═══ ВТОРОЙ ВОПРОС: разряд «перемерь» (карточка #392) ══════════════════════════════
# Маркеры утверждения о ЖИВОМ мире — из замера @CHROME (карточка #392) плюс «в силе».
# «стои́т» с ударением и без: в памятях встречаются оба написания.
_REMEASURE_MARKERS = re.compile(
    r"не\s+отозван\w*|не\s+снят\w*|жд[её]т\b|блокер|жив[её]т\s+в\b"
    r"|стои́?т\s+на\b|в\s+силе\b", re.IGNORECASE)
# Надгробие гасит разряд. Просмотры назад с «не » — потому что «НЕ отозвано»/«не снято» —
# это, наоборот, живое утверждение, и глушить его его же словом было бы дырой в сам предмет.
_REMEASURE_TOMB = re.compile(
    r"⚰|надгроб|(?<!не )(?<!НЕ )отозван|(?<!не )(?<!НЕ )отмен|(?<!не )(?<!НЕ )сня[лт]",
    re.IGNORECASE)
_REMEASURE_DATE = re.compile(
    r"(?P<y>20\d\d)-(?P<m>\d\d)-(?P<d>\d\d)"
    r"|(?<![\d.])(?P<d2>\d{1,2})\.(?P<m2>\d\d)(?:\.(?P<y2>20\d\d))?(?![\d.])")


def _claim_age_days(line: str, now) -> float | None:
    """Возраст САМОЙ СТАРОЙ даты в строке, в сутках; None — дат нет.

    Судим по старейшей: утверждение «живо с 26.08» протухает от часа УТВЕРЖДЕНИЯ,
    а не от свежей даты, дописанной рядом. День.месяц без года — текущий год;
    вышло будущее — это прошлый год (декабрьская запись, читаемая в январе)."""
    import datetime as _dt
    oldest = None
    for m in _REMEASURE_DATE.finditer(line):
        try:
            if m.group("y"):
                d = _dt.date(int(m.group("y")), int(m.group("m")), int(m.group("d")))
            else:
                y = int(m.group("y2")) if m.group("y2") else now.year
                d = _dt.date(y, int(m.group("m2")), int(m.group("d2")))
                if not m.group("y2") and d > now:
                    d = _dt.date(y - 1, d.month, d.day)
        except ValueError:
            continue                      # 32.13 и подобное — не дата
        if oldest is None or d < oldest:
            oldest = d
    return None if oldest is None else (now - oldest).days


def _window(line: str, span: tuple[int, int], width: int = 150) -> str:
    """Окно ВОКРУГ совпадения, а не начало строки.

    🪤 Оплачено первым же применением, 2026-08-10 15:36 UTC: у ING строка §identity:40
    попала по живому приказу «🚨 Аварийный --md», но он стоял на 190-м символе, а печатались
    первые 150. Я увидел безобидное начало и чуть не списал НАСТОЯЩУЮ находку в ложные —
    то есть инструмент, созданный против «глаз пролистывает знакомое», сам показывал
    знакомое вместо причины. Печатать надо ТО, ЧТО СРАБОТАЛО.
    """
    if len(line) <= width:
        return line
    start, end = span
    left = max(0, start - (width - (end - start)) // 2)
    right = min(len(line), left + width)
    left = max(0, right - width)
    return ("…" if left > 0 else "") + line[left:right] + ("…" if right < len(line) else "")


def sieve(db: str, role: str, show_excused: bool, remeasure_days: int = 2) -> int:
    con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    rows = con.execute(
        "SELECT section, body, saved_at FROM phoenix WHERE UPPER(role)=? ORDER BY section",
        (role.upper(),)).fetchall()
    con.close()
    if not rows:
        print(f"⛔ НЕ ЗАПУСТИЛОСЬ: сохранённой памяти роли {role} в базе нет — это третий исход, не «чисто»")
        return 2

    print(f"🔎 ПРОВЕРКА ПАМЯТИ на устаревшие утверждения · роль {role.upper()} · разделов {len(rows)}")
    print("   Возраст секций (старое протухает молча — смотри в первую очередь):")
    for sec, body, saved in rows:
        print(f"      §{sec:9} {saved}  {len(body):6} симв")
    print()

    hits = excused = 0
    for label, rx in FORMS.items():
        found = []
        for sec, body, _ in rows:
            for i, line in enumerate(body.splitlines(), 1):
                m = rx.search(line)
                if not m:
                    continue
                # Позиция совпадения нужна печати: показываем ПРИЧИНУ попадания, а не начало строки.
                span = (m.start(), m.end())
                # Порядок прощений: провенанс (запись о сделанном) → цитата в «ёлочках» →
                # формы урока/надгробия. Все три считаются в excused и видны с --show-excused.
                if (_is_provenance(label, sec, line) or _in_quotes(line, span)
                        or EXCUSED.search(line)):
                    excused += 1
                    if show_excused:
                        found.append((sec, i, line.strip(), True, span))
                    continue
                found.append((sec, i, line.strip(), False, span))
                hits += 1
        if found:
            print(f"── {label}")
            for sec, i, line, is_excused, span in found:
                # Причина прощения печатается СЛОВОМ: «прощено» без причины не проверить глазами.
                if is_excused:
                    why = ("провенанс: запись о сделанном" if _is_provenance(label, sec, line)
                           else "цитата в «ёлочках»" if _in_quotes(line, span)
                           else "хоронит или предостерегает")
                    mark = f"  (прощено: {why})"
                else:
                    mark = ""
                print(f"   [{sec}:{i:3}] {_window(line, span)}{mark}")
            print()

    # ═══ ВТОРОЙ ВОПРОС (карточка #392): протухший приказ знакомой формы не имеет ═════
    import datetime as _dt
    today = _dt.datetime.now(_dt.timezone.utc).date()
    remeasure = []
    for sec, body, _ in rows:
        if sec == "history":
            continue                       # хроника по построению: там всё — рассказ
        for i, line in enumerate(body.splitlines(), 1):
            m = _REMEASURE_MARKERS.search(line)
            if not m or _REMEASURE_TOMB.search(line):
                continue
            age = _claim_age_days(line, today)
            if age is None or age < remeasure_days:
                continue
            remeasure.append((sec, i, line.strip(), (m.start(), m.end()), age))
    if remeasure:
        print(f"── УТВЕРЖДЕНИЕ О ЖИВОМ МИРЕ СТАРШЕ {remeasure_days} СУТОК — ПЕРЕМЕРЬ")
        print("   Это не находка, а требование перемера: проверка не знает, отозвано ли, —")
        print("   но знает, что утверждение старое и ПРОВЕРЯЕМОЕ. Спроси мир, не память.")
        for sec, i, line, span, age in remeasure:
            print(f"   [{sec}:{i:3}] ({age} сут) {_window(line, span)}")
        print()

    print(f"ИТОГО кандидатов: {hits} · прощено как надгробия и уроки: {excused}"
          f" · требуют перемера: {len(remeasure)}")
    print("⚖️ Кандидат — НЕ находка: каждого разбирай ГЛАЗАМИ. Прощённые тоже смотри —")
    print("   если среди них живой приказ, проверка промолчала ЗРЯ, и чинить надо проверку.")
    print("⚠️ Ищутся ЗНАКОМЫЕ формы. Отменённое непривычными словами не найдётся ВООБЩЕ:")
    print("   пустой вывод значит «знакомых форм нет», а не «память чиста».")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description="Проверка памяти роли на устаревшие утверждения (подготовка к пересозданию)")
    ap.add_argument("--role", required=True)
    ap.add_argument("--db", default=None)
    ap.add_argument("--show-excused", action="store_true",
                    help="показать и прощённые строки: они бывают живым приказом в маске урока")
    ap.add_argument("--remeasure-days", type=int, default=2, dest="remeasure_days",
                    help="порог разряда «перемерь» в сутках (карточка #392): утверждение "
                         "о живом мире со часом старше порога требует перемера. "
                         "По умолчанию 2 — настоящие протухания замера жили 1–3 суток")
    a = ap.parse_args()
    db = a.db or str(mezo_paths.live_db())
    return sieve(db, a.role, a.show_excused, a.remeasure_days)


if __name__ == "__main__":
    sys.exit(main())
