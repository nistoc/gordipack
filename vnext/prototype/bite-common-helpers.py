# -*- coding: utf-8 -*-
r"""bite-common-helpers.py — приёмка карточки #578: общие по имени помощники ДВУХ рабочих
каталогов контура обязаны быть ОДНОЙ версией, и расхождение обязано краснеть.

═══ ЧТО БЫЛО
У инструментов v-next своя копия разрешателя путей, отставшая на 17 суток. Её зовут
136 инструментов из 192 ⇒ починка, сделанная в каталоге контура, до них не доезжала.
🩸 И это не «просто отставание»: в старой копии жил ровно тот дефект, который в новой
вылечен, — при ненайденном корне она МОЛЧА возвращала «ожидаемое место», а подключение
по этому пути создавало ПУСТУЮ базу вместо отказа.

═══ ПОЧЕМУ НЕ ЛОВИЛОСЬ
Сверки знают пары «рантайм ↔ зеркало» и «v-next ↔ образец». Файл, живущий в ОБЕИХ парах
разными копиями, ни в одной из них не сравнивается сам с собой. Молчание по построению.

═══ ВЕДУЩАЯ СТОРОНА У КАЖДОГО ФАЙЛА СВОЯ — ЭТО ГЛАВНОЕ
📏 Замер 2026-09-06: общих по имени файлов ДВА, и оба расходились.
    mezo_paths.py .... новее в каталоге контура (21994б против 10916б)
    mezo_stand.py .... новее в каталоге v-next (11690б против 7433б: там работа #572)
⇒ «Синхронизировать в одну сторону» стёрло бы одну из двух работ. Поэтому проверка
НЕ сводит сама и не советует направления — говорит, ЧТО разошлось.

═══ ОЖИДАНИЯ ПОЛОМКИ — НАЗВАНЫ ДО ПРОГОНА
    П1 вызов третьей пары убран из инструмента
       ждём: ① перестаёт краснеть, ② остаётся зелёным (он и так про совпадение)

═══ ДОБАВЛЕНО 2026-09-07 (карточка #586)
Случаи ①-⑤ проверяют МЕХАНИЗМ на подставном "helper.py" внутри стенда — они никогда
не читают настоящие рабочие каталоги и потому не могут поймать регресс в КОНКРЕТНОМ
общем помощнике. Случай ⑥ — единственный здесь, что смотрит на настоящую пару
`.mezosync/scripts/mezo_hints.py` ↔ `vnext-tools/mezo_hints.py` (заведена той же
карточкой #586: механизм «подсказка один раз, дальше строка-ссылка»). Зеркало и шаблон
у него по-прежнему подставные — реальный бэкап-репозиторий не должен решать зелёное/
красное ЭТОГО случая, тот же довод, что у случаев ①-⑤.
"""
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import mezo_paths  # noqa: E402
import mezo_stand  # noqa: E402

ИНСТРУМЕНТ = Path(mezo_paths.live_scripts(__file__)) / "guard-scripts-drift.py"
итог: list[tuple[str, bool, str]] = []


def случай(имя: str, ок: bool, слово: str) -> None:
    итог.append((имя, ок, слово))
    print(f"{'✅' if ок else '🔴'} {имя}: {слово}")


def прогон(стенд: Path, инструмент: Path | None = None):
    """Зову сверку на ПОДСТАВНЫХ каталогах: живого хозяйства приёмка не касается."""
    r = subprocess.run(
        [sys.executable, str(инструмент or ИНСТРУМЕНТ),
         "--runtime", str(стенд / "contour"), "--repo", str(стенд / "mirror"),
         "--vnext-runtime", str(стенд / "vnext"), "--vnext-template", str(стенд / "template")],
        capture_output=True, text=True, encoding="utf-8", timeout=300)
    return r.returncode, (r.stdout or "") + (r.stderr or "")


def прогон_настоящих(стенд: Path):
    """Как прогон(), но --runtime/--vnext-runtime указывают на НАСТОЯЩИЕ рабочие каталоги
    контура (.mezosync/scripts и vnext-tools), а не на подставные. Зеркало и шаблон
    остаются подставным пустым каталогом стенда — реальный бэкап-репозиторий не должен
    решать зелёное/красное случая ⑥ (карточка #586)."""
    r = subprocess.run(
        [sys.executable, str(ИНСТРУМЕНТ),
         "--runtime", str(mezo_paths.live_scripts(__file__)),
         "--repo", str(стенд / "repo"),
         "--vnext-runtime", str(mezo_paths.container_root(__file__) / "vnext-tools"),
         "--vnext-template", str(стенд / "template")],
        capture_output=True, text=True, encoding="utf-8", timeout=300)
    return r.returncode, (r.stdout or "") + (r.stderr or "")


def построить(стенд: Path, общий_разный: bool, только_в_одном: bool = False) -> None:
    for имя in ("contour", "mirror", "vnext", "template"):
        (стенд / имя).mkdir(parents=True, exist_ok=True)
    (стенд / "contour" / "helper.py").write_text("ЗНАЧЕНИЕ = 1" + chr(10), encoding="utf-8")
    (стенд / "vnext" / "helper.py").write_text(
        ("ЗНАЧЕНИЕ = 2" if общий_разный else "ЗНАЧЕНИЕ = 1") + chr(10), encoding="utf-8")
    if только_в_одном:
        (стенд / "contour" / "одинокий.py").write_text("# только здесь" + chr(10),
                                                       encoding="utf-8")
    # зеркало = точная копия каталога контура, чтобы ПЕРВАЯ пара не шумела
    shutil.rmtree(стенд / "mirror")
    shutil.copytree(стенд / "contour", стенд / "mirror")


def main() -> int:
    стенд = Path(mezo_stand.new("bite-common-helpers-"))

    построить(стенд, общий_разный=True)
    код, вывод = прогон(стенд)
    случай("① разные копии общего помощника — проверка КРАСНЕЕТ и называет файл",
           "ОБЩИЕ ПОМОЩНИКИ РАСХОДЯТСЯ" in вывод and "helper.py" in вывод,
           "названо расхождение" if "ОБЩИЕ ПОМОЩНИКИ РАСХОДЯТСЯ" in вывод
           else "молчит — а копии разные")

    случай("② красное ВЛИЯЕТ на код возврата, а не только печатается",
           код == 1,
           f"код {код}" + ("" if код == 1 else " — проверка, не меняющая исход, не мешает никому"))

    построить(стенд, общий_разный=False)
    код2, вывод2 = прогон(стенд)
    случай("③ ВСТРЕЧНЫЙ: сведённые копии — зелёное и код 0",
           код2 == 0 and "совпадают байт в байт" in вывод2,
           f"код {код2}, сказано о совпадении"
           if "совпадают байт в байт" in вывод2 else "о совпадении не сказано")

    построить(стенд, общий_разный=False, только_в_одном=True)
    код3, вывод3 = прогон(стенд)
    случай("④ ВСТРЕЧНЫЙ: файл, который есть ТОЛЬКО в одном каталоге, не краснеет",
           код3 == 0 and "ОБЩИЕ ПОМОЩНИКИ РАСХОДЯТСЯ" not in вывод3,
           f"код {код3} — иначе проверка требовала бы копировать всё подряд из каталога "
           "в каталог, а каталоги разные по назначению")

    # ⑤ ОБРАТНЫЙ ХОД: вызов третьей пары убран — расхождение снова молчит.
    копия_стенд = Path(mezo_stand.new("bite-common-helpers-blind-"))
    копия = mezo_stand.copy_tool(ИНСТРУМЕНТ, копия_стенд)
    текст = копия.read_text(encoding="utf-8")
    копия.write_bytes(текст.replace("    return сверить_общих_помощников()",
                                    "    return 0", 1).encode("utf-8"))
    построить(стенд, общий_разный=True)
    код5, вывод5 = прогон(стенд, копия)
    случай("⑤ ОБРАТНЫЙ ХОД: вызов третьей пары убран → те же копии снова молчат",
           "ОБЩИЕ ПОМОЩНИКИ РАСХОДЯТСЯ" not in вывод5,
           "молчит — значит краснеет ИМЕННО третья пара, а не что-то рядом"
           if "ОБЩИЕ ПОМОЩНИКИ РАСХОДЯТСЯ" not in вывод5
           else "красит и без вызова — красит что-то другое")
    mezo_stand.release(копия_стенд)
    mezo_stand.release(стенд)

    # ⑥ РЕАЛЬНАЯ ПАРА (карточка #586): .mezosync/scripts/mezo_hints.py ↔
    # vnext-tools/mezo_hints.py — сверка НАСТОЯЩИХ рабочих каталогов, не стенда.
    # ⚖️ Этот случай не про фиксированный ожидаемый исход, как ①-⑤ на подставных данных:
    # он честно отражает состояние ДВУХ РЕАЛЬНЫХ файлов на диске в момент прогона.
    # Так и задумана его роль в приёмке: три прогона подряд (сведены → нарочно испорчено
    # → возвращено) обязаны дать зелёный → красный с именем файла → зелёный.
    стенд6 = Path(mezo_stand.new("bite-common-helpers-real-"))
    (стенд6 / "repo").mkdir(parents=True, exist_ok=True)
    (стенд6 / "template").mkdir(parents=True, exist_ok=True)
    _, вывод6 = прогон_настоящих(стенд6)
    разошлось6 = "ОБЩИЕ ПОМОЩНИКИ РАСХОДЯТСЯ" in вывод6 and "mezo_hints.py" in вывод6
    случай("⑥ РЕАЛЬНАЯ ПАРА: .mezosync/scripts/mezo_hints.py ↔ vnext-tools/mezo_hints.py",
           not разошлось6,
           "сведены байт в байт" if not разошлось6
           else "🔴 РАСХОДЯТСЯ прямо сейчас — копии не совпадают")
    mezo_stand.release(стенд6)

    красных = [и for и, ок, _ in итог if not ок]
    print("")
    print("=" * 78)
    print(f"РАЗЛИЧАЮЩИХ СЛУЧАЕВ {len(итог)}, из них ВСТРЕЧНЫХ 2 (③ и ④)")
    print("⚖️ ГРАНИЦА: сверяются БАЙТЫ. Совпадение байтов НЕ означает равносильности —")
    print("   инструмент зависит и от того, что лежит рядом с ним. И переименованную")
    print("   копию того же помощника проверка не поймает: её не с чем сравнить.")
    if красных:
        print(f"🔴 ПРОВАЛЕНО {len(красных)}: {' · '.join(красных)}")
        return 1
    print("✅ ВСЕ СЛУЧАИ ПРОЙДЕНЫ")
    return 0


if __name__ == "__main__":
    sys.exit(mezo_stand.finish(main()))
