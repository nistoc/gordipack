# -*- coding: utf-8 -*-
r"""ПРИЁМКА общего различителя «употребление или упоминание» (mention.py, карточка #57).

Каждый случай — ЖИВОЙ, из оплаченных ошибок; выдуманных здесь нет. Приёмка стережёт обе
стороны разом: детектор, ослепший от вежливости, и детектор, кричащий на вежливость.

⛔ Число случаев печатает прогон.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
try:
    import mention
except ImportError:
    print(f"⛔ ИСПЫТУЕМОГО НЕТ: {HERE}/mention.py — отказ мерить, не «чисто»")
    sys.exit(2)

CASES = 0
DIFFER = 0


def case(title, verdict, detail, differ=False):
    global CASES, DIFFER
    CASES += 1
    DIFFER += bool(differ)
    print(f"{'✅' if verdict else '🔴'} {title}")
    print(f"   {detail}")
    return verdict


def main() -> int:
    ok = True

    # ① ПРЕДПИСАНИЕ — не упоминание. Контроль: без него молчание ничего не значит.
    ok &= case("① голое предписание — УПОТРЕБЛЕНИЕ",
               not mention.is_mention("зови: python read-messages.py --role X"),
               "детектор, считающий упоминанием всё, бесполезен так же, как слепой")

    # ② ОТМЕНА В ТОЙ ЖЕ ЕДИНИЦЕ — упоминание (историю писать нужно)
    ok &= case("② «⛔ ОТОЗВАНО: …форма…» — УПОМИНАНИЕ",
               mention.is_mention("⛔ ОТОЗВАНО: python x.py --db — так больше не зовут"),
               "иначе проверка наказывает за честное объяснение отмены", differ=True)

    # ③ ЖИВОЙ СЛУЧАЙ #151: отмена — в СОСЕДНЕЙ строке, про ДРУГОЕ. Единица — строка,
    #    поэтому предписание остаётся предписанием.
    order = "подтверди: python .mezosync/scripts/read-messages.py --ack X"
    ok &= case("③ отмена строкой НИЖЕ и про другое — предписание остаётся (урок #151)",
               not mention.is_mention(order),
               "у соседства не спрашивают, о чём оно; единица суждения — сама строка",
               differ=True)

    # ④ ЖИВОЙ СЛУЧАЙ #152: код. `add_argument("--md",` и его help= — ОДНА единица,
    #    и пометка в продолжении засчитывается.
    code = ('parser.add_argument("--md", action="store_true",\n'
            '                    help="⛔ СНЯТ владельцем 08.08: вызов отклонён.")')
    us = list(mention.units(code))
    ok &= case("④ выражение кода — ОДНА единица, пометка в продолжении засчитывается",
               len(us) == 1 and mention.is_mention(us[0][1]),
               f"единиц {len(us)} (ждём 1); иначе честная запись объявляется неправдой",
               differ=True)

    # ⑤ ВСТРЕЧНЫЙ к ④: законченное выражение + самостоятельная соседняя строка = ДВЕ единицы
    code2 = 'print("сломается база — пиши --md")\n# ⛔ СНЯТО: речь о ДРУГОМ механизме.'
    us2 = list(mention.units(code2))
    ok &= case("⑤ законченное выражение и соседняя строка — РАЗНЫЕ единицы (встречный к ④)",
               len(us2) == 2 and not mention.is_mention(us2[0][1]),
               f"единиц {len(us2)} (ждём 2); послабление ④ обязано быть узким", differ=True)

    # ⑥ ЖИВОЙ СЛУЧАЙ #144: поправка ПРО ДРУГОЕ не гасит — тема обязательна.
    other = "(обход снят живьём, токен-инструкция исправлена по #2809)"
    ok &= case("⑥ поправка про ДРУГОЕ с темой «время» — НЕ упоминание нашего предмета",
               not mention.is_mention(other, subject=r"UTC|метк|время|час"),
               "живая записка так погасила дефект метки в чужой ноте", differ=True)

    # ⑦ ВСТРЕЧНЫЙ к ⑥: та же форма, но ПРО ЭТО — гасит
    ours = "ПОПРАВКА: метки времени в записке #3419 на два часа вперёд"
    ok &= case("⑦ поправка ПРО ЭТО — упоминание (встречный к ⑥)",
               mention.is_mention(ours, subject=r"UTC|метк|время|час"),
               "иначе честное признание не закрывает дефект и роль наказана за него",
               differ=True)

    # ⑧ ЖИВОЙ СЛУЧАЙ #154: цитата в «ёлочках» — не утверждение
    ok &= case("⑧ число в «ёлочках» — упоминание (цитата урока)",
               mention.is_mention("урок: «11 правил» при четырёх — впечатанное число врёт"),
               "цитата чужой ошибки не есть своя ошибка", differ=True)

    # ⑨ ОБРАЗЕЦ ФОРМАТА — упоминание (живой случай гарда времени: строка @ING про формат)
    ok &= case("⑨ «Формат „2026-07-26 11:22 UTC“» — упоминание, а не метка события",
               mention.is_mention('Формат «2026-07-26 11:22 UTC», суффикс обязателен'),
               "пример показывает форму, а не предписывает событие", differ=True)

    # ⑩ РОДЫ НАЗЫВАЮТСЯ ПОИМЁННО — потребитель обязан видеть, ЧЕМ погашено, иначе
    #    гашение неотличимо от слепоты (и отладить его нечем).
    got = mention.marks("⛔ ОТОЗВАНО, раньше писали «так» — например, вот так")
    ok &= case("⑩ приметы называются родами, а не булевым «да»",
               {"cancel", "history", "quote", "example"} <= got,
               f"роды: {sorted(got)}", differ=True)

    # ⑪ ВЫБОР РОДОВ СУЖАЕТСЯ ПОТРЕБИТЕЛЕМ: там, где история НЕ должна гасить
    #    (канон «число ролей не держим»), род history просто не запрашивается.
    line = "⚠️ РОЛЕЙ 8 на 26.07 — НО ЧИСЛО НЕ ЗАПОМИНАЙ, ПРОВЕРЯЙ"
    ok &= case("⑪ потребитель выбирает роды: дата не гасит там, где запрет безусловен",
               mention.is_mention(line) and
               not mention.is_mention(line, kinds=("quote", "example")),
               "у канона нет исключения «если рядом дата» — и модуль не навязывает его",
               differ=True)

    # ⑫ ЖИВОЙ СЛУЧАЙ 09.08 23:44: слово-примета ВНУТРИ ИМЕНИ ФАЙЛА. Перевод второго
    #    потребителя на общий словарь сделал красное зелёным именно здесь.
    named = ("python <КОНТУР>/.mezosync/scripts/check-retired-mechanism.py"
             " --db <копия> --root <кат>")
    ok &= case("⑫ «retired» ВНУТРИ имени файла — НЕ примета (имена и пути не говорят)",
               not mention.is_mention(named),
               f"роды: {sorted(mention.marks(named))} (ждём пусто); иначе гард слепнет "
               "на строке, названной по предмету", differ=True)

    # ⑬ ВСТРЕЧНЫЙ к ⑫: то же слово РЕЧЬЮ, рядом с тем же именем — примета остаётся
    spoken = "⛔ ОТОЗВАНО: check-retired-mechanism.py больше не зовут — механизм снят"
    ok &= case("⑬ отмена СЛОВАМИ рядом с тем же именем — упоминание (встречный к ⑫)",
               mention.is_mention(spoken),
               "вымарывание имён обязано быть узким: речь про предмет не должна пропасть",
               differ=True)

    print()
    print(f"{'✅ РАЗЛИЧИТЕЛЬ ПРИНЯТ' if ok else '🔴 РАЗЛИЧИТЕЛЬ НЕ ПРИНЯТ'} — случаев {CASES}, "
          f"различающих {DIFFER}; все случаи — ЖИВЫЕ, из оплаченных ошибок")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
