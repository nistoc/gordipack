# -*- coding: utf-8 -*-
"""КАКУЮ КОПИЮ ИСПЫТЫВАЕМ — одно место на все приёмки.

ПОВОД (карточка #148, замер 2026-08-09). Приёмки жёстко указывали на ЖИВЫЕ скрипты. Отсюда
следствие, которое легко принять за успех: прогон ПОСЛЕ переноса в шаблон доказывает
исправность ОРИГИНАЛА, а не копии. Хуже того, приёмка прав читала описание таблицы из файла
шага схемы рядом со скриптом — и, будучи направленной на шаблон, МОЛЧА брала его из живого
контура, потому что в шаблоне каталога шагов не было вовсе.

Два рычага, оба через переменные окружения — приёмку не надо переписывать под каждый прогон:
    MEZO_SCRIPTS_ROOT=<путь>   какой каталог считать испытуемым (по умолчанию — живой)
    MEZO_FORBID_LIVE=1         ⛔ ЗАПРЕТИТЬ обращение к живому контуру. Не «предупредить» —
                               именно остановиться: молчаливый заём из живого и есть тот
                               дефект, ради которого всё это заведено.

⚖️ Третий исход обязателен: «НЕ ЗАПУСТИЛАСЬ» — не «сломано» и НЕ «зелено».
"""
import os
import sys
from pathlib import Path

LIVE_SCRIPTS = Path(r"C:\guts\.atlas\.mezosync\scripts")


def scripts_root() -> Path:
    return Path(os.environ.get("MEZO_SCRIPTS_ROOT") or LIVE_SCRIPTS)


def _check_not_live(p: Path, what: str) -> None:
    if os.environ.get("MEZO_FORBID_LIVE") != "1":
        return
    try:
        p.resolve().relative_to(LIVE_SCRIPTS.resolve())
    except ValueError:
        return
    sys.exit(f"⛔ НЕ ЗАПУСТИЛАСЬ: {what} взят(о) ИЗ ЖИВОГО КОНТУРА ({p}).\n"
             "   Прогон запрещён явно (MEZO_FORBID_LIVE=1): иначе испытуемой копией\n"
             "   молча оказывается оригинал, и зелёный ответ не значит ничего.")


def script(name: str) -> Path:
    """Путь к испытуемому механизму. Нет файла — это ОТКАЗ, а не тихий заём из живого."""
    p = scripts_root() / name
    _check_not_live(p, f"механизм {name}")
    if not p.exists():
        sys.exit(f"⛔ НЕ ЗАПУСТИЛАСЬ: в испытуемом каталоге нет {name}\n"
                 f"   каталог: {scripts_root()}\n"
                 "   Это НЕ «сломано» и НЕ «в порядке» — испытывать нечего.")
    return p


def migration(name: str) -> Path:
    """Файл шага схемы. Ищется РЯДОМ с испытуемым механизмом, а не там, где удобно."""
    p = scripts_root() / "migrations" / name
    _check_not_live(p, f"шаг схемы {name}")
    if not p.exists():
        sys.exit(f"⛔ НЕ ЗАПУСТИЛАСЬ: рядом с испытуемым каталогом нет шага схемы {name}\n"
                 f"   искал: {p}\n"
                 "   Раньше он молча брался из живого контура — и прогон «по шаблону»\n"
                 "   на деле проверял живой.")
    return p
