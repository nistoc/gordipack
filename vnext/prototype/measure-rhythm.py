            # в find-owner-word.py как ОБЁРТКА_БУДИЛЬНИКА_СТАРАЯ.
            # 🎯 ЗАМЕР 05.09 11:40 UTC по находке @COORD (записка #4833 §①). Он мерил ПОЛЕ
            # promptSource и был прав о нём: по одному этому полю «ударами» вышло бы 4064
            # записи из 4064 — вместе со всеми словами владельца. Прибор так не судил
            # с 04.09, и в его же чате все ПЯТЬ слов владельца были отсеяны полем origin.
            # ⚖️ Но его различитель isMeta принёс ОДНО настоящее улучшение, и оно взято:
            #    мой признак ..... 1854 · isMeta ..... 1810
            #    мой без isMeta пропускал 1 слово человека (origin нет, isMeta нет)
            #    isMeta без origin пропускал 2 сообщения СОСЕДНИХ сессий (origin=peer)
