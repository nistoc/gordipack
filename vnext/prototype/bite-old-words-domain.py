# -*- coding: utf-8 -*-
r"""ПРИЁМКА предметных исключений замера прежних слов — карточка #265.

🩸 ЧЕМ ОПЛАЧЕНО: четыре ложных срабатывания из поимённого разбора 179 контекстов
(перемер #209, 26.08): «мутант» mutation testing у CHROME · «витрина данных» у RCC
не отпускалась узким признаком · глагол «укусил/укусило» считался термином «укус» ·
метафора «перед дверью» и «аренда» у TAXO (сужены ещё 18.08 — здесь их пара держит
сделанное). Обвинение без разбора дороже пропуска: читающий перестаёт верить
проверке целиком.

Каждый случай — ПАРА: предметное употребление зеленеет (0), жаргонное краснеет (1).
Без пары сужение неотличимо от ослепления: «ловит ноль» умеет и мёртвый признак.
Обратный ход: одно сужение снято — жаргонная половина его пары обязана дать ДРУГОЕ.
"""
from __future__ import annotations

import importlib.util
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sp = importlib.util.spec_from_file_location("mow", HERE / "measure-old-words.py")
mow = importlib.util.module_from_spec(sp)
_argv, sys.argv = sys.argv, ["bite"]
sp.loader.exec_module(mow)
sys.argv = _argv

CASES = DIFFER = 0


def case(title, verdict, detail, differ=False):
    global CASES, DIFFER
    CASES += 1
    DIFFER += bool(differ)
    print(f"{'✅' if verdict else '🔴'} {title}")
    print(f"   {detail}")
    return verdict


def n(word, text):
    return mow.count(word, mow.WORDS[word], text)


def main() -> int:
    ok = True

    # ① мутант: mutation testing — предметно; «мутант» о нарочной поломке без языка
    # области — жаргон механизма (термин контура: нарочная поломка).
    предмет = "Выживший мутант ценнее убитого — вопрос «чем сломанное отличается от целого»."
    жаргон = "прогнал мутанта по приёмке — сторож не заметил, чиню признак"
    ok &= case("① «мутант» в mutation testing — отпущен", n("мутант", предмет) == 0,
               f"живой текст CHROME: найдено {n('мутант', предмет)} (ждём 0)", differ=True)
    ok &= case("①-пара: «мутант» жаргоном механизма — считается", n("мутант", жаргон) == 1,
               f"без языка области: {n('мутант', жаргон)} (ждём 1)", differ=True)

    # ② витрина: слой хранилища — предметно (живые тексты RCC, оба прежде НЕ отпускались);
    # «витрина курации» — жаргон механизма (норма: экран, список, выдача).
    предмет2а = "дистиллят (источники → слои BQ+Falcon, витрины/метрики, lineage-цепочки)"
    предмет2б = "«посчитай по всем регистрациям» на 670 млн — не тот же вопрос, что на витрине в миллион. И .table_samples — top-100 строк"
    жаргон2 = "витрина курации показывает кандидатов на разбор стюарду"
    ok &= case("② «витрины/метрики» у RCC (BQ, не BigQuery) — отпущена",
               n("витрина", предмет2а) == 0,
               f"найдено {n('витрина', предмет2а)} (ждём 0; прежний признак давал 1)",
               differ=True)
    ok &= case("②-бис: «на витрине в миллион … table_samples» — отпущена",
               n("витрина", предмет2б) == 0,
               f"найдено {n('витрина', предмет2б)} (ждём 0)", differ=True)
    ok &= case("②-пара: «витрина курации» жаргоном — считается", n("витрина", жаргон2) == 1,
               f"найдено {n('витрина', жаргон2)} (ждём 1)", differ=True)

    # ③ укус: глагол — обычная речь; существительное — термин механизма (норма: приёмка).
    глагол = "И этот предел укусил меня 25.08 — с другой стороны; меня укусило дважды за час"
    сущ = "оплачено укусом 18.08: приёмка тогда ещё звалась укусом и лежала рядом"
    ok &= case("③ глагол «укусил/укусило» — не термин", n("укус", глагол) == 0,
               f"живые тексты COORD и OPSSRE: найдено {n('укус', глагол)} (ждём 0)",
               differ=True)
    ok &= case("③-пара: существительное «укус(ом)» — считается", n("укус", сущ) == 2,
               f"именные формы: {n('укус', сущ)} (ждём 2 — «укусом» и «укусом»)",
               differ=True)

    # ④ дверь/аренда (сужены 18.08, @TAXO #3610) — пара ДЕРЖИТ сделанное.
    метафора = "строка запрёт преемницу перед дверью, которую никто не толкал"
    термин4 = "дверь инструмента: запуск lease.py объявлен единственным входом"
    ok &= case("④ метафора «перед дверью» — не термин", n("дверь (инструмента)", метафора) == 0,
               f"живой текст TAXO: найдено {n('дверь (инструмента)', метафора)} (ждём 0)",
               differ=True)
    ok &= case("④-пара: «дверь инструмента … запуск» — считается",
               n("дверь (инструмента)", термин4) == 1,
               f"найдено {n('дверь (инструмента)', термин4)} (ждём 1)", differ=True)

    # ОБРАТНЫЙ ХОД: сужение ③ снято (прежний образец «укус\w*») — глагольная
    # половина пары обязана дать ДРУГОЕ (2 вместо 0). Ослабляется КОПИЯ словаря,
    # живой словарь не трогается.
    прежний = dict(mow.WORDS, **{"укус": r"укус\w*"})
    слабое = mow.count("укус", прежний["укус"], глагол)
    ok &= case("⑤ ОБРАТНЫЙ ХОД: прежний образец «укус\\w*» на тех же глаголах",
               слабое == 2 and n("укус", глагол) == 0,
               f"прежний находит {слабое} (глаголы!), суженный 0 — разница и есть починка",
               differ=True)

    print()
    print(f"{'✅ ИСКЛЮЧЕНИЯ ПРИНЯТЫ' if ok else '🔴 НЕ ПРИНЯТО'} — случаев {CASES}, "
          f"различающих {DIFFER}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
