# -*- coding: utf-8 -*-
r"""ПРИЁМКА ЕДИНИЦЫ СУЖДЕНИЯ в стороже стандарта роли (карточка #155, класс #151).

КЛАСС: гашение находки ОКРЕСТНОСТЬЮ. У соседней строки не спросишь, про что её слово, —
и надгробие соседнего пункта тушит чужую находку. В стороже печатных форм это вылечено
09.08 (единица — строка); здесь жило дальше, в ШЕСТИ местах с окнами ±2, ±3, (−2,+4)…

⚡ ЧЕМ ЭТА ПРИЁМКА ОТЛИЧАЕТСЯ ОТ ОЖИДАНИЙ, С КОТОРЫМИ Я НАЧИНАЛ (замер 10.08 00:47–00:54):
Буквальное «везде строка» БЫЛО ОТВЕРГНУТО ЗАМЕРОМ — оно ломало 3 честных гашения из 5.
Абзац до пустой строки отвергнут следом: в слепках блоки по 20+ строк, и он оказался ШИРЕ
прежнего окна. Принята третья единица — ПРЕДЛОЖЕНИЕ: его ширину задаёт сам текст, а не
вёрстка и не расстояние. Для ⑨ — предложение ПЛЮС одно следующее суждение, потому что
граница у нас пишется отдельной строкой под обещанием («⛔ ЧЕГО НЕ МЕРИЛА: …»).

📌 ГЛАВНОЕ, ЧТО ВСКРЫЛО СУЖЕНИЕ: широкая окрестность ПРЯТАЛА ДЕФЕКТ САМОГО ПРИЗНАКА ⑨ —
он ловил слова «ни одного» и «все 7 секций» в ОТРИЦАНИЯХ и ПРЕДПИСАНИЯХ, а пометка из
соседнего суждения случайно его гасила. Тише было не потому, что верно.

⛔ Число случаев печатает прогон.
"""
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GUARD = os.path.join(HERE, "guard-role-standard.py")
if not os.path.exists(GUARD):
    print(f"⛔ ИСПЫТУЕМОГО НЕТ: {GUARD} — отказ мерить, не «чисто»")
    sys.exit(2)
sys.path.insert(0, HERE)
spec = importlib.util.spec_from_file_location("guard_unit_under_test", GUARD)
G = importlib.util.module_from_spec(spec)
spec.loader.exec_module(G)

CASES = 0
DIFFER = 0


def case(title, verdict, detail, differ=False):
    global CASES, DIFFER
    CASES += 1
    DIFFER += bool(differ)
    print(f"{'✅' if verdict else '🔴'} {title}")
    print(f"   {detail}")
    return verdict


def main() -> int:
    ok = True

    # ═══ ЕДИНИЦА: ПРЕДЛОЖЕНИЕ, А НЕ СТРОКА И НЕ ОКНО ═══

    # ① ЖИВОЙ СЛУЧАЙ @TAXO §launcher: пометка и предмет — ОДНО предложение, разорванное
    #    переносом. «Везде строка» объявила бы честную запись долгом.
    wrapped = ["📌 `--db` НЕ набирай — снят 26.07 (R15a): дефолт = живая база рядом",
               "со скриптом. `--db <путь>` указывай ТОЛЬКО для не-дефолтной БД."]
    ok &= case("① перенос ВНУТРИ предложения не кончает суждение (живой @TAXO)",
               bool(G.near(wrapped, 2, G.DB_OK, para=True)),
               "физическая строка — единица ВЁРСТКИ, а не мысли", differ=True)

    # ② ВСТРЕЧНЫЙ к ①: соседнее СУЖДЕНИЕ (начинается со значка) не приклеивается
    neighbour = ["⛔ ОТОЗВАНО: механизм исчез, так больше не зовут.",
                 "python x.py --db C:/live.db"]
    ok &= case("② надгробие СОСЕДНЕГО суждения не гасит (урок #151)",
               not G.near(neighbour, 2, G.DB_OK, para=True),
               "у соседа не спросишь, про что его слово", differ=True)

    # ③ ЖИВОЙ СЛУЧАЙ, ОТВЕРГНУВШИЙ АБЗАЦ: блок в 20+ строк без пустых. Знак ⛔ из пункта,
    #    отстоящего на 15 строк, гасил живую находку «правил 23» — абзац оказался шире окна.
    block = ["⑥ ЧЕГО НЕ ДЕЛАТЬ БЕЗ ЖИВОГО СЛОВА"] + \
            ["⛔ разрушающее (force push · drop) · мутации стенда ·"] + \
            [f"пункт блока {k} ·" for k in range(12)] + \
            ["форма рабочая: у владельца ею закрыто 23 правила"]
    ok &= case("③ значок из пункта за 14 строк НЕ дотягивается (абзац отвергнут замером)",
               not G.near(block, len(block), G.REVOKED_NEAR, para=True),
               "единица, чья ширина зависит от чужой привычки верстать, — не единица",
               differ=True)

    # ═══ ⑨ ОБЕЩАНИЕ ОХВАТА: единица шире на ОДНО суждение — и это названо ═══

    ok &= case("④ обещание охвата БЕЗ границы — кричит",
               len(G.check_coverage_bounded(["Проверено всё: девять ролей."], "t")) == 1,
               "иначе зелёное читается шире, чем измерено")

    ok &= case("⑤ граница СЛЕДУЮЩИМ суждением — молчит (норма нашего письма)",
               len(G.check_coverage_bounded(
                   ["Проверено всё: девять ролей.",
                    "⛔ ЧЕГО НЕ МЕРИЛ: смысл секций."], "t")) == 0,
               "«⛔ ЧЕГО НЕ МЕРИЛА» пишется отдельной строкой под замером — так пишут роли",
               differ=True)

    ok &= case("⑥ граница ЧЕРЕЗ чужую мысль — НЕ гасит (встречный к ⑤)",
               len(G.check_coverage_bounded(
                   ["Проверено всё: девять ролей.", "", "Совсем другая мысль.",
                    "⛔ ЧЕГО НЕ МЕРИЛ: иное."], "t")) == 1,
               "расширение ровно на ОДНО суждение, дальше начинается чужое", differ=True)

    # ═══ ДЕФЕКТЫ ПРИЗНАКА, КОТОРЫЕ ПРЯТАЛА ШИРОКАЯ ОКРЕСТНОСТЬ ═══

    ok &= case("⑦ ПРЕДПИСАНИЕ «2) слепок ЦЕЛИКОМ, все 7 секций» — не обещание охвата",
               len(G.check_coverage_bounded(
                   ["2) Свой слепок ЦЕЛИКОМ, все 7 секций:"], "t")) == 0,
               "рецепт преемнику границы не обещает; ложный крик гасила случайность вёрстки",
               differ=True)

    ok &= case("⑧ ОТРИЦАНИЕ «⛔ Ни одного не начинаю сам» — не обещание охвата",
               len(G.check_coverage_bounded(["⛔ Ни одного не начинаю сам."], "t")) == 0,
               "заявление о поведении; «ни одного» убрано из триггера 10.08", differ=True)

    # ⑨ ЖИВОЙ СЛУЧАЙ @opssre §state: надгробие САМОМУ производному факту
    tomb = ["⚰️ ~~«archs ahead 0 · дерево чисто»~~ — УБРАНО 08.08. Хранил руками."]
    ok &= case("⑨ надгробие производному факту в ТОЙ ЖЕ строке — не долг",
               bool(G.TOMBSTONE.search(tomb[0])),
               "прежде это гасил «перемерь» из следующего суждения — спасала вёрстка",
               differ=True)

    # ⑩ ГРАНИЦА САМОЙ ЕДИНИЦЫ, названная вслух: ключ замера не умеет работать МОЛЧА
    ok &= case("⑩ ключ замера MEZO_UNIT объявлен и по умолчанию выключен",
               G.NARROW is False,
               "переключатель поведения проверки, о котором не знает читатель вывода, —"
               " это ослепление с рычагом")

    print()
    print(f"{'✅ ЕДИНИЦА СУЖДЕНИЯ ПРИНЯТА' if ok else '🔴 НЕ ПРИНЯТА'} — случаев {CASES}, "
          f"различающих {DIFFER}; ⑤⑥ и ①② — встречные пары")
    print("⚖️ ГРАНИЦА: приёмка судит ЕДИНИЦУ и триггеры ⑨. Она НЕ проверяет словари примет"
          " (их предмет — карточка #57) и НЕ решает, верна ли сама находка.")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
