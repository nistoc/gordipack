        db = make_stand(tmp, "empty-section", [("ZZS", "identity", "## §ПРАВА\n\nпока пусто")],
                        RIGHTS)
        out, code = run(db, guard)
        case("㉛ раздел «§ПРАВА» без таблицы и без указателя → «⚠️ раздел найден, но ПУСТ»",
             code == 0 and "⚠️ раздел найден, но ПУСТ" in out)

        # ㉜ все ряды отсеяны — третье слово нуля
        db = make_stand(tmp, "all-dropped", [("ZZT", "identity", table(
            "| force push | ⛔ НЕТ | rule8-destructive |"))], RIGHTS)
        out, code = run(db, guard)
        case("㉜ все ряды отсеяны → «ℹ️ все ряды отсеяны», код 0",
             code == 0 and "ℹ️ все ряды отсеяны" in out)

        # ㉝ ПУСТОЙ реестр и ТОЛЬКО указатель в прозе — права объявлены, сверять не с чем (код 2),
        #    а не «⚪ прав не объявлено» (ветка карточки #606 смотрела только таблицы)
        db = make_stand(tmp, "empty-registry-prose", [("LLMG", "identity",
            "## §ПРАВА\n\n[реестр #14]")], [])
        out, code = run(db, guard)
        case("㉝ реестр пуст, права только указателем в прозе → код 2 «ПУСТ», не «прав не объявлено»",
             code == 2 and "ПУСТ" in out and "прав не объявлено" not in out)

        # ㉞ ВОЗВРАТ ПРИЁМКИ НЕ АВТОРА 10.10: у роли С таблицей негодный указатель в прозе не судится
        #    (отступление 2) — но итог обязан это НАЗВАТЬ, а не сказать «негодных указателей нет».
        #    Первая редакция печатала границу только при провале, а при успехе — «чисто».
        db = make_stand(tmp, "table-and-bad-pointer", [("ZZU", "identity", table(
            "| что-то | ✅ ДА | запись #12 |") + "\n\nсм. также [реестр #999]")], RIGHTS)
        out, code = run(db, guard)
        case("㉞ роль С таблицей и негодным указателем в прозе: код 0, но несверенное названо — "
             "строка «ℹ️ … НЕ сверены», число в итоге и граница «ЧЕГО ПРОВЕРКА НЕ ВИДИТ»",
             code == 0 and "🔴" not in out
             and "ℹ️ указателей на реестр в прозе 1 (#999) — НЕ сверены" in out
             and "у ролей С таблицей не сверено указателей: 1" in out
             and "⚖️ ЧЕГО ПРОВЕРКА НЕ ВИДИТ" in out,
             "итог «негодных указателей нет» о несмотренном — ложь об охвате")

        # ㉞-бис таблица в СОСЕДНЕМ разделе той же роли — тоже «у роли есть таблица»: суд по разделу
        #    вернул бы ложный провал OPSSRE (таблица в identity, история #12 — в rebirth)
        db = make_stand(tmp, "table-in-other-section", [
            ("ZZV", "history", table("| что-то | ✅ ДА | запись #12 |")),
            ("ZZV", "identity", "## §ПРАВА\n\n[реестр #999]")], RIGHTS)
        out, code = run(db, guard)
        case("㉞-бис таблица в соседнем разделе роли: указатель не судится, но назван «НЕ сверены»",
             code == 0 and "🔴" not in out
             and "ℹ️ указателей на реестр в прозе 1 (#999) — НЕ сверены" in out)

        # ㉟ ПРОЗА УЧИТ ПРАВУ, СНЯТОМУ В РЕЕСТРЕ (карточка #709, находка @RCC, записка #5751):
        #    таблица у роли чиста, а четыре других раздела учили «отправка вопроса НЕ требует» —
        #    и проверка давала код 0 рядом с ними. Каждая строка названа поимённо: раздел и строка.
        db = make_stand(tmp, "prose-taught", TAUGHT, PUSH_RIGHTS)
        out, code = run(db, guard)
        for letter, section, n in TAUGHT_EXPECTED:
            mark = f"⚠️ [ZZW · {section} · строка {n}] проза учит праву «push», снятому в реестре"
            case(f"㉟{letter} проза учит снятому push: {section}, строка {n} → «{mark[:40]}…»",
                 mark in out, "" if mark in out else f"нет строки находки:\n   {out[:600]}")
        # ㊱ код 0 при находках не печатается как «чисто»: граница — В ТОЙ ЖЕ строке, что итог
        summary = next((l for l in out.splitlines() if l.startswith("✅ строк права без записи")), "")
        case("㊱ итог при находках прозы: код 0, и в ТОЙ ЖЕ строке «⚠️ строк прозы, учащих снятому "
             "праву: 7 … не «чисто»» с границей «судится только push»",
             code == 0 and "⚠️ строк прозы, учащих снятому праву: 7" in summary
             and "это не «чисто»" in summary and "судится только push" in summary,
             f"строка итога: {summary[:300]}")

        # ㊲ встречные — по одной роли на признак; провал называет признак
        db = make_stand(tmp, "prose-not-taught",
                        [(r, s, b) for r, s, b, _ in NOT_TAUGHT], PUSH_RIGHTS)
        out, code = run(db, guard)
        for r, s, b, why in NOT_TAUGHT:
            case(f"㊲ встречный {r}: {why} — не находка", f"⚠️ [{r} ·" not in out,
                 "" if f"⚠️ [{r} ·" not in out else f"ложная находка у {r}")
        case("㊲ итог встречных: «прозы, учащей снятому праву, не найдено (судится только push…)»",
             code == 0 and "прозы, учащей снятому праву, не найдено (судится только push" in out)

        # ㊳ реестр старой формы без столбца right_key — не отказ, а названная граница
        db = make_stand(tmp, "prose-no-key", TAUGHT,
                        [(1, "ALL", "2026-08-11 11:32:08"), (12, "ALL", "2026-09-25 11:12:02")],
                        with_key=False)
        out, code = run(db, guard)
        case("㊳ реестр без столбца right_key → код 0 и «проза о снятых правах не судится», "
             "находок нет",
             code == 0 and "проза о снятых правах не судится: в реестре нет столбца right_key" in out
             and "⚠️ [ZZW" not in out)

        # ⑮ ⑯ отказы чтения — «не проверено», а не «чисто»
        out, code = run(Path(tmp) / "нет-такой.db", guard)
        case("⑮ базы нет → «НЕ ПРОВЕРЕНО» кодом 2, а не зелёное", code == 2)

        db = make_stand(tmp, "no-rights", [("ZZH", "identity", table(
            "| что-то | ✅ стоячее право | без ссылки |"))], [])
        out, code = run(db, guard)
        case("⑯ реестр прав ПУСТ → код 2 «сверять не с чем», а не обвинение всех подряд",
             code == 2 and "ПУСТ" in out,
             "пустой реестр красит ВСЕ строки — это про реестр, а не про роли")

        if not a.break_key:
            print("\n🎯 ПОРЧИ — каждая обязана покрасить СВОЙ случай:")
            db = make_stand(tmp, "p-target", [("OPSSRE", "identity", table(
                "| **`git push`** | ✅ **ДА** | Слово владельца 08.08 |"))], RIGHTS)
            run_break("target", db, "рассмотрено: 0")
            db = make_stand(tmp, "p-refs", [("OPSSRE", "identity", table(
                "| **`git push`** | ✅ **ДА** | Слово владельца (записка #4602), стоячее |"))],
                RIGHTS)
            run_break("refs", db, "такой записи в реестре НЕТ")
            db = make_stand(tmp, "p-duty", [("ZZE", "identity", table(
                "| ⚠️ **СВЕРКА СОСТАВА** | ✅ ОСТАЁТСЯ, ОБЯЗАТЕЛЬНА | стоячее слово |"))], RIGHTS)
            run_break("duty", db, "🔴 [ZZE")
            db = make_stand(tmp, "p-revoked", [("COORD", "identity", table(
                "| правка живых инструментов | ✅ стоячее право | запись #3 |"))], RIGHTS)
