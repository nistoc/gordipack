r"""ПРИЁМКА точки входа у refs_check.py — заявка @ING, записка #4016 (карточка #333).

🩸 ЧЕМ ОПЛАЧЕНО (27.08 ~17:20 UTC, живой случай у @ING). Файл `.mezosync/scripts/refs_check.py`
был модулем БЕЗ точки входа. Роль позвала его командой перед отправкой записки, получила
ПУСТОЙ ВЫВОД и код 0 — и прочла это как «голых ссылок нет, записка чистая». На пробе
с двумя голыми «#N» он молчал ровно так же: заставить его заговорить было нельзя ничем.

🎯 Дефект не в проверке ссылок — она работает и зовётся при каждой отправке. Дефект в том,
что у файла была ФОРМА ВЫЗОВА, которая ничего не делает и выглядит успехом. Наш общий класс:
молчащий отказ читается как успех.

⚠️ И почему «просто не зовите его командой» не годится: имя лежит в каталоге, куда наказ
посылает все роли, а настоящая проверка — в другом каталоге. Правило, опирающееся на то,
что каждый помнит разницу, уже подвело одного за день.

Случаи (различающий = обязан ответить ИНАЧЕ, а не одинаково):
  ① файл с голыми «#N» через эту форму — ГОВОРИТ, код ненулевой         РАЗЛИЧАЮЩИЙ
  ② ВСТРЕЧНЫЙ: файл без голых — говорит «нет», код 0                    РАЗЛИЧАЮЩИЙ
  ③ вызов без доводов — отказ с указанием, где живёт проверка, код ≠ 0  РАЗЛИЧАЮЩИЙ
  ④ проверка НЕДОСТУПНА — «НЕ ВЫПОЛНЕНА» и код ≠ 0, а не молчание       РАЗЛИЧАЮЩИЙ
  ⑤ ВСТРЕЧНЫЙ к ④: при доступной проверке этих слов НЕТ                 КОНТРОЛЬ
  ⑥ ОБРАТНЫЙ ХОД: точка входа отобрана — случай ① КРАСНЕЕТ              РАЗЛИЧАЮЩИЙ

⛔ Живого ничего не трогает: работает на копиях во временном каталоге.
"""
from __future__ import annotations

import os
import pathlib
import re
import subprocess
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import mezo_paths   # noqa: E402
import mezo_stand   # noqa: E402

МОДУЛЬ = mezo_paths.container_root(__file__) / ".mezosync" / "scripts" / "refs_check.py"
ГОЛЫЕ = "Проба. Смотри #1234 и ещё #4009 — обе голые." + chr(10)
ЧИСТО = "Проба чистая: карточка #1234 и записка #4009." + chr(10)

CASES = DIFFER = 0


def case(title, verdict, detail, differ=False):
    global CASES, DIFFER
    CASES += 1
    DIFFER += bool(differ)
    print(f"{'✅' if verdict else '🔴'} {title}")
    print(f"   {detail}")
    return verdict


def прогон(скрипт, *доводы):
    env = dict(os.environ)
    env["PYTHONPATH"] = os.pathsep.join(
        [p for p in (str(МОДУЛЬ.parent), env.get("PYTHONPATH", "")) if p])
    r = subprocess.run([sys.executable, str(скрипт), *доводы],
                       capture_output=True, text=True, encoding="utf-8",
                       errors="replace", timeout=120, env=env)
    return r.returncode, (r.stdout or "") + (r.stderr or "")


def main() -> int:
    ok = True
    корень = mezo_stand.new("bite-refs-entry-")
    голые = корень / "probe-refs.md"
    чисто = корень / "probe-clean.md"
    голые.write_text(ГОЛЫЕ, encoding="utf-8")
    чисто.write_text(ЧИСТО, encoding="utf-8")

    код1, вывод1 = прогон(МОДУЛЬ, "--file", str(голые))
    ok &= case("① файл с голыми «#N» через эту форму — ГОВОРИТ и отказывает кодом",
               код1 != 0 and "неразрешимых ссылок — 2" in вывод1,
               f"код {код1}; молчание тут читалось как «записка чистая» — и записка ушла",
               differ=True)

    код2, вывод2 = прогон(МОДУЛЬ, "--file", str(чисто))
    ok &= case("② ВСТРЕЧНЫЙ: чистый файл — сказано «ссылок нет», код 0",
               код2 == 0 and "неразрешимых ссылок нет" in вывод2,
               "иначе ① зеленел бы у формы, которая ругается на что угодно", differ=True)

    код3, вывод3 = прогон(МОДУЛЬ)
    ok &= case("③ вызов без доводов — отказ, названо ГДЕ живёт проверка, код ≠ 0",
               код3 != 0 and "check-dangling-refs.py" in вывод3,
               "роль пришла сюда по наказу; отправить её обратно молча значит повторить беду",
               differ=True)

    # ④ проверка НЕДОСТУПНА. Ослабляем копию: список мест поиска ведёт в пустоту.
    текст = МОДУЛЬ.read_text(encoding="utf-8")
    якорь = "CHECKER = next((c for c in CANDIDATES if c.exists()), CANDIDATES[0])"
    if якорь not in текст:
        raise SystemExit("⛔ ПРИЁМКА НЕ СОСТОЯЛАСЬ: в модуле нет места, которое ослабляют —"
                         " он менялся, правь приёмку. Молчать нельзя: вышло бы зелёное")
    слепой = корень / "refs_check_no_checker.py"
    слепой.write_text(текст.replace(
        якорь, "CHECKER = _HERE / 'нет-такого-файла-проверки.py'"), encoding="utf-8")
    код4, вывод4 = прогон(слепой, "--file", str(голые))
    ok &= case("④ проверка НЕДОСТУПНА — сказано «НЕ ВЫПОЛНЕНА», код ≠ 0",
               код4 != 0 and "НЕ ВЫПОЛНЕНА" in вывод4,
               "«проверки не было» обязано отличаться и от «чисто», и от находок", differ=True)

    ok &= case("⑤ ВСТРЕЧНЫЙ к ④: при доступной проверке слов «НЕ ВЫПОЛНЕНА» нет",
               "НЕ ВЫПОЛНЕНА" not in вывод1,
               "иначе ④ зеленел бы у формы, которая жалуется на пропажу всегда")

    # ⑥ ОБРАТНЫЙ ХОД: отбираем саму точку входа — ① обязан покраснеть.
    без_входа = корень / "refs_check_no_entry.py"
    урезанный = re.split(r'\nif __name__ == "__main__":', текст)[0]
    if урезанный == текст:
        raise SystemExit("⛔ ПРИЁМКА НЕ СОСТОЯЛАСЬ: точки входа в модуле не нашлось —"
                         " именно её проверяет ①, и без неё прогон был бы пустым")
    без_входа.write_text(урезанный, encoding="utf-8")
    код6, вывод6 = прогон(без_входа, "--file", str(голые))
    ok &= case("⑥ ОБРАТНЫЙ ХОД: точка входа отобрана — молчит и отдаёт ноль (① краснеет)",
               код6 == 0 and not вывод6.strip(),
               f"код {код6}, вывод пуст — ровно то состояние, в котором @ING прочёл "
               f"пустоту как чистоту", differ=True)

    print()
    print(f"{'✅ ПРИНЯТО' if ok else '🔴 НЕ ПРИНЯТО'} — случаев {CASES}, различающих {DIFFER}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(mezo_stand.finish(main()))
