CASES = DIFFER = 0


def case(title, verdict, detail, differ=False):
    global CASES, DIFFER
    CASES += 1
    DIFFER += bool(differ)
    print(f"{'✅' if verdict else '🔴'} {title}")
    print(f"   {detail}")
    return verdict


def прогон(скрипт, *доводы):
    """PYTHONPATH на каталог инструментов: ослабленная копия писателя живёт во временном
    каталоге и без этого умерла бы на импорте. 🪤 Обратный ход уже был однажды ПУСТЫМ
    ровно так: копия падала на импорте, ненулевой код читался как работа признака."""
    env = dict(os.environ)
    env["PYTHONPATH"] = os.pathsep.join(
        [p for p in (str(pathlib.Path(скрипт).parent), str(ПИСАТЕЛЬ.parent),
                     env.get("PYTHONPATH", "")) if p])
    r = subprocess.run([sys.executable, str(скрипт), *доводы],
                       capture_output=True, text=True, encoding="utf-8",
                       errors="replace", timeout=300, env=env)
    return r.returncode, (r.stdout or "") + (r.stderr or "")


def посеять(db):
    """Выставить в КОПИИ четыре состояния, которые различает признак.

    ⚠️ Сеем ОБА признака сразу — и последнюю свою ноту, и отметку прочтения. Посеяв
    один, мы бы проверяли не «И», а то, какой из двух случайно оказался решающим.
    """
    con = sqlite3.connect(db)
    старо = "2026-08-01 00:00:00"
    con.execute("UPDATE messages SET timestamp=? WHERE writer_role IN (?,?)",
                (старо, СПЯЩИЙ, ЧИТАЕТ))
    for роль, читал in ((СПЯЩИЙ, старо), (ЖИВОЙ, "now"), (ЧИТАЕТ, "now"), (ПИШЕТ, старо)):
        когда = "datetime('now')" if читал == "now" else "?"
        доводы = (роль,) if читал == "now" else (читал, роль)
        con.execute(f"UPDATE read_cursors SET updated_at={когда} WHERE reader_role=?", доводы)
    # У «пишущего» и «живого» своя нота обязана быть СВЕЖЕЙ, иначе они уедут в спящие
    край = con.execute("SELECT MAX(id) FROM messages").fetchone()[0]
    for роль in (ЖИВОЙ, ПИШЕТ):
        con.execute("INSERT INTO messages (writer_role, timestamp, body_md, tags, priority)"
                    " VALUES (?, datetime('now'), ?, '[]', 'normal')",
                    (роль, f"посев приёмки #330: свежая нота роли {роль}"))
    con.commit()
    con.close()
    return край


def отправить(db, тело, кому, копия=None):
    нота = pathlib.Path(db).parent / "nota.md"
    нота.write_text(тело + chr(10) + МЕТКА + chr(10), encoding="utf-8")
    доводы = ["--role", "PROTO", "--db", str(db), "--file", str(нота), "--to", кому]
    if копия:
        доводы += ["--cc", копия]
    return прогон(ПИСАТЕЛЬ, *доводы)


def ослабить(корень, чем: str) -> pathlib.Path:
    """Копия писателя, у которой признак судит ТОЛЬКО ОДНО из двух условий.

    Ломаем ровно ту ветку, которую стережёт встречный случай: «только отметка прочтения»
    обязана уронить ③, «только своя нота» — ④. Ослабление, ломающее оба, доказывало бы
    лишь то, что признак вообще работает.
    """
    текст = ПИСАТЕЛЬ.read_text(encoding="utf-8")
    оригинал = "MAX(COALESCE(c.updated_at,''), COALESCE(m.последняя,''))"
    замена = {"курсор": "COALESCE(c.updated_at,'')",
              "нота": "COALESCE(m.последняя,'')"}[чем]
    if оригинал not in текст:
        raise SystemExit("⛔ ПРИЁМКА НЕ СОСТОЯЛАСЬ: в писателе нет места, которое ослабляют."
                         " Молчать нельзя — вышло бы зелёное на непроверенном коде.")
    копия = корень / f"weak-{чем}.py"
    копия.write_text(текст.replace(оригинал, замена), encoding="utf-8")
    return копия


