IN_TEXT, IN_NOTE = 'дословный текст', 'пояснение'
IN_BOTH = 'оба: дословный текст и пояснение'

# Граница поиска, печатаемая и в справке, и при нуле находок.
FIND_BOUNDARY = ('регистр свёрнут средствами Python; НЕ лечится: «ё» против «е» (разные буквы) '
                 'и латинская буква внутри русского слова')


def cmd_find(conn, a):
    conn.create_function(FOLD, 1, fold_text, deterministic=True)
    total = conn.execute("SELECT COUNT(*) FROM owner_words").fetchone()[0]
    rows = conn.execute(
        f"SELECT *, ({FOLD}(text_verbatim) LIKE {FOLD}(?)) AS in_text,"
        f" ({FOLD}(note) LIKE {FOLD}(?)) AS in_note FROM owner_words"
        f" WHERE in_text OR in_note ORDER BY said_at DESC",
        (f'%{a.word}%', f'%{a.word}%')).fetchall()
    if not rows:
        if total == 0:
            print(f'🔴 хранилище пусто: слов 0 — искать негде (по куску «{a.word}»).')
            return 4
        # ⚖️ Причина нуля НЕ выдумывается: инструмент не знает, нет слова или не сошлась
        # буква, и не говорит «слово не записано» — это вывод о предмете из своего молчания.
        print(f'🔴 по куску «{a.word}» совпадений нет. Слов в хранилище: {total}')
        print(f'⚠️ граница поиска: {FIND_BOUNDARY}.')
        print('   Пустой ответ не отвечает, было ли слово: проверь написание куска или ищи по')
        print('   самим записям разговоров — find-owner-word.py')
        return 1
    print(f'найдено слов: {len(rows)}')
    for row in rows:
        where = IN_BOTH if (row['in_text'] and row['in_note']) else (
            IN_TEXT if row['in_text'] else IN_NOTE)
        print('-' * 70)
        show_row(row, full=False, matched=where)
    return 0


def cmd_list(conn, a):
    rows = conn.execute("SELECT * FROM owner_words ORDER BY said_at DESC LIMIT ?",
                        (a.limit,)).fetchall()
    total = conn.execute("SELECT COUNT(*) FROM owner_words").fetchone()[0]
    print(f'слов владельца в хранилище: {total}'
          + (f' · показаны последние {len(rows)}' if total > len(rows) else ''))
    for row in rows:
        print('-' * 70)
        show_row(row, full=False)
    if total > len(rows):
        print('-' * 70)
        print(f'⚠️ УПЁРЛОСЬ В ПРЕДЕЛ --limit {a.limit}: за показанными ещё '
              f'{total - len(rows)}. Это НЕ «всё» — это «упёрлось»')
    return 0


def cmd_source(conn, a):
    """Дописать адрес источника уже записанным словам (карточка #795).

    Тем же поиском, что при записи: сверка дословности, час в названном чате, адрес из находки.
    По умолчанию — холостой прогон. Пишет только туда, где номера строки нет; записанный файл,
    расходящийся с найденным, не перезаписывает, а называет."""
    if a.ids:
        marks = ','.join('?' * len(a.ids))
        rows = conn.execute(f"SELECT * FROM owner_words WHERE id IN ({marks}) ORDER BY id",
                            a.ids).fetchall()
        absent = sorted(set(a.ids) - {r['id'] for r in rows})
        if absent:
            print(f'🔴 таких номеров нет: {", ".join(f"слово #{x}" for x in absent)}')
            return 1
    else:
        rows = conn.execute("SELECT * FROM owner_words WHERE coalesce(source_file,'')='' "
                            "OR source_line IS NULL ORDER BY id").fetchall()
    mode = ('ЗАПИСЬ (--apply)' if a.apply else
            '⟨ХОЛОСТОЙ ПРОГОН⟩ база не изменится; записать — тот же вызов с --apply')
    print(f'📍 АДРЕС ИСТОЧНИКА уже записанным словам · {mode}')
    print(f'   к разбору слов: {len(rows)} '
          + ('(названы номерами)' if a.ids else '(у них нет файла или номера строки)'))
    planned, left = [], []
    for row in rows:
        n, said_at = row['id'], row['said_at']
        if row['source_file'] and row['source_line']:
            print(f'   слово #{n}: адрес уже есть — {row["source_file"]}:{row["source_line"]}')
            continue
        prefixes, _, refusal = chat_prefixes(conn, row['chat'])
        if refusal:
            left.append((n, refusal))
            continue
        ok, report, _, per_line = verify_verbatim(row['text_verbatim'], said_at, a.finder)
        if not ok:
            if ('НЕ ПОДТВЕРЖДЕНА (код 4)' in report and unread_in(report)
                    and not of_chat(unread_in(report), prefixes)):
                # карточка #797: не дочитаны только ЧУЖИЕ файлы, а записи чата слова прочитаны целиком —
                # тогда «не прочитана» была бы ложной причиной: текста в его чате нет
                names = ', '.join(os.path.basename(p) for p, _ in unread_in(report))
                left.append((n, f'текст не найден в прочитанных записях чата {row["chat"]} за '
                                f'{said_at[:10]}; не дочитаны только файлы чужих чатов ({names}) — '
                                'искатель: код 4'))
                continue
            left.append((n, unverified_reason(report, said_at[:10])))
            continue
        found = sources_of(per_line, prefixes, said_at)
        if not found:
            mine_unread = of_chat(unread_in(report), prefixes)
            if mine_unread:
                # карточка #797: файл чата слова не прочитан — «нет находки» было бы ложной причиной
                left.append((n, f'запись разговора не прочитана: искатель не дочитал файл чата '
                                f'{row["chat"]} ({", ".join(os.path.basename(p) for p in mine_unread)}) — '
                                'адрес мог лежать там; повтори позже (карточка #797)'))
                continue
            left.append((n, f'в чате {row["chat"]} нет находки с часом {said_at} и строкой «файл:»'))
            continue
        path, line = found[0]
        if row['source_file'] and not same_path(row['source_file'], path):
            left.append((n, f'записанный файл {row["source_file"]} РАСХОДИТСЯ с найденным '
                            f'{path}:{line} — не перезаписываю'))
            continue
        if row['source_line'] is not None and row['source_line'] != line:
            left.append((n, f'записанный номер строки {row["source_line"]} РАСХОДИТСЯ с найденным '
                            f'{path}:{line} — не перезаписываю'))
            continue
        planned.append((n, path, line))
        print(f'   слово #{n} → {path}:{line}'
              + (f'  (строк текста в разных строках записей: {len(found)}, взят адрес первой)'
                 if len(found) > 1 else ''))
    written = 0
    if a.apply and planned:
        note = f'; адрес источника дописан owner-word.py source, прогон {now_utc()}'
        for n, path, line in planned:
            cur = conn.execute("UPDATE owner_words SET source_file=?, source_line=?, "
                               "verified_by=verified_by || ? WHERE id=? "
                               "AND (coalesce(source_file,'')='' OR source_line IS NULL)",
                               (path, line, note, n))
            written += cur.rowcount
        conn.commit()
    for n, why in left:
        print(f'   🔴 слово #{n}: {why}')
    if a.apply:
        print(f'ИТОГ: записано адресов {written} из {len(planned)} найденных · '
              f'без адреса осталось {len(left)}')
        if written != len(planned):
            print('   ⚠️ записано меньше найденного: у части слов адрес появился между поиском')
            print('      и записью (другая рука) — их строки не тронуты')
    else:
        print(f'ИТОГ: будет записано адресов {len(planned)} · без адреса останется {len(left)}')
    return 1 if left else 0


