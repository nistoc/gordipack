r"""ПРИЁМКА мерки блоков в хранителе памяти — карточка #287.

🩸 ЧЕМ ОПЛАЧЕНО (@COORD, записка #3918 §②, 26.08 22:03 UTC): его отчёт о сохранении
сказал «ИСЧЕЗАЮТ БЛОКИ 2 из 2» и строкой ниже «исчезло дословно 0 (0%)» — на записи,
где не потеряно ничего. Признак блоков выбирался лестницей ОТДЕЛЬНО для старого и нового
тела: прежнее тело без «## » мерялось жирными строками, дописанный сверху раздел с «## »
переключал новое тело на заголовки — и величины, снятые РАЗНЫМИ мерками, сравнивались
между собой. Пересечение пусто по построению.
⚖️ Сторож, кричащий на исправном, учит не слышать крик — и следующая тревога,
настоящая, будет пролистана.

Случаи (различающий = обязан ответить ИНАЧЕ, а не одинаково):
  ① случай COORD: дописали сверху раздел с «## » → блоки ЦЕЛЫ            РАЗЛИЧАЮЩИЙ
  ② НАСТОЯЩАЯ потеря при той же смене разметки → по-прежнему видна       РАЗЛИЧАЮЩИЙ
  ③ разметку сменили ЦЕЛИКОМ (прежних блоков нет вовсе) → сказано вслух
    «сравнивать нечем», а не «всё исчезло»                               РАЗЛИЧАЮЩИЙ
  ④ КОНТРОЛЬ: однородные тела (оба с «## »), блок стёрт → тревога        КОНТРОЛЬ
  ⑤ ОБРАТНЫЙ ХОД: вернуть выбор признака заново → случай ① снова ложно
    красный — разница и есть починка                                     РАЗЛИЧАЮЩИЙ

⛔ Живой базы не касается вовсе: судятся ТЕЛА ТЕКСТА, база не открывается.
"""
from __future__ import annotations

import importlib.util
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import mezo_paths  # noqa: E402

СКРИПТЫ = mezo_paths.live_scripts()  # путь выводится, не впечатан (#248)
sys.path.insert(0, str(СКРИПТЫ))
_sp = importlib.util.spec_from_file_location("saveph", СКРИПТЫ / "save-phoenix.py")
saveph = importlib.util.module_from_spec(_sp)
_argv, sys.argv = sys.argv, ["bite"]
_sp.loader.exec_module(saveph)
sys.argv = _argv

CASES = DIFFER = 0


def case(title, verdict, detail, differ=False):
    global CASES, DIFFER
    CASES += 1
    DIFFER += bool(differ)
    print(f"{'✅' if verdict else '🔴'} {title}")
    print(f"   {detail}")
    return verdict


# Тело в форме памяти COORD: разметка — ЖИРНЫЕ строки, заголовков «## » нет.
СТАРОЕ = ("**Неназванная граница читается как полнота.**\n"
          "строка про замер и его границы, длиннее двенадцати знаков ровно\n"
          "**подкрепил ОПИСЬЮ, которая доказывала «объект цел»**\n"
          "ещё одна содержательная строка, тоже длиннее двенадцати знаков\n")
СВЕРХУ = ("## Свежая запись сверху\n"
          "новая строка про сегодняшнюю смену, длиннее двенадцати знаков\n\n")


def отчёт(старое, новое):
    доля, строки = saveph.loss_report(старое, новое)
    return доля, "\n".join(строки)


def main() -> int:
    ok = True

    # ① случай COORD дословно: дописали сверху, не стерев ничего.
    _, r1 = отчёт(СТАРОЕ, СВЕРХУ + СТАРОЕ)
    ok &= case("① случай @COORD: дописано СВЕРХУ, ничего не стёрто → блоки ЦЕЛЫ",
               "ИСЧЕЗАЮТ БЛОКИ" not in r1 and "исчезло 0" in r1,
               f"отчёт: {r1.splitlines()[0].strip()}", differ=True)

    # ② НАСТОЯЩАЯ потеря при той же смене разметки: одну жирную строку стёрли.
    урезанное = СТАРОЕ.replace("**подкрепил ОПИСЬЮ, которая доказывала «объект цел»**\n", "")
    _, r2 = отчёт(СТАРОЕ, СВЕРХУ + урезанное)
    ok &= case("② НАСТОЯЩАЯ потеря при той же смене разметки — по-прежнему ВИДНА",
               "ИСЧЕЗАЮТ БЛОКИ" in r2 and "1 из 2" in r2 and "ОПИСЬЮ" in r2,
               "починка не ослепила проверку: потерянный блок назван поимённо", differ=True)

    # ③ разметку сменили ЦЕЛИКОМ: жирных строк в новом теле нет вовсе.
    другое = ("## Совсем другая запись\n"
              "текст без единой жирной строки, зато с заголовком, длиннее двенадцати\n"
              "и вторая строка тоже содержательная, чтобы доля строк считалась\n")
    _, r3 = отчёт(СТАРОЕ, другое)
    ok &= case("③ разметка сменилась ЦЕЛИКОМ → «сравнивать нечем», а не «всё исчезло»",
               "РАЗМЕТКА СМЕНИЛАСЬ" in r3 and "ИСЧЕЗАЮТ БЛОКИ" not in r3,
               "обвинение без разбора дороже пропуска; настоящую потерю тут ловят СТРОКИ",
               differ=True)

    # ④ КОНТРОЛЬ: тела ОДНОРОДНЫ (оба с «## »), заголовок стёрт — тревога обязана быть.
    одно = ("## Первый раздел\n"
            "содержательная строка первого раздела, длиннее двенадцати знаков\n"
            "## Второй раздел\n"
            "содержательная строка второго раздела, длиннее двенадцати знаков\n")
    без_второго = ("## Первый раздел\n"
                   "содержательная строка первого раздела, длиннее двенадцати знаков\n")
    _, r4 = отчёт(одно, без_второго)
    ok &= case("④ КОНТРОЛЬ: однородные тела, раздел стёрт → тревога есть",
               "ИСЧЕЗАЮТ БЛОКИ" in r4 and "Второй раздел" in r4,
               "без этого случая «тишина» была бы неотличима от ослепшей проверки")

    # ⑤ ОБРАТНЫЙ ХОД: вернуть прежний выбор признака заново — случай ① снова красный.
    целый = saveph.blocks_by

    def прежний(text, kind):          # прежнее поведение: признак выбирается ЗАНОВО
        return saveph.blocks_of(text)[1]

    saveph.blocks_by = прежний
    try:
        _, r5 = отчёт(СТАРОЕ, СВЕРХУ + СТАРОЕ)
    finally:
        saveph.blocks_by = целый
    ok &= case("⑤ ОБРАТНЫЙ ХОД: признак выбирается заново → случай ① снова ЛОЖНО КРАСНЫЙ",
               "ИСЧЕЗАЮТ БЛОКИ" in r5 and "2 из 2" in r5,
               "у сломанной «2 из 2» при целых строках — ровно то, что видел @COORD",
               differ=True)

    print()
    print(f"{'✅ МЕРКА БЛОКОВ ПРИНЯТА' if ok else '🔴 НЕ ПРИНЯТО'} — случаев {CASES}, "
          f"различающих {DIFFER}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
