from __future__ import annotations

import importlib.util
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import mezo_paths  # noqa: E402

СКРИПТЫ = mezo_paths.live_scripts()  # путь выводится, не впечатан (#248)
sys.path.insert(0, str(СКРИПТЫ))
_sp = importlib.util.spec_from_file_location("saveph", СКРИПТЫ / "save-phoenix.py")
saveph = importlib.util.module_from_spec(_sp)
_argv, sys.argv = sys.argv, ["bite"]
_sp.loader.exec_module(saveph)
sys.argv = _argv

CASES = DIFFER = 0


def case(title, verdict, detail, differ=False):
    global CASES, DIFFER
    CASES += 1
    DIFFER += bool(differ)
    print(f"{'✅' if verdict else '🔴'} {title}")
    print(f"   {detail}")
    return verdict


# Тело в форме памяти COORD: разметка — ЖИРНЫЕ строки, заголовков «## » нет.
СТАРОЕ = ("**Неназванная граница читается как полнота.**\n"
          "строка про замер и его границы, длиннее двенадцати знаков ровно\n"
          "**подкрепил ОПИСЬЮ, которая доказывала «объект цел»**\n"
          "ещё одна содержательная строка, тоже длиннее двенадцати знаков\n")
СВЕРХУ = ("## Свежая запись сверху\n"
          "новая строка про сегодняшнюю смену, длиннее двенадцати знаков\n\n")


def отчёт(старое, новое):
    доля, строки = saveph.loss_report(старое, новое)
    return доля, "\n".join(строки)


def main() -> int:
    ok = True

    # ① случай COORD дословно: дописали сверху, не стерев ничего.
    _, r1 = отчёт(СТАРОЕ, СВЕРХУ + СТАРОЕ)
    ok &= case("① случай @COORD: дописано СВЕРХУ, ничего не стёрто → блоки ЦЕЛЫ",
               "ИСЧЕЗАЮТ БЛОКИ" not in r1 and "исчезло 0" in r1,
               f"отчёт: {r1.splitlines()[0].strip()}", differ=True)

    # ② НАСТОЯЩАЯ потеря при той же смене разметки: одну жирную строку стёрли.
    урезанное = СТАРОЕ.replace("**подкрепил ОПИСЬЮ, которая доказывала «объект цел»**\n", "")
    _, r2 = отчёт(СТАРОЕ, СВЕРХУ + урезанное)
    ok &= case("② НАСТОЯЩАЯ потеря при той же смене разметки — по-прежнему ВИДНА",
               "ИСЧЕЗАЮТ БЛОКИ" in r2 and "1 из 2" in r2 and "ОПИСЬЮ" in r2,
               "починка не ослепила проверку: потерянный блок назван поимённо", differ=True)

    # ③ разметку сменили ЦЕЛИКОМ: жирных строк в новом теле нет вовсе.
    другое = ("## Совсем другая запись\n"
              "текст без единой жирной строки, зато с заголовком, длиннее двенадцати\n"
              "и вторая строка тоже содержательная, чтобы доля строк считалась\n")
    _, r3 = отчёт(СТАРОЕ, другое)
    ok &= case("③ разметка сменилась ЦЕЛИКОМ → «сравнивать нечем», а не «всё исчезло»",
               "РАЗМЕТКА СМЕНИЛАСЬ" in r3 and "ИСЧЕЗАЮТ БЛОКИ" not in r3,
               "обвинение без разбора дороже пропуска; настоящую потерю тут ловят СТРОКИ",
               differ=True)

    # ④ КОНТРОЛЬ: тела ОДНОРОДНЫ (оба с «## »), заголовок стёрт — тревога обязана быть.
    одно = ("## Первый раздел\n"
            "содержательная строка первого раздела, длиннее двенадцати знаков\n"
            "## Второй раздел\n"
            "содержательная строка второго раздела, длиннее двенадцати знаков\n")
    без_второго = ("## Первый раздел\n"
                   "содержательная строка первого раздела, длиннее двенадцати знаков\n")
    _, r4 = отчёт(одно, без_второго)
    ok &= case("④ КОНТРОЛЬ: однородные тела, раздел стёрт → тревога есть",
               "ИСЧЕЗАЮТ БЛОКИ" in r4 and "Второй раздел" in r4,
               "без этого случая «тишина» была бы неотличима от ослепшей проверки")

    # ⑤ ОБРАТНЫЙ ХОД: вернуть прежний выбор признака заново — случай ① снова красный.
    целый = saveph.blocks_by

    def прежний(text, kind):          # прежнее поведение: признак выбирается ЗАНОВО
        return saveph.blocks_of(text)[1]

    saveph.blocks_by = прежний
    try:
        _, r5 = отчёт(СТАРОЕ, СВЕРХУ + СТАРОЕ)
    finally:
        saveph.blocks_by = целый
    ok &= case("⑤ ОБРАТНЫЙ ХОД: признак выбирается заново → случай ① снова ЛОЖНО КРАСНЫЙ",
               "ИСЧЕЗАЮТ БЛОКИ" in r5 and "2 из 2" in r5,
               "у сломанной «2 из 2» при целых строках — ровно то, что видел @COORD",
               differ=True)

    # ── Карточка #389: устойчивая часть заголовка и ✂ при тревоге ──────────────
    ШАПКА_СТАРАЯ = "## §5 ПЛАН — куда идёшь   [пересмотрен 2026-08-29 09:32 UTC — РОЛЬ ПЕРЕСОЗДАЁТСЯ]\n"
    ШАПКА_ДАТА = "## §5 ПЛАН — куда идёшь   [пересмотрен 2026-08-29 13:05 UTC — ПОСЛЕ ПОЛУДНЯ СМЕНЫ]\n"
    # Строк достаточно, чтобы смена шапки (она тоже «исчезнувшая строка» дословно)
    # не пробила порог доли 25% — в живом замере @TAXO доля была 24%.
    ТЕЛО_ПЛАНА = ("первая содержательная строка плана, длиннее двенадцати знаков\n"
                  "вторая содержательная строка плана, тоже длиннее двенадцати\n"
                  "третья содержательная строка плана, длиннее двенадцати знаков\n"
                  "четвёртая содержательная строка плана, длиннее двенадцати\n"
                  "пятая содержательная строка плана, длиннее двенадцати знаков\n")

    # ⑥ случай @TAXO дословно: изменена ТОЛЬКО дата в скобках шапки (тело даже
    # переписано частично — как в живом замере, где правились протухшие блоки).
    _, r6 = отчёт(ШАПКА_СТАРАЯ + ТЕЛО_ПЛАНА,
                  ШАПКА_ДАТА + ТЕЛО_ПЛАНА + "третья свежая строка, дописанная при правке плана\n")
    ok &= case("⑥ случай @TAXO: в шапке изменена ТОЛЬКО дата → блоки ЦЕЛЫ",
               "ИСЧЕЗАЮТ БЛОКИ" not in r6 and "блоки целы" in r6,
               f"отчёт: {r6.splitlines()[0].strip()}", differ=True)

    # ⑦ встречный: настоящее переименование устойчивой части — тревога остаётся.
    _, r7 = отчёт(ШАПКА_СТАРАЯ + ТЕЛО_ПЛАНА,
                  "## §5 ПЛАН — куда пришли   [пересмотрен 2026-08-29 13:05 UTC]\n" + ТЕЛО_ПЛАНА)
    ok &= case("⑦ встречный: настоящее ПЕРЕИМЕНОВАНИЕ заголовка → тревога есть",
               "ИСЧЕЗАЮТ БЛОКИ" in r7 and "куда идёшь" in r7,
               "починка не ослепила: переименованный блок назван прежним именем", differ=True)

    # ⑧ при исчезнувшем блоке ✂-строки печатаются (тела случая ④: раздел стёрт).
    _, r8 = отчёт(одно, без_второго)
    ok &= case("⑧ при исчезнувшем блоке ✂-строки ПЕЧАТАЮТСЯ",
               "ИСЧЕЗАЮТ БЛОКИ" in r8 and "✂" in r8 and "второго раздела" in r8,
               "тревога громче — данных БОЛЬШЕ, а не меньше (карточка #389 ②)", differ=True)

    # ⑨ подпись начинается со скобки: ключ = вся строка, пустой ключ не склеивает.
    скобочные = ("## [A] первый скобочный раздел\nсодержательная строка первого, длиннее двенадцати\n"
                 "## [B] второй скобочный раздел\nсодержательная строка второго, длиннее двенадцати\n")
    _, r9 = отчёт(скобочные, "## [A] первый скобочный раздел\nсодержательная строка первого, длиннее двенадцати\n")
    ok &= case("⑨ граница: скобка сразу после «## » — потеря одного из двух видна",
               "ИСЧЕЗАЮТ БЛОКИ" in r9 and "[B]" in r9,
               "короткая устойчивая часть не склеила блоки: счёт держит и её")

    # ⑩ одна устойчивая часть у двух подписей (разные скобки) — счёт, не множество.
    двойня = ("## План [утро]\nсодержательная строка утренней половины, длиннее двенадцати\n"
              "## План [вечер]\nсодержательная строка вечерней половины, длиннее двенадцати\n")
    _, r10 = отчёт(двойня, "## План [утро]\nсодержательная строка утренней половины, длиннее двенадцати\n")
    ok &= case("⑩ граница: две подписи с одной устойчивой частью, одна стёрта → видна",
               "ИСЧЕЗАЮТ БЛОКИ" in r10 and "1 из 2" in r10,
               "ключи считаются со СЧЁТОМ: множество спрятало бы потерю близнеца")

    # ⑪ ОБРАТНЫЙ ХОД: ключ = вся подпись дословно → случай ⑥ снова ложно красный.
    целый_ключ = saveph.stable_key
    saveph.stable_key = lambda b: b
    try:
        _, r11 = отчёт(ШАПКА_СТАРАЯ + ТЕЛО_ПЛАНА, ШАПКА_ДАТА + ТЕЛО_ПЛАНА)
    finally:
        saveph.stable_key = целый_ключ
    ok &= case("⑪ ОБРАТНЫЙ ХОД: ключ дословный → случай ⑥ снова ЛОЖНО КРАСНЫЙ",
               "ИСЧЕЗАЮТ БЛОКИ" in r11 and "1 из 1" in r11,
               "у сломанной «1 из 1» на смене даты — ровно то, что видел @TAXO", differ=True)

    print()
    print(f"{'✅ МЕРКА БЛОКОВ ПРИНЯТА' if ok else '🔴 НЕ ПРИНЯТО'} — случаев {CASES}, "
          f"различающих {DIFFER}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
