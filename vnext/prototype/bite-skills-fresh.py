#!/usr/bin/env python
# -*- coding: utf-8 -*-
r"""ПРИЁМКА пары «генератор навыков + сторож свежести».

Сторож, стерегущий отставание навыка от свода, обязан быть испытан поломкой: иначе он
зелен ровно потому, что ничего не сравнивает. Это первый день навыков в контуре — и та же
пара ошибок, что уже оплачена на стартовом наборе правил, здесь стоит дешевле всего.

Случаи (различающий = обязан ответить ИНАЧЕ, а не одинаково):
  ① контроль: навык собран по нынешнему своду — молчит, и видно, что смотрел
  ② правило правлено ПОСЛЕ сборки → красное                          РАЗЛИЧАЮЩИЙ
  ③ ВСТРЕЧНЫЙ к ②: правлено ДО сборки → молчит
  ④ правило СНЯТО, а навык его несёт → отдельный исход, не «отстал»   РАЗЛИЧАЮЩИЙ
  ⑤ у файла нет отпечатка → он ЧУЖОЙ, не наше дело (не «свежо»)       РАЗЛИЧАЮЩИЙ
  ⑥ навыков нет вовсе → сказано вслух, а не «всё свежо»               РАЗЛИЧАЮЩИЙ
  ⑦ каталога навыков нет → отказ мерить кодом 2                        РАЗЛИЧАЮЩИЙ
  ⑧ описание длиннее предела → названо (оно в контексте ВСЕГДА)        РАЗЛИЧАЮЩИЙ
  ⑨ ГЕНЕРАТОР: правила нет в своде → ОТКАЗ собрать, а не навык без правила  РАЗЛИЧАЮЩИЙ
  ⑩ ГЕНЕРАТОР: правило снято → ОТКАЗ собрать (навык учил бы отменённому)    РАЗЛИЧАЮЩИЙ

⛔ Живого контура не касается: свод — копия в памяти, навыки — во временном каталоге.
"""
from __future__ import annotations

import pathlib
import sqlite3
import subprocess
import sys
import tempfile

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import mezo_paths  # noqa: E402 — пути машины выводятся, не впечатаны (#153)

import mezo_stand  # временный каталог убирается при успехе, сохраняется при провале

ЗДЕСЬ = pathlib.Path(__file__).resolve().parent
СТОРОЖ = ЗДЕСЬ / "guard-skills-fresh.py"
ГЕНЕРАТОР = ЗДЕСЬ / "rules-to-skills.py"
CASES = DIFFER = 0


def case(title, ok, detail, differ=False):
    global CASES, DIFFER
    CASES += 1
    DIFFER += bool(differ)
    print(f"{'✅' if ok else '🔴'} {title}")
    print(f"   {detail}")
    return ok


def свод(правила) -> pathlib.Path:
    """Копия свода: (ключ, тело, статус, час правки)."""
    d = mezo_stand.new("bite-skills-")
    db = d / "rules.db"
    con = sqlite3.connect(str(db))
    con.execute("""CREATE TABLE rules (id INTEGER PRIMARY KEY, rule_key TEXT UNIQUE, body TEXT,
                   locked_by TEXT, version INT, status TEXT, updated_at TEXT)""")
    for i, (k, тело, статус, час) in enumerate(правила, 1):
        con.execute("INSERT INTO rules (id, rule_key, body, locked_by, version, status,"
                    " updated_at) VALUES (?,?,?,?,?,?,?)", (i, k, тело, "owner", 1, статус, час))
    con.commit()
    con.close()
    return db


def навык(имя: str, отпечаток: dict | None, описание="короткое описание навыка") -> pathlib.Path:
    d = mezo_stand.new("bite-skills-out-")
    p = d / имя / "SKILL.md"
    p.parent.mkdir(parents=True)
    L = ["---", f"name: {имя}", f'description: "{описание}"', "---", "", f"# {имя}", "", "тело", ""]
    if отпечаток is not None:
        L += ["<!-- СОБРАНО ИЗ БАЗЫ: rules-to-skills.py"]
        L += [f"     {k} = {v}" for k, v in отпечаток.items()]
        L += ["-->"]
    p.write_text("\n".join(L) + "\n", encoding="utf-8")
    return d


def сторож(каталог, db):
    r = subprocess.run([sys.executable, str(СТОРОЖ), "--skills", str(каталог), "--db", str(db)],
                       capture_output=True, text=True, encoding="utf-8", timeout=300)
    return (r.stdout or "") + (r.stderr or ""), r.returncode


def генератор(db, out, only="atlas-sync"):
    r = subprocess.run([sys.executable, str(ГЕНЕРАТОР), "--db", str(db), "--out", str(out),
                        "--only", only, "--write"],
                       capture_output=True, text=True, encoding="utf-8", timeout=300)
    return (r.stdout or "") + (r.stderr or ""), r.returncode


ТЕЛО = "НОРМА ЖИВЁТ ЗДЕСЬ, и дальше идёт разбор случаев."


def main() -> int:
    ok = True
    for инструмент in (СТОРОЖ, ГЕНЕРАТОР):
        if not инструмент.exists():
            sys.exit(f"⛔ НЕ ЗАПУСТИЛАСЬ: нет механизма — {инструмент}")

    db = свод([("общее-правило", ТЕЛО, "active", "2026-08-01 10:00")])

    # ① КОНТРОЛЬ. Без него краснота дальше ничего не значит: молчать можно и от слепоты.
    к1 = навык("проба", {"общее-правило": "2026-08-01 10:00"})
    out1, code1 = сторож(к1, db)
    ok &= case("① контроль: навык собран по нынешнему своду — молчит, и видно, что смотрел",
               code1 == 0 and "навыков смотрено 1" in out1 and "собраны по нынешнему своду" in out1,
               f"код {code1}; «ничего не нашёл» и «ничего не искал» обязаны различаться")

    # ② ПРАВИЛО ПРАВЛЕНО ПОСЛЕ СБОРКИ — навык учит вчерашнему.
    db2 = свод([("общее-правило", ТЕЛО + " Дополнено.", "active", "2026-08-21 23:00")])
    out2, code2 = сторож(к1, db2)
    ok &= case("② правило правлено ПОСЛЕ сборки навыка — красное",
               code2 == 1 and "правлено 2026-08-21" in out2,
               "иначе роль позовёт навык и получит отменённую норму как действующую",
               differ=True)

    # ③ ВСТРЕЧНЫЙ: правка ДО сборки — молчание. Без него ② зеленел бы у сторожа,
    #    который красит ЛЮБОЕ несовпадение текстов.
    db3 = свод([("общее-правило", ТЕЛО + " Иначе оформлено.", "active", "2026-07-30 09:00")])
    out3, code3 = сторож(к1, db3)
    ok &= case("③ ВСТРЕЧНЫЙ: правка ДО сборки — молчит, хотя тела разные",
               code3 == 0 and "отставших 0" in out3,
               "тело навыка не обязано совпадать с телом правила дословно: судим по часу",
               differ=True)

    # ④ ПРАВИЛО СНЯТО — это ХУЖЕ отставания и обязано звучать иначе.
    db4 = свод([("общее-правило", ТЕЛО, "revoked", "2026-08-01 10:00")])
    out4, code4 = сторож(к1, db4)
    ok &= case("④ правило СНЯТО, а навык его несёт — отдельный исход",
               code4 == 1 and "учит отменённому" in out4,
               "«отстал» и «учит отменённому» лечатся одинаково, но значат разное", differ=True)

    # ⑤ ЧУЖОЙ НАВЫК (без отпечатка) — не наше дело. Красить чужое значило бы приучить
    #    не читать сторожа: рядом живут навыки, собранные не нами.
    к5 = навык("чужой", None)
    out5, code5 = сторож(к5, db2)
    ok &= case("⑤ навык без отпечатка — ЧУЖОЙ, не судим",
               code5 == 0 and "смотрено 0" in out5 and "судить не о чем" in out5,
               "обвинять чужой навык — верный способ, чтобы проверку перестали читать",
               differ=True)

    # ⑥ НАВЫКОВ НЕТ ВОВСЕ — сказано вслух. «Всё свежо» здесь было бы ложью.
    пусто = mezo_stand.new("bite-skills-пусто-")
    out6, code6 = сторож(пусто, db)
    ok &= case("⑥ навыков нет вовсе — сказано вслух, а не выдано за чистоту",
               code6 == 0 and "судить не о чем" in out6 and "НЕ «всё свежо»" in out6,
               "молчание пустого каталога неотличимо от молчания исправного", differ=True)

    # ⑦ КАТАЛОГА НЕТ — отказ мерить отдельным кодом, а не «чисто».
    out7, code7 = сторож(pathlib.Path(tempfile.gettempdir()) / "нет-такого-навыка-242", db)
    ok &= case("⑦ каталога навыков нет — отказ мерить кодом 2",
               code7 == 2 and "НЕ ЗАПУСТИЛАСЬ" in out7,
               f"код {code7}; опечатка в пути обязана звучать иначе, чем чистота", differ=True)

    # ⑧ ДЛИННОЕ ОПИСАНИЕ — названо. Описание лежит в контексте роли ВСЕГДА, и абзац здесь
    #    возвращает ту же беду, ради которой навыки и заводились.
    к8 = навык("многословный", {"общее-правило": "2026-08-01 10:00"}, описание="слово " * 60)
    out8, code8 = сторож(к8, db)
    ok &= case("⑧ описание длиннее предела — названо вслух",
               "описание" in out8 and "в контексте роли ВСЕГДА" in out8,
               "десять таких описаний — треть страницы в КАЖДОМ контексте", differ=True)

    # ⑨ ГЕНЕРАТОР: правила нет в своде — ОТКАЗ. Навык без правила читался бы как
    #    «правила не существует», а это неправда о своде.
    пустой = свод([("другое-правило", ТЕЛО, "active", "2026-08-01 10:00")])
    out9, code9 = генератор(пустой, mezo_stand.new("bite-skills-fresh-"))
    ok &= case("⑨ генератор: правила нет в своде — ОТКАЗ собрать",
               code9 != 0 and "НЕ ЗАПУСТИЛСЯ" in out9,
               "навык с пропущенным правилом читается как «правила нет» — неправда о своде",
               differ=True)

    # ⑩ ГЕНЕРАТОР: правило снято — ОТКАЗ. Собрать навык из снятого значит раздать
    #    отменённое как действующее, и сторож потом краснел бы на СВОЁМ же изделии.
    снятые = свод([(k, ТЕЛО, "revoked", "2026-08-01 10:00")
                   for k in ("full-scan-every-tick", "no-pipe-tool-output",
                             "ack-deadline", "escalation-and-ground-truth")])
    out10, code10 = генератор(снятые, mezo_stand.new("bite-skills-fresh-"))
    ok &= case("⑩ генератор: правило СНЯТО — ОТКАЗ собрать",
               code10 != 0 and "СНЯТО" in out10,
               "иначе навык раздаёт отменённую норму, а проверка краснеет на своём же изделии",
               differ=True)

    print()
    print(f"{'✅ НАВЫКИ ПРИНЯТЫ' if ok else '🔴 НЕ ПРИНЯТЫ'} — случаев {CASES}, "
          f"различающих {DIFFER}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(mezo_stand.finish(main()))
