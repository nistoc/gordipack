# -*- coding: utf-8 -*-
# SURFACES: phoenix, role_rights
"""guard-rights-registry.py — строка права в памяти роли без записи реестра (карточка #546).

ПРАВИЛО-ОСНОВАНИЕ: right-to-registry-same-move (заведено COORD 2026-09-05 05:0x UTC
по слову владельца 05:00:53). Право, данное владельцем, ложится в реестр ТЕМ ЖЕ ходом;
строка таблицы прав в памяти роли обязана нести ЛИБО ссылку на запись реестра,
ЛИБО пометку «⛔ НЕ В РЕЕСТРЕ — след: …».

ЖИВОЙ СЛУЧАЙ (карточка #543): у STUD право «Подъём :5291 — ✅ БЕЗ спроса (30.08 ~09:47 UTC)»
жило в памяти пять суток, а в реестре его не было. Стартовая сводка печатала «прав именных
нет», память — «есть». Обе честны, сравнивал никто ⇒ роль спросила владельца заново.

⚖️ ЧТО ЭТО ЗА ПРОВЕРКА: она ЧИТАЕТ. Ни памяти, ни реестра не правит; чужую память
не трогает вовсе. Красное называет долг поимённо — руки у каждой роли свои.

━━ ОПРЕДЕЛЕНИЕ ПРЕДМЕТА — ШИРЕ БУКВЫ КРИТЕРИЯ, И ВОТ ПОЧЕМУ ━━
Критерий карточки называет форму ссылки «запись #N». Замер живой памяти 2026-09-05
06:17 UTC показал ДВЕ живые формы одного предмета:
    TAXO   ... «запись прав **#11**»
    OPSSRE ... «право #13 в базе»
Обе указывают на строку реестра. Проверка, знающая одну форму, покрасила бы вторую
ложно — и это ровно тот класс, за который контур платил утром 05.09 (у ответа
интерфейса две формы начала, отбор знал одну; записка #4796 §①).
⇒ Судим ПРЕДМЕТ (ссылка на строку реестра), а не одно его написание.

🪤 И ОБРАТНАЯ ПОЛОВИНА ТОГО ЖЕ: «#N» в тексте чаще НЕ реестр. В строке OPSSRE стои́т
«(записка #4602)» — номер ленты. Широкий образец «запис… #N» засчитал бы его
за ссылку на реестр и выдал ЛОЖНОЕ ЗЕЛЁНОЕ ровно на строке, где ссылки нет.
⇒ Номер разрешается СЛОВОМ ВПЛОТНУЮ: «запись/записи/право/права #N».
Слова «записка», «карточка», «нота» ссылкой на реестр НЕ являются.

🩸 ЧЕМ ОПЛАЧЕНА ФОРМА ПОИСКА ЗАГОЛОВКА (первая редакция, 05.09 06:23 UTC): она брала
ПЕРВОЕ вхождение слова «§ПРАВА» в разделе. У OPSSRE это слово стои́т в ШАПКЕ раздела
(«§ПРАВА добавлены opssre 2026-08-06…»), настоящий заголовок — восемнадцатой строкой.
⇒ проверка искала таблицу под шапкой, не находила и МОЛЧА пропускала роль целиком:
ни красных, ни зелёных, ни слова о пропуске. Роль с пятью строками прав выглядела
как роль без таблицы. Ищем таблицы под ВСЕМИ вхождениями, а число ролей с таблицей
печатаем — чтобы пропажу было видно числом, а не по отсутствию строк.
"""
from __future__ import annotations

import argparse
import re
import sqlite3
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import mezo_paths  # noqa: E402

# заголовок таблицы прав; у RCC он в рамке «═══», у прочих — «## §ПРАВА»
ЗАГОЛОВОК_ПРАВ = re.compile(r"§\s*ПРАВА", re.I)
# конец секции: следующий заголовок любого принятого в памяти вида
СЛЕДУЮЩИЙ_ЗАГОЛОВОК = re.compile(r"^\s*(?:#{1,6}\s|═══|───\s|§\d)")

# признак строки-права: галочка + слово о разрешении ЛИБО названный источник-владелец.
# 🩸 Вторая половина добавлена приёмкой 05.09 06:27 UTC: случай ⑭ был построен на
# укороченной строке «| push | ✅ ДА | Слово владельца 08.08 |» — и проверка НЕ СУДИЛА её
# вовсе, потому что слова «право» в ней нет. Живая строка OPSSRE спасалась случайным
# «БЕЗ отдельного вопроса»; убери эти два слова — и право от владельца прошло бы мимо.
# ⚡ Класс: признак ловил СЛОВО, а предмет правила — ИСТОЧНИК. Право, названное без слова
# «право», остаётся правом, и реестр отвечает именно за него.
ПРИЗНАК_ПРАВА = re.compile(
    r"прав\w*|разрешен\w*|стояч\w*|без\s+спроса|без\s+вопроса|без\s+слова|без\s+отдельного|"
    r"владел[ья]\w*|\bowner\b",
    re.I)

# ⛔ источник строки — КОНСТРУКЦИЯ РОЛИ, а не слово владельца: такие строки не судятся
#    (граница названа в карточке #546: «не судить строки, где право — разрешение РОЛИ роли»)
ИСТОЧНИК_НЕ_ВЛАДЕЛЕЦ = re.compile(
    r"зона\s+роли|контракт\s+роли|профил[ья]\s+роли|конструкц\w*\s+роли|мо[яей]\s+зона|"
    r"милстоун|протокол\b|§\s*1\b",
    re.I)

# ✅ ссылка на строку реестра: слово ВПЛОТНУЮ к номеру. «записка #N» сюда НЕ попадает
ССЫЛКА_РЕЕСТРА = re.compile(
    r"(?:запис[ьи]|прав[оа])\s*(?:прав\w*)?[\s*_«»\"]*#\s*(\d+)", re.I)

# ✅ честная пометка «в реестре этого нет, вот след»
ПОМЕТКА_НЕ_В_РЕЕСТРЕ = re.compile(r"НЕ\s+В\s+РЕЕСТРЕ", re.I)


def строки_таблицы_прав(body: str):
    """(номер строки, текст) — строки таблиц ПОД заголовком §ПРАВА и до следующего заголовка.

    Вхождений слова «§ПРАВА» в разделе бывает несколько (шапка, ссылка, сам заголовок),
    и заголовок далеко не всегда первый. Обходим ВСЕ — пустые вхождения ничего не дают.
    """
    строки = (body or "").splitlines()
    итог, взято = [], set()
    for нач in [i for i, l in enumerate(строки) if ЗАГОЛОВОК_ПРАВ.search(l)]:
        for i in range(нач + 1, len(строки)):
            if СЛЕДУЮЩИЙ_ЗАГОЛОВОК.match(строки[i]):
                break
            s = строки[i].strip()
            if s.startswith("|") and i not in взято:
                взято.add(i)
                итог.append((i + 1, s))
    return sorted(итог)


def ячейка_с_галочкой(s: str) -> str:
    """Текст той ячейки таблицы, где стои́т ✅ — в ней роль пишет, ЧТО ей можно."""
    return next((c for c in s.split("|") if "✅" in c), "")


def судится(s: str) -> bool:
    """Строка заявляет ПРАВО, за которое отвечает реестр?"""
    if "✅" not in s:
        return False
    if set(s) <= set("|- :"):           # разделитель таблицы
        return False
    if not ПРИЗНАК_ПРАВА.search(s):
        return False
    if ИСТОЧНИК_НЕ_ВЛАДЕЛЕЦ.search(s):
        return False
    # ⛔ ОБЯЗАННОСТЬ — НЕ ПРАВО, и реестр прав о ней ничего не знает.
    # 🩸 Живой ложный случай (первая редакция, 05.09 06:24 UTC): строка OPSSRE
    # «⚠️ СВЕРКА СОСТАВА перед каждым push | ✅ ОСТАЁТСЯ, ОБЯЗАТЕЛЬНА» покрашена как
    # право без записи реестра. Закрыть её нельзя НИКАК: записи о сверке в реестре
    # не будет никогда, потому что реестр — про разрешения. Проверка требовала
    # невыполнимого, то есть учила не верить себе.
    # ⇒ Судим по ячейке С ГАЛОЧКОЙ: в ней роль пишет, что ей МОЖНО. Слово
    # «обязательна/обязан» в этой самой ячейке говорит, что строка про ДОЛГ.
    if re.search(r"обязательн\w*|обязан\w*", ячейка_с_галочкой(s), re.I):
        return False
    return True


def приговор(s: str, роль: str, реестр: dict):
    """(зелёная?, слово) — чем строка закрыта либо почему красная."""
    if ПОМЕТКА_НЕ_В_РЕЕСТРЕ.search(s):
        return True, "пометка «НЕ В РЕЕСТРЕ» со следом"
    m = ССЫЛКА_РЕЕСТРА.search(s)
    if not m:
        return False, ("ни ссылки на запись реестра, ни пометки «⛔ НЕ В РЕЕСТРЕ — след: …» "
                       "⇒ право живёт только в памяти")
    n = int(m.group(1))
    зап = реестр.get(n)
    if зап is None:
        return False, f"ссылка на запись #{n}, а такой записи в реестре НЕТ"
    чья, отозвана = зап
    if отозвана:
        return False, f"запись #{n} ОТОЗВАНА ({отозвана}) — право по ней не действует"
    if чья != роль and чья != "ALL":
        return False, f"запись #{n} принадлежит роли {чья}, а не {роль}"
    return True, f"запись #{n} ({чья})"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=None)
    ap.add_argument("--role", default=None, help="проверить одну роль")
    ap.add_argument("--verbose", action="store_true", help="печатать и зелёные строки")
    a = ap.parse_args()
    db = Path(a.db) if a.db else mezo_paths.live_db()
    try:
        con = sqlite3.connect(f"file:{db.as_posix()}?mode=ro", uri=True)
        память = con.execute("SELECT role, section, body FROM phoenix "
                             "ORDER BY role, section").fetchall()
        реестр = {i: (r, rev) for i, r, rev in
                  con.execute("SELECT id, role, revoked_at FROM role_rights")}
        con.close()
    except sqlite3.Error as e:
        print(f"⛔ память или реестр не прочитаны ({e}) — НЕ ПРОВЕРЕНО, это не «чисто»")
        return 2
    if not память:
        print("⛔ в памяти НОЛЬ разделов — мерить нечего (это не «чисто»)")
        return 2
    if not реестр:
        print("⛔ реестр прав ПУСТ — сверять не с чем, это не «чисто»")
        return 2

    красные, зелёные, с_таблицей = [], [], set()
    for роль, раздел, body in память:
        if a.role and роль != a.role:
            continue
        строки = строки_таблицы_прав(body)
        if строки:
            с_таблицей.add(роль)
        for n, s in строки:
            if not судится(s):
                continue
            ok, слово = приговор(s, роль, реестр)
            (зелёные if ok else красные).append((роль, раздел, n, s, слово))

    print(f"ролей с таблицей прав: {len(с_таблицей)} · записей реестра: {len(реестр)} · "
          f"строк-прав рассмотрено: {len(красные) + len(зелёные)} · без записи реестра: "
          f"{len(красные)}")
    for роль, раздел, n, s, слово in красные:
        print(f"🔴 [{роль} · {раздел} · строка {n}] {слово}")
        print(f"      {s[:180]}")
    if a.verbose:
        for роль, раздел, n, s, слово in зелёные:
            print(f"✅ [{роль} · {раздел} · строка {n}] {слово}")
    if not красные:
        print("✅ строк права без записи реестра нет")
    else:
        print("ℹ️ Это ПРОВЕРКА, а не запрет: сохранение памяти проходит как обычно. "
              "Закрыть строку — ДВА пути, оба законны: завести право в реестр "
              "(role-rights.py add, по слову владельца) и вписать «запись #N» ЛИБО, если "
              "права в реестре нет и не будет, пометить строку «⛔ НЕ В РЕЕСТРЕ — след: …».")
        print("⚖️ ЧЕГО ПРОВЕРКА НЕ ВИДИТ: верна ли САМА ссылка по существу (что запись #N "
              "про это же право), и права, записанные прозой вне таблицы §ПРАВА.")
    return 1 if красные else 0


if __name__ == "__main__":
    sys.exit(main())
