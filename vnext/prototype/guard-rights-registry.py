# заголовок таблицы прав; у RCC он в рамке «═══», у прочих — «## §ПРАВА» либо «## §2 ПРАВА…»
# 🩸 ПРЕДЛОЖЕНИЕ AIA 01 (карточка #644, замер их живой базы 2026-09-15): между знаком
# раздела и словом ПРАВА бывает НОМЕР раздела («## §2 ПРАВА И ЗАПРЕТЫ РОЛИ»). Прежний
# образец искал «§ПРАВА» ВПЛОТНУЮ и такую роль терял МОЛЧА — ни красных, ни зелёных,
# ни слова о пропуске (тот же класс, что уже описан ниже про «заголовок не первый»).
RIGHTS_HEADER = re.compile(r"§\s*\d*\s*ПРАВА", re.I)
# конец секции: следующий заголовок любого принятого в памяти вида
NEXT_HEADER = re.compile(r"^\s*(?:#{1,6}\s|═══|───\s|§\d)")

# ✅ РАЗРЕШИТЕЛЬНАЯ ПРИМЕТА — то, чем роль говорит «мне это можно».
# 🩸 ВТОРАЯ ПЕРЕДЕЛКА ОТБОРА (05.09 08:1x UTC, находка @COORD, записка #4814).
# Первая редакция требовала ГАЛОЧКУ: «if "✅" not in s: return». У @COORD таблица прав
# из восьми строк, и вид права записан СЛОВОМ — «стоячее · свободно · зона», галочки нет
# ни в одной. ⇒ ни одна его строка не судилась ВОВСЕ, а молчание читалось как «у COORD
# чисто». Он нашёл это не по красному (красного не было), а АРИФМЕТИКОЙ моего же вывода:
# 14 + 3 = 17 рассмотренных, и своего имени среди них нет.
# 📏 Цену намерил @STUD (записка #4818): строк в таблицах 119, судилось 31, отсеяно 88 —
# и из отсеянных НЕЗАКОННО ровно 4, все четыре COORD.
# ⚡ Класс тот же, что я поймала утром этажом выше: там молча пропадала РОЛЬ ЦЕЛИКОМ,
# здесь молча пропадают СТРОКИ внутри найденной роли. И лечение то же: печатать ЧИСЛО
# осмотренного и отсеянного — с ПРИЧИНОЙ отсева, иначе «отсеяно 88» обвинит весь контур.
PERMIT_PATTERN = re.compile(
    r"✅|стояч\w*|свободн\w*|\bда\b|разрешен\w*|без\s+спроса|без\s+вопроса|без\s+слова|"
    r"без\s+отдельного|^\s*зона\s*$",
    re.I)
DENY_PATTERN = re.compile(r"⛔|❌|⚰️|\bНЕТ\b|нельзя|запрещ\w*", re.I)
DUTY_PATTERN = re.compile(r"обязательн\w*|обязан\w*", re.I)

# ⛔ источник строки — КОНСТРУКЦИЯ РОЛИ, а не слово владельца: такие строки не судятся
#    (граница названа в карточке #546: «не судить строки, где право — разрешение РОЛИ роли»)
# ⚠️ «реестр зон» добавлен той же правкой: у @COORD две строки опираются на него, и он
#    сам НЕ назвал их среди четырёх, которые должны краснеть. Зона — не слово владельца.
SOURCE_NOT_OWNER = re.compile(
    r"зона\s+роли|контракт\s+роли|профил[ья]\s+роли|конструкц\w*\s+роли|мо[яей]\s+зона|"
    r"реестр\s+зон|милстоун|протокол\b|конвенц\w*|§\s*\d",
    re.I)
SOURCE_OWNER = re.compile(r"владел[ьц]\w*|\bowner\b", re.I)

# ✅ ссылка на строку реестра: слово ВПЛОТНУЮ к номеру. «записка #N» сюда НЕ попадает
REGISTRY_REF = re.compile(
    r"(?:запис[ьи]|прав[оа])\s*(?:прав\w*)?[\s*_«»\"]*#\s*(\d+)", re.I)

# ✅ честная пометка «в реестре этого нет, вот след»
NOT_IN_REGISTRY_MARK = re.compile(r"НЕ\s+В\s+РЕЕСТРЕ", re.I)

# ✅ указатель на реестр в ПРОЗЕ или кодовом блоке — «[реестр #14/#15/#18]» (правка AIA 7c4eba1,
#    роль LLMG их контура: права записаны блоком, таблицы нет). Построчный суд такую форму
#    не видит, но сами указатели сверить с реестром можно — и это ДРУГОЕ слово, чем «раздел
#    пуст». «записка #N» сюда не попадает (запис[ьи] с границей слова).
PROSE_POINTER = re.compile(
    r"(?:реестр\w*|запис[ьи]\b|прав[оа]\b)\s*(?:прав\w*)?[\s*_«»\"\[]*#\s*\d+(?:\s*/\s*#?\s*\d+)*",
    re.I)


def rights_table_rows(body: str):
    """(номер строки, текст) — строки таблиц ПОД заголовком §ПРАВА и до следующего заголовка.

    Вхождений слова «§ПРАВА» в разделе бывает несколько (шапка, ссылка, сам заголовок),
    и заголовок далеко не всегда первый. Обходим ВСЕ — пустые вхождения ничего не дают.
    """
    lines = (body or "").splitlines()
    result, taken = [], set()
    for start in [i for i, l in enumerate(lines) if RIGHTS_HEADER.search(l)]:
        for i in range(start + 1, len(lines)):
            if NEXT_HEADER.match(lines[i]):
                break
            s = lines[i].strip()
            if s.startswith("|") and i not in taken:
                taken.add(i)
                result.append((i + 1, s))
    # ⛔ ШАПКА ТАБЛИЦЫ — не строка права, и отсеять её надо ПО МЕСТУ, а не по словам.
    # 🩸 Оплачено правкой 05.09 08:15 UTC: расширив отбор с галочки на слова, я захватила
    # заголовок столбца «| Действие | Разрешено? | Источник |» — слово «Разрешено?»
    # разрешительное, и шапка стала краснеть как право без записи. Одиннадцать случаев
    # приёмки покраснели разом, и все — по этой одной причине.
    # ⇒ шапка узнаётся НАДЁЖНО: за ней идёт разделитель «|---|». Ни одно слово не нужно.
    separators = {n for n, s in result if set(s) <= set("|- :")}
    headers = {n - 1 for n in separators}
    return sorted((n, s) for n, s in result if n not in headers)


def parse_starts(body: str):
    """По каждому вхождению «§ПРАВА»: (строка, заголовок?, рядов таблицы под ним, указатели в прозе).

    🩹 ПРАВКА AIA 7c4eba1 (08.09, их записки #4873–#4876; перенесена в пакет карточкой #679,
    этап Э5): «судилось 0» — ОДИН ноль на ТРИ разных случая (раздел пуст · права прозой или
    блоком с указателями · всё отсеяно), а «вхождение» — одно на два (заголовок · упоминание
    в прозе, под которым таблицы быть не должно). Сбор строк НЕ сужаем — сужение до
    заголовков ослепило бы роль с разделом-прозой молча, и отчёт показал бы не провал, а
    тишину. Различаем СЛОВАМИ на печати.

    ⚖️ ОТСТУПЛЕНИЕ ОТ ТЕКСТА AIA (замер на копии базы Atlas 2026-10-10 10:54 UTC): у AIA
    заголовком считалась только строка, начатая «#». У RCC заголовок в рамке «═══ §ПРАВА … ═══»
    — законная форма, её знает и NEXT_HEADER; их правка назвала бы его прозой и напечатала
    ложное «таблица под упоминанием в прозе». Заголовок — те же формы, что конец раздела.
    """
    lines = (body or "").splitlines()
    result, taken = [], set()
    starts = [i for i, l in enumerate(lines) if RIGHTS_HEADER.search(l)]
    for start in starts:
        is_heading = bool(NEXT_HEADER.match(lines[start]))
        rows, pointers = 0, []
        for i in range(start + 1, len(lines)):
            if NEXT_HEADER.match(lines[i]):
                break
            if i in taken:
                continue
            taken.add(i)
            s = lines[i].strip()
            if s.startswith("|"):
                if not set(s) <= set("|- :"):
                    rows += 1
            else:
                for m in PROSE_POINTER.finditer(s):
                    pointers += [int(x) for x in re.findall(r"\d+", m.group(0))]
        result.append((start + 1, is_heading, rows, pointers))
    return result


def permission_cell(s: str) -> str:
    """Ячейка, где роль говорит «мне это можно» — по разрешительной примете.

    Номер ячейки НЕ фиксирован: у одних ролей это «✅ ДА», у @COORD — «стоячее»,
    и стои́т она второй, третьей или последней. Ищем по СОДЕРЖАНИЮ, а не по месту.

    🩸 ЗАПРЕТ В ТОЙ ЖЕ ЯЧЕЙКЕ НЕ ОТМЕНЯЕТ ПРАВА. Первая редакция этой функции требовала
    ячейку БЕЗ запретительной приметы — и убивала ГЛАВНЫЙ случай карточки: у @STUD стои́т
    «✅ БЕЗ спроса (30.08) · ⛔ ГАШЕНИЕ — спрашивать каждый раз», то есть право и его
    оговорка в одной ячейке. Строка переставала судиться вовсе, а это ровно та строка,
    ради которой правило и заведено.

    🩸 НО И ОБРАТНОЕ ОКАЗАЛОСЬ ЛОЖНЫМ (замер 05.09 08:17 UTC): взяв «любую ячейку
    с разрешением», я набрала НАДГРОБИЙ и ЗАПРЕТОВ — «⚰️ ПОГЛОЩЕНО», «❌ окно закрыто…
    разрешение из чужой ноты НЕ наследуется». Слово «разрешение» стояло в ПОЯСНЕНИИ,
    четвёртой ячейкой, а вердикт строки — во второй, и он запретительный.
    ⇒ ВЕРДИКТ ВЫНОСИТ ПЕРВАЯ ЯЧЕЙКА, КОТОРАЯ ВООБЩЕ СУДИТ (несёт разрешение либо запрет).
    Внутри неё выигрывает то, что стои́т РАНЬШЕ: «✅ БЕЗ спроса · ⛔ ГАШЕНИЕ» — право
    с оговоркой; «⚰️ … стоячее по репозиторию» — надгробие.
    """
    for c in s.split("|"):
        permit = PERMIT_PATTERN.search(c)
        deny = DENY_PATTERN.search(c)
        if not permit and not deny:
            continue                      # ячейка ничего не судит — смотрим следующую
        if permit and (not deny or permit.start() < deny.start()):
            return c
        return ""                         # первой высказалась запретительная — строка не про право
    return ""


def is_judged(s: str) -> tuple[bool, str]:
    """(судить?, причина отсева) — строка заявляет ПРАВО, за которое отвечает реестр?"""
    if set(s) <= set("|- :"):
        return False, "шапка или разделитель"
    cell = permission_cell(s)
    if not cell:
        return False, "запрет или строка без разрешения"
    # ⛔ ОБЯЗАННОСТЬ — НЕ ПРАВО, и реестр прав о ней ничего не знает.
    # 🩸 Живой ложный случай (первая редакция, 05.09 06:24 UTC): строка OPSSRE
    # «⚠️ СВЕРКА СОСТАВА перед каждым push | ✅ ОСТАЁТСЯ, ОБЯЗАТЕЛЬНА» покрашена как
    # право без записи реестра. Закрыть её нельзя НИКАК: записи о сверке в реестре
    # не будет никогда, потому что реестр — про разрешения. Проверка требовала
    # невыполнимого, то есть учила не верить себе.
    if DUTY_PATTERN.search(cell):
        return False, "обязанность, а не право"
    # ⛔ источник — конструкция роли, а НЕ слово владельца. Слово владельца в строке
    #    перевешивает: у @COORD есть строка «дежурно graphify | зона | владелец 16.07»,
    #    и она про право владельца, хотя слово «зона» в ней стои́т.
    if SOURCE_NOT_OWNER.search(s) and not SOURCE_OWNER.search(s):
        return False, "источник — конструкция роли, не слово владельца"
    return True, ""


def verdict(s: str, role: str, registry: dict, rules: set = frozenset()):
    """(зелёная?, слово) — чем строка закрыта либо почему красная."""
    if NOT_IN_REGISTRY_MARK.search(s):
        return True, "пометка «НЕ В РЕЕСТРЕ» со следом"
    m = REGISTRY_REF.search(s)
    if not m:
        # ⚖️ ДВА РАЗНЫХ КРАСНЫХ, А НЕ ОДНО ОБЩЕЕ — по слову @COORD (записка #4810 §②).
        # Его довод, и он сильный: обвинение, которое НЕЧЕМ ЗАКРЫТЬ, учит не верить
        # проверке целиком. Строка, честно сославшаяся на действующее правило свода,
        # виновата не в самозванстве — виновата незаведённая запись, и это чинит
        # не она одна. Одним словом эти два случая красить нельзя.
        names = sorted(k for k in rules if k in s)
        if names:
            return False, (f"источник — правило свода «{names[0]}», записи реестра НЕТ ⇒ "
                           f"завести запись ЛИБО пометить «⛔ НЕ В РЕЕСТРЕ — след: …»")
        return False, ("ни ссылки на запись реестра, ни пометки «⛔ НЕ В РЕЕСТРЕ — след: …» "
                       "⇒ право живёт только в памяти")
    n = int(m.group(1))
    entry = registry.get(n)
    if entry is None:
        return False, f"ссылка на запись #{n}, а такой записи в реестре НЕТ"
    owner, revoked = entry
    if revoked:
        return False, f"запись #{n} ОТОЗВАНА ({revoked}) — право по ней не действует"
    if owner != role and owner != "ALL":
        return False, f"запись #{n} принадлежит роли {owner}, а не {role}"
    return True, f"запись #{n} ({owner})"


def pointer_word(n: int, role: str, registry: dict) -> tuple[bool, str]:
    """(годен?, слово) — указатель «реестр #N» из прозы против самого реестра (правка AIA 7c4eba1)."""
    entry = registry.get(n)
    if entry is None:
        return False, f"#{n} — такой записи в реестре НЕТ"
    owner, revoked_at = entry
    if revoked_at:
        return False, f"#{n} — ОТОЗВАНА ({revoked_at})"
    if owner not in (role, "ALL"):
        return False, f"#{n} — принадлежит {owner}, а не {role}"
    return True, f"#{n} ✅"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=None)
    ap.add_argument("--role", default=None, help="проверить одну роль")
    ap.add_argument("--verbose", action="store_true", help="печатать и зелёные строки")
    a = ap.parse_args()
    db = Path(a.db) if a.db else mezo_paths.live_db()
    try:
        con = sqlite3.connect(f"file:{db.as_posix()}?mode=ro", uri=True)
        memory = con.execute("SELECT role, section, body FROM phoenix "
                             "ORDER BY role, section").fetchall()
        registry = {i: (r, rev) for i, r, rev in
                  con.execute("SELECT id, role, revoked_at FROM role_rights")}
        rules = {k for (k,) in con.execute(
            "SELECT rule_key FROM rules WHERE status='active'")}
        con.close()
    except sqlite3.Error as e:
        print(f"⛔ память или реестр не прочитаны ({e}) — НЕ ПРОВЕРЕНО, это не «чисто»")
        return 2
    if not memory:
        print("⛔ в памяти НОЛЬ разделов — мерить нечего (это не «чисто»)")
        return 2
    if not registry:
        # ⚪ Различаем ПРИЧИНУ пустоты реестра, а не гадаем «новорождённость» (карточка #606).
        # Если НИ В ОДНОМ разделе памяти нет ни одной строки таблицы §ПРАВА, реестру нечего
        # было бы принять в любом случае — сверять действительно не с чем, и это честный
        # свежий контур, а не пропажа. Если хоть одна строка права в памяти ЕСТЬ, а реестр
        # пуст — это по-прежнему пропажа записи, прежний отказ остаётся дословно.
        # Указатель на реестр в прозе — тоже объявленное право (правка AIA 7c4eba1): при пустом
        # реестре он заведомо негоден, и молчать «прав не объявлено» о нём нельзя.
        no_rights_rows_anywhere = not any(
            rights_table_rows(body) or any(p for *_, p in parse_starts(body))
            for _, _, body in memory)
        if no_rights_rows_anywhere:
            print("⚪ прав не объявлено ни в памяти, ни в реестре — сверять нечего")
            return 0
        print("⛔ реестр прав ПУСТ — сверять не с чем, это не «чисто»")
        return 2

    red_rows, green_rows, roles_with_table = [], [], set()
    found, dropped = 0, {}
    # 🩹 ПРАВКА AIA 7c4eba1 (их записки #4867/#4869/#4870): «ноль провалов» двусмысленно —
    # проверка могла просто НЕ НАЙТИ раздел (заголовок без §, проза вместо таблицы) и
    # промолчать. Поэтому по КАЖДОЙ роли печатается, с каких строк взят раздел и сколько
    # рядов судилось; роль без единого вхождения «§ПРАВА» — «НЕ ПРОВЕРЕНА», а не «чисто».
    by_role = {}
    for role, section, body in memory:
        if a.role and role != a.role:
            continue
        starts = parse_starts(body)
        lines = rights_table_rows(body)
        if lines:
            roles_with_table.add(role)
        judged = 0
        for n, s in lines:
            found += 1
            judge, why = is_judged(s)
            if not judge:
                dropped[why] = dropped.get(why, 0) + 1
                continue
            judged += 1
            ok, word = verdict(s, role, registry, rules)
            (green_rows if ok else red_rows).append((role, section, n, s, word))
        st = by_role.setdefault(role, {"starts": [], "rows": 0, "judged": 0, "pointers": []})
        st["starts"] += [(section, n, h, r) for n, h, r, _ in starts]
        st["rows"] += len(lines)
        st["judged"] += judged
        st["pointers"] += [(section, n, k) for n, _, _, ptrs in starts for k in sorted(set(ptrs))]

    # ⚖️ ВТОРОЕ ОТСТУПЛЕНИЕ ОТ ТЕКСТА AIA (тот же замер Atlas 10.10): у AIA указатели в прозе
    # сверяются у ВСЕХ ролей. У роли С таблицей прав проза рядом — пояснение, а не форма права:
    # у CORE, OPSSRE и TAXO под заголовком §ПРАВА стоит история отозванной записи #12 («общая
    # запись #12 ОТОЗВАНА 2026-09-25…») — правка AIA дала бы три провала, и все три ложных.
    # Сверяем указатели ТОЛЬКО у роли без единого ряда таблицы — ровно случай, ради которого
    # правка заведена (у AIA роль LLMG: права блоком «[реестр #14/#15/#18]»).
    # Таблица считается по РОЛИ, а не по разделу: у OPSSRE таблица в identity, а история #12 —
    # в разделе rebirth; суд по разделу вернул бы её ложный провал. 🩹 Несверенное НЕ молчит
    # (возврат приёмки не автора 10.10): у роли с таблицей число несверенных указателей
    # печатается строкой «ℹ️», а итог не говорит «негодных нет» о том, чего не смотрел.
    red_pointers, unchecked_pointers = [], 0
    for role, st in by_role.items():
        st["pointer_words"] = []
        if st["rows"]:
            unchecked_pointers += len(st["pointers"])
            continue
        for section, n, k in st["pointers"]:
            ok, word = pointer_word(k, role, registry)
            st["pointer_words"].append((ok, word))
            if not ok:
                red_pointers.append((role, section, n, word))

    considered = len(red_rows) + len(green_rows)
    print(f"ролей с таблицей прав: {len(roles_with_table)} · записей реестра: {len(registry)} · "
          f"строк в таблицах НАЙДЕНО: {found} · рассмотрено: {considered} · "
          f"без записи реестра: {len(red_rows)}")
    for role in sorted(by_role):
        st = by_role[role]
        if not st["starts"]:
            print(f"   ⚠️ {role}: раздел «§ПРАВА» НЕ НАЙДЕН — роль НЕ ПРОВЕРЕНА (это не «чисто»)")
            continue
        heads = [f"{sec}:{n}" for sec, n, h, _ in st["starts"] if h]
        prose = [f"{sec}:{n}" for sec, n, h, _ in st["starts"] if not h]
        under_prose = [f"{sec}:{n}" for sec, n, h, r in st["starts"] if not h and r]
        parts = [("заголовок " + ", ".join(heads)) if heads else "заголовка НЕТ (раздел — проза)"]
        if prose:
            parts.append(f"упоминаний в прозе {len(prose)} ({', '.join(prose)})")
        parts.append(f"рядов {st['rows']} · судилось {st['judged']}")
        print(f"   {role}: " + " · ".join(parts))
        if under_prose:
            print(f"      ⚠️ таблица ПОД упоминанием в прозе {', '.join(under_prose)} — строки судятся, "
                  f"но разделом прав это место не является; проверь, чьи они")
        # 🔑 у нуля два слова (правка AIA, их записка #4874): «раздел пуст» и «форма не табличная» —
        #    разные вещи
        if st["rows"] == 0:
            if st["pointer_words"]:
                words = ", ".join(w for _, w in st["pointer_words"])
                bad = any(not ok for ok, _ in st["pointer_words"])
                print(f"      ℹ️ таблицы нет — права прозой или блоком с указателями на реестр: {words}. "
                      f"Форма не табличная, построчно не судится; указатели сверены с реестром"
                      + (" — ⛔ есть негодные, см. 🔴 ниже" if bad else ""))
            else:
                print("      ⚠️ раздел найден, но ПУСТ: ни таблицы, ни указателя на реестр — "
                      "роль НЕ ПРОВЕРЕНА (это не «чисто»)")
        elif st["judged"] == 0:
            print("      ℹ️ все ряды отсеяны (см. отсев ниже): судить было нечего — "
                  "это не «чисто», а «ни одна строка не про право»")
        if st["rows"] and st["pointers"]:
            nums = ", ".join(f"#{k}" for k in sorted({k for _, _, k in st["pointers"]}))
            print(f"      ℹ️ указателей на реестр в прозе {len(st['pointers'])} ({nums}) — НЕ сверены: "
                  f"у роли есть таблица прав, проза рядом считается пояснением")
    # 🩸 ОТСЕВ ПЕЧАТАЕТСЯ С ПРИЧИНОЙ, А НЕ ОДНИМ ЧИСЛОМ — по замеру @STUD (записка #4818):
    # «отсеяно 88» при 31 рассмотренной читается как «проверка не смотрит почти ни на что»,
    # а незаконным был отсев ЧЕТЫРЁХ строк. Голое число обвиняет весь контур; разряды
    # показывают роли её собственную строку.
    if dropped:
        print("   отсеяно " + str(sum(dropped.values())) + ", по причине: "
              + " · ".join(f"{k}: {v}" for k, v in sorted(dropped.items())))
        print("   ⚖️ отсев — НЕ «чисто»: это строки, за которые реестр прав не отвечает. "
              "Своя строка среди них? Скажи — признак поправим, он уже ошибался.")
    for role, section, n, s, word in red_rows:
        print(f"🔴 [{role} · {section} · строка {n}] {word}")
        print(f"      {s[:180]}")
    for role, section, n, word in red_pointers:
        print(f"🔴 [{role} · {section} · раздел со строки {n}] указатель в прозе: {word}")
    if a.verbose:
        for role, section, n, s, word in green_rows:
            print(f"✅ [{role} · {section} · строка {n}] {word}")
    reds = len(red_rows) + len(red_pointers)
    if not reds:
        print("✅ строк права без записи реестра нет; негодных указателей в прозе у ролей без таблицы нет"
              + (f" · у ролей С таблицей не сверено указателей: {unchecked_pointers} (см. ℹ️ выше)"
                 if unchecked_pointers else ""))
    else:
        print("ℹ️ Это ПРОВЕРКА, а не запрет: сохранение памяти проходит как обычно. "
              "Закрыть строку — ДВА пути, оба законны: завести право в реестр "
              "(role-rights.py add, по слову владельца) и вписать «запись #N» ЛИБО, если "
              "права в реестре нет и не будет, пометить строку «⛔ НЕ В РЕЕСТРЕ — след: …».")
    # граница печатается и при успехе: итог «чисто» без неё обещал бы больше, чем смотрели
    print("⚖️ ЧЕГО ПРОВЕРКА НЕ ВИДИТ: верна ли САМА ссылка по существу (что запись #N "
          "про это же право); права, записанные прозой БЕЗ указателя на реестр; указатели "
          "в прозе у роли С таблицей прав (в любом её разделе) — там проза считается "
          "пояснением и не судится.")
    return 1 if reds else 0


