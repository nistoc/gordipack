def selftest():
    """Доказательство чувствительности: слепок с ИЗВЕСТНЫМИ долгами обязан краснеть,
    приведённый — молчать. Требование @TAXO (#2769): «порча, которую не удаётся навести,
    не доказательство прочности, пока не названа причина, по которой её нельзя навести»."""
    import tempfile
    tmp = mezo_stand.new("guard-std-") / "m.db"
    con = sqlite3.connect(str(tmp))
    con.execute("CREATE TABLE phoenix (role TEXT, section TEXT, body TEXT, saved_at TEXT)")
    # ⚡ ТАБЛИЦА ФАКТОВ ДЛЯ ④+ (карточка #159). Без неё признак «число неверно» в самопроверке
    # НЕ УЧАСТВОВАЛ ВОВСЕ: он сверяет сказанное с фактом, а факта в тестовой базе не было —
    # запрос отдавал None, и признак молча пропускался. Самопроверка при этом рапортовала
    # «гард чувствителен»: она перечисляла сработавшие признаки, но не замечала НЕ вызванных.
    # 🎯 Молчание признака и его отсутствие давали один ответ — тот самый класс, который
    # этот гард и ловит у ролей. Три правила ⇒ «правил 3», и на этом строится пара ниже.
    con.execute("CREATE TABLE rules (rule_key TEXT, status TEXT)")
    for k in ("проба-один", "проба-два", "проба-три"):
        con.execute("INSERT INTO rules VALUES (?, 'active')", (k,))
    for role, data in (("DIRTY", DIRTY), ("DIRTY_NEW_WORDS", DIRTY_NEW_WORDS),
                       ("CLEAN", CLEAN), ("QUOTED", QUOTED)):
        for sec, body in data.items():
            con.execute("INSERT INTO phoenix VALUES (?,?,?, datetime('now'))",
                        (role, sec, body))
    con.commit()
    con.close()
    con = sqlite3.connect(f"file:{tmp}?mode=ro", uri=True)
    mt = script_mtimes()
    # 🪤 СЧЁТ СЛУЧАЕВ — норма STUD (#2991): «прогон, не назвавший ЧИСЛО выполненных
    #    проверок, не считается прогоном». Он поймал у себя прогон тестов, вернувший
    #    УСПЕХ при НУЛЕ выполненных: «196 прошли» и «0 прошли» дают один код возврата.
    #    Здесь то же было возможно — опустей DIRTY/CLEAN, вывод остался бы гордым.
    ok = True
    cases = 0
    for role, want_red, want_yellow in (("DIRTY", True, True),
                                        # только новые слова: жёлтое обязано быть —
                                        # иначе признак знает лишь прежнее написание
                                        ("DIRTY_NEW_WORDS", False, True),
                                        ("CLEAN", False, False),
                                        ("QUOTED", False, False)):
        # ⚡ counts ПЕРЕДАЮТСЯ (карточка #159). Прежде selftest звал check_role без них,
        # и признак ④+ не участвовал в самопроверке ВООБЩЕ — а она рапортовала «гард
        # чувствителен». Отсутствие признака и его молчание давали один ответ: ровно тот
        # класс, который этот гард ловит у ролей, — только на самой проверке.
        red, yellow, _ = check_role(con, role, mt, False, live_counts(con))
        kinds = {w.split()[0] for _, w, _ in red + yellow}
        got_red, got_yellow = bool(red), bool(yellow)
        good = (got_red == want_red) and (got_yellow == want_yellow)
        # ⚠️ ВСТРЕЧНАЯ ПОЛОВИНА ПАРЫ: на DIRTY признак ④+ обязан ПРИСУТСТВОВАТЬ поимённо.
        # Проверять только «есть жёлтые» мало: жёлтые дадут и другие признаки, а ④+ при
        # этом промолчит — и гашение цитат окажется гашением всего подряд, незамеченным.
        if role == "DIRTY":
            has_stale = any(w.startswith("④+") for _, w, _ in yellow)
            good &= has_stale
            if not has_stale:
                print("      🔴 ④+ НЕ СРАБОТАЛ на DIRTY — гашение цитат гасит и утверждения")
        # ⚠️ ПОИМЁННОЕ ТРЕБОВАНИЕ, а не «есть жёлтое»: жёлтое дадут и другие признаки
        # (нет прав, нет даты), и случай окажется зелёным при ослепшем признаке. Проверено
        # нарочным сужением образца: без этой строки сужение проходило незамеченным.
        if role == "DIRTY_NEW_WORDS":
            named = any("отметка прочитанного числом" in w for _, w, _ in yellow)
            good &= named
            if not named:
                print("      🔴 ПРИЗНАК ЗНАЕТ ТОЛЬКО СТАРОЕ НАПИСАНИЕ: память, написанную "
                      "новыми словами, он не видит — и промолчит на всех переписанных")
        ok &= good
        cases += 1
        print(f"{'✅' if good else '🔴'} память {role}: 🔴 {len(red)} · 🟡 {len(yellow)} "
              f"· признаки {sorted(kinds) or '—'} "
              f"(ожидали {'красное' if want_red else 'тишину'})")
        for where, what, line in red + yellow:
            print(f"      {where:14} {what}")
    con.close()
    if cases == 0:
        print("\n⛔ ОТКАЗ: самопроверка не выполнила НИ ОДНОГО случая — это не «чисто»")
        return 2
    print(f"\n{'✅ ГАРД ЧУВСТВИТЕЛЕН' if ok else '🔴 ГАРД СЛЕП ИЛИ ШУМИТ'} — "
          f"ВЫПОЛНЕНО {cases} случаев: краснеет на известных долгах и молчит "
          f"на приведённой памяти")
    return 0 if ok else 1


