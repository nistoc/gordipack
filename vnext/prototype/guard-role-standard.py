    if NARROW:
        print("🔬 РЕЖИМ ЗАМЕРА MEZO_UNIT=line: ВСЕ окрестности сужены до строки. Это НЕ"
              " штатный прогон — числа ниже отвечают на вопрос «на чём держатся гашения»")
    if a.selftest:
        return selftest()
    db = Path(a.db)
