# Чем кончается суждение. «·» — наш разделитель перечисления: он кончает ЭЛЕМЕНТ
# списка, и без него строки блока без точек склеивались в одно 15-строчное
# «предложение» (поймано собственной приёмкой, случай ③).
ENDS = ("...", ".", "!", "?", ":", "»", "`", "*", "|", ";", ")", "·", "—", ",")
STARTS_NEW = re.compile(r"^\s*(?:[-*·>#`]|\d+[.)]|[⛔⚠️✅🔴🟡🎯📌⚰️🪤⇒👉📏⚖️🔬⚡]|##)")


def sentence(lines, i):
    """Строки ОДНОГО ПРЕДЛОЖЕНИЯ, в которое попала строка i (1-based).

    ═══ ЧЕМ ЭТО КОНЧИЛОСЬ: ДВЕ ЕДИНИЦЫ ОТВЕРГНУТЫ ЗАМЕРОМ, ПРЕЖДЕ ЧЕМ НАШЛАСЬ ТРЕТЬЯ ═══
    ① «ВЕЗДЕ СТРОКА» (буквальное чтение урока #151) — ОТВЕРГНУТО: ломает 3 честных
       гашения из 5. `--db … снят R15a (…)` у @TAXO — это ОДНО предложение, разорванное
       переносом; физическая строка есть единица ВЁРСТКИ, а не мысли.
    ② «АБЗАЦ до пустой строки» — ОТВЕРГНУТО ТУТ ЖЕ: в наших слепках блоки идут по 20+
       строк без единой пустой, и «абзац» оказался ШИРЕ прежнего окна ±3. Замер: погасил
       8 находок, среди них живую «правил 23» — знаком ⛔ из строки, отстоящей на 15.
       ⇒ Единица, чья ширина зависит от чужой привычки верстать, — не единица.
    ③ ПРЕДЛОЖЕНИЕ (принято): строка плюс её продолжение, если фраза не закончена. Ширина
       определяется ТЕКСТОМ САМОГО СУЖДЕНИЯ, а не расстоянием и не вёрсткой. Строка,
       начинающаяся с маркера списка или значка, — всегда НОВОЕ суждение: так наши роли
       и пишут (⛔ · 📌 · «1.» · «-»), и именно значок ⛔ соседнего пункта гасил чужое.
    ⚖️ Урок #151 не отменён, а уточнён: гашение не должно перетекать между СУЖДЕНИЯМИ.
    Перенос строки внутри одного суждения — не переход к соседу.
    """
    start, end = sentence_span(lines, i)
    return lines[start:end]


def sentence_span(lines, i):
    """Границы предложения строки i как индексы среза (0-based, end исключительно)."""
    start = i - 1
    while start > 0:
        prev = lines[start - 1].rstrip()
        if not prev or prev.endswith(ENDS) or STARTS_NEW.match(lines[start]):
            break
        start -= 1
    end = i
    while end < len(lines):
        cur = lines[end - 1].rstrip()
        if not cur or cur.endswith(ENDS) or STARTS_NEW.match(lines[end]) \
                or not lines[end].strip():
            break
        end += 1
    return start, end


def with_next(lines, i):
    """Предложение строки i ПЛЮС следующее суждение — единица для ⑨ (обещание охвата).

    ⚖️ РАСШИРЕНИЕ НАЗВАНО, А НЕ ЗАВЕДЕНО МОЛЧА. Граница у нас пишется ОТДЕЛЬНЫМ
    суждением сразу под обещанием — «⛔ ЧЕГО НЕ МЕРИЛА: …» (@TAXO §state), — и это
    норма письма, а не небрежность. Отрезав его, я сломал ⑨ на честной форме, и поймала
    это не мысль, а ПРОБА: она краснела там, где механизм обязан молчать.
    ⛔ Ровно ОДНО следующее суждение, не окно: дальше начинается чужая мысль.
    """
    start, end = sentence_span(lines, i)
    j = end                                   # первая строка ЗА предложением (0-based)
    while j < len(lines) and not lines[j].strip():
        j += 1
    if j >= len(lines):
        return lines[start:end]
    _, end2 = sentence_span(lines, j + 1)
    return lines[start:end2]


def near(lines, i, rx, before=0, after=0, para=False, plus_next=False):
    """Ищет примету в ЕДИНИЦЕ СУЖДЕНИЯ вокруг строки i (1-based).

    ═══ ЗАЧЕМ ОДНА ФУНКЦИЯ ВМЕСТО ШЕСТИ САМОДЕЛЬНЫХ ОКРЕСТНОСТЕЙ (#155) ═══
    До 10.08 каждое место строило свою: ±2, ±3, (−2,+4), (−3,+2), (−2,+3). Разнобой не
    имел причин — просто писался в разное время, — но КАЖДАЯ окрестность есть решение
    «пометка про соседа считается пометкой про нас», и оно должно быть НАЗВАНО, а не
    заведено случайно. Теперь ширина стои́т в вызове рядом с предметом.
    ⛔ ПО УМОЛЧАНИЮ — СТРОКА (before=after=0): урок #151/#152. Расширение допустимо
    только там, где связь СТРУКТУРНАЯ (заголовок над блоком, граница под обещанием),
    и в вызове это объяснено словами.
    ⚠️ Ширина НЕ спрашивает, ПРО ЧТО соседняя строка, — этого регексп не умеет вовсе.
    Поэтому расширение оправдано лишь там, где ЛОЖНОЕ ГАШЕНИЕ дешевле ложного крика.
    """
    if NARROW:                       # ключ ЗАМЕРА (см. NARROW выше) — не тихий
        return rx.search(lines[i - 1] if 0 < i <= len(lines) else "")
    if plus_next:                     # обещание + следующее суждение (⑨, см. with_next)
        return rx.search(" ".join(with_next(lines, i)))
    if para:                          # para=True ⇒ единица = ПРЕДЛОЖЕНИЕ (см. sentence)
        return rx.search(" ".join(sentence(lines, i)))
    lo = max(0, i - 1 - before)
    hi = i + after
    return rx.search(" ".join(lines[lo:hi]))


def check_rights(rows):
    """⑦ §ПРАВА — секцией и таблицей, с источником разрешения.

    Одна проверка на РОЛЬ, а не на секцию: правило требует наличия прав где-то в слепке,
    и посекционный обход дал бы шесть жёлтых за одно отсутствие (класс ⑥ до его свёртки).
    """
    head_at = table = src = None
    for section, body, _ in rows:
        lines = (body or "").splitlines()
        for i, line in enumerate(lines, 1):
            if RIGHTS_HEAD.search(line):
                head_at = head_at or f"§{section}:{i}"
                block = lines[i - 1:i + 25]
                if any(ln.count("|") >= 2 for ln in block):
                    table = True
                if any(RIGHTS_SRC.search(ln) for ln in block):
                    src = True
    if head_at is None:
        return [("§—", "⑦ §ПРАВА: секции прав нет вовсе",
                 "правило v2: права — отдельной секцией и таблицей, не прозой")]
    out = []
    if not table:
        out.append((head_at, "⑦ §ПРАВА не таблицей",
                    "прозой право и его источник неразличимы — цена ошибки необратима"))
    if not src:
        out.append((head_at, "⑦ §ПРАВА без источника",
                    "не сказано ОТКУДА разрешение (кто и когда) — проверить нечем"))
    return out


