class _Quench:
    """Совместимая обёртка .search(): своё предметное ИЛИ общие роды из mention."""

    def __init__(self, own, kinds=("cancel",)):
        self._own = re.compile(own, re.IGNORECASE)
        self._kinds = kinds

    def search(self, text):
        return self._own.search(text or "") or (
            any(mention.is_mention(ln, kinds=self._kinds)
                for ln in (text or "").splitlines()) or None)


