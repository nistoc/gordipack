#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""ПРИЁМКА измерителя вызовов инструментов (measure-tool-calls.py).

🩸 ЧЕМ ОПЛАЧЕНА. 2026-09-07 COORD дважды подряд написала в приёмке чужой работы:
«перенос выгоды на весь набор своей рукой НЕ перемерила — мой способ счёта негоден».
Способ был негоден по одной причине: команда искалась в поле «command» ВЕРХНЕГО УРОВНЯ
записи, а лежит она в message.content[] → элемент type="tool_use", name="Bash" →
input.command. Пока это так, любое число о расходе принимается на слово автора.
🎯 Отсюда главный случай этой приёмки — ② : ровно тот промах, поставленный НАРОЧНО.
Если измеритель начнёт читать поле верхнего уровня, приёмка обязана покраснеть.

⚖️ ЧТО ЭТА ПРИЁМКА НЕ ПРОВЕРЯЕТ, названо прямо, чтобы её зелёное не читали шире:
· верность оценки «знаков на вызов» (--per-call) — это вход от человека, не измерение;
· полноту записей разговоров: если чат не сохранён на диск, его вызовов не увидит никто;
· отделение вызовов роли от вызовов её помощников — измеритель сам говорит, что не делит.
"""
from __future__ import annotations

import io
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import mezo_stand  # noqa: E402 — временный каталог убирается при успехе, сохраняется при провале

ИЗМЕРИТЕЛЬ = str(Path(__file__).resolve().parent / "measure-tool-calls.py")
# Путь контура в подопытных командах — ОТ РАСПОЛОЖЕНИЯ ФАЙЛА, не буквами этой машины: буквальный
# путь в исполняемой строке сверка копий не пускает в образец (карточка #576), и правильно —
# у потребителя образца он был бы чужим. Правка PROTO 2026-09-07 12:45 UTC по отказу переноса.
КОНТУР = Path(__file__).resolve().parent.parent.as_posix()
ДЕНЬ = "2026-09-07"
итог: list[tuple[str, bool]] = []


def случай(имя: str, ок: bool, слово: str) -> None:
    итог.append((имя, ок))
    print(f"{'✅' if ок else '🔴'} {имя}")
    print(f"   {слово}")


def запись(команда: str, *, день: str = ДЕНЬ) -> dict:
    """Запись разговора с вызовом оболочки — ТАК, как её кладёт Claude Code."""
    return {"timestamp": f"{день}T10:00:00.000Z", "type": "assistant",
            "message": {"role": "assistant", "content": [
                {"type": "tool_use", "name": "Bash", "input": {"command": команда}}]}}


def запись_текстом(текст: str, *, день: str = ДЕНЬ) -> dict:
    """Запись БЕЗ вызова: имя инструмента лишь упомянуто в тексте."""
    return {"timestamp": f"{день}T10:00:00.000Z", "type": "assistant",
            "message": {"role": "assistant", "content": [{"type": "text", "text": текст}]}}


def запись_верхним_полем(команда: str, *, день: str = ДЕНЬ) -> dict:
    """🪤 ПОЛОМКА ②: команда положена в поле ВЕРХНЕГО УРОВНЯ — так её искала COORD 06.09."""
    return {"timestamp": f"{день}T10:00:00.000Z", "type": "assistant", "command": команда,
            "message": {"role": "assistant", "content": [{"type": "text", "text": "…"}]}}


def запись_чужого_средства(команда: str, *, день: str = ДЕНЬ) -> dict:
    """Вызов НЕ оболочки (другое средство) с тем же текстом внутри."""
    return {"timestamp": f"{день}T10:00:00.000Z", "type": "assistant",
            "message": {"role": "assistant", "content": [
                {"type": "tool_use", "name": "Read", "input": {"command": команда}}]}}


def положить(каталог: Path, имя: str, записи: list[dict]) -> None:
    with io.open(каталог / imя_файла(имя), "w", encoding="utf-8") as fh:
        for r in записи:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")


def imя_файла(имя: str) -> str:
    return imя_файла_безопасно(имя)


def imя_файла_безопасно(имя: str) -> str:
    return f"{имя}.jsonl"


def померить(каталог: Path, *доп: str) -> tuple[int, str]:
    p = subprocess.run([sys.executable, ИЗМЕРИТЕЛЬ, "--dir", str(каталог),
                        "--since", ДЕНЬ, "--until", ДЕНЬ, *доп],
                       capture_output=True, text=True, encoding="utf-8",
                       errors="replace", timeout=120)
    return p.returncode, (p.stdout or "") + (p.stderr or "")


def число(вывод: str, имя: str) -> int:
    """Счёт из строки вида «имя … N». Берём ПОСЛЕДНЕЕ число строки, где стоит имя."""
    for строка in вывод.splitlines():
        if имя in строка:
            числа = [ч for ч in строка.replace("·", " ").split() if ч.isdigit()]
            if числа:
                return int(числа[0]) if len(числа) == 1 else max(int(ч) for ч in числа)
    return 0


def main() -> int:
    стенд = mezo_stand.new("bite-measure-tool-calls-")

    # ── ① КОНТРОЛЬ: обычный вызов виден. Без него зелёное значило бы «искать не стали»
    кат1 = стенд / "one"
    кат1.mkdir()
    положить(кат1, "chat", [запись(f"python {КОНТУР}/.mezosync/scripts/guard-all.py")] * 3)
    код1, вывод1 = померить(кат1)
    n1 = число(вывод1, "guard-all")
    случай("① КОНТРОЛЬ: вызовы оболочки считаются", код1 == 0 and n1 == 3,
           f"положено 3 вызова, насчитано {n1} — без этого случая зелёное значило бы, "
           f"что измеритель не смотрел вовсе")

    # ── ② ПОЛОМКА, ради которой приёмка и заведена: команда в поле ВЕРХНЕГО УРОВНЯ
    кат2 = стенд / "top-level"
    кат2.mkdir()
    положить(кат2, "chat", [запись_верхним_полем("python .../guard-all.py")] * 3)
    _, вывод2 = померить(кат2)
    n2 = число(вывод2, "guard-all")
    случай("② ПОЛОМКА: команда в поле верхнего уровня — НЕ засчитана", n2 == 0,
           f"насчитано {n2}, ждём 0. 🩸 Это дословно промах COORD 06.09: она искала поле "
           f"«command» верхнего уровня и получила ноль там, где вызовов были сотни. "
           f"Начни измеритель читать это поле — случай ① перестанет отличать его от верного")

    # ── ③ ВСТРЕЧНЫЙ: имя инструмента в ТЕКСТЕ записи — не вызов
    кат3 = стенд / "mention"
    кат3.mkdir()
    положить(кат3, "chat", [запись_текстом("надо позвать guard-all.py, но я не зову")] * 5)
    _, вывод3 = померить(кат3)
    n3 = число(вывод3, "guard-all")
    случай("③ ВСТРЕЧНЫЙ: имя в тексте записи, а не в команде — не считается", n3 == 0,
           f"насчитано {n3}, ждём 0 — иначе измеритель считал бы УПОМИНАНИЯ. Мой грубый счёт "
           f"так и дал 1 845 «вызовов» там, где их 277: имя стои́т и в команде, и в выводе, "
           f"и в пересказе")

    # ── ④ ВСТРЕЧНЫЙ: вызов внутри составной команды — считается
    кат4 = стенд / "compound"
    кат4.mkdir()
    положить(кат4, "chat", [
        запись(f"cd {КОНТУР} && python .mezosync/scripts/guard-all.py > out.txt 2>&1"),
        запись("ls && python .mezosync/scripts/guard-all.py | cat"),
    ])
    _, вывод4 = померить(кат4)
    n4 = число(вывод4, "guard-all")
    случай("④ ВСТРЕЧНЫЙ: вызов внутри составной команды считается", n4 == 2,
           f"насчитано {n4}, ждём 2 — роли почти всегда зовут инструмент из составной строки "
           f"(смена каталога, перенаправление). Счёт «только по началу строки» занизил бы почти всё")

    # ── ⑤ ВСТРЕЧНЫЙ: два похожих вызова различаются, а не сливаются
    кат5 = стенд / "distinct"
    кат5.mkdir()
    положить(кат5, "chat", [
        запись("python backlog.py list --role COORD --status all"),
        запись("python backlog.py list --role COORD"),
        запись("python backlog.py list --role PROTO"),
    ])
    _, вывод5 = померить(кат5)
    все = число(вывод5, "backlog list --status all")
    прочие = число(вывод5, "backlog list (прочие)")
    случай("⑤ ВСТРЕЧНЫЙ: похожие вызовы различены, а не слиты", все == 1 and прочие == 2,
           f"«--status all» {все} (ждём 1) · «прочие» {прочие} (ждём 2) — образец с отрицанием "
           f"обязан отделять полный список от обычного, иначе оба числа врут в разные стороны")

    # ── ⑥ ВСТРЕЧНЫЙ: вызов НЕ оболочки не считается, даже если текст тот же
    кат6 = стенд / "other-tool"
    кат6.mkdir()
    положить(кат6, "chat", [запись_чужого_средства("python guard-all.py")] * 4)
    _, вывод6 = померить(кат6)
    n6 = число(вывод6, "guard-all")
    случай("⑥ ВСТРЕЧНЫЙ: вызов другого средства с тем же текстом не считается", n6 == 0,
           f"насчитано {n6}, ждём 0 — считаются команды ОБОЛОЧКИ; иначе чтение файла со "
           f"строкой команды внутри пошло бы в счёт вызовов")

    # ── ⑦ ВСТРЕЧНЫЙ: отрезок времени соблюдается
    кат7 = стенд / "period"
    кат7.mkdir()
    положить(кат7, "chat", [
        запись("python guard-all.py", день="2026-09-07"),
        запись("python guard-all.py", день="2026-09-01"),
        запись("python guard-all.py", день="2026-09-01"),
    ])
    _, вывод7 = померить(кат7)
    n7 = число(вывод7, "guard-all")
    случай("⑦ ВСТРЕЧНЫЙ: вызовы вне названного отрезка не считаются", n7 == 1,
           f"насчитано {n7}, ждём 1 (три вызова, из них в отрезке один) — число без отрезка "
           f"растёт само и потому несравнимо: утренние 236 и дневные 277 — один и тот же день")

    # ── ⑧ ДВА РАЗНЫХ НУЛЯ РАЗЛИЧЕНЫ. Пара ⑧ + ⑧-бис — сердцевина, а не формальность.
    # 🩸 Оплаченный класс: ОДНО «НИЧЕГО» НА ДВЕ РАЗНЫЕ БЕДЫ. «0 вызовов» может значить
    # «их и не было» либо «я смотрел не туда» — и вызывающий гадает, обычно неверно.
    # ⚖️ Здесь мой первый ожидаемый исход был НЕВЕРЕН: я ждала кода 0 и тихого нуля.
    # Инструмент оказался прав, а приёмка — нет; случай переписан по его поведению.
    кат8 = стенд / "empty"
    кат8.mkdir()
    код8, вывод8 = померить(кат8)
    сказал_путь = str(кат8) in вывод8
    случай("⑧ каталог НЕ ТОТ: отказ с объяснением, а не тихий ноль",
           код8 != 0 and сказал_путь and "--dir" in вывод8,
           f"код {код8} (ждём НЕ 0), назван путь и способ поправить. Тихий ноль тут был бы "
           f"хуже отказа: он читается как «вызовов не было», хотя смотрели не туда")

    # ── ⑧-бис ВСТРЕЧНЫЙ к ⑧: записи ЕСТЬ, вызовов в отрезке нет — ноль ЗАКОННЫЙ и код 0
    кат8b = стенд / "zero-lawful"
    кат8b.mkdir()
    положить(кат8b, "chat", [запись_текстом("сегодня инструментов не звал")])
    код8b, вывод8b = померить(кат8b)
    случай("⑧-бис ВСТРЕЧНЫЙ: записи есть, вызовов нет — ноль ЗАКОННЫЙ, код 0",
           код8b == 0 and вывод8b.strip() != "",
           f"код {код8b} (ждём 0) — иначе ⑧ значил бы «инструмент всегда ругается на ноль», "
           f"и настоящий ноль стал бы неотличим от беды. Два нуля обязаны говорить РАЗНОЕ")

    # ── ИТОГ
    print()
    плохие = [и for и, ок in итог if not ок]
    if плохие:
        print(f"🔴 ПРОВАЛЕНО {len(плохие)}: " + " · ".join(плохие))
    else:
        print(f"✅ ИЗМЕРИТЕЛЬ ВЫЗОВОВ — ПРИНЯТ — случаев {len(итог)}: "
              f"контроль ① · нарочная поломка ② · встречные ③④⑤⑥⑦⑧-бис · отказ ⑧")
        print("🩸 ПРОВЕРЕНО ПОЛОМКОЙ САМОГО ИЗМЕРИТЕЛЯ (COORD, 2026-09-07 12:40 UTC): в копию "
              "добавлено чтение поля верхнего уровня ⇒ покраснел случай ②, и ИМЕННО он. "
              "Зелёное этой приёмки значит «измеритель считает верно», а не «мы не смотрели».")
    print("⚖️ ГРАНИЦА: приёмка судит, ЧТО измеритель считает вызовом. Верность оценки "
          "«знаков на вызов», полноту записей на диске и деление вызовов роли от вызовов "
          "её помощников она НЕ проверяет — измеритель говорит об этом сам.")
    return mezo_stand.finish(1 if плохие else 0)


if __name__ == "__main__":
    sys.exit(main())
