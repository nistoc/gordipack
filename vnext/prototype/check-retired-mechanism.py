import argparse
import re
import sqlite3
import sys
from pathlib import Path

# ── ПЕРЕЧЕНЬ СНЯТОГО. Пара «механизм → правило, которое его сняло» + ВЕРСИЯ правила,
#    против которой перечень составлен. Версия — якорь: она и делает устаревание видимым.
#    ⚠️ Перечень намеренно КОРОТКИЙ и рукописный: он про решения владельца, которых единицы.
#    Разрастётся — переносить в базу, а не растить здесь (тогда и заводить сосуд).
RETIRED = [
    {
        "механизм": "--md",
        "что это": "аварийная запись в файлы, когда база недоступна",
        "правило": "md-to-sqlite-phased-cutover",
        "версия_сверки": 5,
        "снято": "2026-08-08 16:53 UTC, слово владельца",
        # где роль читает это как ИНСТРУКЦИЮ (не история кода, а то, что исполняют)
        "источники": ["read-phoenix.py", "write-message.py"],
    },
]

# пометка снятия. Словарь сведён с формами, которыми контур ПОЛЬЗУЕТСЯ на деле (замер по
# правкам @COORD 09.08: ⚰️ · «СНЯТ» · «ОТКЛОНЯЕТСЯ» · «НЕ ПИШЕТСЯ НИКОГДА»). Ключ правила
# рядом не требуем: он длинный, его дописывают не всегда; требуем слово отмены — форму,
# которую можно выполнить. Словарь, собранный из головы, признаёт неправдой чужую честную
# запись: первая редакция не знала ⚰️ и обвинила образцово починенный код.
MARK = re.compile(r"СНЯТ|ОТМЕН|ОТОЗВ|УПРАЗДН|ОТКЛОН|НЕ ПИШЕТСЯ|БОЛЬШЕ НЕ|⚰️|retired",
                  re.IGNORECASE)


def units(text: str):
    """Логические единицы: (номер первой строки, склеенный текст).

    🎯 ЕДИНИЦА СУЖДЕНИЯ — ЗАКОНЧЕННОЕ ВЫРАЖЕНИЕ, А НЕ ФИЗИЧЕСКАЯ СТРОКА И НЕ ОКРЕСТНОСТЬ.
    Этим одним различителем закрываются ОБА встречных урока, и они тянут в разные стороны:
      · #151 (09.08): гасить по ОКРЕСТНОСТИ нельзя — надгробие строкой ниже отменяло ДРУГОЕ;
      · #152 (сегодня): требовать пометку в ТОЙ ЖЕ физической строке тоже нельзя —
        `parser.add_argument("--md",` и его `help=` разнесены СИНТАКСИСОМ языка,
        вписать туда пометку некуда. Признак обвинил безупречно починенный код.
    Разница проверяема, а не на вкус: незакрытые скобки означают, что инструкция НЕ кончилась,
    и продолжение — та же единица. Самостоятельная соседняя строка так не приклеится.
    """
    buf, start, depth = [], None, 0
    for n, line in enumerate(text.splitlines(), 1):
        if start is None:
            start = n
        buf.append(line)
        depth += line.count("(") - line.count(")")
        if depth <= 0:
            yield start, "\n".join(buf)
            buf, start, depth = [], None, 0
    if buf:
        yield start, "\n".join(buf)


def scan(root: Path, item: dict):
    """Строки источников, называющие механизм. Возвращает (учат, помечены).

    🪤 ИМЯ СОВПАДАЕТ ЦЕЛИКОМ, А НЕ ПОДСТРОКОЙ — поймано ПЕРВЫМ ЖЕ прогоном по живому
    (16:45 UTC): подстрока `--md` входит в `--md-dir`, и признак обвинил соседний флаг,
    который никто не снимал. На моих же образцах случая не было — его дало только живое.
    ⇒ Приёмка на собственных образцах не доказывает ничего про чужой материал.
    """
    teaches, marked, missing = [], [], []
    needle = re.compile(re.escape(item["механизм"]) + r"(?![\w-])")
    for name in item["источники"]:
        p = root / name
        if not p.exists():
            missing.append(name)
            continue
        for n, unit in units(p.read_text(encoding="utf-8")):
            if not needle.search(unit):
                continue
            head = unit.strip().splitlines()[0].strip()
            (marked if MARK.search(unit) else teaches).append((name, n, head))
    return teaches, marked, missing


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=r"C:\guts\.atlas\.mezosync\mezosync.db")
    ap.add_argument("--root", default=r"C:\guts\.atlas\.mezosync\scripts",
                    help="каталог источников-инструкций")
    a = ap.parse_args()

    db, root = Path(a.db), Path(a.root)
    if not db.exists():
        print(f"⛔ базы нет: {db} — сверять нечем (это НЕ «чисто»)")
        return 2
    conn = sqlite3.connect(f"file:{db}?mode=ro", uri=True)

    if not RETIRED:
        print("⚖️ перечень снятого ПУСТ — сверять нечего. Это не «чисто»: ничего не проверено")
        return 2

    stale, red, green = [], [], []
    for item in RETIRED:
        row = conn.execute("SELECT version FROM rules WHERE rule_key=?",
                           (item["правило"],)).fetchone()
        # ── ОТКАЗ ②: предмета больше нет. Источники НЕ называем — они не виноваты.
        if row is None:
            stale.append(f"{item['механизм']}: правило «{item['правило']}» ИСЧЕЗЛО из свода")
            continue
        if row[0] != item["версия_сверки"]:
            stale.append(f"{item['механизм']}: правило «{item['правило']}» переписано "
                         f"(сверка против v{item['версия_сверки']}, в базе v{row[0]})")
            continue
        # ── ОТКАЗ ①: стороны разошлись. Называем ИСТОЧНИК и строку.
        teaches, marked, missing = scan(root, item)
        for name in missing:
            stale.append(f"{item['механизм']}: источник {name} не найден в {root}")
        if teaches:
            red.append((item, teaches, marked))
        else:
            green.append((item, marked))

    for item, teaches, marked in red:
        print(f"🔴 УЧАТ СНЯТОМУ: {item['механизм']} — {item['что это']}")
        print(f"   снято {item['снято']}, правило «{item['правило']}»")
        for name, n, line in teaches:
            print(f"   · {name}:{n}  {line[:96]}")
        print(f"   ⇒ чинить ИСТОЧНИК: убрать предписание либо пометить снятие В ТОЙ ЖЕ ЕДИНИЦЕ"
              f" — строке прозы или законченном выражении кода"
              f" ({len(marked)} уже помечены и зачтены)")
    for item, marked in green:
        print(f"✅ {item['механизм']}: предписаний нет · помеченных упоминаний {len(marked)}"
              f" (история разрешена)")
    for s in stale:
        print(f"⛔ ПЕРЕЧЕНЬ УСТАРЕЛ — {s}")
    if stale:
        print("   ⇒ чинить САМУ ПРОВЕРКУ: перечитать правило и обновить перечень."
              "\n   ⚖️ Источники здесь НЕ названы НАМЕРЕННО: предмет сверки исчез, и они"
              " могут быть исправны. Обвинить их — послать чинить невиновного.")
        return 2
    return 1 if red else 0


if __name__ == "__main__":
    sys.exit(main())
