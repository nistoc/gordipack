# -*- coding: utf-8 -*-
r"""sync-vnext-pair.py — СТРОИТЕЛЬ пары «рабочий каталог ↔ шаблон» (зона PROTO).

═══ ПОЧЕМУ НЕ ЗЕРКАЛО — ЭТО ОПЛАЧЕНО ОШИБКОЙ, А НЕ ВЫВЕДЕНО ИЗ ГОЛОВЫ ═══
2026-08-09 пара разошлась на 27 файлов. Первое, что просится, — сделать каталоги
одинаковыми. Сделал — и прогон опроверг через две минуты:
```
bite-all из ШАБЛОНА .... держится 34 · сломано 0 · не проверено 1
bite-all из РАБОЧЕГО ... держится 26 · сломано 2 · НЕ ПРОВЕРЕНО 7   ← при ТЕХ ЖЕ файлах
```
Девять из четырнадцати в рабочем каталоге не работают вовсе: они строят стенд из схемы,
лежащей рядом с ШАБЛОНОМ. Замер запуском (17:43 UTC): из десяти приёмок шаблона переносимы
ДВЕ, остальные восемь привязаны к нему по построению.
⇒ **Зеркало ради зелёного сторожа кладёт потребителю падающие инструменты.**

═══ ЧТО ДЕЛАЕТ СТРОИТЕЛЬ — И ЧЕГО ОН НАМЕРЕННО НЕ ДЕЛАЕТ ═══
```
① рабочий → шаблон .... ВСЁ, чего в шаблоне нет или что разошлось. Это направление
                        обязательно: чего нет в шаблоне, того НЕ БУДЕТ У ПОТРЕБИТЕЛЯ,
                        и он об этом не узнает — сверка молчит (@RCC #3338).
                        Документы (.md) сводятся С НАПРАВЛЕНИЕМ по надмножеству строк:
                        «богаче образец» и «в обе стороны» НЕ переносятся (#303)
② шаблон → рабочий .... НИЧЕГО не тянет автоматически. Вместо переноса — ПРОВЕРКА:
                        всё, что живой контур ЗОВЁТ, обязано в рабочем быть
⛔ приведение путей ... в ИСПОЛНИМОМ коде НЕ делает — с 09.08 20:43 UTC оно НЕ НУЖНО:
                        пути машины больше не впечатаны в файлы, они ВЫВОДЯТСЯ (mezo_paths:
                        среда → маркер → local.paths → громкий отказ). Файлы из шаблона
                        запускаются как есть; заглушка «<КОНТУР>» сломала бы общий прогон.
                        ⚖️ Для ПРОЗЫ (примеры команд в пояснениях) это неверно — там путь
                        остаётся текстом, и с карточек #357/#414 ЛЮБОЙ едущий текст,
                        несущий след корня, идёт С ОБРАТНОЙ ПОДСТАНОВКОЙ корень→заглушка
                        (признак — по СОДЕРЖИМОМУ, не по состоянию шаблона); не свёлся
                        начисто — файл НЕ переносится, названо «сводить РУКОЙ»
```
🎯 СПИСОК ВЫЗЫВАЕМОГО БЕРЁТСЯ ЗАМЕРОМ, А НЕ РУКОЙ. Грепом по живым скриптам: что они
зовут из рабочего каталога. Список, писанный рукой, устаревает молча — этим контур уже
платил (стенд копировал зависимости списком из ОДНОГО имени).

    python sync-vnext-pair.py            замер: что разошлось
    python sync-vnext-pair.py --apply    перенести рабочий → шаблон
"""
import argparse
import hashlib
import re
import sys
from pathlib import Path
import sys as _sys
from pathlib import Path as _P
_sys.path.insert(0, str(_P(__file__).resolve().parent.parent / "prototype"))
import mezo_paths  # пути машины выводятся, не впечатаны (#153)

RUNTIME = mezo_paths.container_root() / "vnext-tools"
TEMPLATE = Path(__file__).resolve().parents[1] / "prototype"
LIVE_SCRIPTS = mezo_paths.live_scripts()

# «vnext-tools» / "vnext-tools" ... "имя.py" — как живой скрипт зовёт файл из рабочего каталога
CALLS = re.compile(r"vnext-tools[\"'\s/\\]+[^\n]{0,40}?[\"']([a-z0-9_.-]+\.py)[\"']", re.I)
IMPORT = re.compile(r"^\s*(?:import|from)\s+([a-z_][a-z0-9_]*)", re.M)
FILEREF = re.compile(r"[\"']([a-z0-9_.-]+\.py)[\"']", re.I)


def digest(p: Path) -> str:
    return hashlib.sha256(p.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


ЗАГЛУШКА = "<КОНТУР>"


def только_заглушка(рабочий: Path, шаблон: Path) -> bool:
    """Шаблон отличается от рабочего ТОЛЬКО заглушкой пути — это НЕ расхождение работы.

    🩸 ЧЕМ ОПЛАЧЕНО (карточка #297, замер 27.08). Строитель считал расхождение по БАЙТАМ
    и звал переносить 19 файлов, у которых вся разница — заглушка `<КОНТУР>` в примерах
    команд внутри пояснений. Перенос затёр бы их путями ОДНОЙ машины, и потребитель
    получил бы 19 невыполнимых у себя строк.
    ⚡ И хуже числа: роль видит красное «не доедет до потребителя», зовёт --apply
    и портит образец, будучи уверенной, что чинит доставку. Я сама остановилась
    в шаге от этого — спасла привычка перемерить, а не механизм.
    ⚖️ Шапка строителя при этом честно говорит «приведение путей НЕ делаю, оно не нужно»:
    верно для ИСПОЛНИМОГО кода (пути выводятся через mezo_paths) и неверно для ПРОЗЫ —
    в примере команды путь остаётся текстом. Утверждение о себе разошлось с поведением.
    """
    if ЗАГЛУШКА not in шаблон.read_text(encoding="utf-8", errors="replace"):
        return False
    корень = str(mezo_paths.container_root()).replace("\\", "/")
    приведён = (шаблон.read_text(encoding="utf-8", errors="replace")
                .replace(ЗАГЛУШКА, корень).replace("\r\n", "\n"))
    свой = рабочий.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n")
    return приведён == свой


def called_by_live() -> set:
    """Что живой контур зовёт из рабочего каталога — ЗАМЕРОМ по его коду."""
    names = set()
    if not LIVE_SCRIPTS.is_dir():
        return names
    for p in LIVE_SCRIPTS.glob("*.py"):
        names |= set(CALLS.findall(p.read_text(encoding="utf-8", errors="replace")))
    return names


def doc_home(name: str, tpl: Path):
    """Где документ живёт у шаблона: рядом с кодом (prototype) или этажом выше (vnext).

    Дом документов у шаблона исторически двухэтажный; искать только рядом с кодом —
    объявить «нет в шаблоне» файлу, который лежит этажом выше и БОГАЧЕ рабочего."""
    for cand in (tpl / name, tpl.parent / name):
        if cand.exists():
            return cand
    return None


def doc_direction(рабочий: Path, шаблон: Path):
    """Направление сведения документа — НАДМНОЖЕСТВОМ СТРОК, не датой и не размером.

    mtime после git-checkout врёт, размер не говорит, ЧЬИ строки пропадут. Строгое
    надмножество — единственный признак, при котором перенос заведомо ничего не стирает;
    всё остальное — работа рукой. 🩸 Оплачено (карточка #303): образец нёс 101 строку
    записей «сдано», которых не было в рабочей копии, — перенос рабочий→образец стёр бы
    историю, показав это строкой, которая читается как «доставляю недостающее».
    """
    w = {l.rstrip() for l in рабочий.read_text(encoding="utf-8", errors="replace").splitlines()}
    t = {l.rstrip() for l in шаблон.read_text(encoding="utf-8", errors="replace").splitlines()}
    only_w, only_t = len(w - t), len(t - w)
    if not only_w and not only_t:
        return ("равны", 0, 0)
    if not only_t:
        return ("богаче_рабочий", only_w, 0)
    if not only_w:
        return ("богаче_образец", 0, only_t)
    return ("обе_стороны", only_w, only_t)


def closure(name: str, pool: dict, seen=None) -> set:
    """Файл ВМЕСТЕ с тем, что он зовёт. Единица переноса — замыкание, а не файл.

    🪤 Оплачено в тот же час: судил переносимость, копируя приёмку БЕЗ её проверки,
    и получил «непереносима» у файла, написанного часом раньше и заведомо переносимого.
    """
    seen = seen if seen is not None else set()
    if name in seen or name not in pool:
        return seen
    seen.add(name)
    text = pool[name].read_text(encoding="utf-8", errors="replace")
    for m in IMPORT.findall(text):
        closure(m + ".py", pool, seen)
    for r in FILEREF.findall(text):
        closure(r, pool, seen)
    return seen


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true", help="перенести рабочий → шаблон")
    ap.add_argument("--runtime", default=None)
    ap.add_argument("--template", default=None)
    ap.add_argument("--live", default=None, help="каталог живых скриптов (для проверки вызовов)")
    a = ap.parse_args()

    global LIVE_SCRIPTS
    rt = Path(a.runtime) if a.runtime else RUNTIME
    tpl = Path(a.template) if a.template else TEMPLATE
    if a.live:
        LIVE_SCRIPTS = Path(a.live)

    for d, label in ((rt, "рабочий"), (tpl, "шаблон")):
        if not d.is_dir():
            print(f"⛔ {label} каталог не найден: {d} — строить нечего (это НЕ «совпадают»)")
            return 2

    r = {p.name: p for p in rt.glob("*.py")}
    t = {p.name: p for p in tpl.glob("*.py")}
    if not r:
        print(f"⛔ рабочий каталог пуст: {rt} — переносить нечего. Это НЕ «всё сведено»")
        return 2

    missing = sorted(set(r) - set(t))
    все_разные = [n for n in set(r) & set(t) if digest(r[n]) != digest(t[n])]
    # Файл, чья вся разница — заглушка пути, СВЕДЁН. Звать к его переносу значит звать
    # затереть заглушку путём одной машины (карточка #297).
    по_заглушке = sorted(n for n in все_разные if только_заглушка(r[n], t[n]))
    drift = sorted(n for n in все_разные if n not in set(по_заглушке))
    # замыкание: файл тянет то, что зовёт (иначе у потребителя окажется половина связки)
    # 🩸 ОБХОДНОЙ ПУТЬ ЗАКРЫТ 27.08 (продолжение карточки #297). Защита заглушки стояла
    # ТОЛЬКО на прямом списке: drift её исключал, а замыкание тянуло тот же файл обратно.
    # Замер в тот же час: migrate-addressee-vnext.py стоял ОДНОВРЕМЕННО в «сведены
    # с точностью до заглушки» и в «не доедет (тянется замыканием)» — то есть --apply
    # затёр бы заглушку путём одной машины, показав это строкой, которая читается
    # как «доставляю недостающее».
    # 🎯 Класс мой собственный и повторный: точечное лечение общего класса. Закрыл дверь,
    # не закрыв окно, — и остаток выглядит зелёным, потому что дверь заперта.
    plan = set(missing) | set(drift)
    for n in list(plan):
        plan |= {d for d in closure(n, r)
                 if d in r and d not in set(по_заглушке)
                 and (d not in t or digest(r[d]) != digest(t[d]))}
    plan = sorted(plan)

    # ── направление ②: не переносим, а ПРОВЕРЯЕМ доступность вызываемого
    called = called_by_live()
    lost = sorted(n for n in called if n not in r)

    print(f"📏 рабочий {len(r)} · шаблон {len(t)} · общих {len(set(r) & set(t))}")
    if по_заглушке:
        # ⚠️ Молчать о них нельзя: файл исчез бы из списка без объяснения, и роль решила
        # бы, что он сведён БАЙТ В БАЙТ. Разница есть, она законна — и названа.
        print(f"📝 сведены С ТОЧНОСТЬЮ ДО ЗАГЛУШКИ пути — {len(по_заглушке)}: "
              f"в шаблоне «{ЗАГЛУШКА}», у потребителя настоящий путь. Это НЕ расхождение "
              f"работы, и переносить их НЕЛЬЗЯ — перенос затрёт заглушку путём одной машины")
        for n in по_заглушке:
            print(f"   · {n}")
    if plan:
        print(f"\n🔴 НЕ ДОЕДЕТ ДО ПОТРЕБИТЕЛЯ — {len(plan)} (нет в шаблоне или разошлось):")
        for n in plan:
            why = "нет в шаблоне" if n not in t else "разошлось"
            pulled = " (тянется замыканием)" if n not in missing and n not in drift else ""
            print(f"   · {n:40} {why}{pulled}")
    else:
        print("✅ всё, что есть в рабочем, доехало до шаблона")

    if lost:
        print(f"\n🔴 ЖИВОЙ КОНТУР ЗОВЁТ, А В РАБОЧЕМ НЕТ — {len(lost)}:")
        for n in lost:
            print(f"   · {n}")
    elif called:
        print(f"✅ живой контур зовёт {len(called)} — все на месте")
    else:
        print("⚠️ вызовов из живых скриптов НЕ НАЙДЕНО — это может значить и «их нет»,"
              " и «замер не сработал». Проверь, тот ли каталог живых скриптов")

    # ── документы: сведение С НАПРАВЛЕНИЕМ, не копией байтов (карточка #303).
    # Раньше строитель сводил только .py и МОЛЧАЛ о документах: два не доехали вовсе,
    # а расхождение третьего читалось как «всё сведено».
    rd = {p.name: p for p in rt.glob("*.md")}
    doc_missing, doc_ok, doc_carry, doc_hand = [], [], [], []
    for n in sorted(rd):
        home = doc_home(n, tpl)
        if home is None:
            doc_missing.append(n)
            continue
        verdict, ow, ot = doc_direction(rd[n], home)
        где = home.parent.name + "/" + n
        if verdict == "равны":
            doc_ok.append(n)
        elif verdict == "богаче_рабочий":
            doc_carry.append((n, home, ow))
        elif verdict == "богаче_образец":
            doc_hand.append((n, f"⛔ богаче ОБРАЗЕЦ ({ot} строк только там; {где}) — "
                                f"перенос рабочий→образец СТЁР БЫ историю, сводить рукой"))
        else:
            doc_hand.append((n, f"⚠️ разошлись В ОБЕ СТОРОНЫ (у рабочего {ow} своих строк, "
                                f"у образца {ot}; {где}) — сводить РУКОЙ, авто-перенос "
                                f"запрещён в обе стороны"))
    if rd:
        print(f"\n📄 ДОКУМЕНТЫ ПАРЫ: {len(rd)} в рабочем · равны по строкам: {len(doc_ok)}")
        for n in doc_missing:
            print(f"   · {n:40} 🔴 нет в шаблоне — НЕ ДОЕДЕТ (перенос: --apply)")
        for n, home, ow in doc_carry:
            print(f"   · {n:40} богаче РАБОЧИЙ ({ow} строк только там) — перенос разрешён (--apply)")
        for n, why in doc_hand:
            print(f"   · {n:40} {why}")

    if a.apply and plan:
        # ═══ Карточки #357 → #414: признак — по СОДЕРЖИМОМУ едущего текста ════════════
        # История класса (#297, четыре захода): дверь — только-заглушечная разница
        # не переносится; окно — замыкание её не обходит; форточка #357 — правка ПОВЕРХ
        # заглушки едет с обратной подстановкой; форточка #414 (замер @TAXO) — НОВЫЙ файл
        # с путём машины уезжал молча: признак «нужна ли подстановка» брался из СОСТОЯНИЯ
        # ШАБЛОНА (есть ли там файл с заглушкой), а беда живёт в СОДЕРЖИМОМ переносимого
        # текста. Пока признак и беда в разных местах, пятый вход найдётся сам.
        # ⇒ Признак сменён (развилка карточки #414, вариант ①): едущий текст НЕСЁТ СЛЕД
        # КОРНЯ — подстановка корень→заглушка; не свёлся начисто (обратные косые и прочие
        # написания) — файл НЕ переносится, назван «сводить РУКОЙ». Один признак закрывает
        # все входы: правку поверх заглушки, новый файл, переименование.
        # ⚖️ ГРАНИЦА ВСЛУХ: норма пары — пути НЕ впечатаны (их выводит mezo_paths); файла,
        # где живой путь машины обязан ехать как есть, в паре нет по построению. Появится —
        # получит честное «сводить РУКОЙ», а не молчаливый провоз. Документы (.md) едут
        # своим каналом с судом направления; их пути стережёт guard-machine-paths.
        корень_prose = str(mezo_paths.container_root()).replace("\\", "/")
        # след корня при ЛЮБЫХ косых (\, /, \\): сегменты корня, сшитые классом косых
        след_корня = re.compile(r"[\\/]+".join(re.escape(seg) for seg in
                                               корень_prose.split("/")), re.I)
        перенесено, с_подстановкой, руками = [], [], []
        for n in plan:
            цель = tpl / n
            текст = r[n].read_bytes().decode("utf-8", errors="replace")
            if след_корня.search(текст):
                новый = текст.replace(корень_prose, ЗАГЛУШКА)
                if след_корня.search(новый):
                    руками.append(n)
                    continue
                цель.write_bytes(новый.encode("utf-8"))
                с_подстановкой.append(n)
            else:
                цель.write_bytes(r[n].read_bytes())
            перенесено.append(n)
        print(f"\n✅ перенесено рабочий → шаблон: {len(перенесено)}")
        if с_подстановкой:
            print(f"🛡 из них с ОБРАТНОЙ ПОДСТАНОВКОЙ корень→{ЗАГЛУШКА} — "
                  f"{len(с_подстановкой)}: правка доехала, заглушка в шаблоне жива")
            for n in с_подстановкой:
                print(f"   · {n}")
        if руками:
            print(f"⛔ НЕ ПЕРЕНЕСЕНЫ — путь машины не сводится к заглушке начисто, "
                  f"сводить РУКОЙ — {len(руками)}:")
            for n in руками:
                print(f"   · {n}")
    elif plan:
        print("\n⚖️ это ЗАМЕР. Перенести: --apply")

    if a.apply and (doc_missing or doc_carry):
        for n in doc_missing:
            (tpl / n).write_bytes(rd[n].read_bytes())
        for n, home, _ in doc_carry:
            home.write_bytes(rd[n].read_bytes())
        print(f"✅ документы перенесены: {len(doc_missing) + len(doc_carry)} "
              f"(только «нет в шаблоне» и «богаче рабочий» — остальное рукой)")

    print("⚖️ ГРАНИЦА: сведены ФАЙЛЫ. Совпадение байтов НЕ означает, что копии равносильны:"
          " инструмент зависит от того, что лежит рядом. Обратное направление НЕ переносится"
          " намеренно — из десяти приёмок шаблона переносимы две (замер 09.08).")
    return 1 if (plan or lost or doc_missing or doc_hand) else 0


if __name__ == "__main__":
    sys.exit(main())
