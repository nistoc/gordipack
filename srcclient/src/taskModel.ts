import type { Task } from './types';

/**
 * ОБЩИЙ СЛОВАРЬ ДВУХ ПРЕДСТАВЛЕНИЙ ЗАДАЧ — таблицы и доски.
 *
 * 📌 Почему отдельным файлом, а не парой констант в каждой странице: таблица и доска
 *    показывают ОДНИ И ТЕ ЖЕ карточки. Разойдись у них порядок важностей или признак
 *    «критерий не задан» — и два экрана одной базы начнут спорить о числах, причём
 *    молча: оба «работают», просто отвечают разное. Ровно этот класс расхождения уже
 *    стоил контуру месяцев, и повторять его внутри одного просмотрщика незачем.
 */

// ── важность ────────────────────────────────────────────────────────────────

/** Порядок сортировки: меньше — важнее. Неизвестное значение уходит в конец, но не теряется. */
export const PRIORITY_RANK: Record<string, number> = { critical: 0, high: 1, normal: 2, low: 3 };

/**
 * Важность на плитке — ФОРМОЙ И ЦВЕТОМ, а не словом: четыре засечки, из которых
 * закрашено столько, какова ступень. Слово «critical» занимает на плитке строку
 * и читается медленнее, чем длина полоски, а на доске из сотни плиток решает
 * именно скорость чтения.
 */
export const PRIORITY_META: Record<string, { title: string; pips: number }> = {
  critical: { title: 'критическая', pips: 4 },
  high: { title: 'высокая', pips: 3 },
  normal: { title: 'обычная', pips: 2 },
  low: { title: 'низкая', pips: 1 },
};

export function priorityMeta(priority: string | null) {
  const key = priority ?? 'normal';
  return { key, ...(PRIORITY_META[key] ?? { title: priority ?? 'не задана', pips: 0 }) };
}

// ── статус ──────────────────────────────────────────────────────────────────

/**
 * Знак статуса: у каждого СВОЯ ФОРМА, а не только свой цвет. Различать статусы
 * одним лишь цветом значит потерять их для части людей и на любом чёрно-белом снимке.
 */
export const STATUS_META: Record<string, { title: string; glyph: string }> = {
  open: { title: 'открытая', glyph: '○' },
  in_review: { title: 'на проверке', glyph: '◐' },
  blocked: { title: 'заблокированная', glyph: '▣' },
  done: { title: 'закрытая', glyph: '●' },
  dropped: { title: 'снятая', glyph: '✕' },
};

export function statusMeta(status: string | null) {
  const key = status ?? 'unknown';
  return { key, ...(STATUS_META[key] ?? { title: status ?? 'без статуса', glyph: '·' }) };
}

/**
 * Порядок переключателей статуса. Список — ПОДСКАЗКА ПОРЯДКА, а не разрешённый набор:
 * статусы, которых здесь нет, всё равно попадут в конец списка.
 *
 * 🔴 ИМЕННО ЭТО МЕСТО РАНЬШЕ ВРАЛО МОЛЧАНИЕМ. Прежде набор переключателей был жёстким
 *    ('open','done','blocked','dropped'), а в живой базе завёлся статус `in_review` —
 *    и карточка с ним не показывалась НИ ПОД ОДНИМ переключателем, кроме «все». Не было
 *    ни ошибки, ни пустого места: строка просто отсутствовала, и отсутствие читалось как
 *    «таких задач нет». Поэтому набор берётся из данных, а список задаёт лишь порядок.
 */
const STATUS_ORDER = ['open', 'in_review', 'blocked', 'done', 'dropped'];

/**
 * Порядок статусов ПО СМЫСЛУ, а не по алфавиту: живое выше завершённого.
 *
 * 🔴 ПОЧЕМУ АЛФАВИТ ЗДЕСЬ — ЛОЖЬ, А НЕ ПРОСТО НЕУДОБСТВО. По алфавиту выходит
 *    `blocked, done, dropped, in_review, open`: закрытые всплывают наверх, открытые
 *    падают в конец. Экран при этом выглядит совершенно рабочим — плитки упорядочены,
 *    порядок устойчив, ошибки нет, — и человек читает верхние плитки как «самое важное».
 *    Ровно тот класс отказа, которым занят весь этот просмотрщик: механизм наложен,
 *    отвечает уверенно и отвечает не на тот вопрос.
 */
export const STATUS_RANK: Record<string, number> =
  Object.fromEntries(STATUS_ORDER.map((s, i) => [s, i]));

export function orderStatuses(present: Iterable<string>): string[] {
  // ⚠️ ПЕРЕКЛАДЫВАЕМ В МАССИВ ОДНОЙ СТРОКОЙ, И ЭТО НЕ СТИЛЬ. Сюда приходит `map.keys()` —
  //    ОДИН перебиратель, а не набор: первое же разворачивание опустошает его, и все
  //    следующие дают пустоту. Замер живой страницы 2026-08-07 13:21 UTC: с двумя
  //    разворачиваниями функция возвращала ПУСТОЙ список, и в строке фильтров оставалась
  //    единственная фишка «все» — ни «открытые», ни «закрытые» не показывались вовсе.
  //    Типы при этом зелёные, сборка молчит: `Iterable` честно перебирается — один раз.
  const keys = [...present];
  const rest = keys.filter((s) => !STATUS_ORDER.includes(s)).sort();
  return [...STATUS_ORDER.filter((s) => keys.includes(s)), ...rest];
}

// ── критерий приёмки ────────────────────────────────────────────────────────

/**
 * «Критерий приёмки не задан» — главный признак этого экрана.
 *
 * ⚠️ Проверяются ДВА поля, а не одно. `criterionSupported=false` означает, что колонки
 *    `backlog.done_when` в базе нет вовсе, и тогда «критерий не задан» было бы поклёпом
 *    на карточку: не задавать негде. Это не мелочь — просмотрщик умеет открывать базы
 *    разных поколений, и в старой пометка стояла бы у всех ста процентов карточек.
 */
export function isCriterionGap(t: Task): boolean {
  return t.criterionSupported && !t.hasCriterion;
}

// ── порядок карточек ────────────────────────────────────────────────────────

/**
 * Порядок по умолчанию и в таблице, и в колонке доски: сначала то, ради чего экран, —
 * открытые без критерия приёмки; дальше по важности; дальше по номеру.
 */
export function compareByGapThenPriority(a: Task, b: Task): number {
  const gap = (t: Task) => (isCriterionGap(t) && t.status === 'open' ? 0 : 1);
  if (gap(a) !== gap(b)) return gap(a) - gap(b);
  const p = (t: Task) => PRIORITY_RANK[t.priority ?? 'normal'] ?? 9;
  if (p(a) !== p(b)) return p(a) - p(b);
  return a.id - b.id;
}

/**
 * ПОРЯДОК ПЛИТОК ВНУТРИ КОЛОНКИ РОЛИ — набор для строки сортировки на доске.
 *
 * 🎯 Требование владельца 2026-08-07 14:04 UTC: «рядом со строками фильтрации не хватает
 *    строки с опциями сортировки». Речь о доске: у таблицы сортировка живёт в шапках
 *    столбцов, у колонок шапок нет — и упорядочить плитки было нечем вовсе.
 *
 * 📌 ПРИЗНАКИ ВЗЯТЫ РОВНО ТЕ, ЧТО ВИДНЫ НА ПЛИТКЕ. Сортировка по полю, которого на плитке
 *    нет, даёт порядок, который нечем проверить глазами: плитки переставились, а почему —
 *    неизвестно. Поэтому здесь номер, возраст, дата правки, важность, статус и наличие
 *    критерия — всё это плитка показывает.
 *
 * ⚠️ У КАЖДОГО НАПРАВЛЕНИЯ СВОИ СЛОВА, А НЕ «ПО ВОЗРАСТАНИЮ». «Возраст по возрастанию» —
 *    это старые сверху или новые? Ответа нет: возрастает возраст или дата — вопрос
 *    договорённости, которой у читающего нет. Поэтому переключатель говорит «сначала
 *    давние» / «сначала свежие», и гадать не о чем.
 */
export type BoardSortKey =
  'default' | 'id' | 'created' | 'updated' | 'priority' | 'status' | 'criterion';

export type BoardSort = {
  key: BoardSortKey;
  /** Подпись фишки. */
  title: string;
  /** Что означает прямое направление и что — обратное. */
  asc: string;
  desc: string;
  /** Прямое направление; обратное получается умножением на −1. */
  cmp: (a: Task, b: Task) => number;
};

/** Текстовые даты сравниваем как строки: формат базы (ISO-подобный) для этого и годен. */
const byText = (x: string | null, y: string | null) => {
  const a = x ?? '';
  const b = y ?? '';
  return a < b ? -1 : a > b ? 1 : 0;
};

