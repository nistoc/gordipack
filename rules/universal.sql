🔴 ПОТЕРЯ ХВОСТА ВИДНА, ПОТЕРЯ ГОЛОВЫ — НЕТ. И три мерки одного текста подряд
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
Предыдущий блок дал форму «мерка своего текста устаревает вместе с текстом; проверь её
на известном случае». За час она поймала ДВЕ роли — и вторая нашла у неё изнанку.
```
случай A ... роль сменила начертание метки в СЕРЕДИНЕ смены, образец писала по ранней
             ⇒ мерка потеряла ХВОСТ. Автор заметил САМ: «список обрывается на 01:07,
               а я точно давал отчёты позже»
случай B ... роль писала РАНЬШЕ в старой форме, образец — по нынешней
             ⇒ мерка потеряла ГОЛОВУ. Признака НЕТ ВОВСЕ
```
⚡ **Ряд начинается там, где начинается, и ничем не сообщает, что мог бы начинаться
раньше.** Ни обрыва, ни пустого места: у потери головы нет ни одного следа, тогда как
хвост выдаёт себя памятью автора о своих поздних текстах.
👉 ФОРМА: проверять не «доходит ли мерка до конца», а **«с чего она НАЧИНАЕТСЯ и было ли
что-то ДО»**. Посмотри на самый ПЕРВЫЙ найденный и спроси, точно ли до него ничего не было.

🩸 И ЧТО ЭТО ДАЛО НЕМЕДЛЕННО: ТРИ МЕРКИ ОДНОГО ТЕКСТА, И КАЖДАЯ СЛЕДУЮЩАЯ НАХОДИЛА
ПРОПУСК С НОВОГО КОНЦА.
```
① образец без жирного начертания .............. 15 отчётов (потерян хвост)
② образец с парной меткой «(HH:mm местное)» ... 21 (потеряна ГОЛОВА: ранние отчёты
                                                 метки-пары ещё не несли)
③ образец по одной метке времени .............. ТРИДЦАТЬ ШЕСТЬ
⇒ первый отчёт не в 15:51, а в 08:43. Роль объявила владельцу «двадцать» и ошиблась
  почти вдвое — уже ПОСЛЕ того, как сама же дала форму «проверь мерку»
```
⚖️ ⇒ **Исправленная мерка не становится верной. Она становится менее узкой.** Каждый
следующий образец шире прежнего, и остановиться можно только на том, у которого проверены
ОБА конца, а не один.

⚡ И ЧЕТВЁРТЫЙ ЖИВОЙ СЛУЧАЙ ТОГО ЖЕ ЧАСА, с другим признаком негодности: третья роль
получила от своей мерки **39 отчётов и НУЛИ во всех столбцах** — ни одного упоминания
ни одной задачи. Она точно знала, что искомые строки у неё есть.
```
⇒ ответ был СЛИШКОМ ХОРОШИМ ДЛЯ ВОПРОСА, и поймала мерку НЕВОЗМОЖНОСТЬ,
  а не аккуратность: тридцать девять нулей подряд не бывают
👉 годный признак: у своей мерки спрашивай не «сошлось ли», а «бывает ли ТАКОЕ вообще»
```
🩸 И её же замер о себе, самый неприятный из четырёх: из ТРЁХ утверждений о частоте своих
строк не измерено НИ ОДНО, и разошлись они В РАЗНЫЕ СТОРОНЫ — два преувеличения и одно
занижение.
```
⇒ это НЕ пощада себе и не строгость к себе. Это ОТСУТСТВИЕ ЗАМЕРА как таковое —
  в тех же записках, где каждое число о МИРЕ снято запросом
