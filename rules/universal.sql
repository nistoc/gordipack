🔴 НАЗВАННАЯ ГРАНИЦА ОЩУЩАЕТСЯ КАК РАБОТА — а снималась одним вызовом
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
Это правило учит НАЗЫВАТЬ границы замера, и роли научились. Оборотная сторона обошлась
дороже, чем стои́ла бы проверка.
```
живой случай ... сводный прогон печатает про одну проверку «2 из 7 активных» — БЕЗ имён.
                 Роль написала владельцу и коллегам: «присвоить эту красную себе не могу,
                 имён нет» — и повторила это ТРИЖДЫ за ночь, считая добросовестностью
что было на деле  та же проверка, позванная ОТДЕЛЬНО, печатает состав поимённо
                 и вдобавок зелена. Имена прячет СВОДНЫЙ ПРОГОН, а не проверка
⇒ честная граница стои́ла трёх повторений; замер, который её снимал, стои́л ОДНОГО вызова
```
⚡ **Свёртка не врёт — она отнимает возможность проверить.** «N из M» истинно, и потому
не краснеет нигде; роль, читающая только сводку, приходит к выводу честному и неверному.
🩸 И вот чем этот класс опаснее простого промаха: **правило само его и произвело.**
Требование называть границы поощряет роль остановиться на границе — а остановка выглядит
дисциплиной, не ленью. Никто не спросит «а ты пробовал?», потому что признание в незнании
читается как проверенное утверждение.
👉 ФОРМЫ, обе дешёвые:
```
① прежде чем НАЗВАТЬ границу — проверь, не снимается ли она ОДНИМ ходом.
   «Я не могу» — про способ, а звучит как про возможность
② красную строку сводного прогона присваивай не по сводке, а ВЫЗОВОМ САМОЙ ПРОВЕРКИ:
   у неё вывод уже разобран поимённо
③ долю в общем красном считай ПРОВЕРКАМИ поимённо, а не строками внутри одной:
   «моих две» о строках рядом с числом о проверках — два числа, считающих разное
```

⚡ И ЕЩЁ ДВА УТОЧНЕНИЯ, принесённые ролями НА СВОИХ ЖЕ ФОРМАХ — обе оказались неполны:
```
① форма «снимать замер одним вызовом» чинит СПОСОБ и молчит о ПОРЯДКЕ. Роль исполнила
   её дословно — и всё равно ошиблась: ТЕКСТ написала ДО того, как посмотрела вывод.
   👉 сначала замер — ПОТОМ строка, и число КОПИРУЕТСЯ из вывода, а не набирается
② копируемая строка расходится с миром В ОБЕ СТОРОНЫ:
      либо роль дописывает ей рамку ......... видно при письме
      либо МИР дописывает ей содержание ..... не видно НИКОГДА
   Живой случай второго: строка «красных три, мои две» не менялась ни разу, а через
   два часа роль молча попала во ВТОРУЮ красную проверку. Строка не менялась —
   значит и перечитывать её как будто незачем
```
⚖️ Отсюда общее: **неизменная строка требует перечитывания ЧАЩЕ изменённой.** Правку
своей строки роль хотя бы замечает; неизменную она переносит не глядя, а мир под ней идёт.

