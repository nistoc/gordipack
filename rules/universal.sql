двадцать четыре, старшая ждёт полтора месяца. Решение принято о предмете, названном неверно.

⚡ ПЯТЬ РАЗНЫХ МЕХАНИЗМОВ ОДНОЙ БЕДЫ — их стои́т различать, лечатся они по-разному:
```
① СВЕЖЕСТЬ ВЫТЕСНЯЕТ СТАРШИНСТВО ... в голове стои́т заведённое сегодня; старое
   не забыто — о нём нечего рассказать. ⇒ пропадают ровно САМЫЕ ДОЛГИЕ, то есть те,
   о которых важнее всего сказать
② ПЕРЕЧЕНЬ ИЗ ПАМЯТИ О «НАСТОЯЩЕЙ РАБОТЕ» ... пропадает сделанное быстро и без разбора
③ ОТБОР ФОРМОЙ ОТЧЁТА ... в отчёт попадает то, по чему есть ВОПРОС или ПРЕДЛОЖЕНИЕ.
   Задача, по которой предложить нечего, выпадает МОЛЧА — не забытая, а отфильтрованная.
   Выпадают ровно те, что ничего не ждут от владельца и потому стоя́т дольше всех
④ ОЧЕРЕДЬ СВЁРНУТА В ЧИСЛО, А ЧИСЛУ ДАНО ОДНО ИМЯ ... слагаемых нет вовсе, сверить
   не с чем: там, где у других список, тут одно слово. Измерено количество —
   ИМЯ РЯДОМ С НИМ не мерил никто
⑤ В ПЕРЕЧЕНЬ ПОПАДАЕТ ТО, ЧЕМ РОЛЬ ЗАНЯТА, А НЕ ТО, ЧТО НА НЕЙ ЧИСЛИТСЯ ... ЧУЖАЯ
   задача, которой роль занималась, въезжает; СВОЯ, до которой не дошли руки, выпадает
```
🔴 ПЯТЫЙ ОПАСНЕЕ ПРОЧИХ, И ВОТ ЧЕМ: у первых четырёх перечень СУЖАЕТСЯ, и сверка по числу
их ловит. У пятого **число сходится, а состав другой** — не подмножество и не надмножество.
Проверка «названо 2, измерено 2» скажет «сходится» и пропустит подмену половины.

⚡ И ОБЩЕЕ УСТРОЙСТВО, которое делает это формой, а не рассеянностью: **полный список
ЛЕЖАЛ ПЕРЕД ГЛАЗАМИ.** Инструмент ленты печатает его в подвале КАЖДОЙ порции — «твоих
незакрытых: N · старшей M дн» и строки поимённо, — а правило запрещает обрезать вывод,
то есть роль читала это КАЖДЫЙ раз, тремя строками выше собственной неверной строки.
```
⇒ обе правды были открыты: и машинная, и своя же сохранённая память
⇒ роль писала строку ПО ПАМЯТИ О СЕГОДНЯШНЕМ ДНЕ рядом с готовым верным списком
```
👉 ФОРМА, СОБРАННАЯ ТРЕМЯ РОЛЯМИ И ДЕШЁВАЯ ДО НУЛЯ:
```
① строку о своей очереди не ПИСАТЬ, а ВСТАВЛЯТЬ замером: у инструмента она уже есть
   и уже верна. Всё, что роль добавляет от себя, — это возможность её сузить
② одним запросом на ОБА текста — и в записку коллегам, и в отчёт владельцу. Разные
   списки в двух текстах об одном — не пересказ, а два разных утверждения
③ если очередь свёрнута в ЧИСЛО — имя при нём обязано быть замером тоже: не
   «одиннадцать по такому-то предмету», а перечень с приоритетом и возрастом
④ сверять не только ЧИСЛО, но и СОСТАВ: совпавшая длина ничего не доказывает
```
⚖️ И половина против самой формы, названная там же: роль собрала очередь замером —
и тут же посчитала «высокого приоритета» ГЛАЗОМ по списку, получив 8 вместо 9.
**Считать глазом рядом с замером так же соблазнительно, как писать по памяти рядом
с журналом.** Замер обязан давать ВСЕ числа строки, а не первое из них.
⛔ И граница, неустранимая: отчёты владельцу живут в разговоре, а не в базе. Сколько раз
строка туда уехала — роль назвать не может, и обязана это говорить, а не оценивать.

