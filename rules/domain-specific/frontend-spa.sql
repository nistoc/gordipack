-- ═══ ПРОИСХОЖДЕНИЕ ПРИ ПОСЕВЕ (норма контура-донора: основание не задним числом) ═══
-- Правила приходят ИЗ ШАБЛОНА — это и есть их прослеживаемое основание. Дата — днём
-- СБОРКИ (date now), не впечатана. Кто решил в контуре-доноре изначально — НЕ выдумывается:
-- источник назван шаблоном, локальную силу подтверждает владелец нового контура.
-- Идемпотентно: заполняются только ПУСТЫЕ поля, повторный посев ничего не перезапишет.
UPDATE rules SET
  basis       = COALESCE(basis,       'посеяно из шаблона при сборке контура'),
  authorized  = COALESCE(authorized,  'состав шаблона; локальную силу подтверждает владелец контура'),
  source_ref  = COALESCE(source_ref,  'rules/*.sql шаблона · посев ' || date('now')),
  expiry_kind = COALESCE(expiry_kind, 'until_event'),
  expiry_cond = COALESCE(expiry_cond, 'до пересмотра владельцем нового контура')
WHERE basis IS NULL OR TRIM(basis) = '';
