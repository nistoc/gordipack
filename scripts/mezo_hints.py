# -*- coding: utf-8 -*-
"""mezo_hints.py — «подсказка печатается роли один раз, дальше — строка-ссылка» (карточка #586).

ЗАЧЕМ. Инструменты координации печатают общие пояснения (границы механизма, порядок
вызова, куда смотреть при отказе) КАЖДЫЙ РАЗ — той же роли, тем же текстом, при каждом
вызове. Роль это уже прочитала, и с каждым повторением текст читают всё меньше внимательно:
тот же класс беды, что у предупреждения без срока годности (`warning-must-carry-expiry`) —
оно есть, его перестают замечать, а вместе с ним и то новое, что стоит рядом.

ЧТО ДЕЛАЕТ. `подсказка()` — один вызов на одном месте печати общего пояснения:
  · первый показ этой паре (роль, ключ) — печатает ПОЛНЫЙ текст, запоминает отпечаток
    текста и час показа;
  · тот же текст той же роли, срок (TTL) ещё не истёк — печатает ОДНУ строку-ссылку;
  · текст изменился, роль не названа, TTL истёк, вызывающий сам просит полный текст
    (`full=True`), ИЛИ база не открылась / таблицы нет / она занята — печатает ПОЛНЫЙ
    текст. Откат — ВСЕГДА в сторону полноты, никогда в сторону молчания: непоказанная
    подсказка дороже одной лишней строки.

ГРАНИЦЫ, НАЗВАННЫЕ ВСЛУХ — чего этот помощник НЕ решает:
  · он НЕ решает, какая подсказка обязательна к прочтению, а какая нет, — это решает
    вызывающий код выбором ключа, текста и `ttl_hours`;
  · он НЕ сокращает `отказ()` и `итог()` — они печатают целиком ВСЕГДА. Сокращать
    там, где по определению читают один раз (отказ — про то, что случилось СЕЙЧАС;
    итог — короткая строка сама по себе), нечего;
  · он НЕ хранит историю показов — только последний факт: строка (role, hint_key)
    перезаписывается заново при каждом полном показе. Вопрос здесь только «видела ли
    роль ЭТОТ текст недавно», а не «когда были все разы».

ЧТЕНИЕ НА mode=ro / `db_path` — для инструментов без пишущего соединения. Часть
инструментов координации открывает базу ТОЛЬКО ДЛЯ ЧТЕНИЯ (role-brief.py и подобные —
`sqlite3.connect("file:...?mode=ro", uri=True)` через `resolve_db(..., readonly=True)`,
карточка #391): им есть чем читать отметку «эта роль это видела», но нечем её записать —
`conn.execute(INSERT...)` на таком соединении падает `sqlite3.OperationalError: attempt
to write a readonly database`. Для них — необязательный именованный параметр `db_path`:
путь к ТОЙ ЖЕ живой базе, по которому подсказка, если запись через `conn` не удалась,
открывает СВОЁ короткое соединение (обычное, не ro), делает INSERT OR REPLACE, коммитит
и сразу закрывает — и только ради этой одной отметки; `conn` вызывающего при этом не
трогается (ни commit, ни rollback на нём после неудачи). Это НЕ меняет характер самого
вызова инструмента: то, что инструмент показывает роли (полный текст подсказки или
строка-ссылка), не зависит от того, как записалась отметка, — отметка показа сама по
себе служебная и не часть ответа инструмента. `db_path` не передан — поведение то же,
что и раньше: неудачная запись на ro-соединении, как и любая другая беда базы,
откатывается в сторону полного текста, ничего не падает.

Использование в инструменте координации:
    import sqlite3
    import mezo_hints

    conn = sqlite3.connect(db_path)
    mezo_hints.подсказка(conn, role, "guard-all-порядок", ТЕКСТ_ПОДСКАЗКИ, full=args.full)

    # инструмент, читающий базу через mode=ro (role-brief.py и подобные):
    conn = sqlite3.connect(f"file:{db.as_posix()}?mode=ro", uri=True)
    mezo_hints.подсказка(conn, role, "ключ", ТЕКСТ, db_path=str(db))

Схема — таблица `hint_seen` (role, hint_key, content_hash, shown_at; PK role+hint_key),
заводится миграцией `migrations/20260907-hint-seen.py`.

КОМУ ЗАСЧИТЫВАЕТСЯ ПОКАЗ. `подсказка()` принимает роль ПАРАМЕТРОМ и сама не решает,
чьё это имя, — решает вызывающий код. Находка COORD (записка #4930): в пяти местах
вызывающий код передавал роль ВЛАДЕЛЬЦА карточки/памяти (`--role`), а не роль руки,
которая на самом деле читает вывод (`--actor`). Итог — показ засчитывался чужой роли,
а настоящий читатель видел подсказку заново при каждом вызове. Функция `кто_читает()`
ниже собирает верное имя по порядку точности: явная рука (`--actor`) → переменная
среды `MEZO_ROLE` → владелец предмета (`--role`) как последний довод. Вызывающему
инструменту достаточно передать в `подсказка()` результат `кто_читает(...)` вместо
голого `role`.

Дата: 2026-09-07 07:57 UTC. Карточка #586, #593.
"""
from __future__ import annotations

import hashlib
import os
import sqlite3
import sys
from datetime import datetime, timedelta, timezone


def _час_сейчас_iso() -> str:
    """Текущий час UTC как naive ISO-строка (без смещения) — формат hint_seen.shown_at."""
    return datetime.now(timezone.utc).replace(tzinfo=None, microsecond=0).isoformat()


def _разобрать_час(текст):
    """→ datetime (naive) или None. Негодная строка в базе не роняет вызывающего —
    просто считается просроченной (см. подсказка())."""
    try:
        return datetime.fromisoformat(текст)
    except (ValueError, TypeError):
        return None


def _когда_человеку(iso_текст: str) -> str:
    """shown_at → «2026-09-07 01:17 UTC» для строки-ссылки. Не разобралось — печатаем
    как есть, лишь бы не падать на форматировании собственной подсказки."""
    час = _разобрать_час(iso_текст)
    if час is None:
        return f"{iso_текст} UTC"
    return час.strftime("%Y-%m-%d %H:%M") + " UTC"


def подсказка(conn, role, key: str, text: str, *, ttl_hours: float = 24, full: bool = False,
             db_path=None) -> bool:
    """Напечатать подсказку `text` под ключом `key` для роли `role`.

    Возвращает True, если напечатан ПОЛНЫЙ текст, False — если напечатана только
    строка-ссылка.

    full=True, `role` пустая/None, ИЛИ `conn` и `db_path` оба не заданы: печатаем целиком
    и БАЗУ НЕ ТРОГАЕМ. Сравнивать «уже видела» не с чем, когда роль не названа, — печатать
    сокращённо для «никого» нельзя.

    db_path — путь к живой базе (необязателен). Нужен, когда `conn` открыт только для
    чтения (mode=ro) или вовсе не передан: отметка показа тогда пишется через отдельное
    короткое соединение по этому пути, `conn` вызывающего при этом не трогается. Чтение
    отметки всегда идёт через `conn`, если он дан (SELECT на ro-соединении работает как
    обычно); `db_path` открывается на чтение только когда `conn is None`. Не меняет то,
    что видит роль, — только то, сохраняется ли факт показа.
    """
    if full or not role or (conn is None and db_path is None):
        print(text)
        return True

    свой_conn = None
    try:
        if conn is None:
            # conn не дан, но есть db_path — своё соединение обслуживает и чтение,
            # и запись (см. докстринг): инструменту без соединения этого достаточно.
            свой_conn = sqlite3.connect(db_path)
            рабочий_conn = свой_conn
        else:
            рабочий_conn = conn

        row = рабочий_conn.execute(
            "SELECT content_hash, shown_at FROM hint_seen WHERE role = ? AND hint_key = ?",
            (role, key)).fetchone()

        свежая = False
        if row is not None:
            прежний_hash, прежний_shown_at = row
            текущий_hash = hashlib.sha1(text.encode("utf-8")).hexdigest()
            час = _разобрать_час(прежний_shown_at)
            не_протухла = (час is not None
                           and datetime.now(timezone.utc).replace(tzinfo=None) - час
                           <= timedelta(hours=ttl_hours))
            свежая = (прежний_hash == текущий_hash) and не_протухла

        if свежая:
            print(f"ℹ️ подсказка «{key}» показана {_когда_человеку(row[1])}; "
                  f"полный текст — добавь --full")
            return False

        # Записи нет, ИЛИ текст сменился, ИЛИ отметка старше TTL — показываем целиком.
        # Показ роли и запись отметки — РАЗНЫЕ действия: текст печатается ЗДЕСЬ, один
        # раз, и дальше ничто в этой функции его не печатает повторно — неудача записи
        # ниже меняет только то, помнит ли база «роль это видела», а не то, что роль
        # уже увидела.
        print(text)

        отметка = (role, key, hashlib.sha1(text.encode("utf-8")).hexdigest(), _час_сейчас_iso())
        try:
            рабочий_conn.execute(
                "INSERT OR REPLACE INTO hint_seen (role, hint_key, content_hash, shown_at) "
                "VALUES (?, ?, ?, ?)", отметка)
            рабочий_conn.commit()
        except Exception:  # noqa: BLE001 — запись через рабочий_conn не удалась (типично:
            # «attempt to write a readonly database» на mode=ro-соединении, но ловим ЛЮБУЮ
            # беду — тот же принцип отката, что и у внешнего except ниже). conn вызывающего
            # дальше НЕ трогаем: ни commit, ни rollback на нём после этой неудачи не зовём.
            if db_path is not None and рабочий_conn is not свой_conn:
                # Отдельное КОРОТКОЕ соединение на запись — только когда рабочий_conn это
                # ЧУЖОЕ соединение (свой_conn уже пытался писать сам, второй попытки той же
                # связкой не нужно).
                try:
                    отдельный_conn = sqlite3.connect(db_path)
                    try:
                        отдельный_conn.execute(
                            "INSERT OR REPLACE INTO hint_seen (role, hint_key, content_hash, "
                            "shown_at) VALUES (?, ?, ?, ?)", отметка)
                        отдельный_conn.commit()
                    finally:
                        отдельный_conn.close()
                except Exception:  # noqa: BLE001 — и запасной путь не удался (негодный
                    # db_path, база занята и т.п.). Не страшно: текст уже показан ПОЛНОСТЬЮ
                    # строкой выше — откат в сторону полноты уже случился. Отметка просто не
                    # сохранится, и в следующий раз подсказка снова покажется целиком —
                    # это и есть корректный откат, а не молчание.
                    pass
        return True
    except Exception:  # noqa: BLE001 — беда СЛУЧИЛАСЬ ДО печати текста (нет таблицы, база
        # не открылась, она занята другим процессом, db_path сам не открылся и т.п.) —
        # печатаем целиком, это единственный показ в этом вызове.
        print(text)
        return True
    finally:
        if свой_conn is not None:
            свой_conn.close()


def кто_читает(actor=None, role=None) -> str:
    """Имя роли, которой ЗАСЧИТЫВАЕТСЯ показ подсказки: явное имя руки (--actor) →
    переменная среды MEZO_ROLE → владелец карточки/памяти (--role) → пустая строка
    (тогда подсказка печатается целиком и ничего не запоминает).
    Порядок — от точного к предположительному: явное имя стоит в командной строке
    самой руки; среду роль ставит редко (замер в lease.py, 30.08); --role — хозяин
    предмета, а не читатель, и это последний довод, а не первый. Находка COORD,
    записка #4930, 2026-09-07: показ списывался на хозяина, и настоящий адресат
    подсказку не видел."""
    return ((actor or "") or (os.environ.get("MEZO_ROLE") or "") or (role or "")).strip().upper()


def отказ(text: str) -> None:
    """Отказ — печатается ЦЕЛИКОМ ВСЕГДА, в stderr. Ничего не решает и не режет —
    только единообразное место печати для мест отказа, зовущих этот помощник."""
    print(text, file=sys.stderr)


def итог(text: str) -> None:
    """Итог (строки вида «OK #NNNN») — печатается ЦЕЛИКОМ ВСЕГДА, в stdout."""
    print(text)


def забыть(conn, role: str, key: str | None = None) -> int:
    """Удалить отметки роли — ОДНУ (по `key`) или ВСЕ (`key=None`). Возвращает число
    удалённых строк. Для приёмки и ручной проверки: без этого способа «подсказка
    показывается заново» проверить нельзя иначе, чем ждать истечения TTL."""
    if key is None:
        cur = conn.execute("DELETE FROM hint_seen WHERE role = ?", (role,))
    else:
        cur = conn.execute("DELETE FROM hint_seen WHERE role = ? AND hint_key = ?", (role, key))
    conn.commit()
    return cur.rowcount
