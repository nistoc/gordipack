import atexit
import sqlite3
import sys
import time
from pathlib import Path

BANNER = ("⟨ХОЛОСТОЙ ПРОГОН⟩ база НЕ изменится: инструмент работает с копией в памяти, "
          "живой файл открыт только на чтение.")

# Снятие копии (source.backup) на ЗАНЯТОЙ базе повторяет попытку без собственного предела —
# без ограничения снизу ждало бы, пока не отпустят (проба @PROTO 2026-09-25: копирование
# повисло насовсем). Тот же предел и тот же приём (progress-колбэк), что уже стоит в
# records_preview_copy у save-phoenix.py (PREVIEW_BUSY_SECONDS): холостой прогон — не
# сохранение, столько ждать не обязан.
BUSY_SECONDS = 10


class _DryConnection(sqlite3.Connection):
    """Соединение, которое всё умеет и ничего не сохраняет.

    Вторая страховка (редакция 2026-09-25) — ПЕРВАЯ и главная теперь в том, что этому
    соединению просто нечего фиксировать, кроме памяти самого процесса: см. `_connect_dry`
    и разбор в шапке модуля. Пустой commit() оставлен на случай способа фиксации, которого
    не учла и текущая правка.
    """

    def commit(self):        # noqa: D102 — намеренно пустой
        pass


def connect(db, dry, **kw):
    """Открыть базу. При dry=True — холостой копией в памяти, с громкой подписью.
    При dry=False — БЕЗ ИЗМЕНЕНИЙ: тот же `sqlite3.connect` с теми же аргументами,
    что вызывался бы без этого модуля вовсе.

    ⚠️ Подпись печатается ДВАЖДЫ — в начале и на выходе. Один раз мало: у пишущих
    инструментов вывод длинный, шапка уезжает, и читают хвост. Мой промах 13.08 случился
    ровно на чтении хвоста.
    """
    if not dry:
        return sqlite3.connect(db, factory=sqlite3.Connection, **kw)
    print(BANNER, file=sys.stderr)
    conn = _connect_dry(db, **kw)
    atexit.register(_finish, conn)
    return conn


def _source_path(db, is_uri: bool) -> Path:
    """Путь к файлу источника — из голого пути ИЛИ из готовой URI-строки (`file:...?...`).

    Второе нужно живому вызову save-phoenix.py: он зовёт `connect(f"file:{db}?mode=rw",
    dry, uri=True, ...)`, чтобы сам sqlite3.connect не создавал БД-фантом при опечатке пути
    (П1 16.07). Разбор — текстовый (срезать «file:» слева, «?...»/«#...» справа), тем же
    простым приёмом, каким сама эта URI-строка и собрана на живом вызове, — без urllib:
    у реальных вызовов в пути нет процентных кодировок, а срезка верно работает и на
    обратных косых чертах Windows-пути (Path() ниже сам сводит их к прямым — as_posix()).
    """
    if not is_uri:
        return Path(db)
    text = str(db)
    if text.lower().startswith("file:"):
        text = text[len("file:"):]
    return Path(text.split("?", 1)[0].split("#", 1)[0])


def _refuses_missing_file(uri_db) -> bool:
    """URI несёт `mode=ro` или `mode=rw` — режим, в котором сам sqlite3 НЕ создаёт файл
    и отказывает (`OperationalError: unable to open database file`), если его нет.

    ЗАЧЕМ (возврат PROTO по правке, тот же день): без этой проверки холостой прогон
    расходился с настоящим РОВНО на опечатке пути. Живой вызов save-phoenix.py —
    `dryrun.connect(f"file:{db}?mode=rw", dry, uri=True, ...)` — при dry=False на
    несуществующем пути поднимает `OperationalError`, и caller ловит её словами «ERR:
    БД не найдена». При dry=True без этой проверки _connect_dry молча отдавала бы
    ПУСТУЮ РАБОЧУЮ копию — другую ветку, другое сообщение, никакого экрана «БД не
    найдена» при холостом прогоне на той же опечатке. Голый путь и `mode=rwc`
    (проверено отдельно) сам sqlite3 НЕ отказывает — создаёт файл и продолжает,
    поэтому там пустая копия остаётся верным подобием и эта проверка их не трогает.
    """
    text = str(uri_db)
    if "?" not in text:
        return False
    query = text.split("?", 1)[1].split("#", 1)[0]
    for part in query.split("&"):
        if part.startswith("mode="):
            return part[len("mode="):] in ("ro", "rw")
    return False


def _connect_dry(db, **kw):
    """Собрать холостую копию: источник читается (mode=ro), инструмент получает базу
    в памяти — см. разбор механизма и границ в шапке модуля.

    Разбор **kw — какой параметр куда идёт:
      · `uri` СЪЕДАЕТСЯ здесь: он решает только то, КАК читать `db` (голый путь или
        готовая URI-строка) — источнику ниже всегда даётся своя, ЗАВЕДОМО ЧИТАЮЩАЯ,
        URI-строка (`file:...?mode=ro`), а не то, что пришло от вызывающего;
      · `timeout`, если он задан вызывающим, идёт И источнику (живая база может быть
        занята ровно в этот миг), И копии (просто чтобы у возвращённого соединения
        настройка была той, что просил вызывающий, — на приватной базе в памяти
        состязаться за блокировку не с кем, но и вреда от этого нет);
      · всё остальное (`isolation_level`, `detect_types`, `check_same_thread`, любой
        другой валидный для sqlite3.connect параметр) идёт ТОЛЬКО копии — это настройки
        поведения СОЕДИНЕНИЯ, которое получит и будет держать вызывающий, а не настройки
        разового чтения источника, которое делает эта функция сама и тут же закрывает;
      · `factory` НЕ ПРИНИМАЕТСЯ вовсе — та же ошибка, что дал бы обычный
        sqlite3.connect(..., factory=X, factory=Y): фабрика холостого соединения не
        предмет спора с вызывающим, она и есть вторая страховка (см. _DryConnection).

    ⏱ ЗАНЯТАЯ БАЗА: снятие копии ждёт не дольше BUSY_SECONDS (progress-колбэк считает
    время и обрывает попытку исключением) — дольше молчаливого ожидания холостой прогон
    терпеть не обязан, это не сохранение. Отказ — громкий, sys.exit с понятными словами
    и НЕнулевым кодом; живая база при этом читается, но НЕ открывается на запись.
    """
    kw = dict(kw)
    if "factory" in kw:
        raise TypeError("dryrun.connect() got multiple values for keyword argument 'factory'")
    is_uri = kw.pop("uri", False)
    timeout = kw.get("timeout")
    path = _source_path(db, is_uri)
    if not path.exists() and is_uri and _refuses_missing_file(db):
        # Та же ветка, что и у настоящего connect() с этим mode — см. _refuses_missing_file.
        raise sqlite3.OperationalError("unable to open database file")
    copy = sqlite3.connect(":memory:", factory=_DryConnection, **kw)
    if not path.exists():
        print(f"⟨ХОЛОСТОЙ ПРОГОН⟩ файла базы нет ({path}) — работаю на ПУСТОЙ копии "
              "в памяти, живой файл НЕ создаю.", file=sys.stderr)
        return copy
    source_kw = {"uri": True}
    if timeout is not None:
        source_kw["timeout"] = timeout
    source = sqlite3.connect(f"file:{path.as_posix()}?mode=ro", **source_kw)
    started = time.monotonic()

    def _give_up_when_busy(status, remaining, total):
        # Снятие копии повторяет попытку на занятой базе без своего предела — холостой
        # прогон столько не ждёт (проба @PROTO 2026-09-25: попытка повисла насовсем).
        if time.monotonic() - started > BUSY_SECONDS:
            raise TimeoutError(f"база занята дольше {BUSY_SECONDS} с")

    try:
        source.backup(copy, progress=_give_up_when_busy)
    except TimeoutError:
        copy.close()
        sys.exit(f"⟨ХОЛОСТОЙ ПРОГОН⟩ база занята другим пишущим дольше {BUSY_SECONDS} с — "
                 "копию снять не удалось; живая база не тронута.")
    finally:
        source.close()
    return copy


def _finish(conn):
    try:
        conn.rollback()
    except sqlite3.Error:
        pass
    print("⟨ХОЛОСТОЙ ПРОГОН ЗАВЕРШЁН⟩ НИЧЕГО НЕ ЗАПИСАНО. Номера и метки выше — то, что "
          "получилось бы; ссылаться на них нельзя.", file=sys.stderr)


