"""dryrun — ХОЛОСТОЙ ПРОГОН для пишущих инструментов: посмотреть, не сделав.

ПОВОД (мой собственный промах, @PROTO 2026-08-13 10:29 UTC). Я проверял, что отказ `--md`
объясняет причину, — и позвал `write-message.py` НА ЖИВОЙ БАЗЕ с настоящим телом записки.
Отказ касался только md-половины, нота ушла в ленту. Мусор пришлось отменять запиской.

🪤 И РАЗБОР ОКАЗАЛСЯ НЕ ТОТ, ЧТО Я СНАЧАЛА НАПИСАЛ. Я объявил урок «испытывая отказ, проверь,
что отказ покрывает ВСЁ действие» — то есть обвинил механизм в частичном отказе. Перемерил:
инструмент напечатал **«✅ Твоя нота ЗАПИСАНА В БАЗУ — отклонена только md-половина»**, и эта
строка была в том самом выводе, который я читал. Механизм сказал правду; не дочитал я.
⇒ Значит чинить надо НЕ честность отказа (она была), а то, что **увидеть поведение можно было
только СОВЕРШИВ его.** Вот это — свойство, и оно лечится здесь.

⚖️ ЧЕГО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ, И ЭТО НАДО СКАЗАТЬ ПРЯМО:
он НЕ спасает от невнимательности. Флаг надо не забыть позвать — а я в тот раз не забыл его,
я о нём вовсе не подумал. Модуль убирает не ошибку, а НЕОБХОДИМОСТЬ ПИСАТЬ, ЧТОБЫ ПОСМОТРЕТЬ.
Это меньше, чем «класс закрыт», и больше, чем норма в памяти.

КАК УСТРОЕНО: соединение подменяется подклассом, у которого `commit()` — пустышка, а на выходе
делается откат. Код инструмента исполняется ВЕСЬ, как в бою: те же ветки, те же отказы, те же
сообщения. Не пишется только результат.
🔍 Почему подклассом, а не проверками в каждом месте записи: у пишущих инструментов от одного
до четырёх мест `commit()`, и обход по одному — ровно то «точечное лечение общего класса»,
после которого остаток выглядит зелёным. Одна точка на инструмент, и новый путь записи
наследует холостой ход даром.
"""
import atexit
import sqlite3
import sys

BANNER = "⟨ХОЛОСТОЙ ПРОГОН⟩ база НЕ изменится: коммиты проглатываются, на выходе откат."


class _DryConnection(sqlite3.Connection):
    """Соединение, которое всё умеет и ничего не сохраняет."""

    def commit(self):        # noqa: D102 — намеренно пустой
        pass


def connect(db, dry, **kw):
    """Открыть базу. При dry=True — в холостом режиме, с громкой подписью.

    ⚠️ Подпись печатается ДВАЖДЫ — в начале и на выходе. Один раз мало: у пишущих
    инструментов вывод длинный, шапка уезжает, и читают хвост. Мой промах 13.08 случился
    ровно на чтении хвоста.
    """
    conn = sqlite3.connect(db, factory=(_DryConnection if dry else sqlite3.Connection), **kw)
    if dry:
        print(BANNER, file=sys.stderr)
        atexit.register(_finish, conn)
    return conn


def _finish(conn):
    try:
        conn.rollback()
    except sqlite3.Error:
        pass
    print("⟨ХОЛОСТОЙ ПРОГОН ЗАВЕРШЁН⟩ НИЧЕГО НЕ ЗАПИСАНО. Номера и метки выше — то, что "
          "получилось бы; ссылаться на них нельзя.", file=sys.stderr)


def add_argument(parser):
    """Один и тот же флаг у всех пишущих инструментов — чтобы роль не гадала про форму."""
    parser.add_argument("--dry-run", action="store_true",
                        help="ХОЛОСТОЙ прогон: выполнить всё и НЕ сохранить. Для проверки "
                             "поведения (в том числе отказов) без следа в живой базе")
