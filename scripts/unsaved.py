from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

# Корни поиска. Не список репозиториев — список МЕСТ, где контур их держит.
DEFAULT_ROOTS = [Path("C:/guts/.atlas"), Path("C:/github")]
MAX_DEPTH = 2  # глубже держать репозитории у нас не принято; узлы вроде node_modules отсекаем


def git(repo: Path, *args: str) -> tuple[int, str]:
    """Вызов git в репозитории. Возвращает (код, вывод) — код НЕ теряем."""
    try:
        r = subprocess.run(
            ["git", "-C", str(repo), *args],
            capture_output=True, text=True, timeout=20,
        )
        return r.returncode, (r.stdout or "") + (r.stderr or "")
    except subprocess.TimeoutExpired:
        return 124, "таймаут"
    except OSError as e:
        return 127, str(e)


def find_repos(roots: list[Path]) -> list[Path]:
    found: list[Path] = []
    for root in roots:
        if not root.exists():
            continue
        for depth in range(MAX_DEPTH + 1):
            pattern = "/".join(["*"] * depth + [".git"]) if depth else ".git"
            for git_dir in root.glob(pattern):
                repo = git_dir.parent
                # .git бывает файлом (worktree/submodule) — такое тоже репозиторий
                if repo not in found:
                    found.append(repo)
    return sorted(found)


def survey(repo: Path) -> dict:
    """Замер одного репозитория. Ни одного вывода из имени — только ответы git."""
    d: dict = {"repo": repo, "ошибки": []}

    # Репозиторий БЕЗ ЕДИНОГО КОММИТА — законное состояние, а не поломка. Различаем его
    # до всех прочих замеров: иначе он кричит «ambiguous argument HEAD» и читается как
    # риск, которого нет. Ложная тревога учит не смотреть на инструмент вовсе.
    code, _ = git(repo, "rev-parse", "--verify", "HEAD")
    d["пустой"] = code != 0
    if d["пустой"]:
        d["ветка"] = "(нет коммитов)"
    else:
        code, out = git(repo, "rev-parse", "--abbrev-ref", "HEAD")
        d["ветка"] = out.strip() if code == 0 else "?"
        if code != 0:
            d["ошибки"].append(f"ветка: {out.strip().splitlines()[0][:70]}")

    # ① грязное дерево. --porcelain: устойчивый формат, не зависит от языка и настроек.
    # -uall ОБЯЗАТЕЛЕН: без него неотслеживаемая ПАПКА — одна строка независимо от того,
    # два в ней файла или 2510. Именно так `gordipack` выглядел как «неотслеживаемых 2».
    # Число, называющее себя файлами и мерящее строки, — тот самый дефект, против
    # которого этот инструмент и заведён.
    code, out = git(repo, "status", "--porcelain", "-uall")
    if code == 0:
        lines = [l for l in out.splitlines() if l.strip()]
        d["изменено"] = sum(1 for l in lines if not l.startswith("??"))
        d["неотслеж"] = sum(1 for l in lines if l.startswith("??"))
        # что РЕАЛЬНО уедет в коммит: git add -An учитывает .gitignore, а `??` — нет.
        # Разница между этими числами и есть «2510 файлов, из них 38 значащих».
        c2, o2 = git(repo, "add", "-An")
        d["в_коммит"] = len([l for l in o2.splitlines() if l.strip()]) if c2 == 0 else None
    else:
        d["изменено"] = d["неотслеж"] = d["в_коммит"] = None
        d["ошибки"].append(f"status: {out.strip()[:80]}")

    # ② коммиты без отправки. Отсутствие upstream — НЕ ноль: это третий случай, и он опаснее
    if d["пустой"]:
        d["ahead"], d["upstream"] = 0, "(нечего отправлять)"
        return d
    code, out = git(repo, "rev-parse", "--abbrev-ref", "@{upstream}")
    if code != 0:
        d["ahead"] = None
        d["upstream"] = None
    else:
        d["upstream"] = out.strip()
        c2, o2 = git(repo, "rev-list", "--count", "@{upstream}..HEAD")
        d["ahead"] = int(o2.strip()) if c2 == 0 and o2.strip().isdigit() else None
    return d


def main() -> int:
    ap = argparse.ArgumentParser(
        description="Обзор незаписанного: что умрёт с чатом, что с машиной",
    )
    ap.add_argument("--root", action="append", type=Path,
                    help="где искать репозитории (можно несколько; по умолчанию C:/guts/.atlas и C:/github)")
    ap.add_argument("--quiet-clean", action="store_true",
                    help="не печатать репозитории, где всё записано")
    args = ap.parse_args()

    roots = args.root or DEFAULT_ROOTS
    repos = find_repos(roots)
    if not repos:
        print("⛔ репозиториев не найдено — проверь --root, это НЕ значит «всё записано»",
              file=sys.stderr)
        return 2

    print(f"📦 НЕЗАПИСАННОЕ — {len(repos)} репозиториев, корни: {', '.join(str(r) for r in roots)}")
    print()

    risky = 0
    for repo in repos:
        d = survey(repo)
        dirty = (d["изменено"] or 0) + (d["неотслеж"] or 0)
        ahead = d["ahead"]
        # У пустого репозитория upstream не бывает по построению — это не «никуда не смотрит»
        no_upstream = d["upstream"] is None and not d["пустой"]
        quiet = not dirty and not ahead and not no_upstream and not d["ошибки"]
        if quiet and args.quiet_clean:
            continue
        if not quiet:
            risky += 1

        mark = "✅" if quiet else "🔴"
        print(f"{mark} {repo}  [{d['ветка']}]")

        if dirty:
            в_коммит = d["в_коммит"]
            хвост = ""
            if в_коммит is not None and в_коммит != dirty:
                # Именно здесь ловится «2510 неотслеживаемых, а поедут 38»
                хвост = f"  ⇒ в коммит пойдут {в_коммит} (остальное отсечено .gitignore)"
            print(f"   ① НА ДИСКЕ, БЕЗ ИСТОРИИ: изменено {d['изменено']} · неотслеживаемых {d['неотслеж']}{хвост}")
            # Текст @opssre (#3139) — он же и нашёл здесь ложный СРОК. Строка стоит ВНУТРИ
            # `if dirty`: подстрочник без своей строки прилипает к соседней (класс «сирота-
            # подстрочник», пойман им же). И печатается она здесь, а не только в шапке файла:
            # шапку читает автор инструмента, а цитируют — то, что инструмент СКАЗАЛ.
            print("      переживёт чат и перезагрузку · исчезнет МОЛЧА от git checkout/clean")
            print("      или правки этого же файла ⇒ лечится КОММИТОМ, не сохранением чата")
        if no_upstream:
            print("   ⚠️ ВЕТКА НИКУДА НЕ СМОТРИТ (нет upstream) — «ahead» посчитать не из чего,")
            print("      и это НЕ «всё отправлено»: работа может не иметь копии нигде")
        elif ahead:
            print(f"   ② В КОММИТЕ, УМРЁТ С МАШИНОЙ: {ahead} коммитов не отправлено → {d['upstream']}")
        for e in d["ошибки"]:
            print(f"   ⛔ {e}")
        print()

    print("─" * 78)
    if risky:
        print(f"🔴 требуют внимания: {risky} из {len(repos)}")
        print("   ① лечит роль сама (коммит или строка в §состояние слепка)")
        # ⚰️ Здесь печаталось «② лечит только СЛОВО ВЛАДЕЛЬЦА (push) — роль перевести себя
        # не может». ОТМЕНЕНО: запрет снят владельцем 2026-08-08 15:56 UTC. Самая дорогая
        # из трёх строк этого файла: она не описывала правило, а ПРЯМО ГОВОРИЛА роли,
        # что спасти свою работу она не вправе, — и печаталась в момент, когда работа
        # уже под угрозой.
        print("   ② лечит роль сама: отправка разрешена без отдельного слова (08.08 15:56 UTC)")
        print("      ⚠️ но перед отправкой сверь состав ВЕТКИ: отменён вопрос, а не сверка")
    else:
        print("✅ незаписанного нет ни в одном репозитории")
    print("⛔ и то, чего этот обзор НЕ проверял: полноту СЛЕПКОВ. Чистое дерево не значит,")
    print("   что роль воскреснет — она воскресает из слепка, а не из git. Это к guard-all.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
