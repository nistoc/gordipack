# -*- coding: utf-8 -*-
"""20260904-phoenix-archive — АРХИВ ПАМЯТИ РОЛИ ОТДЕЛЬНОЙ ТАБЛИЦЕЙ (карточка #523).

ПРЕДМЕТ. Память роли читается ЦЕЛИКОМ при каждом пробуждении. Замер 2026-09-04 13:25 UTC:

    роль читает за пробуждение ..... 65 938 … 123 980 знаков (7 разделов у каждой)
    порог, который считали защитой .. 20 000 — НО ОН СТОИТ НА РАЗДЕЛЕ
    ⇒ потолок по факту .............. 7 × 20 000 = 140 000 знаков на роль

⚡ НАХОДКА ШИРЕ КАРТОЧКИ: ограничение поставлено НЕ НА ТОТ ПРЕДМЕТ, ЧТО РАСХОДУЕТСЯ.
Тратится окно чтения РОЛИ, а сторож стои́т на РАЗДЕЛЕ — и честно молчит, пока каждый
из семи не дорос до потолка поодиночке.

⚖️ ПОЧЕМУ АРХИВ — ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ ПОЛЕ И НЕ СУФФИКС В ИМЕНИ РАЗДЕЛА.
Замер перед выбором: `phoenix` читают 49 инструментов. Любой признак ВНУТРИ таблицы
(колонка «горячее/архив», раздел «state.archive») виден всем сорока девяти, и каждый
из них, не зная о признаке, считал бы архив обычной памятью: сторож объёма судил бы
его наравне, счётчики считали бы дважды, пробуждение читало бы целиком.

    ⇒ ОТДЕЛЬНАЯ ТАБЛИЦА ДЕЛАЕТ АРХИВ НЕВИДИМЫМ ДЛЯ НИХ ПО ПОСТРОЕНИЮ.
      Встречный критерий карточки ④ («пробуждение не сломано») выполняется УСТРОЙСТВОМ,
      а не проверкой — читатели `phoenix` не меняются вовсе и меняться не должны.

🩸 И это тот же класс, которым контур платил в августе: правка, трогающая много мест,
оставляет половину дефекта в ветках, куда рука не дошла. Здесь рука не идёт НИКУДА —
это и есть довод.

ЧТО ДЕЛАЕТ ШАГ
  · заводит `phoenix_archive` — куски памяти, унесённые из горячей части, ПО ПРЕДМЕТУ:
    у каждого куска есть тема (заголовок блока), чтобы архив спрашивали по предмету,
    а не читали целиком. Непрочитываемый архив равен удалению (критерий ② карточки);
  · заводит указатели для поиска по роли и по теме;
  · записывает себя в журнал схемы.

⛔ ЧЕГО НЕ ДЕЛАЕТ: ничего не переносит. Перенос — рука роли (инструмент memory-archive.py),
и каждая роль жмёт СВОЮ память: слово владельца 2026-09-04 13:41 UTC — «только свою,
остальные сами». Чужую память шаг схемы не трогает и трогать не вправе.
"""
import argparse
import io
import os
import sqlite3
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPTS = os.path.dirname(HERE)
sys.path.insert(0, SCRIPTS)
from schema_journal import record_step, verify  # noqa: E402

VERSION = "20260904-phoenix-archive"

# ⚡ СХЕМА — СПИСОК ЗАПРОСОВ, А НЕ ОДИН ТЕКСТ, И ЭТО ОПЛАЧЕНО ЗДЕСЬ ЖЕ.
# Первая редакция держала всё одной строкой и резала её по «;». Но точка с запятой
# стои́т и ВНУТРИ комментариев («Роль жмёт свою память сама;»), поэтому CREATE TABLE
# разрезался на четыре куска, и база ответила «неполный запрос».
# 🎯 КЛАСС: РАЗДЕЛИТЕЛЬ ВСТРЕЧАЕТСЯ И ВНУТРИ ДАННЫХ. Лечится не более хитрым разбором,
# а тем, что разделителя не остаётся вовсе: границы заданы списком.
ЗАПРОСЫ = (
    """CREATE TABLE phoenix_archive (
    id              INTEGER PRIMARY KEY,
    role            TEXT NOT NULL,
    -- ИЗ КАКОГО раздела унесено. Кусок помнит своё происхождение: без этого
    -- возврат в горячую часть кладёт его наугад, а «наугад» в памяти роли
    -- означает приказ не в ту секцию.
    section         TEXT NOT NULL,
    -- ПРЕДМЕТ куска — заголовок блока, по которому его спрашивают. Архив без
    -- предмета читается только целиком, то есть не читается вовсе.
    topic           TEXT NOT NULL,
    body            TEXT NOT NULL,
    body_chars      INTEGER NOT NULL,
    moved_at        TEXT NOT NULL DEFAULT (datetime('now')),
    -- ЧЬЯ РУКА унесла. Роль жмёт свою память сама, чужая рука обязана быть видна.
    moved_by        TEXT NOT NULL,
    -- КОГДА кусок был сохранён в горячей части. Возраст куска — это возраст
    -- знания, а не час переноса: смешаешь их, и архив соврёт о своей свежести.
    origin_saved_at TEXT
)""",
    "CREATE INDEX idx_phoenix_archive_role  ON phoenix_archive(role, section)",
    "CREATE INDEX idx_phoenix_archive_topic ON phoenix_archive(role, topic)",
)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--db', default=os.path.join(os.path.dirname(SCRIPTS), 'mezosync.db'))
    ap.add_argument('--dry-run', action='store_true')
    a = ap.parse_args()

    db = os.path.abspath(a.db)
    print('=' * 78)
    print(f'{VERSION}{"  ⟨ВХОЛОСТУЮ — база не меняется⟩" if a.dry_run else ""}')
    print(f'📂 БАЗА: {db}')
    print('=' * 78)
    if not os.path.isfile(db):
        sys.exit(f'⛔ НЕ ЗАПУСТИЛСЯ: БД не найдена: {db}')

    conn = sqlite3.connect(db)
    есть = {r[0] for r in conn.execute(
        "SELECT name FROM sqlite_master WHERE type='table'")}
    if 'phoenix_archive' in есть:
        print('✅ уже сведено (таблица phoenix_archive на месте) — делать нечего')
        return

    свод = conn.execute(
        "SELECT role, COUNT(*), SUM(LENGTH(body)) FROM phoenix GROUP BY role "
        "ORDER BY 3 DESC").fetchall()
    всего = sum(r[2] for r in свод)
    print('ЧТО РОЛЬ ЧИТАЕТ ПРИ ПРОБУЖДЕНИИ СЕЙЧАС — замер до переноса:')
    print('─' * 78)
    for роль, n, знаков in свод:
        print(f'   {роль:8} разделов {n} · {знаков:>7} знаков')
    print('─' * 78)
    print(f'   ВСЕГО по контуру: {всего} знаков у {len(свод)} ролей')
    print('⚖️ Это число — мерка ПЕРЕД работой. Встречный критерий карточки ③ требует,')
    print('   чтобы после переноса сумма (горячее + архив) была НЕ МЕНЬШЕ: потерь ноль.')

    if a.dry_run:
        print('\n⟨ВХОЛОСТУЮ⟩ база не тронута. Чтобы применить, прогони без --dry-run.')
        return

    conn.execute("BEGIN")
    # 🪤 НЕ executescript: он делает НЕЯВНЫЙ КОММИТ перед выполнением и закрывает
    #    только что открытый BEGIN — правка схемы уходит в автокоммит, а запись
    #    о ней остаётся в транзакции, которой уже нет. Поймано механизмом журнала
    #    при первом же прогоне (2026-09-04 13:27 UTC): таблица создалась, запись
    #    о ней — нет. ⚡ Класс: удобная обёртка молча меняет ГРАНИЦЫ транзакции,
    #    и «в той же транзакции» становится словами. Выполняем по одному запросу.
    for запрос in ЗАПРОСЫ:
        conn.execute(запрос)
    fp = record_step(conn, VERSION,
                     "phoenix_archive: архив памяти роли ОТДЕЛЬНОЙ таблицей — куски "
                     "по предмету (topic), с происхождением (section, origin_saved_at) "
                     "и рукой переноса (moved_by). Отдельная таблица выбрана намеренно: "
                     "phoenix читают 49 инструментов, и признак внутри таблицы был бы "
                     "виден каждому из них. Ничего не переносит — перенос рука роли. "
                     f"Карточка #523. Замер до переноса: {всего} знаков у {len(свод)} ролей")
    conn.commit()
    print(f'\n✅ ВРЕЗАНО. отпечаток схемы: {fp}')
    ok, why = verify(conn)
    print(f'{"✅" if ok else "🔴"} проверка журнала: {why}')
    print('целостность:', conn.execute("PRAGMA integrity_check").fetchone()[0])
    print('контрольное чтение: строк в архиве',
          conn.execute("SELECT COUNT(*) FROM phoenix_archive").fetchone()[0],
          '— пусто, как и должно быть: шаг заводит место, а не переносит')


if __name__ == '__main__':
    main()
