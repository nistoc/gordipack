VERSION = "20260904-phoenix-records"

# ⚡ СПИСОК ЗАПРОСОВ, А НЕ ОДИН ТЕКСТ С «;»: точка с запятой стои́т и внутри комментариев,
# и разбор по ней резал CREATE TABLE на куски (оплачено шагом 20260904-phoenix-archive
# двумя часами ранее). Разделителя здесь нет вовсе — границы заданы списком.
ЗАПРОСЫ = (
    """CREATE TABLE phoenix_records (
    id              INTEGER PRIMARY KEY,
    role            TEXT NOT NULL,
    -- ИЗ КАКОГО раздела памяти запись. Разделы остаются: они отвечают на «когда это
    -- читают» (пробуждение · план · история), а предмет — на «о чём это».
    section         TEXT NOT NULL,
    -- ПРЕДМЕТ: о чём запись. Именно по нему владелец отбирает «всё про права».
    -- ⛔ Список предметов НЕ закрыт схемой намеренно: закрытый список состарился бы
    -- молча, а видимо стареющий держит инструмент (он печатает известные предметы).
    subject         TEXT NOT NULL,
    body            TEXT NOT NULL,
    body_chars      INTEGER NOT NULL,
    -- ЧАС, к которому запись относится: не час вставки, а час события. Смешаешь их —
    -- «что записано вчера» ответит про сегодняшний разбор вчерашнего дня.
    happened_at     TEXT,
    -- ЧЕМ ДОБЫТО: свой замер · чужая находка (чья) · слово владельца · разбор.
    -- Без источника факт неотличим от гипотезы — правило dowry-facts-carry-source.
    source          TEXT,
    -- ⚡ ПРИ КАКОМ НАБЛЮДАЕМОМ СОБЫТИИ ЗАПИСЬ ПЕРЕСТАЁТ ДЕЙСТВОВАТЬ. Ровно того,
    -- чего сегодня нет НИ У ОДНОЙ записи памяти. Пустое поле — законное состояние
    -- («не назначено»), но оно ОТЛИЧИМО запросом, а не молчит (критерий ⑥ карточки).
    expiry_cond     TEXT,
    -- ЖИВОСТЬ: 'active' действует · 'revoked' снята. Чем и когда снята — в revoked_note.
    alive           TEXT NOT NULL DEFAULT 'active',
    revoked_at      TEXT,
    revoked_note    TEXT,
    -- ПОРЯДОК внутри раздела: чтобы собрать прежнее сплошное тело обратно, знак в знак.
    ord             INTEGER NOT NULL DEFAULT 0,
    -- ДЛИНА ТЕЛА, ИЗ КОТОРОГО СДЕЛАНА ЗАПИСЬ: по ней видно расхождение слоёв.
    origin_chars    INTEGER,
    created_at      TEXT NOT NULL DEFAULT (datetime('now')),
    created_by      TEXT NOT NULL
)""",
    "CREATE INDEX idx_phoenix_records_role    ON phoenix_records(role, section, ord)",
    "CREATE INDEX idx_phoenix_records_subject ON phoenix_records(role, subject)",
    "CREATE INDEX idx_phoenix_records_alive   ON phoenix_records(role, alive)",
    "CREATE INDEX idx_phoenix_records_when    ON phoenix_records(role, happened_at)",
)


