# ⚡ ЗАЧЕМ ЭТО ЗДЕСЬ, А НЕ ОТДЕЛЬНЫМ ИНСТРУМЕНТОМ: правило обезличивания (PLACEHOLDERS)
# уже живёт в этом файле и им пользуется СРАВНЕНИЕ. Пока переносил человек, правило знало
# сравнение, а рука повторяла его по памяти — и дважды за одну смену 05.09 едва не увезла
# в публичный шаблон путь этой машины (2 файла в 20:48, 4 файла в 22:39; оба раза поймано
# сличением ДО отправки, то есть случайно). Один код на два применения разойтись не может.
#
# ⛔ ГРАНИЦА, КОТОРУЮ НЕЛЬЗЯ НАРУШИТЬ (она записана выше, в шапке про RUNTIME, и оплачена
# соседним контуром): обезличивать ИСПОЛНЯЕМУЮ строку заглушкой нельзя — у потребителя
# такой инструмент падает на первом прогоне. Заглушка законна ТОЛЬКО в тексте, который
# читает человек: комментарий, докстрока, печатаемая строка. Путь, который код ВЫЧИСЛЯЕТ,
# обязан остаться выводимым от расположения файла.
# ⇒ Перенос отличает одно от другого и ОТКАЗЫВАЕТСЯ, когда путь стои́т в исполняемом месте:
#   молча обезличить его значило бы изготовить поломку и отдать её соседям.

_PRINTING_CALLS = {"print", "case", "суд", "случай", "write", "sys.exit", "exit"}


def _call_name(node):
    """Имя вызываемого — для Call. «obj.method» приводим к «method»."""
    f = node.func
    if isinstance(f, ast.Name):
        return f.id
    if isinstance(f, ast.Attribute):
        return f.attr
    return ""


def _safe_spans(text):
    """Смещения (начало, конец) кусков текста, где заглушка законна: комментарии,
    докстроки и строки внутри печатающих вызовов.

    ⚖️ Список печатающих имён — НАШ, не общий: у приёмок контура человекочитаемый текст
    идёт не в print, а в case/суд/случай. Незнакомая печатающая обёртка сюда не попадёт,
    и перенос честно ОТКАЖЕТСЯ, а не обезличит наугад.
    """
    line_starts, pos = [0], 0
    for line in text.splitlines(keepends=True):
        pos += len(line)
        line_starts.append(pos)

    def offset(row, col):
        return line_starts[row - 1] + col

    spans = []
    try:
        tree = ast.parse(text)
    except SyntaxError:
        return None                      # неразбираемый файл — судить нечем, вызывающий откажет

    printable = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and _call_name(node) in _PRINTING_CALLS:
            for sub in ast.walk(node):
                if isinstance(sub, ast.Constant) and isinstance(sub.value, str):
                    printable.add((sub.lineno, sub.col_offset))
        # докстрока: строковое выражение первым в теле модуля, функции или класса
        if isinstance(node, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            body = getattr(node, "body", [])
            if body and isinstance(body[0], ast.Expr) and isinstance(body[0].value, ast.Constant) \
                    and isinstance(body[0].value.value, str):
                doc_node = body[0].value
                printable.add((doc_node.lineno, doc_node.col_offset))

    for tok in tokenize.generate_tokens(io.StringIO(text).readline):
        if tok.type == tokenize.COMMENT:
            spans.append((offset(*tok.start), offset(*tok.end)))
        elif tok.type == tokenize.STRING and (tok.start[0], tok.start[1]) in printable:
            spans.append((offset(*tok.start), offset(*tok.end)))
    return spans


def anonymize_text(text):
    """→ (новый текст, сколько заменено, [строки с путём В ИСПОЛНЯЕМОМ месте]).

    Заменяем ТОЛЬКО внутри безопасных мест. Путь, найденный вне их, не трогаем и
    возвращаем как причину отказа — с номером строки, чтобы человек посмотрел сам.
    """
    spans = _safe_spans(text)
    if spans is None:
        return None, 0, ["файл не разбирается — обезличивать вслепую нельзя"]
    replacements, unsafe = [], []
    for real, mark in PLACEHOLDERS:
        if not real:
            continue
        pos = text.find(real)
        while pos != -1:
            inside = any(start <= pos and pos + len(real) <= end for start, end in spans)
            if inside:
                replacements.append((pos, pos + len(real), mark))
            else:
                line_no = text.count("\n", 0, pos) + 1
                unsafe.append(f"строка {line_no}: «{real}» вне читаемого человеком текста")
            pos = text.find(real, pos + 1)
    if unsafe:
        return None, 0, unsafe
    for start, end, mark in sorted(replacements, reverse=True):
        text = text[:start] + mark + text[end:]
    return text, len(replacements), []


def transfer_to_template(names, runtime_dirs, template_dir):
    """Скопировать названные файлы в шаблон, обезличив пути. Вернуть код возврата."""
    if template_dir is None:
        print("⛔ ШАБЛОН НЕ ОБЪЯВЛЕН (meta.template_checkout пуст) — переносить некуда")
        return 2
    # ⚠️ Каталога может не быть — и это СОСТОЯНИЕ («образец не выкачан», «путь опечатан»),
    # а не поломка инструмента. Первая редакция падала здесь трассировкой: роль видела
    # семь строк про pathlib вместо одной строки про свой каталог. Нашла приёмка
    # (случай ③б), а не человек: встречный случай переносил файл в каталог, которого нет.
    if not Path(template_dir).is_dir():
        print(f"⛔ КАТАЛОГА ОБРАЗЦА НЕТ: {template_dir}")
        print("   Это состояние, а не поломка: образец не выкачан либо путь указан неверно.")
        print("   Сам его не создаю — публичный каталог заводит человек, а молча созданный"
              " пустой каталог выглядел бы как выкачанный образец.")
        return 2
    bad = 0
    for name in names:
        source = None
        for folder in runtime_dirs:
            candidate = Path(name) if Path(name).is_absolute() else inside_dir(folder, name)
            if candidate.exists():
                source = candidate
                break
        if source is None:
            print(f"🔴 {name}: не найден ни в одном рабочем каталоге — переносить нечего")
            bad += 1
            continue
        text = source.read_bytes().decode("utf-8", "replace")
        new_text, replaced, unsafe = anonymize_text(text)
        if new_text is None:
            print(f"🔴 {source.name}: ОТКАЗ — путь этой машины стои́т там, где его нельзя"
                  f" заменить заглушкой (обезличенная ИСПОЛНЯЕМАЯ строка ломает инструмент"
                  f" у потребителя):")
            for reason in unsafe:
                print(f"      {reason}")
            print("   👉 вынеси путь из вычисления (он обязан выводиться от расположения"
                  " файла) — и повтори перенос")
            bad += 1
            continue
        target = template_dir / source.name
        # 🔴 ЗДЕСЬ БЫЛО `write_text(...)`, И ОНО УДВАИВАЛО КОНЦЫ СТРОК (находка @COORD,
        # записка #4904). Файл читается БАЙТАМИ, значит «\r\n» доезжает в текст как есть;
        # запись текстом на Windows переводит каждый «\n» ещё раз — выходит «\r\r\n».
        # 📏 Замер: в образце 298 файлов, испорчен был РОВНО ОДИН — единственный, который
        # успел перенести этот инструмент. То есть средство, заведённое убрать ручную
        # работу, испортило ровно то, к чему прикоснулось.
        # ⚡ И почему это не поймала сверка: она нормализует концы строк ПЕРЕД сравнением,
        # значит «\r\r\n» для неё то же, что «\r\n». Правка и проверяющая её сверка читали
        # ПО-РАЗНОМУ — сверка слепа именно к той порче, которую правка вносит.
        # ⇒ Пишем БАЙТАМИ: что прочитали, то и записали, кроме подставленных заглушек.
        target.write_bytes(new_text.encode("utf-8"))
        print(f"✅ {source.name} → шаблон · заглушек подставлено {replaced}")
    if bad:
        print(f"\n⛔ ПЕРЕНЕСЕНО НЕ ВСЁ: отказов {bad}. Ничего из отказавшего не тронуто.")
        return 1
    print("\n⚖️ ГРАНИЦА: перенос обезличил ПУТИ. Что содержимое верно по существу —"
          " он не знает и не обещает; прогон шаблона по-прежнему за человеком.")
    return 0


def inside_dir(folder, name):
    """Путь внутри каталога — отдельной функцией, чтобы имя с подкаталогом тоже работало."""
    return Path(folder) / name


def scripts_in(root):
    """Все .py ПОД каталогом, ключ — путь ОТНОСИТЕЛЬНО корня.

    🔴 БЫЛО `glob("*.py")` — только верхний уровень (замер COORD 08.08 15:06 UTC).
    Из-за этого каталог `migrations/` не сверялся ВООБЩЕ: в репозитории-бэкапе лежала
    ОДНА миграция из пяти, а четыре сегодняшних правки схемы существовали в единственном
    экземпляре — и проверка при этом печатала «рантайм и копия идентичны».
    🎯 Класс ровно тот, ради которого эта проверка и заведена: вторая копия, которую считают
    точной. Она честно следила за ТОЙ ЧАСТЬЮ, которую видела, и молчала про остальное — а молчание
    неотличимо от «там всё в порядке».
    ⚠️ Ключ — ОТНОСИТЕЛЬНЫЙ ПУТЬ, а не имя: одноимённые файлы в разных каталогах иначе
    схлопнутся в один, и расхождение спрячется за совпадением имён.
    """
    return {p.relative_to(root).as_posix(): p
            for p in root.rglob("*.py") if "__pycache__" not in p.parts}


def report_pair(left, right, left_name, right_name, whose):
    """Показать расхождение двух копий, НЕ трогая ни одну. Код возврата не меняет."""
    if not (left.exists() and right.exists()):
        print(f"\n⚠️ {left_name} ↔ {right_name}: каталога нет, сверка НЕ ВЫПОЛНЕНА "
              f"({left if not left.exists() else right})")
        return
    a, b = scripts_in(left), scripts_in(right)
    diff_raw = sorted(n for n in set(a) & set(b) if not filecmp.cmp(a[n], b[n], shallow=False))
    # Из расходящихся выделяем ОБЕЗЛИЧЕННЫЕ: совпадающие после приведения путей к заглушкам.
    # Это не разная работа, а публичность шаблона. Молчать о них всё равно нельзя: роль,
    # скопировавшая команду ИЗ ШАБЛОНА, получит невыполнимую строку.
    sanitized = [n for n in diff_raw if sha_sanitized(a[n]) == sha_sanitized(b[n])]
    diff = [n for n in diff_raw if n not in set(sanitized)]
    # 🔴 БЫЛО: сверялось ТОЛЬКО пересечение, и файл, лежащий лишь в одной копии,
    # расхождением не считался ВООБЩЕ (замер COORD 2026-08-09: положил новую приёмку
    # в vnext-tools — проверка напечатала «42 общих совпадают» и была формально права).
    # 🎯 Это самая острая форма класса, ради которого проверка заведена: у потребителя файла
    # НЕТ ВОВСЕ, а сверка молчит — «сдано у автора ≠ доступно потребителю» (@RCC #3338).
    # ⚠️ И односторонний файл опаснее расходящегося: расходящийся хотя бы откроется.
    # ⚖️ СВОЙСТВО ПАРЫ АСИММЕТРИЧНО — правка @COORD 2026-08-09 по замеру @PROTO (записка #3471).
    # Прошлая моя редакция кричала на ОБЕ стороны одинаково, и это гнало к настоящей поломке:
    # @PROTO, увидев красное, перенёс 14 файлов из шаблона в рабочий каталог — ДЕВЯТЬ из них
    # там не работают вовсе (строят стенд из схемы, лежащей рядом с шаблоном). Он откатил сам.
    # 🎯 Зеркало ради молчания проверки кладёт потребителю падающие инструменты, и проверка довольна.
    #    left  = ПОТРЕБИТЕЛЬ (рабочий каталог, откуда роль берёт инструмент)
    #    right = ШАБЛОН (источник раскатки; полнее по построению — это НОРМА)
    only_a = sorted(set(a) - set(b))   # 🔴 есть у потребителя, в шаблоне нет ⇒ НЕ ДОЕДЕТ
    only_b = sorted(set(b) - set(a))   # ✅ есть только в шаблоне ⇒ норма, молчим
    if sanitized:
        print("")
        print(f"📝 {left_name} ↔ {right_name}: обезличено {len(sanitized)} — совпадают"
              f" с точностью до путей (в шаблоне заглушки, у потребителя настоящие)")
        print("   ⚖️ Это НЕ расхождение работы. Но роль, копирующая команду ИЗ ШАБЛОНА,"
              " получит невыполнимую строку — заглушку подставляет человек.")
    if not (diff or only_a):
        tail = f" · шаблон полнее на {len(only_b)} — это НОРМА" if only_b else ""
        print(f"\n✅ {left_name} ↔ {right_name}: {len(set(a) & set(b))} общих совпадают, "
              f"не доедет — ноль{tail}")
        print("   ⚖️ ГРАНИЦА: сверены ФАЙЛЫ. Совпадение байтов НЕ означает, что копии "
              "равносильны — инструмент зависит от того, что лежит рядом с ним "
              "(замер @PROTO: каталоги совпали файл в файл, а прогоны дали разное). "
              "Работоспособность доказывается только ПРОГОНОМ обеих.")
        return
    if only_a:
        print(f"\n⚠️ {left_name} ↔ {right_name}: НЕ ДОЕДЕТ ДО ПОТРЕБИТЕЛЯ ({len(only_a)}) — "
              f"есть в «{left_name}», в шаблоне «{right_name}» НЕТ. Чинит {whose}, не этот гард")
        for n in only_a[:8]:
            print(f"   🔴 {n}")
        if len(only_a) > 8:
            print(f"   … ещё {len(only_a) - 8}")
        print("   ⛔ ЛЕЧИТЬ ТОЛЬКО В ОДНУ СТОРОНУ: рабочий → шаблон. Обратный перенос "
              "«чтобы проверка замолчала» кладёт потребителю то, что рядом с ним не работает.")
    if only_b:
        print(f"   ✅ и {len(only_b)} есть только в шаблоне — НОРМА, шаблон полнее по построению")
    if not diff:
        return
    print(f"\n⚠️ {left_name} ↔ {right_name}: РАСХОДЯТСЯ {len(diff)} из {len(set(a) & set(b))} общих "
          f"— чинит {whose}, не этот гард")
    for n in diff[:8]:
        newer = left_name if a[n].stat().st_mtime > b[n].stat().st_mtime else right_name
        # ⚖️ ЧЕМ расходятся — строками ПО СУЩЕСТВУ, а не только байтами (карточка #244,
        # правило bytes-are-not-content): «46753б ≠ 46767б» не говорит читающему, правка
        # это или окончания строк, и разбор занимал 15 минут руками при одном различии.
        # Различий больше, чем строк в файле, — признак, что сверка сравнивает не то.
        # ⚠️ КАРТОЧКА #625: число ниже — НЕ построчный zip (тот считает по ПОЗИЦИИ и
        # сходит с ума на одной вставленной строке), а difflib-разбор _line_diff_count().
        a_lines = _sanitized_lines(a[n])
        b_lines = _sanitized_lines(b[n])
        changed_lines = _line_diff_count(a_lines, b_lines)
        print(f"   {n:30} {a[n].stat().st_size:6}б ≠ {b[n].stat().st_size:6}б   "
              f"свежее: {newer} · строк по существу: {changed_lines}")
    if len(diff) > 8:
        print(f"   … ещё {len(diff) - 8}")
    print("   👉 роль идёт за инструментом ПО ПУТИ ИЗ СВОЕЙ ПАМЯТИ: сдано у автора ≠ доступно ей")


