def check_shared_helpers() -> int:
    """ТРЕТЬЯ ПАРА КОПИЙ: файлы с ОДНИМ ИМЕНЕМ в двух рабочих каталогах контура.

    🩸 НАЙДЕНО 2026-09-06 (карточка #578) нарочной поломкой: копия инструмента на временном
    каталоге напечатала СТАРЫЙ текст отказа. Оказалось, у инструментов v-next своя копия
    разрешателя путей, отставшая на 17 суток, и её зовут 136 из 192 — то есть починка
    в каталоге контура до них не доезжала вовсе.
    ⚡ Почему это не ловила ни одна прежняя сверка: они знают пары «рантайм ↔ зеркало»
    и «v-next ↔ образец». Файл, живущий в ОБЕИХ парах разными копиями, не сравнивается
    сам с собой ни в одной из них — молчание по построению, а не по недосмотру.
    ⚖️ ВЕДУЩАЯ СТОРОНА У КАЖДОГО ФАЙЛА СВОЯ, и это главное, что показал замер: у одного
    новее копия контура, у другого — копия v-next (там работа по карточке #572). Свести
    «в одну сторону» значило бы стереть одну из двух работ. Поэтому проверка НЕ сводит
    сама и не советует направления: она говорит, ЧТО разошлось, а решает человек.
    ⛔ ГРАНИЦА: сверяются БАЙТЫ файлов с совпадающим именем. Разные имена одного и того же
    помощника (переименованная копия) не ловятся — их не с чем сравнить.
    """
    if not (RUNTIME.is_dir() and VNEXT_RUNTIME and VNEXT_RUNTIME.is_dir()):
        return 0
    common = sorted({p.name for p in RUNTIME.glob("*.py")}
                    & {p.name for p in VNEXT_RUNTIME.glob("*.py")})
    if not common:
        print("📎 общие помощники двух рабочих каталогов: файлов с общим именем НЕТ")
        return 0
    diverged = [n for n in common
                if not filecmp.cmp(RUNTIME / n, VNEXT_RUNTIME / n, shallow=False)]
    if not diverged:
        print(f"✅ общие помощники двух рабочих каталогов: {len(common)} совпадают байт в байт")
        return 0
    print("")
    print(f"⛔ ОБЩИЕ ПОМОЩНИКИ РАСХОДЯТСЯ ({len(diverged)} из {len(common)}) — "
          f"инструменты двух каталогов работают РАЗНЫМ кодом под одним именем:")
    for n in diverged:
        a, b = RUNTIME / n, VNEXT_RUNTIME / n
        print(f"   {n:22} контур {sha(a)} ({a.stat().st_size}б) ≠ "
              f"v-next {sha(b)} ({b.stat().st_size}б)")
    print("   👉 сведи их ОДНОЙ версией (у каждого файла своя ведущая сторона — смотри "
          "глазами, автоматом не сводим) и повтори прогон")
    return len(diverged)


