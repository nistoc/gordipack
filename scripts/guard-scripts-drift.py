def scripts_in(root):
    """Все .py ПОД каталогом, ключ — путь ОТНОСИТЕЛЬНО корня.

    🔴 БЫЛО `glob("*.py")` — только верхний уровень (замер COORD 08.08 15:06 UTC).
    Из-за этого каталог `migrations/` не сверялся ВООБЩЕ: в репозитории-бэкапе лежала
    ОДНА миграция из пяти, а четыре сегодняшних правки схемы существовали в единственном
    экземпляре — и проверка при этом печатала «рантайм и копия идентичны».
    🎯 Класс ровно тот, ради которого эта проверка и заведена: вторая копия, которую считают
    точной. Она честно следила за ТОЙ ЧАСТЬЮ, которую видела, и молчала про остальное — а молчание
    неотличимо от «там всё в порядке».
    ⚠️ Ключ — ОТНОСИТЕЛЬНЫЙ ПУТЬ, а не имя: одноимённые файлы в разных каталогах иначе
    схлопнутся в один, и расхождение спрячется за совпадением имён.
    """
    return {p.relative_to(root).as_posix(): p
            for p in root.rglob("*.py") if "__pycache__" not in p.parts}


def report_pair(left, right, left_name, right_name, whose):
    """Показать расхождение двух копий, НЕ трогая ни одну. Код возврата не меняет."""
    if not (left.exists() and right.exists()):
        print(f"\n⚠️ {left_name} ↔ {right_name}: каталога нет, сверка НЕ ВЫПОЛНЕНА "
              f"({left if not left.exists() else right})")
        return
    a, b = scripts_in(left), scripts_in(right)
    diff_raw = sorted(n for n in set(a) & set(b) if not filecmp.cmp(a[n], b[n], shallow=False))
    # Из расходящихся выделяем ОБЕЗЛИЧЕННЫЕ: совпадающие после приведения путей к заглушкам.
    # Это не разная работа, а публичность шаблона. Молчать о них всё равно нельзя: роль,
    # скопировавшая команду ИЗ ШАБЛОНА, получит невыполнимую строку.
    sanitized = [n for n in diff_raw if sha_sanitized(a[n]) == sha_sanitized(b[n])]
    diff = [n for n in diff_raw if n not in set(sanitized)]
    # 🔴 БЫЛО: сверялось ТОЛЬКО пересечение, и файл, лежащий лишь в одной копии,
    # расхождением не считался ВООБЩЕ (замер COORD 2026-08-09: положил новую приёмку
    # в vnext-tools — проверка напечатала «42 общих совпадают» и была формально права).
    # 🎯 Это самая острая форма класса, ради которого проверка заведена: у потребителя файла
    # НЕТ ВОВСЕ, а сверка молчит — «сдано у автора ≠ доступно потребителю» (@RCC #3338).
    # ⚠️ И односторонний файл опаснее расходящегося: расходящийся хотя бы откроется.
    # ⚖️ СВОЙСТВО ПАРЫ АСИММЕТРИЧНО — правка @COORD 2026-08-09 по замеру @PROTO (записка #3471).
    # Прошлая моя редакция кричала на ОБЕ стороны одинаково, и это гнало к настоящей поломке:
    # @PROTO, увидев красное, перенёс 14 файлов из шаблона в рабочий каталог — ДЕВЯТЬ из них
    # там не работают вовсе (строят стенд из схемы, лежащей рядом с шаблоном). Он откатил сам.
    # 🎯 Зеркало ради молчания проверки кладёт потребителю падающие инструменты, и проверка довольна.
    #    left  = ПОТРЕБИТЕЛЬ (рабочий каталог, откуда роль берёт инструмент)
    #    right = ШАБЛОН (источник раскатки; полнее по построению — это НОРМА)
    # ⚡ С Э4 (карточка #678, Ш3) right — клон ПАКЕТА, единственного источника, а left — его
    # установленная копия. Прежнее «не доедет — перенеси рабочий → шаблон» потеряло смысл: переноса
    # нет. Файл только у контура — СОЗДАН МИМО ПАКЕТА (его не обновит и не доставит никто), а
    # расхождение общего файла — либо правка мимо пакета, либо клон новее установленного: что
    # именно, отвечает план update-tools.py по отпечаткам установки, а не этот разбор по байтам.
    only_a = sorted(set(a) - set(b))   # 🔴 есть у контура, в пакете нет ⇒ создан мимо пакета
    only_b = sorted(set(b) - set(a))   # ✅ есть только в пакете ⇒ норма, молчим
    if sanitized:
        print("")
        print(f"📝 {left_name} ↔ {right_name}: обезличено {len(sanitized)} — совпадают"
              f" с точностью до путей (в шаблоне заглушки, у потребителя настоящие)")
        print("   ⚖️ Это НЕ расхождение работы. Но роль, копирующая команду ИЗ ШАБЛОНА,"
              " получит невыполнимую строку — заглушку подставляет человек.")
    if not (diff or only_a):
        tail = (f" · в пакете ещё {len(only_b)}, которых у контура нет — это НОРМА"
                if only_b else "")
        print(f"\n✅ {left_name} ↔ {right_name}: {len(set(a) & set(b))} общих совпадают, "
              f"создано мимо пакета — ноль{tail}")
        print("   ⚖️ ГРАНИЦА: сверены ФАЙЛЫ. Совпадение байтов НЕ означает, что копии "
              "равносильны — инструмент зависит от того, что лежит рядом с ним "
              "(замер @PROTO: каталоги совпали файл в файл, а прогоны дали разное). "
              "Работоспособность доказывается только ПРОГОНОМ обеих.")
        return
    if only_a:
        print(f"\n⚠️ {left_name} ↔ {right_name}: СОЗДАНО МИМО ПАКЕТА ({len(only_a)}) — "
              f"есть в «{left_name}», в «{right_name}» (клон пакета) НЕТ. Решает {whose}, не эта проверка")
        for n in only_a[:8]:
            print(f"   🔴 {n}")
        if len(only_a) > 8:
            print(f"   … ещё {len(only_a) - 8}")
        print("   👉 такой файл обновление не обновит и потребителям не доставит. Нужен другим — "
              "заводи его в клоне пакета: commit → push → update-tools.py --rev <commit> --apply.")
        print("   ⛔ И обратно руками не докладывать: часть файлов пакета работает только рядом с его "
              "схемой и стендом — недостающее «чтобы проверка замолчала» кладёт то, что не работает.")
    if only_b:
        print(f"   ✅ и {len(only_b)} есть только в пакете — НОРМА: update-tools.py ставит во второй "
              f"каталог лишь те файлы, что там уже лежат")
    if not diff:
        return
    print(f"\n⚠️ {left_name} ↔ {right_name}: РАСХОДЯТСЯ {len(diff)} из {len(set(a) & set(b))} общих "
          f"— решает {whose}, не эта проверка")
    print("   ⚖️ Правлен мимо пакета или клон новее установленного — отвечает план update-tools.py "
          "(«✋ правлен у тебя» / «≠ обновится»), а не сличение байтов")
    for n in diff[:8]:
        newer = left_name if a[n].stat().st_mtime > b[n].stat().st_mtime else right_name
        # ⚖️ ЧЕМ расходятся — строками ПО СУЩЕСТВУ, а не только байтами (карточка #244,
        # правило bytes-are-not-content): «46753б ≠ 46767б» не говорит читающему, правка
        # это или окончания строк, и разбор занимал 15 минут руками при одном различии.
        # Различий больше, чем строк в файле, — признак, что сверка сравнивает не то.
        # ⚠️ КАРТОЧКА #625: число ниже — НЕ построчный zip (тот считает по ПОЗИЦИИ и
        # сходит с ума на одной вставленной строке), а difflib-разбор _line_diff_count().
        a_lines = _sanitized_lines(a[n])
        b_lines = _sanitized_lines(b[n])
        changed_lines = _line_diff_count(a_lines, b_lines)
        print(f"   {n:30} {a[n].stat().st_size:6}б ≠ {b[n].stat().st_size:6}б   "
              f"свежее: {newer} · строк по существу: {changed_lines}")
    if len(diff) > 8:
        print(f"   … ещё {len(diff) - 8}")
    print("   👉 роль идёт за инструментом ПО ПУТИ ИЗ СВОЕЙ ПАМЯТИ: правка в клоне ≠ установлено у неё")


