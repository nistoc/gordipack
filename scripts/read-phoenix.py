            # ── §4⅞ СЛОЙ ДИСКА — ЗАКРЫВАЕТ ГРАНИЦУ «ЗНАЮ БАЗУ, НЕ ЗНАЮ ДИСК» ──
            # Написан ЧУЖОЙ рукой (@opssre #3445, `6f96fde`), врезан по слову владельца
            # 2026-08-09 13:24 UTC. Повод замером, не опасением: факты о диске роли хранили
