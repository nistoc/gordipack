"""Показ времени читающими инструментами: «<час> UTC (<час> местное)».

ЕДИНСТВЕННОЕ место конвертации времени в контуре (карточка #384).

Слово владельца (чат COORD 29.08.2026 11:59 UTC; уточнение 12:08 UTC «брать местное
время машины, где запускается скрипт»; чат PROTO 12:16 UTC «часовой пояс из host OS
получать самостоятельно, а не хардкодить; смещение зимой и летом показывать не надо,
текущее локальное время с учётом смещения показывать надо»):
  · рядом с UTC — местное время МАШИНЫ ЗАПУСКА; зону даёт host OS, не настройка и не хардкод;
  · смещение считается НА ДАТУ ЗАПИСИ (лето/зима — сами; хардкод +02:00 зимой врал бы на час);
  · само смещение не печатается — печатается местный час.

История, которую эта правка НЕ отменяет: правило timestamp-utc-in-sqlite (v2, 16.07.2026)
сняло конвертацию вовсе — две шкалы породили фантом «синк умер 2 часа назад». Возврат
скобок — НЕ возврат двух шкал: хранение и записки — только UTC; скобки живут только
в ПОКАЗЕ читающих инструментов и всегда стоят РЯДОМ с UTC, а не вместо него.
⚠️ Принятая цена (названа в карточке #384 вслух): на чужой машине (облако, конвейер)
в скобках будет час ТОЙ машины — это решение владельца, а не недосмотр.

guard-utc пропускает astimezone ТОЛЬКО в этом файле — поимённо и вслух; в любом
другом файле конвертация в местное время по-прежнему краснит.
"""
from datetime import datetime, timezone


def utc_to_local(s, tz=None):
    """'YYYY-MM-DD HH:MM[:SS[.ffffff]]' (UTC из базы) → «<как было> UTC (<HH:MM> местное)».

    tz нужен ТОЛЬКО приёмке (обратный ход: подменённая зона обязана менять скобки,
    а лето и зима — считаться от ДАТЫ записи); в бою tz=None = зона host OS.
    Непарсибельная метка честно остаётся «<как было> UTC» без скобок: солгать
    скобками хуже, чем не показать местное."""
    if not s:
        return "—"
    txt = str(s).strip()
    try:
        dt = datetime.fromisoformat(txt).replace(tzinfo=timezone.utc)
        loc = dt.astimezone(tz)  # None → системная зона машины запуска, НА ДАТУ записи
    except (ValueError, OSError, OverflowError):
        return f"{txt} UTC"
    if loc.date() != dt.date():  # местные сутки сменились — час без даты соврал бы
        return f"{txt} UTC ({loc.strftime('%d.%m %H:%M')} местное)"
    return f"{txt} UTC ({loc.strftime('%H:%M')} местное)"
