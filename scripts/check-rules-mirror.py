r"""
check-rules-mirror.py — ФАЙЛ С ПРАВИЛАМИ ОТСТАЛ ОТ БАЗЫ.

═══ ЗАЧЕМ ═══
Правила живут в таблице `rules`. Рядом лежит человекочитаемый файл, собранный из неё
`export-rules.py`, — чтобы человек читал глазами. Файл не лжёт сам по себе. Он лжёт,
когда ОТСТАЁТ, и читающий принимает вчерашнее за действующее, не зная об этом.
```
07.08 — отстал на ТРИ версии правила за четыре часа
ранее — ПЯТЬ ЧАСОВ держал отменённое как действующее (записано в шапке самого сборщика)
27.07 — контур-родитель: генератор не звали 11 суток, зеркало отстало на три ревизии
        САМОГО ЧИТАЕМОГО правила свода — нашлось случайно, когда попросили дописать одно
```
Слово владельца 2026-08-07 13:40 UTC: файл и ссылки на него ОСТАЮТСЯ, но обновляться должен
при любом изменении правил в базе.

═══ ПОЧЕМУ ЭТА ПРОВЕРКА НУЖНА ОТДЕЛЬНО ОТ АВТОПЕРЕСБОРКИ ═══
Автопересборка (`set-rule.py --apply` зовёт генератор сам) — правильный первый ход, но она
может НЕ СРАБОТАТЬ МОЛЧА: упасть на полпути, быть обойдённой прямой правкой базы, отвалиться
при переносе инструмента. Тогда всё выглядит исправным, а файл вчерашний — и это худший исход.
⇒ Первый механизм закрывает ОДИН путь (мимо `set-rule.py`), эта проверка отвечает на вопрос
«сошлось ли на самом деле» для ЛЮБОГО пути — прямой SQL, восстановление базы, чужая рука.

═══ ЧТО СВЕРЯЕТСЯ (и всё — ПОИМЁННО; «файл устарел» без перечня равно молчанию) ═══
    · правило есть в базе, но его НЕТ в файле
    · правило есть в обоих, но в файле версия СТАРШЕ
    · версии равны, а ТЕКСТ различается — правка прошла мимо номера версии
    · правило осталось в файле, а из базы удалено

═══ ГДЕ ИЩЕТСЯ ФАЙЛ-ЗЕРКАЛО (карточка #618 — единая редакция для scripts, vnext-tools и пакета) ═══
mezo_paths.py не заводит понятия «каталог координации/генерации» — свой список раскладок
здесь не выдуман заново, а взят у СОСЕДА: `export-rules.py` (его `_default_out`) уже решает
этот же вопрос при ЗАПИСИ файла. Та же пара мест, здесь — для ЧТЕНИЯ (ищем оба по порядку,
а не выбираем один заранее):
    ① раскладка контура-автора (Atlas) — файл рядом с человеческой координацией,
       <контейнер>/atlas.archs/.mezosync/coordination/sync.rules.md;
    ② раскладка новорождённого контура (собран из пакета) — файл рядом с базой,
       <MEZO>/generated/sync.rules.md.
Прежде копия в scripts знала только ②, а копия в vnext-tools — только ①, да ещё и не от
СВОЕГО `--db`: она искала от НАЙДЕННОГО КОНТЕЙНЕРА, так что явный `--db` в другую раскладку
её не переубеждал. Отсюда и разъезд: под одним и тем же контуром одна копия отказывала
«сверить нечем», другая молча проходила — обе были правы про СВОЙ единственный литерал
и обе не знали про раскладку соседа. Ни та, ни другая раскладка здесь не в приоритете —
берётся первая, что НАЙДЕНА; если её сборка сменит порядок кандидатов на «только одно
место», отказ у контура из другой раскладки вернётся (см. bite-rules-mirror-search.py).

СВЕЖАЯ СИСТЕМА. Если правил НЕТ и файла НЕТ ни в одном известном месте — сверять нечего,
проверка пропускается с пометкой и НЕ краснит. Но если правила ЕСТЬ, а файла нет нигде —
это «сверить НЕЧЕМ», и это красное: правила существуют, а прочитать их глазами нельзя.

ЗАПУСК:
    python check-rules-mirror.py                    # пути по умолчанию (ищет по обеим раскладкам)
    python check-rules-mirror.py --db … --file …    # явный путь — поиск не нужен (проверки на копии)
ВЫХОД: 0 — сошлось или сверять нечего (свежий контур) · 1 — расхождения или файл не найден
       ни в одной раскладке при живых правилах («сверить нечем») · 2 — не смог прочитать базу
"""

import argparse
import re
import sqlite3
import sys
from pathlib import Path

import mezo_paths  # пути контура выводятся, не впечатаны (#153, донесено #618)

LIVE = mezo_paths.live_db()

# Заголовок правила в файле: ### `ключ` 🔒замок vN  (с возможной пометкой отзыва)
# 🪤 КЛЮЧ — ЛЮБОЙ ТЕКСТ В ОБРАТНЫХ КАВЫЧКАХ, а не только латиница.
#    Первая редакция требовала [a-z0-9-]+ — и правило с ключом из кириллицы (или с прописной
#    буквой, или с подчёркиванием) НЕ РАСПОЗНАВАЛОСЬ в файле. Проверка вечно объявляла такое
#    правило пропавшим: ложное КРАСНОЕ, которое ничем не лечится и к которому привыкают.
# 🩸 ЗАМОК БЫВАЕТ ДАТИРОВАННЫМ («owner-2026-07-29»): прежний `🔒(\w+)` не брал дефис, и такой
#    заголовок не распознавался вовсе — «ЕСТЬ В БАЗЕ, НЕТ В ФАЙЛЕ» на исправном файле (найдено
#    контуром AIA, 13.09). [\w:.-] берёт дефис, точку и двоеточие — формы замков, встреченные
#    в живых правилах (`owner`, `coord`, `owner-2026-07-29`). Приёмка bite-check-rules-mirror.py
#    испытывает обе копии этой строки.
HEAD = re.compile(r"^###\s+(?:⛔\s*\*\*ОТОЗВАНО\*\*\s*)?`([^`\n]+)`\s*🔒([\w:.-]+)\s*v(\d+)\s*$",
                  re.M)


def mirror_candidates(mezo: Path) -> list[Path]:
    """Известные места файла-зеркала, БЕЗ литерала под один контур (карточка #618).

    `mezo` — каталог, ГДЕ ЛЕЖИТ база (…/.mezosync), не каталог-контейнер: та же точка
    отсчёта, что у `_default_out` в export-rules.py, который ЭТИМ же списком решает,
    куда файл ПИСАТЬ. Здесь — для ЧТЕНИЯ: возвращаем ОБА кандидата по порядку важности
    раскладки контура-автора, а не выбираем один заранее.
    """
    return [
        mezo.parent / "atlas.archs" / ".mezosync" / "coordination" / "sync.rules.md",
        mezo / "generated" / "sync.rules.md",
    ]


def find_mirror(mezo: Path) -> Path:
    """Первый СУЩЕСТВУЮЩИЙ кандидат; ни одного — последний по списку (чтобы отказ ниже
    назвал ОЖИДАЕМОЕ место, а не промолчал о том, где искала)."""
    candidates = mirror_candidates(mezo)
    return next((c for c in candidates if c.exists()), candidates[-1])


def same_bytes(a: bytes, b: bytes) -> bool:
    """Содержимое, а не байты дословно: перевод строк CRLF/LF не считаем расхождением
    (правило bytes-are-not-content — тот же приём, что у update-tools.py: same_text)."""
    return a.replace(b"\r\n", b"\n") == b.replace(b"\r\n", b"\n")


def stale_mirror_note(candidates: list, chosen: Path):
    """ЗАМЕЧАНИЕ COORD (карточка #618, повторная приёмка, принято 2026-09-14 17:58 UTC):
    если файл-зеркало есть в ОБЕИХ раскладках, судится по-прежнему ПЕРВЫЙ найденный
    (`chosen` — тот же, что вернул find_mirror) — эта функция ничего не меняет в выборе.
    Она только НАЗЫВАЕТ второго кандидата, если он ТОЖЕ существует и его содержимое
    ОТЛИЧАЕТСЯ от выбранного: раньше про такой отставший второй файл проверка молчала
    вовсе. Совпадающий второй файл — не беда (дубль, не расхождение), строки нет.
    Предупреждение — код выхода НЕ МЕНЯЕТ, сверяется по-прежнему только `chosen`."""
    lines = []
    for other in candidates:
        if other == chosen or not other.exists():
            continue
        if not same_bytes(other.read_bytes(), chosen.read_bytes()):
            lines.append(f"⚠️  есть и второй файл: {other} — не сверялся (отличается от "
                        f"выбранного {chosen})")
    return "\n".join(lines) if lines else None


def from_db(db: Path):
    if not db.exists():
        return None
    con = sqlite3.connect(f"file:{db.as_posix()}?mode=ro", uri=True)
    con.execute("PRAGMA query_only=ON")
    try:
        rows = con.execute("SELECT rule_key, body, version FROM rules").fetchall()
    except sqlite3.OperationalError:
        con.close()
        return {}                     # свежая база без таблицы `rules` — не повод падать
    con.close()
    return {k: (int(v), (b or "").strip()) for k, b, v in rows}


def from_file(path: Path):
    """{ключ: (версия, текст)} — текст берётся до следующего заголовка того же уровня."""
    text = path.read_text(encoding="utf-8", errors="replace")
    heads = list(HEAD.finditer(text))
    out = {}
    # ⚡ ГРАНИЦА ТЕЛА — СЛЕДУЮЩЕЕ ПРАВИЛО, А НЕ СЛЕДУЮЩИЙ ЗАГОЛОВОК КАКОГО-ЛИБО УРОВНЯ.
    # 🩸 Это ТРЕТЬЯ редакция места, и первые две — качель, оплаченная дважды:
    # ```
    # ① граница = первый `^## `   → обрывалась на подзаголовке ВНУТРИ правила (1699 → 481)
    # ② граница = любой `^### `   → обрывалась на подзаголовке третьего уровня (4550 → 2442)
    # ```
    # Второй случай принёс @COORD (записка #3762) и показал худшее: у правила с внутренним
    # `###` проверка перестаёт РАЗЛИЧАТЬ состояния — она красная и при совпадении текста,
    # и при настоящем расхождении. К вечно-красному привыкают, и следующее, уже настоящее,
    # прочтут как привычное.
    # 📏 ЗАМЕР, КОТОРЫЙ РЕШИЛ СПОР (PROTO 2026-08-24 16:52 UTC, по живому своду):
    # ```
    # заголовков `## `  — 14, ВНУТРИ тел правил 13   ⇒ резать по ним нельзя
    # заголовков `### ` — 76, ВНУТРИ тел правил 12   ⇒ и по ним нельзя
    # правил (шаблон HEAD) — 64                       ⇒ а вот он различает
    # ```
    # ⚠️ Отсюда же видно, почему предложенная починка «HEAD либо `^## `» не годилась:
    # она вернула бы ошибку ①, потому что почти все `## ` живут ВНУТРИ тел.
    for i, m in enumerate(heads):
        if i + 1 < len(heads):
            end = heads[i + 1].start()
        else:
            # ⚖️ ПОСЛЕДНЕЕ ПРАВИЛО: за ним идут разделы файла (инварианты, пояснение
            #    про генерацию) — их заголовки верхнего уровня стоя́т ПОСЛЕ всех правил.
            #    Без этой ветки последнее правило вбирало бы их целиком (замер: 2545 знаков
            #    тела против 10338 знаков хвоста).
            #    ⛔ ЗНАЕМ, ЧТО НЕ ЛОВИМ: если однажды внутри ПОСЛЕДНЕГО правила появится
            #    свой `## `, тело обрежется рано. Беда будет ГРОМКОЙ — проверка покраснеет
            #    расхождением с базой, а не промолчит; тихой она была именно в редакциях ①②.
            tail = re.search(r"^##\s(?!#)", text[m.end():], re.M)
            end = m.end() + tail.start() if tail else len(text)
        body = text[m.end():end]
        # 🪤 РЕЖЕМ ПО СЛЕДУЮЩЕМУ ПРАВИЛУ, А НЕ ПО ПЕРВОМУ ЖЕ «## ».
        #    Первая редакция обрывала тело на первом заголовке второго уровня — а такие
        #    заголовки есть ВНУТРИ самих правил. Из тела в 1699 знаков оставалось 481,
        #    и проверка объявила расхождение там, где текст совпадал полностью.
        #    ⇒ Ложное обвинение файла. Поймано тем, что я посмотрел РАЗНИЦУ, прежде чем
        #      объявить находку: «нашлось 2 расхождения» звучало убедительно и было ложью.
        #    Заголовок раздела, если он стоит перед следующим правилом, — не часть тела:
        #    снимаем его с хвоста, но только с хвоста.
        lines = body.rstrip().split("\n")
        while lines and (lines[-1].startswith("## ") or not lines[-1].strip()):
            lines.pop()
        out[m.group(1)] = (int(m.group(3)), "\n".join(lines).strip())
    return out


def norm(s: str) -> str:
    """Сравниваем по существу: пробелы и пустые строки не считаем расхождением."""
    return re.sub(r"\s+", " ", s).strip()


def main() -> int:
    ap = argparse.ArgumentParser(description="файл с правилами отстал от базы")
    ap.add_argument("--db", default=str(LIVE),
                    help="база с правилами; иная — только для проверок на копии")
    ap.add_argument("--file", default=None,
                    help="файл-зеркало; по умолчанию ищется по обеим раскладкам контура (#618)")
    ap.add_argument("--quiet", action="store_true", help="молчать, когда всё сошлось")
    args = ap.parse_args()

    db_path = Path(args.db)
    db = from_db(db_path)
    if db is None:
        print(f"⛔ не нашёл базу: {args.db}")
        return 2

    mezo = db_path.resolve().parent               # каталог, где лежит база (…/.mezosync)
    if args.file:
        path = Path(args.file)
        searched = [path]
    else:
        searched = mirror_candidates(mezo)
        path = find_mirror(mezo)

    if not path.exists():
        if not db:
            print(f"⏭️  зеркало правил — пропущено: правил нет и файла нет "
                  f"(искал: {', '.join(str(c) for c in searched)})")
            return 0            # свежая система: сверять нечего, и это не поломка
        print(f"⛔ ЗЕРКАЛО ПРАВИЛ: правил в базе {len(db)}, а файла НЕТ ни в одном "
              f"известном месте:")
        for c in searched:
            print(f"   · {c}")
        print("   ⇒ это НЕ «сошлось», а «сверить НЕЧЕМ»: правила есть, прочитать их глазами нельзя.")
        print(f"   Собрать: python {Path(__file__).resolve().parent / 'export-rules.py'} "
              f"--db {args.db} --apply")
        return 1

    # ЗАМЕЧАНИЕ COORD (карточка #618): второй файл-зеркало, если он тоже есть и отличается
    # от выбранного, — назвать одной строкой, а не молчать. Судится по-прежнему `path`
    # (chosen) — код выхода эта строка не меняет, это предупреждение.
    stale = stale_mirror_note(searched, path)
    if stale:
        print(stale)

    mirror = from_file(path)

    missing = sorted(k for k in db if k not in mirror)
    extra = sorted(k for k in mirror if k not in db)
    older = sorted(k for k in db if k in mirror and mirror[k][0] < db[k][0])
    newer = sorted(k for k in db if k in mirror and mirror[k][0] > db[k][0])
    # 🪤 СРАВНИВАЕМ ПО НАЧАЛУ, А НЕ ПО РАВЕНСТВУ — и это не послабление, а точность.
    #    Сборщик пишет тело правила ДОСЛОВНО, а следом — своё оформление файла (заголовки
    #    разделов, врезки). Требование полного равенства объявляло расхождением именно это
    #    оформление: три «находки» подряд оказались ошибками разбора, а не расхождением
    #    файла. Проверка, чьи находки все до одной ложные, хуже отсутствующей — ей поверят
    #    один раз, потом перестанут.
    #    Что при этом НЕ теряется: если текст правила изменён в базе — начало разойдётся,
    #    и находка останется настоящей. Проверено встречным случаем в bite-rules-mirror.py.
    drift = sorted(k for k in db if k in mirror and mirror[k][0] == db[k][0]
                   and not norm(mirror[k][1]).startswith(norm(db[k][1])))

    if not args.quiet:
        print("ПРОВЕРКА: файл с правилами против базы")
        print(f"  база ..... {len(db)} правил")
        print(f"  файл ..... {len(mirror)} правил   {path}")

    problems = 0
    if missing:
        problems += len(missing)
        print(f"\n🔴 ЕСТЬ В БАЗЕ, НЕТ В ФАЙЛЕ — {len(missing)}")
        for k in missing:
            print(f"   · {k}  (в базе v{db[k][0]})")
        print("   ⇒ читающий файл НЕ ЗНАЕТ об этих правилах вовсе")
    if older:
        problems += len(older)
        print(f"\n🔴 В ФАЙЛЕ ВЕРСИЯ СТАРШЕ — {len(older)}")
        for k in older:
            print(f"   · {k}:  файл v{mirror[k][0]} · база v{db[k][0]}")
        print("   ⇒ читающий видит прежнюю редакцию и принимает её за действующую")
    if drift:
        problems += len(drift)
        print(f"\n🔴 ВЕРСИИ РАВНЫ, А ТЕКСТ РАЗНЫЙ — {len(drift)}")
        for k in drift:
            print(f"   · {k} (v{db[k][0]}) — правка прошла мимо номера версии")
    if extra:
        problems += len(extra)
        print(f"\n⚠️  ОСТАЛОСЬ В ФАЙЛЕ, УДАЛЕНО ИЗ БАЗЫ — {len(extra)}")
        for k in extra:
            print(f"   · {k}")
    if newer:
        problems += len(newer)
        print(f"\n⚠️  В ФАЙЛЕ ВЕРСИЯ НОВЕЕ, ЧЕМ В БАЗЕ — {len(newer)}")
        for k in newer:
            print(f"   · {k}:  файл v{mirror[k][0]} · база v{db[k][0]}")
        print("   ⇒ так не бывает при обычной работе: файл правили руками либо база откатилась")

    if problems:
        print(f"\nИТОГ: 🔴 РАСХОЖДЕНИЙ {problems}. Пересобрать: python "
              f"{Path(__file__).resolve().parent / 'export-rules.py'} --db {args.db} --apply")
        return 1
    if not args.quiet:
        print("\nИТОГ: ✅ СОШЛОСЬ — файл показывает то же, что база")
    return 0


if __name__ == "__main__":
    sys.exit(main())
