    # (до этого держался вне набора: привычное красное хуже отсутствующего).
    sub_guard("заглушки", "guard-stub-expectations.py", skip)
    # ⑬ метка-под-UTC — локальное время, подписанное словом «UTC», в слепках и НОТАХ.
    # Включён 2026-08-06 14:08 UTC. Инструмент в зоне @PROTO (vnext-tools), зову по пути.
    # 🪤 ЗАЧЕМ ЗДЕСЬ, А НЕ «когда вспомнят»: сторож существовал с 26.07 и ловил только тех, кто
    #    помнил его позвать. @TAXO 05.08 закрыла класс у себя ДИСЦИПЛИНОЙ (вписала шаг в слепок),
    #    @OPSSRE не знал, что должен, — и 06.08 повторил дефект дважды в одной ноте (#2958).
    #    Формула, которой это оплачено: СТОРОЖ ВНЕ ОБЩЕГО ПРОГОНА — НЕ СТОРОЖ, А ПАМЯТКА.
    # ⏱ ОКНО 24 ч — не вкус, а замер @PROTO (#2975) по всем девяти ролям:
    #    без окна 🔴19 у 4 ролей (история неустранима, ноты не переписываются) ⇒ прогон красный ВЕЧНО
    #    с окном  🔴 2 у 1 роли  (ровно свежий дефект)                        ⇒ отношение 1 : 18
    #    История не потеряна: тот же гард БЕЗ --since-hours отдаёт все 19.
    # ✅ Признак верности порога (назван @opssre, подтверждён числом @PROTO): общий прогон обязан
    #    быть ЗЕЛЁНЫМ у роли, которая СЕГОДНЯ ничего не нарушала. Станет красным у чистой — порог неверен.
    sub_guard("метка-под-UTC", None, skip, "--since-hours", "24",
              script_path=tool("guard-phoenix-time.py"))

    # ②-бис ПЕРЕСКАЗ ИЗМЕРИМОГО — врезано 2026-08-09 по предложению @PROTO (записка #3479).
    # Признак не требует пометок: он ПЕРЕМЕРЯЕТ число запросом к базе и печатает обе стрелки
    # («в слепке 4, в базе 7»). Предмет — числа, которые база отвечает сама: карточки, правила,
    # шаги схемы; число ролей красное даже ВЕРНЫМ — канон запрещает держать его текстом.
    #
    # ⚖️ ЗОВЁТСЯ ЖЁЛТЫМ, А НЕ КРАСНЫМ, И ЭТО РЕШЕНИЕ, А НЕ ПОЛУМЕРА. Прогон до врезки дал
    # две находки, обе НАСТОЯЩИЕ и обе в ЧУЖОМ слепке (@ING: «ролей 8» при девяти) — то есть
    # красное, которое я не могу погасить своей рукой: слепки чужие, роль правит их сама.
    # 🎯 Мой же довод из сторожа копий: красное, которое некому погасить, приучает пролистывать
    # красное вообще — и первым будет пролистан настоящий свежий сигнал.
    # ⇒ Видно в выводе каждому, exit-код не трогает. Станет предметом СВОЕЙ зоны — подниму
    # до красного, и это будет замер, а не смена настроения.
    yellow_probe = tool("check-retold-numbers.py")
    if yellow_probe.exists() and "пересказ измеримого" not in skip:
        r = subprocess.run([sys.executable, str(yellow_probe)],
                           capture_output=True, text=True, encoding="utf-8", errors="replace")
        hits = [l for l in (r.stdout or "").splitlines() if l.startswith("🔴")]
        if hits:
            print(f"⚠️ пересказ измеримого: {len(hits) - 1 if len(hits) > 1 else len(hits)} "
                  f"— число в памяти роли разошлось с тем, что база отвечает запросом")
            for l in hits[:4]:
                print(f"   {l[:150]}")
            print("   👉 правит РОЛЬ-владелец слепка: чужую память чинить нельзя, "
                  "можно только показать")
        # 🪤 ЗДЕСЬ Я НАПИСАЛ `note(...)` И УРОНИЛ ВЕСЬ ПРОГОН — через час после того, как
        # чинил ровно этот класс по находке @PROTO (записка #3470). Функция называется
