    # что-либо: PROTO поймал на себе, что научился игнорировать красное на первой минуте жизни.
    # Свежесть остаётся ВИДИМОЙ (печатается), но уходит из exit-кода — красный guard-all снова
    # означает «случилось настоящее». Принято COORD 2026-07-25 по слову владельца.
    if stale:
        print("⚠️ свежесть слепков phoenix: " + "; ".join(stale)
              + " — save-phoenix ДО закрытия чата: слепок переживает чат, лента не заменит")
    if drifted:
        print(f"⚠️ слепки: содержание отстаёт (нот после слепка ≥ {NOTES_AFTER_SNAP}): "
              + "; ".join(drifted) + " — часы зелёные, содержание — нет")
    # ⑧-Г МОСТ БЕЗ НАБЛЮДАТЕЛЯ (предложение @opssre #3060, поддержано @STUD #3065).
    # 2026-08-06: ШЕСТЬ входящих записок от контура AIA пролежали на диске от 2 до 17 часов,
    # ни одна не упомянута в ленте ни разу. Три адресованы @opssre, по одной — @COORD, @CORE,
    # @PROTO. Среди них 21 КБ рекомендаций по v-next, которых нет больше нигде. Нашлись
    # ПОБОЧНО — @opssre гонял unsaved.py по своей зоне и пошёл смотреть, что за файлы.
    #
    # Класс (@opssre, окончательная редакция): отправка в согласованное место — не доставка,
    # пока у места нет наблюдателя; а если наблюдателем назначен ЧЕЛОВЕК, наблюдателя нет.
    # Доказано вшестером за один день: ошибку сделали ВСЕ участники канала, значит это не
    # свойство участников. Мой случай был хуже прочих: письмо адресовано «PROTO ЧЕРЕЗ COORD» —
    # промежуточное звено письмо не задерживает, оно его ТЕРЯЕТ, и молча.
    #
    # Реестра «о чём уже сообщили» НЕ ЗАВОДИМ (дорого, @opssre сам это отверг): источник —
    # сама лента, имя файла ищется в теле нот. Ложные срабатывания возможны (сообщили другими
    # словами) и приняты сознательно: ложная тревога стоит секунду, пропуск стоил @PROTO двух
    # часов. Жёлтый, без exit-кода — признак информирует, а не блокирует.
    # ⚠️ ДАТА БЕРЁТСЯ ИЗ GIT, А НЕ ИЗ mtime — и это не педантизм, а оплаченная ошибка. Первая
    # версия (17:21) сравнивала mtime, и признак закричал о 17 записках, из них 10 с ОДНИМ И ТЕМ
    # ЖЕ mtime 26.07 11:51 — момент копирования моста. Git говорит, что появились они 15 и 25.07.
    # То есть mtime врёт о появлении записки ровно так, как предупреждает шапка этого файла про
    # проверку ⑦ («mtime двигало любое копирование без правки содержимого → вечно-красный без
    # вины»). Предупреждение стоит в 40 строках выше; я прочитал его час назад и наступил.
    # ⇒ Дата = первое появление в коммите; для НЕзакоммиченных (самый горячий случай — записка
    # пришла только что) git даты не даст, и там честно берётся mtime.
    # 🪤 ПЯТЫЙ УКУС, и он снял `--diff-filter=A` (замер @opssre 07.08 17:00 UTC, карточка #120).
    # Фильтр брал коммит, где имя ПОЯВИЛОСЬ ВПЕРВЫЕ. Для записки, переписанной заново под
    # прежним именем, это дата ЧУЖОГО текста: `status.knowledge-scopes.md` — тело 43 ч,
    # первое появление имени 548 ч ⇒ признак считал её 23-суточной и не показывал НИКОГДА,
    # с рождения и навсегда. А `status.*` — как раз то имя, которое обновляют по смыслу.
    # 🎯 Класс — четвёртый экземпляр за сутки и всё тот же: механизм стерёг ИМЯ, а свойство
    # было «когда появилось ЭТО СОДЕРЖИМОЕ». Утром так же промахивался сторож строки
    # подключения (имена с DB_ вместо «заглушка не разрешилась»), днём — гашение по упоминанию.
    # ⇒ Берём коммит ПОСЛЕДНЕГО изменения файла: log идёт от свежих к старым, поэтому
    #   setdefault теперь запоминает САМЫЙ НОВЫЙ, а не самый старый.
    # ⛔ Защита min(git, mtime) остаётся: заменить git-дату на mtime нельзя — это снимет
    #   ровно то, ради чего минимум заводился (@opssre отвёл эту починку сам, до вопроса).
    BRIDGES = COORDINATION.parent / "bridges"
    added = {}
    if BRIDGES.exists():
        r = subprocess.run(["git", "-C", str(BRIDGES.parent.parent), "log",
                            "--format=%at", "--name-only", "--", "*.mezosync/bridges/*"],
                           capture_output=True, text=True)
        ts = None
        for line in r.stdout.splitlines():
            if line.isdigit():
                ts = int(line)
            elif line.strip() and ts:
                added.setdefault(Path(line).name, ts)   # log новее→старее ⇒ первым лёг САМЫЙ СВЕЖИЙ
    unannounced = []
    if BRIDGES.exists():
        for f in sorted(BRIDGES.glob("*/*.md")):
            if f.name == "INDEX.md":       # указатель правится при каждой записке, о нём не сообщают
                continue
            # РАННЯЯ из двух дат, и это третий укус той же правки. Git-дата — момент КОММИТА:
            # 21 КБ для @PROTO легли в 15:12, а закоммичены в 17:19 — по ней записка выглядела
            # «появившейся» позже собственного объявления в ленте (17:17) и лезла в список
            # неназванных. mtime врёт вверх при копировании, git-дата — при позднем коммите;
            # минимум даёт самое раннее ДОКАЗАННОЕ существование и потому честен в обе стороны.
            stamp = min(added.get(f.name) or f.stat().st_mtime, f.stat().st_mtime)
            # ⚠️ ЧЕТВЁРТЫЙ УКУС (@STUD #3067), и он был у меня в выводе на виду: строка
            # печатала «нет ноты» и ТУТ ЖЕ номер ноты о том же файле. Причина — ДВЕ ШКАЛЫ:
            # fromtimestamp() даёт ЛОКАЛЬНОЕ, а лента живёт в UTC. Сравнение «нота < файл»
            # врало ровно на смещение зоны (сейчас 2 ч), и врало САМОИСЦЕЛЯЮЩЕ: добросовестно
            # объявленная записка числилась неназванной два часа, потом «чинилась сама».
            # Это худший вид ложной тревоги — не устойчивый (пошли бы чинить), а МЕРЦАЮЩИЙ:
            # его списывают на «показалось» и вместе с ним списывают настоящие срабатывания.
            # 📌 И guard-utc указывал на СОСЕДНЮЮ строку (age_h, где локальное минус локальное
            # честно): починка по его указанию дефект не убрала бы. Обе строки правятся ВМЕСТЕ —
            # иначе сравнение станет верным, а возраст поедет на те же 2 часа.
            mtime = datetime.fromtimestamp(stamp, timezone.utc).replace(tzinfo=None, microsecond=0)
            # 🪤 ПЯТЫЙ УКУС ЭТОЙ ЖЕ ПРОВЕРКИ, и первый — в её ОСНОВАНИИ, а не в датах.
            # Замер @opssre 07.08 16:36 UTC, воспроизводимый по часам: 16:18 признак горел,
            # 16:23 он написал записку, где НАЗВАЛ имя файла и пожаловался, что записку никто
            # не разобрал, 16:32 признак ПОГАС. Между вторым и третьим не произошло ничего.
            # Причина в этой самой строке: `body_md LIKE '%имя%'` — это ПРИЗНАК (имя встретилось),
            # а свойство было «записку прочли». Любая цитата, пересылка и даже жалоба на сам
            # признак гасили его навсегда — и тем вернее, чем добросовестнее роль называла
            # непрочитанное. Третий экземпляр класса за сутки и первый в чужом признаке моей руки.
            # ⛔ Два сужения поиска отвёл он же замером: исключить автора — погасит следующий
            #    цитирующий; убрать поиск по ленте — признак закричит об исторических пяти.
            # ⇒ Гасит ТОЛЬКО ЖЕСТ: `write-message.py --reviewed <файл>` пишет строку в
            #   bridge_reviewed. Таблицы может не быть (старая база, свежий клон) — тогда
            #   НЕ ГАСИТ НИКТО, и это верное поведение: отсутствие следа не есть разбор.
            said = None
            try:
                said = conn.execute(
                    "SELECT MAX(at) FROM bridge_reviewed WHERE file_name = ?", (f.name,)
                ).fetchone()[0]
            except sqlite3.OperationalError:
                pass
            # Разбор ДО появления файла разбором не считается: так выглядит наш же ask,
            # на который пришёл ответ с тем же именем. Засчитывается только жест ПОСЛЕ.
            if not said or datetime.fromisoformat(said) < mtime:
                # вторая половина той же правки: обе стороны вычитания — в UTC
                age_h = (datetime.now(timezone.utc).replace(tzinfo=None) - mtime).total_seconds() / 3600
                unannounced.append((age_h, f"{f.name} ({age_h:.0f} ч"
                                           + (", РАЗБОРА НЕ БЫЛО)" if not said
                                              else f", последний разбор {said[:16]}, но файл новее)"),
                                    mtime))
    # ОКНО 48 ч — второй оплаченный урок этой же правки. Без окна признак закричал о 23 записках,
    # старейшей 525 часов, и утопил бы свежую в археологии. Про июльские письма либо уже сказали
    # своими словами (имя файла в ленте не назвали), либо они потеряны безвозвратно — ни то,
    # ни другое не чинится сегодня. Признак заводился, чтобы НОВАЯ записка не пролежала молча:
    # за 48 часов гард пройдёт полтора десятка раз, этого достаточно. Хвост не исчезает — он
    # показан ЧИСЛОМ, чтобы «стало тихо» не читалось как «стало чисто».
    FRESH_H = 48
    # ⚰️ ОТСЕЧКА ПО ДАТЕ ВРЕЗКИ ЖЕСТА (стояла здесь 07.08 с 16:44 до 17:00) СНЯТА. Она
    # прощала всё, что появилось раньше неё, — и это выглядело честно: требовать жеста,
    # которого не существовало, нельзя.
    # 🔴 Разобрано двумя замерами подряд, и оба против:
    #   @opssre 16:46 — амнистия отпустила вместе со старьём 15 СВЕЖИХ записок, включая ту,
    #     часовой давности, ради которой всё началось. «Починка сменила СПОСОБ гашения,
    #     сохранив СЛЕДСТВИЕ»: раньше гасило упоминание, теперь гасила дата.
    #   @PROTO 16:50 — досчитал следствие до конца: условие показа было «возраст ≤ 48 ч И
    #     появился после отсечки», значит прощение — ИЛИ: сегодня по дате, завтра по возрасту.
    #     МЕЖДУ НИМИ НЕТ ЗАЗОРА ⇒ те пятнадцать не покраснели бы НИ РАЗУ за всю свою жизнь.
    #     Класс общий: амнистия по дате врезки, наложенная на окно по возрасту, даёт
    #     ПОСТОЯННУЮ дыру ровно в размер окна.
    # ⇒ Остаётся ОДНО условие — возраст. Жест сегодня существует, и любую из этих записок
    #   можно разобрать прямо сейчас: физической невозможности нет ни у одной.
    # ⛔ Закрытый список имён (предложение @PROTO) НЕ ЗАВЁЛСЯ: это вторая копия состояния,
    #   которую надо вычёркивать рукой. Дисциплина у нас не масштабируется — сегодня это
    #   доказано четырежды. У окна 48 ч конец наступает САМ, у списка — по чьей-то памяти.
    # ⚖️ Цена принята вслух: сегодня строка назовёт ~14 записок. Это не шум — это работа,
    #   которую никто не объявил разобранной, и она уйдёт по возрасту за двое суток.
    fresh = [s for h, s, _m in sorted(unannounced, reverse=True) if h <= FRESH_H]
    old = len(unannounced) - len(fresh)
    counted("мост: записки без разбора")

    # ── ⑭ ЗЕРКАЛО ПРАВИЛ ПРОТИВ БАЗЫ. Инструмент @PROTO (vnext-tools), зову по пути.
    #
    # 🪤 ЗДЕСЬ СТОЯЛА МОЯ СОБСТВЕННАЯ ПРОВЕРКА, написанная за 20 минут до этой строки.
    # Она сравнивала ВРЕМЯ (метка генерации против MAX(updated_at)), его — СОДЕРЖИМОЕ
    # (какого правила нет, где версия старше, где текст разошёлся мимо версии).
    # Прогнал оба на двух подлогах, а не рассудил:
    #     метка состарена, содержимое то же .... моя 🔴 · его ✅
    #     правило вырезано, метка свежая ....... моя ✅ · его 🔴 (назвал ИМЯ и версию)
    # ⇒ Разные случаи. Но в РЕАЛЬНОМ отказе — «правило поменяли, генератор не позвали» —
    # срабатывают ОБА, и его при этом говорит, КАКОЕ правило. Мой единственный
    # непокрытый случай (состаренная метка при верном тексте) — искусственный:
    # чтобы он случился, метку надо править рукой.
    # 🎯 ⇒ Своё снял. Две проверки на одно свойство расходятся молча — контур платил
    # за это сегодня четырежды. Двадцать минут работы не довод: цена уже потрачена,
    # а держать вторую копию пришлось бы всегда.
    sub_guard("зеркало правил", None, skip,
              script_path=tool("check-rules-mirror.py"))
    # нет (сегодня их нет — контур всё объявил за час), заголовок молчал, а продолжение «↳ и ещё
    # N старше 48 ч» печаталось и ПРИЛИПАЛО к последней выведенной строке — какой угодно.
    # Воспроизведено: оно встало под «слепки: содержание отстаёт» и читалось как «5 старых
    # СЛЕПКОВ» — бессмыслица, но правдоподобная. Предмет строки задавался тем, что случайно
    # напечаталось выше; при смене порядка проверок прилипло бы к другой.
    # ⇒ Строка обязана нести свой заголовок и отвечать за себя, не завися от соседей.
    if fresh or old:
        head = (f"⚠️ мост: СВЕЖИХ записок БЕЗ РАЗБОРА — {len(fresh)}: " + " · ".join(fresh[:4])
                + (f" · …ещё {len(fresh) - 4}" if len(fresh) > 4 else "")
                + "\n   — отправка в согласованное место НЕ ДОСТАВКА, пока у места нет наблюдателя"
                  " (@opssre #3060). Внутри контура адресата находит только ЛЕНТА"
                  "\n   👉 прочёл и разобрал — скажи это ЖЕСТОМ, вместе со своей нотой:"
                  "\n      python <КОНТУР>/.mezosync/scripts/write-message.py"
                  " --role <ТЫ> --file <нота.md> --reviewed <имя файла>"
                  "\n   ⛔ упоминание имени в тексте признак БОЛЬШЕ НЕ ГАСИТ: цитата не разбор"
                  "\n   ⚠️ часть из них могла быть разобрана ПРОЗОЙ до 07.08 16:44 — жеста тогда"
                  " не было. Механизм этого не знает и знать не может: он показывает"
                  " отсутствие ЖЕСТА, а не отсутствие чтения"
                ) if fresh else "⚠️ мост: свежих записок без разбора НЕТ"
        print(head)
        if old:
            print(f"   ↳ исторический хвост: {old} записок старше {FRESH_H} ч, признака тогда"
                  " не было; разбирать по одной, не гуртом")
    if sect_lag:
        print(f"⚠️ слепки ПОСЕКЦИОННО (>{STALE_HOURS} ч от последней ноты): " + " · ".join(sect_lag)
              + "\n   — состояние врёт о прошлом, ПЛАН ПРИКАЗЫВАЕТ В БУДУЩЕЕ (@PROTO #3051):"
                " преемник исполняет план первым и не подвергает сомнению."
                " Сохранение ОДНОЙ секции это НЕ гасит — считается каждая")

    conn.close()
    bad = [n for n, ok, _ in RESULTS if not ok]
    print(f"\n{'⛔ КРАСНЫХ: ' + str(len(bad)) + ' — ' + ', '.join(bad) if bad else '✅ ВСЕ ГАРДЫ ЗЕЛЁНЫЕ'}"
          f" ({len(RESULTS)} проверок)")
