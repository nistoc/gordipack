def _по_признаку(корень, имя):
    найденные = []
    свой = корень / имя
    if свой.is_dir():
        найденные.append(свой)
    try:
        соседи = sorted(d for d in корень.iterdir() if d.is_dir())
    except OSError:
        соседи = []
    for репо in соседи:
        кандидат = репо / ".mezosync" / имя
        if кандидат.is_dir():
            найденные.append(кандидат)
    return найденные


