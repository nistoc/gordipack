def sub_guard(name, script, skip, *extra, script_path=None):
    """Прогон отдельного гарда подпроцессом.

    script_path — абсолютный путь, если гард живёт ВНЕ scripts/ (напр. vnext-tools, зона PROTO).
    extra       — аргументы гарда (напр. --since-hours 24).
    """
    if name in skip:
        print(f"⏭️ {name} — пропущен по --skip")
        return
    # returncode напрямую, НИКАКИХ пайпов: `guard | head; echo $?` возвращает код head —
    # на этой ловушке гард UTC уже один раз отрапортовал «чисто» сквозь красное.
    target = Path(script_path) if script_path else SCRIPTS / script
    if not target.exists():                      # чужой инструмент мог переехать
        check(name, False, f"гард не найден: {target}")
        return
    r = subprocess.run([sys.executable, str(target), *extra],
                       capture_output=True, text=True)
    lines = [l.rstrip() for l in (r.stdout or r.stderr).strip().splitlines() if l.strip()]

    if r.returncode == 0:
        check(name, True, lines[-1] if lines else "")
        # ⚡ ЖЁЛТЫЕ СТРОКИ ЗЕЛЁНОГО ПРОГОНА ДОЕЗЖАЮТ ДО ОБЩЕГО ВЫВОДА (карточка от записки
        # @COORD #3767). 🩸 Найдено при проверке СВОЕЙ ЖЕ починки: я научила проверку чтения
        # ленты говорить «вне окна 8 ролей, их долг НЕ ПРОВЕРЯЛСЯ: 1257 непрочитанных»,
        # прогнала её отдельно — строка есть; прогнала общий прогон — строки НЕТ. Общий
        # прогон при коде 0 печатал одну галочку, и всё сказанное подпроверкой пропадало.
        # 🎯 То есть починка закрыла ровно половину: заявка была о том, что в ОБЩЕМ прогоне
        # долг невидим, а я сделала его видимым только при прямом вызове.
        # ⚖️ Берём строки, начатые знаком предупреждения: они по договору контура означают
        # «сказано вслух, но прогон не красный». Красные сюда не попадают — код 0.
        for l in lines:
            if l.lstrip().startswith(("⚠️", "ℹ️")):
                print(f"   {l.strip()}")
        return

    # 🪤 БЫЛО: брали ПОСЛЕДНЮЮ строку вывода. У guard-phoenix-time последняя строка —
    # общий совет («правь ПРИВЫЧКУ, не прошлое»), и красное выглядело как разговор
    # об истории. Цена замерена 07.08 (@ING #3189): гард ЛОВИЛ его свежие метки поимённо,
    # а он девять раз подряд списал строку как «известное, чужое, историческое» — и назвал
    # это классом «красный гард с чужим именем усыпляет сильнее зелёного».
    # 🎯 Диагноз он поставил механизму («гард не смотрит в тело») — и тот был неверен:
    #    гард смотрел и нашёл. Неверной была СВОДКА, то есть моя строка, а не его чтение.
    # ⇒ Выбирать строку по ПОЗИЦИИ — предположение о чужом формате. Ищем по СМЫСЛУ:
    #    сперва итог, потом первую красную; и печатаем несколько красных строк, чтобы
    #    свежий экземпляр нельзя было спутать с историческим.
    # 🪤 ВТОРАЯ ПРАВКА ТОГО ЖЕ МЕСТА (07.08 16:28 UTC): прежняя искала только «🔴» и при
    # его отсутствии падала на lines[-1]. У guard-write-without-read вердикт помечен «⛔»,
    # а последняя строка — придаточное из совета, и сводка печатала обрывок фразы
    # («⛔ чтение ленты — значит зовущие её ноты не дойдут…») вместо числа «2 из 6 активных».
    # ⇒ Ищем ЛЮБОЙ знак вердикта, а последним средством берём ПЕРВУЮ строку, не последнюю:
    # оба проверенных гарда печатают вердикт сверху, совет снизу. Это замер, а не вкус.
    итог = next((l for l in reversed(lines) if "ИТОГО" in l), None)
    красные = [l for l in lines if "🔴" in l]
    вердикт = next((l for l in lines if "🔴" in l or "⛔" in l), None)
    check(name, False, итог or вердикт or (lines[0] if lines else ""))
    for l in красные[:6]:
        if l is not итог:
            print(f"      {l.strip()}")
    if len(красные) > 6:
        # 🔴 ПЕЧАТАЕМ СПОСОБ ПОЗВАТЬ, А НЕ ИМЯ ФАЙЛА (замер @STUD #3394, 08.08 11:07 UTC).
        # Здесь стояло `target.name` — голое имя. Роль читает вывод инструмента и действует
        # по нему НЕМЕДЛЕННО: @STUD прочла «полный вывод: guard-phoenix-time.py», пошла звать
        # его из .mezosync/scripts, а он живёт в vnext-tools — три вызова вслепую.
        # 🎯 Класс: подсказка в выводе — это ПРИКАЗ, даже если рядом нет слова «python».
        # ⚠️ И полный путь всё это время лежал в `target`, в той же строке: не хватало не
        # данных, а понимания, что печатаем мы не имя, а команду.
        print(f"      … ещё {len(красные) - 6} красных строк — полный вывод: "
              f"python {target}")


