"""Срочность ВЫЧИСЛЯЕТСЯ, а не хранится. Один предикат на всех потребителей.

СЛОВО ВЛАДЕЛЬЦА 2026-08-08 10:29 UTC (передано @PROTO #3385) и подтверждено живым словом
в чате COORD 10:40 UTC: пометку не гасить в базе, а ПОКАЗЫВАТЬ, пока записка молода
и без ответа.

    показывать «срочно» = пометка срочная  И  моложе 12 часов  И  нет отклика

⚠️ ПОЧЕМУ ХРАНИТЬ БЫЛО НЕЛЬЗЯ: поле гашения существовало и не было позвано НИ РАЗУ —
0 из 546. Механизм «по желанию» умирает молча, и его смерть неотличима от «всё спокойно».
Вычисляемая пометка не может протухнуть: она пересчитывается на каждом чтении.

📏 ПОРОГ 12 ЧАСОВ — ЗАМЕР, А НЕ ВКУС (моей рукой, 2026-08-08 10:49 UTC, 1959 записок):
    задержка первого отклика: медиана 0,1 ч · 95-я доля 5,3 ч
    за 12 часов не уложились 16 откликов из 468 — это и есть цена порога
    (@PROTO намерил 95-ю долю в 7,8 ч на своём определении; деление 12 ч у нас общее)

🎯 И ГЛАВНОЕ ЧИСЛО, КОТОРОЕ РЕШИЛО КОНСТРУКЦИЮ (замер 10:50 UTC):
    записок с пометкой срочности .......... 632
    из них моложе 12 часов .................. 5
⇒ Второе условие отсекает 627 из 632. Поэтому спор о ШИРИНЕ признака отклика (11 % против
57 % против 74 % покрытия) на живой витрине НЕРАЗЛИЧИМ: при всех трёх определениях сейчас
горит одно и то же — четыре записки. Раз цена строгости измеренно нулевая, берётся САМОЕ
СТРОГОЕ: ложное гашение прячет срочное, а лишняя пометка всего лишь заметна.

⛔ ПРИЧИНА СНЯТИЯ ПЕЧАТАЕТСЯ ВСЕГДА, для конкретной записки, а не порогом вообще.
Иначе мы меняем бессмысленную пометку на необъяснённое молчание — а это хуже: молчание
выглядит как «спокойно» и не даёт себя проверить.
"""
import re
from datetime import datetime, timezone

WINDOW_HOURS = 12
MARKED = ("high", "critical")


def _refs_outside_quote(body):
    """Ссылки «#N» ВНЕ цитаты. Цитата — строка, начинающаяся с '>'.

    ⚠️ Цитата не разбор: пересказ чужой записки со ссылкой на неё откликом не является.
    Тот же класс, за который 07.08 правился признак разбора на мосту, — там упоминание
    имени перестало гасить, потому что гасить должен ЖЕСТ, а не упоминание.
    """
    out = set()
    for line in (body or "").splitlines():
        if line.lstrip().startswith(">"):
            continue
        out.update(int(m) for m in re.findall(r"#(\d{3,5})", line))
    return out


def _age_hours(ts, now):
    try:
        return (now - datetime.fromisoformat(ts)).total_seconds() / 3600
    except (ValueError, TypeError):
        return None          # неразбираемая метка → не гасим по возрасту, гасить вслепую хуже


def urgency_state(conn, msg_id, writer, ts, priority, now, reader=None):
    """→ (гореть: bool, причина: str|None). Причина заполнена, когда НЕ горит.

    Возвращает причину даже для не-срочных записок: потребитель вправе показать, почему
    строка молчит, и это единственный способ проверить механизм не читая его код.

    `reader` — КТО СМОТРИТ. Витрина персональная (её зовут с --role), и «срочно» здесь
    значит «требует внимания ЧИТАТЕЛЯ», а не «запись важная вообще».
    """
    if priority not in MARKED:
        return False, None                      # пометки не было — гасить нечего

    # ⛔ СВОЯ НОТА АВТОРУ НЕ ГОРИТ (слово владельца 2026-08-08 11:04 UTC).
    # Внимания автора его собственная запись не требует: он её и написал. Прежняя редакция
    # зажигала мне мою же #3390 — формально верно по трём условиям и бессмысленно по делу.
    # 📌 Класс: предикат отвечал на вопрос «какова записка», а витрина задаёт другой —
    # «что от МЕНЯ нужно». Пока читатель был неизвестен, эти два вопроса нечем было различить.
    # ⚠️ Гашение НЕ распространяется на остальных: для всех прочих ролей записка горит.
    if reader and writer and reader.upper() == writer.upper():
        return False, "своя нота"

    age = _age_hours(ts, now)
    if age is not None and age > WINDOW_HOURS:
        return False, f"старше {WINDOW_HOURS} ч ({age/24:.0f} сут)" if age > 48 \
            else f"старше {WINDOW_HOURS} ч ({age:.0f} ч)"

    # Отклик ищем ТОЛЬКО среди записок ПОЗЖЕ этой и ТОЛЬКО ОТ ДРУГОЙ РОЛИ.
    #
    # 🔴 ЧУЖОЕ АВТОРСТВО — НЕ ПЕДАНТИЗМ, А ДЕФЕКТ, НАЙДЕННЫЙ ВИТРИНОЙ 08.08 10:53 UTC:
    # первая редакция гасила #3384 ссылкой из #3386 — обе МОИ. Роль, сославшаяся на свою же
    # записку и упомянувшая себя в списке адресатов, гасила себе срочность САМА, ничьего
    # внимания не получив. Отклик — это чужое действие; своей рукой его не изобразить.
    like = f"%#{msg_id}%"
    for rid, rbody in conn.execute(
            "SELECT id, body_md FROM messages WHERE id > ? AND body_md LIKE ? "
            "AND writer_role <> ? ORDER BY id",
            (msg_id, like, writer)):
        if msg_id not in _refs_outside_quote(rbody):
            continue
        # Строгий признак: откликающийся НАЗВАЛ автора. Мягкие признаки на живой витрине
        # дают тот же результат (замер 10:50 UTC), поэтому берём тот, что не гасит зря.
        if f"@{writer}".lower() in (rbody or "").lower():
            return False, f"отвечено в #{rid}"
    return True, None


def annotate(conn, rows, now=None, reader=None):
    """rows: [(id, writer, ts, body, tags, priority), ...] → {id: (гореть, причина)}.

    ОДНО место предиката на всех потребителей — указатель и полную ленту. Двум копиям
    предиката свойственно разойтись молча: ровно так 07.08 разъехались две проверки,
    и роль верила той, что мягче.

    ⚠️ `reader` передаётся ОБОИМИ потребителями. Забыть его у одного — значит вернуть
    ту самую пару витрин, что расходится молча: у одной своя нота горит, у другой нет.
    """
    now = now or datetime.now(timezone.utc).replace(tzinfo=None)  # метки в БД naive-UTC
    return {r[0]: urgency_state(conn, r[0], r[1], r[2], r[5], now, reader) for r in rows}


def mark_for(state, priority):
    """Значок для витрины: горит · погашено · не было пометки."""
    burn, _ = state
    if burn:
        return "🔴crit" if priority == "critical" else "⚠️high"
    return "  ·   " if priority in MARKED else "      "
