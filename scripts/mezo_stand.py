def _resolve_home() -> None:
    """Один раз, перед первым стендом: запущен ли этот прогон изнутри прогона с mezo_stand.

    Не при загрузке: tempfile.gettempdir() запоминает папку при первом вызове, а приёмка
    вправе поменять TMP после import mezo_stand и до первого стенда.
    """
    global _home, _home_resolved
    if _home_resolved:
        return
    _home_resolved = True
    home = os.environ.get(_HOME_ENV, "")
    home_temp = os.environ.get(_HOME_TEMP_ENV, "")
    # есть ли дом на диске, проверяет _drop_vanished_home() перед каждым стендом: дом исчезает
    # и посреди прогона, а вторая проверка того же здесь позволила бы поломке одной прятаться
    # за другой
    if not home or not home_temp:
        return
    if _real(home_temp) != _real(tempfile.gettempdir()):
        return            # вызывающий нарочно дал другую временную папку — его слово главнее
    _home = home


def _offer_home(p: Path) -> None:
    """Первый собственный стенд верхнего прогона становится домом для стендов дочерних процессов."""
    global _home_offered
    if _home is not None or _home_offered:
        return
    _home_offered = True
    os.environ[_HOME_ENV] = str(p)
    os.environ[_HOME_TEMP_ENV] = tempfile.gettempdir()


def _drop_vanished_home() -> None:
    """Дом исчез (вызывающий оборвался, его стенд убран) — дальше этот прогон живёт как верхний.

    Проверяется перед КАЖДЫМ стендом, а не один раз: дом исчезает и посреди прогона, и тогда
    mkdtemp(dir=дом) падал бы FileNotFoundError (мелочь третьей приёмки PROTO; в 16c525f
    вложения не было, и этот путь не падал).
    """
    global _home
    if _home is not None and not os.path.isdir(_home):
        _home = None


def new(prefix: str) -> Path:
    """Создать временный рабочий каталог. Дальше он убирается сам — по исходу прогона."""
    _resolve_home()
    _drop_vanished_home()
    _sweep_aged_once()
    p = Path(tempfile.mkdtemp(prefix=prefix, dir=_home))
    _stands.append(p)
    _prefixes.add(prefix)
    _offer_home(p)
    return p


def release(path) -> None:
    """Заменяет `shutil.rmtree(path, ignore_errors=True)` в блоке finally.

    Не удаляет каталог прямо сейчас, а откладывает решение до исхода прогона: при
    успехе он будет убран, при провале — сохранён и напечатан. Нужен там, где уборка
    УЖЕ написана и стои́т в finally: такая уборка честно убирает и при провале тоже,
    то есть уносит обстановку, ради осмотра которой её и сохраняли бы.
    """
    p = Path(path)
    if p not in _stands:
        _stands.append(p)
    # Начало имени здесь не передано — выводим его так, как его строит tempfile.mkdtemp
    # (начало + 8 случайных знаков). Вывод неверен — кандидатов просто не найдётся:
    # уборка дополнительно требует метку того же скрипта, лишнего она не тронет.
    if len(p.name) > _MKDTEMP_SUFFIX:
        _prefixes.add(p.name[:-_MKDTEMP_SUFFIX])


