#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""atomic-install — установка новой версии инструмента ОДНИМ НЕДЕЛИМЫМ ХОДОМ (карточка #204).

    python <КОНТУР>/.mezosync/scripts/atomic-install.py <новый файл> <куда ставить>

ЗАЧЕМ. Пока редактор пишет файл по частям, зовущий может поймать его В ПОЛОВИНЕ — получить
обрыв на середине строки и решить, что сломан инструмент, а не момент. Окно узкое
(миллисекунды), но оно есть, и закрывается оно НЕ арендой, а устройством записи:
пишем рядом, затем ПЕРЕИМЕНОВЫВАЕМ. Переименование в пределах одного тома неделимо:
зовущий видит либо старую версию целиком, либо новую целиком — третьего состояния нет.

⚖️ ГРАНИЦА, НАЗВАННАЯ ЗАРАНЕЕ (исполняю признак ⑨ на себе):
  · неделимость даёт файловая система в пределах ОДНОГО ТОМА. Ставить с другого диска
    нельзя — это уже копирование, и окно возвращается. Инструмент это проверяет и отказывает.
  · неделимость про ФАЙЛ, а не про СМЫСЛ: новая версия может менять поведение, и зовущий
    об этом не узнает. Эту, большую, половину закрывает объявленная аренда (lease.py).
  · старая версия сохраняется рядом (.bak) — не ради красоты: откат должен быть возможен
    ТЕМ ЖЕ неделимым ходом, а не восстановлением из памяти.
"""
from __future__ import annotations

import os
import sys
from pathlib import Path


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    src, dst = Path(sys.argv[1]).resolve(), Path(sys.argv[2]).resolve()

    if not src.exists():
        sys.exit(f"⛔ ОТКАЗ: нечего ставить — {src} не существует")
    if not src.read_text(encoding="utf-8", errors="replace").strip():
        sys.exit(f"⛔ ОТКАЗ: {src.name} ПУСТ. Пустая новая версия — почти всегда авария "
                 f"записи, а не намерение (тот же класс, что пустая секция памяти).")
    if dst.exists() and dst.is_dir():
        sys.exit(f"⛔ ОТКАЗ: {dst} — каталог, а не файл")

    # Один том — условие неделимости. Проверяем ДО, а не выясняем после.
    if src.drive.upper() != dst.drive.upper():
        sys.exit(f"⛔ ОТКАЗ: источник на томе {src.drive}, приёмник на {dst.drive}.\n"
                 f"   Переименование неделимо ТОЛЬКО в пределах тома; между томами это "
                 f"копирование, и окно «файл записан наполовину» возвращается.\n"
                 f"   👉 Положи новую версию рядом с приёмником и повтори.")

    tmp = dst.with_name(dst.name + ".new")
    bak = dst.with_name(dst.name + ".bak")
    was = dst.stat().st_size if dst.exists() else 0

    tmp.write_bytes(src.read_bytes())
    if dst.exists():
        # Копия прежней версии — ради ОТКАТА тем же ходом, а не ради истории:
        # история в git, а откат нужен здесь и сейчас.
        bak.write_bytes(dst.read_bytes())
    os.replace(tmp, dst)          # ← неделимый ход: третьего состояния не существует

    now = dst.stat().st_size
    print(f"✅ УСТАНОВЛЕНО одним неделимым ходом: {dst.name} — было {was} → стало {now} байт")
    if bak.exists():
        print(f"   откат тем же ходом: python {Path(__file__).resolve().as_posix()} "
              f"{bak.as_posix()} {dst.as_posix()}")
    print("   ⚖️ Неделимость про ФАЙЛ, не про СМЫСЛ: если поведение изменилось, скажи "
          "об этом занятостью (lease.py) и запиской — файл об этом не расскажет.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
