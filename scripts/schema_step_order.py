import re as _re

# Шаги-вехи (`NNNNNNNN-milestone-vK.py`) пишут себя в schema_migrations.version ПОД ИМЕНЕМ
# ВЕХИ ('v6'), а не под именем файла — тем же именем, что и записи 'v3'/'v4'/'v5' у более
# ранних вех (замер по снимку живой базы, rowid 40: version='v6', а не '20260907-milestone-v6').
_MILESTONE = _re.compile(r'^\d{8}-milestone-(v\d+)$')


def journal_version(step_name: str) -> str:
    """Имя, под которым шаг ищется в schema_migrations.version.

    Для вех — сама веха ('v6'); для остальных шагов — имя файла без .py, как есть.
    """
    m = _MILESTONE.match(step_name)
    return m.group(1) if m else step_name
