    # честен. Зазор лежал РОВНО МЕЖДУ двумя гардами, и потому его не видел ни один.
    #
    # Механизм, а не дисциплина: `SELECT count(*) WHERE <тот же предикат>` знает ответ —
    # молчал только вывод. Роли не надо ничего помнить и не надо считать в уме.
    # Счёт остатка ПЕРЕНЕСЁН НИЖЕ — считаем ПОСЛЕ возможной урезки батча под R16-перевыдачу,
    # по РЕАЛЬНОМУ верху показанного (batch_max), а не по исходной выборке. Находка PROTO
    # #2757: до переноса укороченный перевыдачей батч МОЛЧАЛ о хвосте — остаток считался по
    # предурезочным rows (len(rows) != limit ⇒ rest_count=0), и «упёрлось в лимит» не срабатывало.
    # Единый предикат «за батчем» = (id > batch_max) покрывает ОБА усечения — лимитом и перевыдачей.
    rest_count = 0
    rest_last = None

