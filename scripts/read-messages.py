        # Находка @opssre (#3442, 2026-08-08 16:52): в пустой ветке витрина `--to-me` печатала
        # «Нет непрочитанных сообщений» — утверждение о ВСЕЙ ЛЕНТЕ, глядя в узкий отбор.
