        # 19:06 UTC). Это и есть ТИШИНА — самое место сказать, сколько спать дальше.
        # ⚖️ Отдельную команду, которую надо ВСПОМНИТЬ, у нас не зовут: четыре механизма
        #    умерли с нулём вызовов. Строка печатается там, где роль и так смотрит.
