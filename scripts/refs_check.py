#!/usr/bin/env python3
"""Предупреждение о неразрешимых ссылках «#N» — вызов проверки @PROTO из инструментов записи.

ЗАЧЕМ. Слово владельца 2026-08-07 13:01 UTC (через @PROTO, правило `task-discipline` v3):
«разрешимую ссылку тоже делай обязательной, предупреждением». Номера записок и карточек —
ОДНО пространство (пересечение 62 из 62), поэтому голый «#3120» вне породившего чата
не открывается: читатель не знает, записка это или карточка.

ПОЧЕМУ ПРЕДУПРЕЖДЕНИЕ, А НЕ ОТКАЗ — выбор владельца, и он верен по цене ошибки:
отказ по регулярке бил бы по законному тексту («миграция #038», перечисления, цитаты),
а цена промаха здесь — потерянная минута читателя, не испорченные данные.

ПОЧЕМУ ЗДЕСЬ, А НЕ КОПИЕЙ В КАЖДОМ СКРИПТЕ. Сама проверка живёт в зоне @PROTO
(vnext-tools), зовём её ПО ПУТИ — так же, как guard-all зовёт его сторожей. Своей копии
правила не заводим: две копии одного правила расходятся молча, а разойдясь, обе выглядят
исправными (его же замер сегодня: логика жила в двух местах и одна из копий печатала
«0 голых ссылок в 0 карточках», не умея напечатать иного НИ ПРИ КАКИХ данных).

⚠️ ЭТА ФУНКЦИЯ НИКОГДА НЕ БЛОКИРУЕТ ЗАПИСЬ. Ни находки, ни отсутствие инструмента,
ни его падение не должны стоить роли ноты. Но и молчать об отсутствии проверки нельзя:
непроверенное не должно выглядеть проверенным — сегодня контур платил за это трижды.
"""
from __future__ import annotations

import subprocess
import sys
import tempfile
from pathlib import Path

# Инструмент в зоне @PROTO. Путь от расположения ЭТОГО файла, не от CWD (R15a):
# .mezosync/scripts/ → .mezosync/ → .atlas/ → vnext-tools/
# 🪤 Раскладок ДВЕ, а путь был ОДИН. В нашем контейнере проверка лежит в vnext-tools рядом
# с .mezosync; в контуре, собранном из шаблона, — в vnext/prototype рядом со scripts.
# 08.08 на первой же сборке из шаблона механизм честно сказал «НЕ ВЫПОЛНЕНА» — то есть
# деградировал ГРОМКО, и это спасло: тихий пропуск выглядел бы как «ссылки в порядке».
# ⇒ Ищем в известных местах по очереди; не нашли — говорим вслух, а не молчим.
_HERE = Path(__file__).resolve().parent
CANDIDATES = [
    _HERE.parent.parent / "vnext-tools" / "check-dangling-refs.py",     # контейнер
    _HERE.parent / "vnext" / "prototype" / "check-dangling-refs.py",    # шаблон: scripts/
                                                                        # и vnext/ — СОСЕДИ
    _HERE.parent.parent / "vnext" / "prototype" / "check-dangling-refs.py",
    _HERE / "check-dangling-refs.py",                                   # рядом со скриптами
]
CHECKER = next((c for c in CANDIDATES if c.exists()), CANDIDATES[0])


def warn_dangling(text: str, label: str = "") -> None:
    """Печатает предупреждение о неразрешимых ссылках в text. Ничего не возвращает и не рвёт."""
    if not (text or "").strip():
        return
    if not CHECKER.exists():
        # Третий исход, который нельзя сливать ни с «чисто», ни с «находки»: проверки НЕ БЫЛО.
        # Молчание здесь читалось бы как «ссылки в порядке» — зелёное от слепоты.
        print(f"⚠️ проверка ссылок НЕ ВЫПОЛНЕНА: не найден {CHECKER}", file=sys.stderr)
        return

    tmp = None
    try:
        # Через файл, а не --text: длинную ноту в argv нести нельзя, и по той же причине,
        # по которой у write-message.py заведён --file — shell молча ест бэктики в строке
        # (покалеченные броадкасты 16.07). Инструмент, обходящий эту ловушку у себя,
        # не должен возвращать её через чёрный ход.
        with tempfile.NamedTemporaryFile("w", suffix=".md", encoding="utf-8",
                                         delete=False) as f:
            f.write(text)
            tmp = Path(f.name)
        r = subprocess.run([sys.executable, str(CHECKER), "--file", str(tmp), "--quiet"],
                           capture_output=True, text=True, encoding="utf-8", timeout=20)
        out = ((r.stdout or "") + (r.stderr or "")).strip()
        if out:
            # Вывод печатается КАК ЕСТЬ (просьба @PROTO): он уже называет строку, позицию
            # и окрестность. Пересказывать его своими словами значило бы завести вторую
            # формулировку одного предмета — ровно то, от чего этот модуль и заведён.
            # Имя файла во временной директории читателю ничего не говорит — заменяем.
            if label:
                out = out.replace(tmp.name, label).replace(Path(tmp).name, label)
            print(out, file=sys.stderr)
    except (OSError, subprocess.SubprocessError) as e:
        print(f"⚠️ проверка ссылок НЕ ВЫПОЛНЕНА ({type(e).__name__}: {e})", file=sys.stderr)
    finally:
        if tmp is not None:
            try:
                tmp.unlink()
            except OSError:
                pass


# ── ТОЧКА ВХОДА (заявка @ING, записка #4016, 27.08 17:29 UTC) ─────────────────────
# 🩸 ЧЕМ ОПЛАЧЕНО. Этот файл был модулем БЕЗ точки входа. Роль, позвавшая его командой
# (`python …/scripts/refs_check.py --file нота.md`), получала ПУСТОЙ ВЫВОД и код 0 —
# и читала это как «голых ссылок нет, записка чистая». На пробе с двумя голыми «#N»
# он молчал ровно так же. Заставить его заговорить было нельзя ничем.
# 🎯 Дефект не в проверке ссылок: она работает и зовётся при каждой отправке. Дефект в том,
# что у файла была ФОРМА ВЫЗОВА, которая ничего не делает и выглядит успехом.
# ⚖️ Почему переадресация, а не своя проверка: правило живёт в одном месте (zone @PROTO),
# и заводить здесь вторую копию значило бы ровно то, от чего этот модуль и создан.
# ⚠️ Почему @ING вообще позвал ЭТОТ файл: его наказ синка велит звать все механизмы
# из `scripts/`, а настоящая проверка лежит в `vnext-tools/`. Правило, опирающееся на то,
# что каждый помнит разницу, уже подвело одного за день — значит и форма отсюда обязана
# делать дело либо громко отказывать, а не молчать.
def _main() -> int:
    args = sys.argv[1:]
    if not args:
        print("⛔ refs_check.py — не команда сам по себе, а вызов проверки ссылок.",
              file=sys.stderr)
        print(f"   Проверка живёт здесь: {CHECKER}", file=sys.stderr)
        print("   Зови так:  python <контейнер>/vnext-tools/check-dangling-refs.py"
              " --file <нота.md>", file=sys.stderr)
        print("   Либо этой же формой с --file — она переадресует туда же.", file=sys.stderr)
        return 2
    if not CHECKER.exists():
        # Молчать нельзя: «проверки не было» обязано отличаться и от «чисто», и от находок.
        print(f"⚠️ проверка ссылок НЕ ВЫПОЛНЕНА: не найден {CHECKER}", file=sys.stderr)
        return 3
    r = subprocess.run([sys.executable, str(CHECKER), *args],
                       text=True, encoding="utf-8")
    return r.returncode


if __name__ == "__main__":
    sys.exit(_main())
