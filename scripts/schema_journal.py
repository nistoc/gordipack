import hashlib
import sqlite3


def split_statements(sql):
    """Разбить набор операторов правки схемы на отдельные — НЕ через `sql.split(";")`.

    🩸 НАЙДЕНО @OPSSRE 23.08, и найдено ценой сломанной схемы. Два шага хранили правку
    одной строкой и резали её по точке с запятой. Первый же комментарий со словами
    «…ПРЕЖНЕГО тела; NULL — первая версия» РАЗОРВАЛ ОПЕРАТОР ПОПОЛАМ, и SQLite ответил
    «incomplete input» — при ПРИМЕНЕНИИ, а не при чтении кода.
    🎯 Его формулировка, забираю: приём работал не потому, что верен, а потому, что
    в комментариях пока не встречалось точки с запятой. **Знак препинания в пояснении
    ломает схему.** То же случилось бы со значением `VALUES ('a;b')`.
    ⚖️ Мест оказалось ДВА, а не одно, как в заявке: `20260816-tool-leases.py`
    и `20260820-role-skills.py`.
    ⛔ Почему не `executescript`: он делает COMMIT перед выполнением и тем разрывает
    транзакцию, в которой шаг обязан записать себя рядом с правкой. Лечение было бы
    хуже болезни — журнал снова начал бы врать про «ту же транзакцию».
    ⚖️ `sqlite3.complete_statement` разбирает сам SQLite: он видит и комментарии,
    и строковые значения (проверено замером, случаи ①② приёмки).
    """
    куски, буфер = [], ""
    for строка in sql.splitlines(keepends=True):
        буфер += строка
        if sqlite3.complete_statement(буфер):
            куски.append(буфер)
            буфер = ""
    if буфер.strip():
        куски.append(буфер)
    # Кусок из одних комментариев и пробелов оператором не является: SQLite на нём
    # промолчит, но «выполнено 5 операторов» станет неправдой, а число тут — замер.
    живые = []
    for к in куски:
        тело = "\n".join(s for s in к.splitlines()
                         if s.strip() and not s.strip().startswith("--"))
        if тело.strip():
            живые.append(к)
    return живые


def fingerprint(conn):
    """Отпечаток СТРУКТУРЫ базы: таблицы, вью, триггеры, индексы — без данных.

    Автоиндексы SQLite исключены: они появляются и исчезают сами при работе с ключами
    и структурным решением не являются — иначе сторож краснел бы на чужой ни в чём
    не повинной вставке.
    """
    rows = conn.execute(
        "SELECT type, name, COALESCE(sql, '') FROM sqlite_master "
        "WHERE name NOT LIKE 'sqlite_autoindex%' ORDER BY type, name").fetchall()
    norm = "\n".join(f"{t}|{n}|{' '.join((s or '').split())}" for t, n, s in rows)
    return hashlib.sha256(norm.encode("utf-8")).hexdigest()[:16]


def ensure_column(conn):
    """Колонки отпечатка и автора. Идемпотентно (правило migration-safety)."""
    have = {r[1] for r in conn.execute("PRAGMA table_info(schema_migrations)")}
    added = False
    if "fingerprint" not in have:
        conn.execute("ALTER TABLE schema_migrations ADD COLUMN fingerprint TEXT")
        added = True
    if "applied_by" not in have:
        conn.execute("ALTER TABLE schema_migrations ADD COLUMN applied_by TEXT")
        added = True
    return added


def _who(by):
    """КЕМ применён шаг — значение, которое механизм добывает САМ.

    🪤 Почему не просто необязательный параметр. Урок поля `resolved` (1 запись из 1483):
    незаполняемое поле — не лень ролей, а отсутствующий механизм. Необязательный `by`
    остался бы пустым у всех, кроме тех, кто ВСПОМНИТ, — а механизм, о котором надо
    вспомнить, умирает. Поэтому автор выводится из вызывателя, когда его не назвали.

    ⚖️ И ЧЕСТНОСТЬ ИСТОЧНИКА ВИДНА В САМОМ ЗНАЧЕНИИ — приём `addressed_by` ('field' /
    'backfill'), уже принятый в контуре: роль названа явно ⇒ пишем её; не названа ⇒
    пишем `tool:<файл>`. Выдавать инструмент за роль нельзя: «кто решил» и «чем
    применено» — разные факты, и слипшись они начнут врать молча.
    """
    # ⚡ ТРИ СТУПЕНИ, И КАЖДАЯ ЧЕСТНА ПРО СВОЙ ИСТОЧНИК (средняя добавлена по карточке #248).
    # 🩸 Оплачено соседним контуром: в семи шагах схемы имя роли было ВПЕЧАТАНО в код.
    # Прогнав такой шаг у себя, сосед получал в СВОЙ журнал автора «PROTO» — роль, которой
    # у него нет и которая его базы не касалась. Журнал схемы существует ровно для вопроса
    # «кто это применил»: впечатанное имя отвечает на него УВЕРЕННО И НЕВЕРНО.
    # ⚖️ Почему ступень из окружения, а не «оставить пусто»: пустое честнее неверного, но
    # `tool:<файл>` честнее и полнее пустого — он говорит, ЧЕМ применено. А `MEZO_ROLE`,
    # если роль его выставила, говорит КЕМ, и это уже её собственное слово, а не догадка кода.
    if by:
        return str(by)
    import inspect
    import os
    из_среды = (os.environ.get("MEZO_ROLE") or "").strip()
    if из_среды:
        return из_среды.upper()
    for frame in inspect.stack()[1:]:
        name = os.path.basename(frame.filename)
        if name != os.path.basename(__file__):
            return f"tool:{name}"
    return "tool:неизвестен"


def record_step(conn, version, note, backdated=False, by=None):
    """Записать шаг В ТОЙ ЖЕ транзакции, что и правка схемы.

    ⛔ Зовётся ПОСЛЕ применения шага, до commit: иначе журнал скажет о шаге, которого
    не случилось, — а это ровно та ложь, от которой journal и заводят.
    `backdated=True` помечает запись, восстановленную ЗАДНИМ ЧИСЛОМ: её отпечаток снят
    не в момент шага, и выдавать его за современный факту нельзя.
    """
    # 🔴 «В ТОЙ ЖЕ ТРАНЗАКЦИИ» БЫЛО СЛОВАМИ, А НЕ ФАКТОМ — находка @PROTO (записка #3474,
    # приёмка bite-schema-journal.py, случай ⑧, доказана контрольной парой).
    # Python-sqlite открывает неявную транзакцию только перед INSERT/UPDATE, а DDL первым
    # действием уходит В АВТОКОММИТ. Замер: CREATE TABLE + record_step + ROLLBACK оставлял
    # ТАБЛИЦУ на месте и откатывал ЗАПИСЬ О НЕЙ.
    # 🎯 То есть схема менялась, а журнал молчал — ровно та ложь, ради защиты от которой
    # журнал и заведён, и приходила она в самом опасном виде: уверенный неверный ответ
    # («шагов столько-то, сверх ноль»), который никто не пойдёт перепроверять.
    # ⇒ Требуем ЯВНОЙ транзакции и падаем громко: обещание, которое нельзя выполнить,
    # обязано отказать, а не выполниться наполовину.
    # ⚖️ ТРЕБОВАНИЕ КАСАЕТСЯ ТОЛЬКО ЗАПИСИ, ИДУЩЕЙ ВМЕСТЕ С ПРАВКОЙ СХЕМЫ.
    # Первая редакция этой починки требовала транзакцию ВСЕГДА — и уронила ретро-запись,
    # у которой правки схемы нет вовсе: она восстанавливает след ПРОШЛОГО шага и обещания
    # «та же транзакция» не даёт. Поймано случаем ④ приёмки @PROTO через минуту после правки.
    # 🎯 Класс мой же, свежий: починка шире своего предмета отказывает исправному вызову —
    # и выглядит это как строгость, а не как ошибка.
    if not backdated and not conn.in_transaction:
        raise RuntimeError(
            "record_step ВНЕ транзакции: DDL первым действием ушёл в автокоммит — "
            "открой явный BEGIN до правки схемы, иначе «та же транзакция» — слова. "
            "Замер @PROTO 2026-08-09: откат оставлял таблицу и стирал запись о ней. "
            "⚖️ Для восстановления задним числом зови с backdated=True: там правки схемы "
            "нет и это требование к ней не относится")
    ensure_column(conn)
    fp = fingerprint(conn)
    mark = " [ЗАПИСАНО ЗАДНИМ ЧИСЛОМ: отпечаток снят позже шага]" if backdated else ""
    conn.execute(
        "INSERT OR REPLACE INTO schema_migrations (version, note, fingerprint, applied_by) "
        "VALUES (?,?,?,?)",
        (version, (note or "") + mark, fp, _who(by)))
    return fp


def verify(conn):
    """→ (сходится: bool, человеческое объяснение).

    Сравнивается отпечаток ТЕКУЩЕЙ схемы с последним записанным. Молчание тут запрещено:
    если сверять нечем (ни одного отпечатка), сторож обязан сказать это ВСЛУХ — «нечем
    проверить» и «всё в порядке» не должны выглядеть одинаково.
    """
    have = {r[1] for r in conn.execute("PRAGMA table_info(schema_migrations)")}
    if "fingerprint" not in have:
        return False, ("в журнале нет колонки отпечатка — сверять нечем; "
                       "прогони migrations/20260808-schema-journal-fingerprint.py")
    row = conn.execute(
        "SELECT version, fingerprint FROM schema_migrations "
        "WHERE fingerprint IS NOT NULL ORDER BY rowid DESC LIMIT 1").fetchone()
    if not row:
        return False, "ни у одного шага нет отпечатка — сверять НЕ С ЧЕМ (это не «чисто»)"
    now = fingerprint(conn)
    if row[1] == now:
        return True, f"схема совпадает с журналом (последний шаг {row[0]}, отпечаток {now})"
    return False, (f"СХЕМУ МЕНЯЛИ МИМО ЖУРНАЛА: сейчас {now}, а последний записанный шаг "
                   f"«{row[0]}» оставил {row[1]}. Шаг, применённый без записи, делает ответ "
                   f"о версии уверенным и неверным")
